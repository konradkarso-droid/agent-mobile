#pragma once

// Склейка заранее обсчитанных записей памяти.
//
// ЗАЧЕМ. Записи памяти уходят модели сообщением агента перед репликой
// собеседника («вспоминание», ConversationJournal.recallOf). Текст старой
// записи от хода к ходу почти не меняется, а обсчитывается каждый раз заново —
// это большая часть ожидания до первого токена. Склейка хранит обсчитанную
// строку записи на диске (кусок) и в ходе вставляет её на место; заново
// считаются начало каждой строки (шов) и всё вне записей.
//
// КУСОК — ЦЕЛАЯ СТРОКА, С ПОДПИСЬЮ. Подпись («С твоих слов в прошлом
// разговоре, на днях:») занимает около половины строки, поэтому кусок без неё
// экономил бы вдвое меньше. Подпись называет время и меняется, но по
// календарным дням: для записи старше сегодняшнего дня она одна весь день.
// Куски строятся ночью с подписями наступающего дня; кусок, чья подпись
// разошлась с ходом, просто не находится, и строка считается целиком.
//
// ЧТО КУСОК ЗНАЕТ И ЧЕГО НЕТ. Кусок обсчитан после одной стены: без ленты и
// соседних записей. Шов возвращает строке начало, обсчитанное на своём месте,
// но ответ со склейкой — не тот же, что при обсчёте целиком, а другой.
// Записи в куске не видят друг друга; связать их модель может только в ответе.
//
// Кусок — производное от текста, а не память: потерянный, испорченный или
// чужой кусок значит только, что строка посчитается целиком. В куске хранится
// всё, против чего он верен (отпечаток загрузки, токены стены, токены строки),
// и всё это сверяется при подъёме.
//
// Без JNI и без состояния библиотеки: модуль проверяется на настоящем движке
// вне телефона.

#include <cstdint>
#include <functional>
#include <string>
#include <vector>

#include "llama.h"

namespace record_splice {

// ── Разрез запроса ─────────────────────────────────────────────────────────

// Строка вспоминания: подпись (до первого ": " с двоеточием) и содержание
// (всё после, с пробелом в начале). Строка без подписи (шапка портрета) целиком
// идёт содержанием, подпись пуста. Подпись отдельно нужна только прибору: в
// кусок строка идёт целиком.
struct Line {
    std::string sig;
    std::string content;
};

// План хода, присланный приложением: текст вспоминания целиком, его строки и
// включена ли склейка. Пустой план — в ходе записей нет.
struct Plan {
    std::string recall;
    std::vector<Line> lines;
    bool on = false;
};

// Разбор плана из JSON {"recall": "...", "on": true, "lines": [{"s": "...",
// "c": "..."}]}. Сломанный JSON даёт пустой план, а не исключение.
Plan parse_plan(const std::string & json);

// Кусок запроса. line >= 0 — строка записи с этим номером (её можно взять
// готовой); line < 0 — текст, который считается свежим: всё до вспоминания,
// переносы между строками, всё после вспоминания.
struct Segment {
    std::string text;
    int line = -1;
};

// Запрос, разрезанный по строкам записей. Склеенные подряд тексты всех кусков
// равны запросу. ok = false — резать нельзя, причина в why, segments пуст.
struct Cut {
    bool ok = false;
    std::string why;
    std::vector<Segment> segments;
};

// Разрезать готовый запрос (после шаблона чата) по плану.
//
// Вспоминание ищется последним вхождением своего текста: оно стоит перед
// последней репликой собеседника, а прошлые вспоминания в ленту не ложатся.
// Внутри него строки ищутся по порядку. Разрез — по тексту; какие токены
// достаются строке, решает spans.
//
// ЧЕГО НЕ УМЕЕТ: если шаблон чата меняет текст сообщения (экранирует, обрезает
// пробелы), вспоминание в запросе не найдётся — об этом скажет why, и ход
// пойдёт целиком.
Cut cut(const std::string & prompt, const Plan & plan);

// Доля начала строки, которая пересчитывается на месте (шов).
//
// Объявленное число, не подобранное на телефоне. Шов нужен потому, что модель
// опирается прежде всего на начало записи, а кусок обсчитан без ленты и
// соседних записей. Пересчёт дальше шва ответ с полным обсчётом не выравнивает:
// он даёт близкий, но другой ответ, а время растёт.
constexpr double SEAM_SHARE = 0.15;

// Длина шва для строки в n токенов: не меньше одного токена, не больше n.
int seam_tokens(int n);

// Токены текста; add_special — со служебным началом (BOS). Разбор служебных
// меток (<|im_start|>) включён: так режет запрос и сам движок.
std::vector<llama_token> tokenize(const llama_vocab * vocab, const std::string & text, bool add_special);

// Текст куска для строки записи: строка вместе с переносом после неё.
//
// ПОЧЕМУ С ПЕРЕНОСОМ. Токенизатор модели сливает знак в конце строки с
// переносом после него в один токен («.⏎», «:⏎»). Строка, переведённая в
// токены отдельно от переноса, дала бы на стыке два токена вместо одного, и
// модель видела бы запрос, нарезанный на токены не так, как его режет она
// сама. Строка с переносом даёт ровно те токены, что достаются ей в запросе
// целиком.
//
// ЧЕГО НЕ УМЕЕТ: строке, за которой переноса нет (последняя во вспоминании,
// дальше конец сообщения) или за которой идёт пустая строка (перенос
// сливается со следующим), кусок не подходит — она считается заново (spans).
std::string chunk_text(const std::string & line);

// Участок токенов запроса [begin, end). line >= 0 — строка записи с этим
// номером; whole — её токены совпадают с токенами chunk_text(text), и участок
// можно взять готовым куском. line < 0 — всё остальное, считается заново.
struct Span {
    int begin = 0;
    int end = 0;
    int line = -1;
    bool whole = false;
    std::string text;   // chunk_text строки; пусто у участков не-строк
};

// Токены запроса, разложенные по участкам. tokens — токены запроса целиком,
// как их режет движок без склейки: склейка не меняет ни одного токена, она
// только берёт часть из них готовыми. Участки идут подряд и покрывают все
// токены. ok = false — токены не складываются обратно в текст запроса
// (причина в why); тогда ход идёт целиком.
struct Layout {
    bool ok = false;
    std::string why;
    std::vector<Span> spans;
};

Layout spans(const llama_vocab * vocab, const std::vector<llama_token> & tokens,
             const std::string & prompt, const Cut & cut);

// Сколько чего в запросе этого хода — для прибора «Записи:».
struct Counts {
    int lines = 0;          // строк в плане
    int sig_tokens = 0;     // токенов подписей
    int content_tokens = 0; // токенов содержаний
    int line_tokens = 0;    // токенов строк целиком (то, что идёт в куски)
    int seam_tokens = 0;    // швов при кусках-строках
};

Counts count(const llama_vocab * vocab, const Plan & plan, const Cut & cut);

// ── Куски ──────────────────────────────────────────────────────────────────
//
// Работают на трёх последовательностях одного общего кэша (контекст с
// n_seq_max >= 3 и kv_unified = true): основная (разговор), стена (держит стену
// на время обсчёта кусков) и рабочая (кусок поднимается и сдвигается в ней).
// В общем кэше ячейки стены у основной последовательности и у стены одни и те
// же, и окно между последовательностями не делится.
//
// ЧЕГО НЕ УМЕЕТ: модели с Mamba-слоями — их состояние не режется на позиции.
// Таким моделям склейка не включается вовсе (см. gguf_lib.cpp).

constexpr llama_seq_id SEQ_MAIN = 0;
constexpr llama_seq_id SEQ_WALL = 1;
constexpr llama_seq_id SEQ_WORK = 2;
constexpr int SEQ_COUNT = 3;

// То, против чего кусок верен.
struct ChunkKey {
    std::string identity;               // отпечаток загрузки: модель, накладка, тип кэша
    std::vector<llama_token> wall;      // токены стены, после которой обсчитана строка
    std::vector<llama_token> content;   // токены строки
};

// Имя файла куска для строки: отпечаток её текста. Текст сверяется ещё и
// внутри файла, так что совпадение имён у разных строк ничего не испортит —
// такой кусок просто окажется негоден.
std::string chunk_file_name(const std::string & line_text);

// Обсчитать строку после стены и упаковать кусок.
//
// Стена должна лежать в SEQ_WALL на позициях 0..key.wall.size()-1. Рабочая
// последовательность очищается до и после. false — сбой движка; out пуст.
bool build_chunk(llama_context * ctx, const ChunkKey & key, std::vector<uint8_t> & out);

// Годен ли кусок для ключа — по заголовку, без подъёма в движок.
bool chunk_matches(const std::vector<uint8_t> & bytes, const ChunkKey & key);

// Поднять кусок и вставить его в основную последовательность с позиции off.
//
// Первые seam токенов строки обсчитываются заново на месте (шов), остальные
// берутся из куска со сдвигом позиций. Основная последовательность должна
// кончаться ровно перед off: движок принимает только продолжение.
// false — кусок негоден или сбой; why — словами. Основная последовательность
// при этом остаётся до off, и строку можно посчитать целиком.
bool insert_chunk(llama_context * ctx, const std::vector<uint8_t> & bytes, const ChunkKey & expect,
                  int off, int seam, std::string & why);

// Положить стену в SEQ_WALL, если её там ещё нет. Из основной
// последовательности стена копируется даром, если та начинается с неё
// (main_tokens — токены, лежащие сейчас в основной); иначе стена обсчитывается
// заново. false — сбой движка.
bool ensure_wall(llama_context * ctx, const std::vector<llama_token> & wall,
                 const std::vector<llama_token> & main_tokens, int main_n_past);

// ── Ход со склейкой ────────────────────────────────────────────────────────

// Итог хода со склейкой — для прибора.
struct TurnStats {
    int lines = 0;          // строк, которые можно было взять готовыми
    int ready = 0;          // из них взято готовыми
    int seam_tokens = 0;    // токенов швов у взятых
    int fresh_tokens = 0;   // токенов, обсчитанных заново (вместе со швами)
    int missing = 0;        // куска нет
    int stale = 0;          // кусок есть, но негоден (подпись, стена, модель)
    int failed = 0;         // сбой подъёма
    int unsplit = 0;        // строку не отрезать от соседнего текста ровно по токенам (chunk_text)
};

// Обсчитать свежие токены в основную последовательность с позиции n_past
// (n_past сдвигается); false — сбой или отмена.
using EvalFresh = std::function<bool(const std::vector<llama_token> &, int & n_past)>;

// Обсчитать запрос по участкам с позиции n_past: всё, что до n_past, уже
// лежит в кэше и не трогается; строки записей берутся из папки dir готовыми,
// когда кусок годен, иначе считаются заново. Свежие токены подряд — и между
// строками, и строки без годного куска — копятся и обсчитываются одной пачкой:
// крупная пачка считается быстрее, чем те же токены мелкими. Последний участок
// запроса всегда свежий (реплика собеседника), так что выходы модели после
// него есть.
//
// tokens и layout — из spans. false — сбой или отмена в eval; кэш тогда
// ничего не гарантирует, и вызывающий поступает так же, как при сбое обычного
// обсчёта.
bool eval_turn(llama_context * ctx, const std::vector<llama_token> & tokens, const Layout & layout,
               const std::string & identity, const std::vector<llama_token> & wall,
               const std::string & dir, int & n_past, const EvalFresh & eval, TurnStats & stats);

// ── Хранилище ──────────────────────────────────────────────────────────────

bool read_file(const std::string & path, std::vector<uint8_t> & out);

// Записать файл через временный и переименование: оборванная запись не
// оставляет полфайла под настоящим именем.
bool write_file(const std::string & path, const std::vector<uint8_t> & bytes);

// Отметить, что кусок взят в ход: вытеснение идёт по давности использования.
void touch_file(const std::string & path);

// Держать папку не больше max_bytes: удалять куски, давнее всего не бравшиеся.
// Возвращает число удалённых. Файлы не кусков не трогаются.
int enforce_cap(const std::string & dir, uint64_t max_bytes, uint64_t & total_after);

} // namespace record_splice
