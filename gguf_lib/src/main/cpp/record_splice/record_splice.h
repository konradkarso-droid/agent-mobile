#pragma once

// Разбор записей хода на подписи и содержание — основа склейки заранее
// обсчитанных записей.
//
// ЗАЧЕМ. Записи памяти уходят модели сообщением агента перед репликой
// владельца («вспоминание», ConversationJournal.recallOf). Их текст почти не
// меняется от хода к ходу, а обсчитывается каждый раз заново. Склейка хранит
// обсчитанное содержание записи и вставляет его на место; заново считаются
// только подпись («С твоих слов в прошлом разговоре, на днях:»), начало
// содержания (шов) и всё вне записей.
//
// ПОЧЕМУ ПОДПИСЬ ОТДЕЛЬНО. Подпись называет время («вчера» → «на днях») и
// стареет, а содержание нет. Кусок с подписью умирал бы при каждой смене
// подписи. Подпись считается свежей в каждом ходе, кусок содержания живёт,
// пока не изменились текст записи, стена и модель.
//
// ЧЕГО ЗДЕСЬ НЕТ. Этот модуль только режет запрос и считает. Он не обсчитывает,
// не хранит кусков и не трогает кэш движка.
//
// Без JNI и без состояния библиотеки: только словарь модели. Так его можно
// проверить на настоящем движке вне телефона.

#include <cstdint>
#include <string>
#include <vector>

#include "llama.h"

namespace record_splice {

// Одна запись вспоминания: подпись (до первого ": " включительно двоеточие) и
// содержание (всё после, с пробелом в начале). Строка без подписи (шапка
// портрета «О собеседнике я знаю только это:») целиком идёт содержанием, а
// подпись пуста.
struct Line {
    std::string sig;
    std::string content;
};

// План, присланный приложением на один ход: текст вспоминания целиком и его
// строки. Пустой план — в этом ходе записей нет.
struct Plan {
    std::string recall;
    std::vector<Line> lines;
};

// Разбор плана из JSON {"recall": "...", "lines": [{"s": "...", "c": "..."}]}.
// Сломанный JSON даёт пустой план, а не исключение.
Plan parse_plan(const std::string & json);

// Кусок запроса. line >= 0 — содержание записи с этим номером (то, что можно
// взять готовым); line < 0 — текст, который считается свежим: всё до
// вспоминания, подписи, переносы между записями, всё после вспоминания.
struct Segment {
    std::string text;
    int line = -1;
};

// Запрос, разрезанный по границам содержаний. Склеенные подряд тексты всех
// кусков равны запросу. ok = false — резать нельзя, причина в why, а
// segments пуст.
struct Cut {
    bool ok = false;
    std::string why;
    std::vector<Segment> segments;
};

// Разрезать готовый запрос (после шаблона чата) по плану.
//
// Вспоминание ищется последним вхождением своего текста: оно стоит перед
// последней репликой владельца, а прошлые вспоминания в ленту не ложатся.
// Внутри него строки ищутся по порядку; перенос строки сразу за
// содержанием относится к содержанию: он часть записи и обсчитывается с ней.
//
// ЧЕГО НЕ УМЕЕТ: если шаблон чата меняет текст сообщения (экранирует,
// обрезает пробелы), вспоминание в запросе не найдётся, и резать будет нечего —
// об этом скажет why, ход пойдёт целиком.
Cut cut(const std::string & prompt, const Plan & plan);

// Доля начала содержания, которая пересчитывается на месте (шов).
//
// Объявленное число, не подобранное на телефоне. Шов нужен потому, что модель
// опирается прежде всего на начало записи, а готовый кусок обсчитан без ленты
// и соседних записей. Склейка с любым швом даёт не тот же ответ, что обсчёт
// целиком, а другой: пересчёт шва его не выравнивает с полным, а только
// делает начало записи обсчитанным на своём месте.
constexpr double SEAM_SHARE = 0.15;

// Длина шва для содержания в n токенов: не меньше одного токена, не больше n.
int seam_tokens(int n);

// Сколько чего в запросе этого хода — для прибора «Записи:» в «Подробно».
struct Counts {
    int lines = 0;          // строк в плане
    int sig_tokens = 0;     // токенов подписей
    int content_tokens = 0; // токенов содержаний
    int seam_tokens = 0;    // из них считалось бы заново на швах
    // Швы, если бы кусок хранился вместе с подписью (подпись тогда входит в
    // кусок, и шов — доля всей записи). Для сравнения на приборе: такой кусок
    // экономит больше, но умирает при каждой смене подписи.
    int seam_whole_tokens = 0;
};

// Подсчёт по разрезанному запросу. Токены считаются по каждому куску
// отдельно — так же их будет считать склейка.
Counts count(const llama_vocab * vocab, const Plan & plan, const Cut & cut);

// ── Готовые куски ───────────────────────────────────────────────────────────
//
// Кусок — кэш обсчитанного содержания одной записи: содержание обсчитано сразу
// после стены (одна стена, без ленты и соседних записей) и сохранено вместе с
// тем, против чего оно верно. Кусок — производное от текста, а не память:
// потерянный или негодный кусок значит только, что запись посчитается целиком.
//
// Работает на трёх последовательностях одного общего кэша (контекст с
// n_seq_max >= 3 и kv_unified = true): основная (разговор), стена (держит
// стену на время обсчёта кусков) и рабочая (кусок поднимается и сдвигается
// в ней). Общий кэш не делит окно между последовательностями: ячейки стены у
// основной и у стены одни и те же.
//
// ЧЕГО НЕ УМЕЕТ: модели с Mamba-слоями (см. record_report в gguf_lib.cpp) —
// их состояние не режется на позиции.

// То, против чего кусок верен. Совпадение проверяется целиком при подъёме:
// другая модель или накладка (identity), другая стена (wall) или другой текст
// записи (content) — кусок негоден.
struct ChunkKey {
    std::string identity;               // отпечаток загрузки: модель, накладка, тип кэша
    std::vector<llama_token> wall;      // токены стены, после которой обсчитано содержание
    std::vector<llama_token> content;   // токены содержания
};

// Обсчитать содержание после стены и упаковать кусок.
//
// Стена должна лежать в wall_seq на позициях 0..key.wall.size()-1. Рабочая
// последовательность очищается до и после. false — сбой движка; out пуст.
bool build_chunk(llama_context * ctx, llama_seq_id wall_seq, llama_seq_id work_seq,
                 const ChunkKey & key, std::vector<uint8_t> & out);

// Поднять кусок и вставить его в основную последовательность с позиции off.
//
// Первые seam токенов содержания обсчитываются заново на месте (шов), остальные
// берутся из куска со сдвигом позиций. Основная последовательность должна
// кончаться ровно перед off: движок принимает только продолжение.
// false — кусок негоден или сбой; why — словами, основная последовательность
// при этом не тронута, и запись можно посчитать целиком.
bool insert_chunk(llama_context * ctx, llama_seq_id main_seq, llama_seq_id work_seq,
                  const std::vector<uint8_t> & bytes, const ChunkKey & expect,
                  int off, int seam, std::string & why);

// Токены текста; add_special — со служебным началом (BOS). Разбор служебных
// меток (<|im_start|>) включён: так режет запрос и сам движок.
std::vector<llama_token> tokenize(const llama_vocab * vocab, const std::string & text, bool add_special);

} // namespace record_splice
