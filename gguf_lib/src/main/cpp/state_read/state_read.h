#pragma once

// Чтение внутреннего состояния модели: среднее выхода одного слоя по токенам
// отрезка текста.
//
// ЗАЧЕМ. Отношение двух записей памяти (спорят, согласуются, не связаны)
// модель держит в своём состоянии и без печати ответа. Чтение снимает это
// состояние, а смысл ему даёт направление, выученное заранее (приложение,
// memory.judge.DirectJudge). Печати нет, инструкции судьи нет — только сами
// записи.
//
// КАК СНИМАЕТСЯ. Обратным вызовом обсчёта ([callback]), который движок ставит
// в контекст при его создании. Пока чтение не взведено, вызов на каждый узел
// графа отвечает «не нужен» — обсчёт идёт одним куском, как без него. Взведённый
// ([read_mean]), он просит у графа выход слоя «l_out-N» и складывает строки
// этого выхода, пока считается отрезок.
//
// ЧТО ПОРТИТ. Память контекста (кэш внимания и состояние Mamba-слоёв) перед
// чтением очищается и после остаётся занятой прочитанным. Тот, кто зовёт, обязан
// после чтения считать разговор необсчитанным — см. nativeReadLayerMean в
// gguf_lib.cpp.
//
// ЖИВОЙ ОТВОД ([locate], [arm], [take]) — то же чтение, но без своего обсчёта:
// слой снимается на лету, пока движок обсчитывает обычный запрос разговора, по
// токенам одного отрезка внутри него (реплики собеседника). Отдельный обсчёт тут
// не годится: у модели с Mamba-слоями состояние не откатить, и чтение после
// ответа стоило бы пересчёта всего разговора от стены. Отвод памяти не трогает
// и ответ не меняет — он только складывает строки слоя.
//
// ЧЕГО НЕ УМЕЕТ:
//  - только процессор: строки слоя читаются прямо из памяти тензора;
//  - последний слой не читается: у него строки уже отобраны под выдачу;
//  - число прочитанного не значит ничего без направления, снятого на той же
//    модели, той же накладке и том же слое, в той же подаче текста.
//
// Без JNI и без состояния библиотеки: проверяется на настоящем движке вне
// телефона.

#include <atomic>
#include <climits>
#include <string>
#include <vector>

#include "llama.h"

struct ggml_tensor;

namespace state_read {

// Состояние обратного вызова. layer < 0 — чтение не взведено.
struct Hook {
    std::atomic<int> layer{-1};
    int n_embd = 0;
    std::vector<double> acc;
    long row0 = 0;   // с какого токена текста начинается отрезок
    long row1 = LONG_MAX;  // на каком кончается (не включая); LONG_MAX — до конца текста
    long seen = 0;   // сколько токенов текста уже прошло через слой (номер следующего)
    long rows = 0;   // сколько строк отрезка сложено
    bool bad_shape = false;
};

// Обратный вызов обсчёта (ggml_backend_sched_eval_callback); user_data — Hook.
bool callback(ggml_tensor * t, bool ask, void * user_data);

// Итог чтения. mean пуст — не прочитано, причина словами в why.
struct Result {
    std::vector<float> mean;
    std::string why;
};

// Обсчитать с чистой памятью head и seg одним текстом и вернуть среднее выхода
// слоя layer по токенам seg. head и seg — токены одного текста, разрезанного там,
// где кончается head (см. [split]). n_batch — логическая пачка контекста.
Result read_mean(llama_context * ctx, Hook & hook, const std::vector<llama_token> & head,
                 const std::vector<llama_token> & seg, int layer, int n_batch);

// Разрезать текст head + tail на токены head и токены остатка так, как режет
// его токенизатор целиком. ok = false — граница сдвинута: последний токен head
// сливается с началом tail, и отрезок не тот, что учили.
struct Split {
    bool ok = false;
    std::vector<llama_token> head;
    std::vector<llama_token> seg;
};
Split split(const llama_vocab * vocab, const std::string & wall, const std::string & head, const std::string & tail);

// Где в запросе лежит отрезок для живого отвода: номера его токенов [t0, t1).
// prompt — текст запроса целиком, tokens — его токены (tokenize с add_special,
// как их режет движок); отрезок — знаки [c0, c1) текста. ok = false — отрезок
// не ложится на границы токенов (токенизатор сливает его край с соседом) или
// пуст; why — словами.
struct Window {
    bool ok = false;
    long t0 = 0;
    long t1 = 0;
    std::string why;
};
Window locate(const llama_vocab * vocab, const std::string & prompt, const std::vector<llama_token> & tokens,
              size_t c0, size_t c1);

// Взвести отвод на обсчёт, который начнётся с токена first (n_past перед ним):
// сложить выход слоя layer по токенам [w.t0, w.t1). false — отрезок уже
// обсчитан (лежит раньше first), читать нечем.
bool arm(Hook & hook, int n_embd, int layer, const Window & w, long first);

// Снять отвод после обсчёта и вернуть среднее. Зовётся при любом исходе
// обсчёта: невзведённый отвод тоже снимается.
Result take(Hook & hook, const Window & w);

}  // namespace state_read
