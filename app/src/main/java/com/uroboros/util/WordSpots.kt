package com.uroboros.util

/**
 * Место в тексте, которое надо выделить: от [start] включительно до [end]
 * невключительно — те же две границы, что принимает setSpan.
 */
data class WordSpot(val start: Int, val end: Int)

/**
 * Найти в тексте вхождения названных слов — целыми словами, не различая
 * регистра.
 *
 * ЗАЧЕМ ОТДЕЛЬНО ОТ ПОКАЗА. Здесь живёт единственное правило, отделяющее
 * верную подсветку от вредной, и проверить его можно только порознь от
 * экрана: внутри Activity оно не берётся обычным тестом, а промах в нём не
 * падает и в логе не виден.
 *
 * КТО РЕШАЕТ, ЧТО ИСКАТЬ. Не этот код. Слова приходят готовыми от того, кто
 * их назвал; здесь только поиск вхождения. Разбирать текст и решать, что в нём
 * примечательного, тут нельзя ни при каких обстоятельствах — это была бы
 * вторая копия чужого правила, и она разошлась бы с первой молча.
 *
 * ГРАНИЦА СЛОВА — ГЛАВНОЕ, ЧТО ЗДЕСЬ ЕСТЬ. Слово «не» стоит внутри «нельзя»,
 * «конечно» и «неделя»; закрасив их, показ сообщил бы об отрицании там, где
 * его нет. Совпадением считается только кусок, с обеих сторон которого стоит
 * не буква и не цифра. Цифра в проверке участвует наравне с буквой: иначе «7»
 * находилось бы внутри «17».
 *
 * РЕГИСТР НЕ РАЗЛИЧАЕТСЯ: слова обычно приведены к нижнему, а в тексте стоит
 * написанное человеком. Приведение идёт посимвольно, чтобы длина не поехала и
 * найденные места не сдвинулись относительно исходного текста.
 *
 * ЧЕГО НЕ УМЕЕТ:
 *  - слово, встречающееся несколько раз, даёт несколько мест. Который из них
 *    имелся в виду, отсюда не видно и видно быть не может;
 *  - слово, которого в тексте нет, не даёт ничего, и пустой ответ при непустом
 *    списке слов — законный исход. Чаще всего это значит, что текст обрезан по
 *    длине и нужное осталось за обрезкой;
 *  - форма слова не подбирается. Ищется ровно то, что дали: «рубанок» не
 *    найдёт «рубанком».
 *
 * @return места по возрастанию начала. Порядок задан затем, чтобы ответ не
 *         зависел от порядка обхода набора слов.
 */
fun wordSpots(text: CharSequence, words: Set<String>): List<WordSpot> {
    if (words.isEmpty() || text.isEmpty()) return emptyList()
    val lowered = buildString(text.length) {
        for (element in text) append(element.lowercaseChar())
    }
    val spots = mutableListOf<WordSpot>()
    for (word in words) {
        if (word.isEmpty()) continue
        var index = lowered.indexOf(word)
        while (index >= 0) {
            val end = index + word.length
            val before = if (index == 0) ' ' else lowered[index - 1]
            val after = if (end >= lowered.length) ' ' else lowered[end]
            if (!before.isLetterOrDigit() && !after.isLetterOrDigit()) {
                spots += WordSpot(index, end)
            }
            index = lowered.indexOf(word, index + 1)
        }
    }
    return spots.sortedBy { it.start }
}
