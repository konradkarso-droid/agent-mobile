package com.uroboros.util

/**
 * Приведение текста для сравнения — одно место на весь проект: поиск,
 * сито, окна отбора и определитель лица сравнивают слова в одном виде.
 *
 * Что делает: нижний регистр; «ё», «Ё» и латинские «ë» (U+00EB), «Ë» (U+00CB)
 * становятся «е».
 *
 * ЗАЧЕМ ЛАТИНСКАЯ «ë». Некоторые клавиатуры ставят вместо русской «ё» латинскую
 * «e» с двумя точками — на глаз буквы не различить. Без приведения запись
 * «жëлтый» не находится по слову «желтый» и не совпадает со словом «жёлтый».
 *
 * ЧЕГО НЕ ПРИВОДИТ: другие латинские двойники кириллицы (латинские «a», «o»,
 * «c», «p» внутри русского слова) — в записях они не встречались. Ударение
 * (U+0301) тоже не снимает: это делает то место, которому оно мешает.
 *
 * Для показа не применяется: слова владельца на экране и в памяти остаются
 * такими, как набраны. Приведённый вид только сравнивается.
 */
object TextFold {

    fun fold(text: String): String =
        text.lowercase()
            .replace('ё', 'е')
            .replace('ë', 'е')
}
