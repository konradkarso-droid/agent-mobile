package com.uroboros.util

/**
 * Похоже ли слово на повелительное наклонение — по окончанию, без словаря.
 * Одно правило на двух потребителей: срочность запроса
 * (will.QueryUrgencyClassifier) и определитель лица (memory.nav.PersonForm).
 *
 * Не словарь смысловых слов, а морфологический паттерн: слово кончается на
 * характерное окончание повелительного наклонения, и корень до окончания не
 * короче [MIN_ROOT_LENGTH]. Тот же стиль, что RiskTrigger.SUFFIXES: дешёвая
 * эвристика без настоящей морфологии.
 *
 * Одиночная «и» («останови») в списке сознательно: она расширяет риск ложных
 * срабатываний (существительные и прилагательные часто кончаются на «и»), но
 * для срочности ложное «тяжёлое» стоит лишней паузы, а ложное «лёгкое» —
 * пропущенной голой команды, которую по словам поймать нечем. Поэтому оба
 * потребителя смотрят только на ПЕРВОЕ слово предложения: в начале
 * повелительное стоит почти всегда, а существительное на «и» там реже, чем
 * в середине.
 *
 * ЧЕГО НЕ УМЕЕТ:
 *  - повелительное на «-ь» («проверь», «поставь», «брось») не ловит: окончания
 *    «ь» в списке нет, а добавить его значило бы ловить и существительные
 *    («морковь»);
 *  - первое слово на «и» — существительное («Дети играют») — даёт ложное
 *    повелительное.
 *
 * Список и порог — объявленные, не подобранные по замеру.
 */
object ImperativeForm {

    val SUFFIXES = listOf("айте", "яйте", "уйте", "ите", "ьте", "ай", "яй", "уй", "и")
    const val MIN_ROOT_LENGTH = 3

    /** [word] — одно слово в нижнем регистре. */
    fun looksImperative(word: String): Boolean =
        SUFFIXES.any { suffix -> word.length - suffix.length >= MIN_ROOT_LENGTH && word.endsWith(suffix) }
}
