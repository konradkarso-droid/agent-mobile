package com.uroboros.util

/**
 * Приведение вывода компилятора к устойчивой "подписи ошибки" — ТОЛЬКО для
 * сравнения шагов между собой (RepeatDetector внутри ToteEngine).
 *
 * Зачем (находка на устройстве 2026-08-23, Mi 10T): kotlinc печатает путь к
 * временному файлу с новым UUID на каждый вызов —
 *     uroboros_tote/dd437a10-2f57-417b-bb9e-81ae8b17359f.kt:9:17: error: ...
 * поэтому сырой stderr никогда не совпадает сам с собой. RepeatDetector честно
 * сравнивал и честно не находил повторов: 19 одинаковых по смыслу итераций
 * подряд прошли мимо stuckThreshold=5 и упёрлись в жёсткий потолок maxIterations.
 * Ось 3 из item 8a была не сломана — ей на вход подавали мусор.
 *
 * ЧТО ЭТОТ ФАЙЛ НАМЕРЕННО НЕ ДЕЛАЕТ: он не готовит текст для модели. Очистка
 * вывода, который видит модель (jansi-шум и прочее окружение), — отдельная
 * задача с ПРОТИВОПОЛОЖНЫМ требованием: там нельзя терять номера строк и
 * позиции, иначе модель не поймёт, где чинить. Здесь наоборот — теряем всё,
 * что мешает узнать повтор. Сводить две задачи в одну функцию нельзя
 * (separated continuity): это разные каналы, они обязаны оставаться
 * независимо непрерывными.
 *
 * Переиспользование, ради которого это вынесено отдельно: item 6b (локальная
 * база решённых проблем) индексируется по КЛАССУ ошибки, а не по её тексту с
 * привязкой к месту — `of()` даёт ровно такой ключ.
 */
object ErrorSignature {

    /** Маркер строки компилятора, несущей саму ошибку. */
    private const val ERROR_MARKER = "error:"

    /** UUID временного файла — единственная часть пути, меняющаяся каждый вызов. */
    private val UUID_LIKE = Regex(
        "[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}"
    )

    /**
     * Возвращает подпись: только тексты ошибок, без пути к файлу и без
     * позиции "строка:колонка".
     *
     * Отбрасывается позиция намеренно. Правка кода почти всегда сдвигает строки,
     * и та же самая ошибка на строке 9 и на строке 10 — это один и тот же тупик,
     * а не два разных. Плата за это осознанная: две РАЗНЫЕ ошибки с совпадающим
     * текстом в разных местах файла сольются в одну подпись. Для цикла, который
     * упирается в повторяющуюся ошибку, это верный размен.
     *
     * Если строк с ошибками нет вообще (например, компилятор упал иначе),
     * подпись строится из всего вывода с заменой UUID на плейсхолдер — чтобы
     * не вернуть пустую строку и не сделать все такие шаги "одинаковыми" по
     * недосмотру.
     */
    fun of(raw: String): String {
        val messages = raw.lineSequence()
            .filter { it.contains(ERROR_MARKER) }
            .map { it.substringAfter(ERROR_MARKER).trim() }
            .filter { it.isNotBlank() }
            .toList()

        val body = if (messages.isNotEmpty()) {
            messages.joinToString("\n")
        } else {
            UUID_LIKE.replace(raw, "<id>").trim()
        }

        return body.ifBlank { "(пустой вывод компилятора)" }
    }
}
