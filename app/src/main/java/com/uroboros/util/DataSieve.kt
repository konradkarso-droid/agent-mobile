package com.uroboros.util

/**
 * Универсальный механизм ограничения объёма данных ("молекулярное сито") —
 * используется везде, где нужно ограничить размер текста перед тем, как
 * передать его дальше (модели, в лог, в UI и т.д.).
 *
 * ОБРЕЗКА НЕОБРАТИМА: отрезанного не восстановит никто ниже по конвейеру.
 * Поэтому единственное, что о ней сообщает, — пометка в конце текста, и она же
 * делает срабатывание видимым и человеку, и модели. Отдельного счётчика нет и
 * не нужно: механизм, чей след уходит в собственный выход, в нём не нуждается.
 *
 * ЧЕГО СИТО НЕ УМЕЕТ ПО ЗАМЫСЛУ. Оно рассчитано на осмысленные ограничения и не
 * защищает от бессмысленных: при пределе меньше самой пометки результат окажется
 * длиннее предела (capBytes), а отрицательный предел уронит вызов исключением
 * (capLines). Проверок на это нет намеренно — такой аргумент означает ошибку у
 * вызывающего, и тихо возвращать пустую строку значило бы её спрятать. Область
 * применимости: предел заведомо больше пометки и неотрицателен.
 *
 * Это решение, а не недоделка, и потому оно записано здесь, а не рядом с
 * функциями: там, ниже, стоят настоящие пробелы механизма, которые однажды
 * закроют. Смешивать их нельзя — иначе «починят» и то, что чинить не надо.
 */
object DataSieve {

    /**
     * Обрезает текст так, чтобы его UTF-8 представление не превышало maxBytes.
     * Не разрывает многобайтовый символ посередине.
     * Если текст был обрезан — дописывает понятную пометку в конце.
     */
    fun capBytes(text: String, maxBytes: Int, marker: String = "…[обрезано]"): String {
        val fullBytes = text.toByteArray(Charsets.UTF_8)
        if (fullBytes.size <= maxBytes) return text

        val markerBytes = marker.toByteArray(Charsets.UTF_8)
        val budget = (maxBytes - markerBytes.size).coerceAtLeast(0)

        var cut = budget.coerceAtMost(fullBytes.size)
        // не резать посередине UTF-8 символа: пятимся, пока не встанем
        // на начало символа (байт вида 10xxxxxx — это продолжение символа)
        while (cut > 0 && (fullBytes[cut].toInt() and 0xC0) == 0x80) {
            cut--
        }

        val truncated = String(fullBytes, 0, cut, Charsets.UTF_8)
        return truncated + marker
    }

    /**
     * То же самое, но ограничение по количеству СТРОК, а не байтам.
     *
     * Байты при этом ничем не ограничены: одна строка любой длины проходит
     * целиком. Значит там, где вход может прийти без переносов — вывод чужого
     * процесса, склеенный лог, — одного capLines мало.
     */
    fun capLines(text: String, maxLines: Int, marker: String = "…[обрезано]"): String {
        val lines = text.lines()
        if (lines.size <= maxLines) return text
        return lines.take(maxLines).joinToString("\n") + "\n" + marker
    }
}
