package com.uroboros.llm

import androidx.room.Dao
import androidx.room.Entity
import androidx.room.Insert
import androidx.room.Query

/**
 * Ход закрытого разговора. Архив ленты.
 *
 * ЗАЧЕМ. Закрытие разговора человеком раньше было удалением: строки
 * [JournalTurn] стирались, и ответы агента исчезали с устройства целиком —
 * единственное место, где они хранились. Теперь закрытие переносит их сюда.
 * Разница не в удобстве: удаление необратимо, а перенос не разрушает ничего,
 * поэтому и сторожить его нечем не надо.
 *
 * ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ ПРИЗНАК В [JournalTurn]. Признак «закрыт» пришлось
 * бы не забыть в условии выборки каждому, кто когда-либо станет читать ленту
 * для промпта. Отдельная таблица со своим DAO делает такое забывание не
 * маловероятным, а невозможным: [JournalArchiveDao] не возвращает
 * [JournalTurn] ни одной функцией, поэтому закрытый ход не может попасть туда,
 * где ждут активный, — и промах ловится компилятором, а не на устройстве.
 *
 * ТА ЖЕ БАЗА, ЧТО У АКТИВНОЙ ЛЕНТЫ. Перенос строк и очистка активной таблицы
 * обязаны быть неделимы, иначе возможна половина переноса. Через две базы
 * атомарности нет — там понадобился бы собственный журнал переноса. Поэтому
 * архив лежит в `uroboros_journal.db` рядом с лентой, а не в третьем файле.
 *
 * ЧЕГО АРХИВ НЕ УМЕЕТ — важно, потому что выглядит он как сохранность:
 *  - он не выносит материал С УСТРОЙСТВА. Разбитый или потерянный телефон
 *    уносит архив вместе с активной лентой. Копия наружу остаётся ручным
 *    действием человека (выгрузка баз) и частью этого механизма не является;
 *  - он растёт без границы. Ни срока, ни счётчика, ни чистки здесь нет
 *    намеренно: чистка — это удаление, а от него и уходили. Читатель у архива
 *    сегодня ровно один и он будущий — замер доли ответов, собранных без
 *    опоры на память. Пока его нет, таблица просто накапливает;
 *  - он не делает материал доверенным. Лента — недоверенный канал, архив
 *    закрытых разговоров тем более: в промпт он не идёт никогда.
 *
 * @property archiveIndex номер архивации, с нуля. Все ходы, закрытые одним
 *   действием человека, получают один номер; следующее закрытие получает
 *   следующий. Это ЕДИНСТВЕННЫЙ надёжный порядок в таблице — сортировать
 *   архив по времени нельзя, см. [archivedAt].
 * @property turnIndex номер хода внутри своей архивации — тот самый, каким
 *   ход жил в активной ленте. В таблице он повторяется: у каждой архивации
 *   своя нумерация с нуля. Пара с [archiveIndex] и есть ключ.
 * @property userContent реплика пользователя целиком, дословно как в
 *   [JournalTurn].
 * @property agentContent ответ движка дословно.
 * @property question то, что человек набрал руками, без подставленных
 *   записей памяти.
 * @property recordsJson участвовавшие записи памяти в том же виде, в каком
 *   они лежали в активной ленте: массив объектов `{"text", "firstSeenTurn"}`.
 *   Разбор — на стороне того, кто читает; здесь строка переносится как есть,
 *   без разбора и пересборки. Разбирать при переносе значило бы дать порче
 *   одного хода власть отменить закрытие всего разговора.
 * @property promptTokens размер запроса на этом ходе по отчёту движка. Ноль
 *   означает «не измерено», а не «пусто» — ровно как в [JournalTurn].
 * @property fingerprint отпечаток модели и параметров на момент хода.
 *   Переносится, потому что архив разных архиваций содержит разные отпечатки
 *   законно, в отличие от активной ленты, где расхождение внутри таблицы само
 *   по себе признак порчи.
 * @property archivedAt время закрытия разговора, миллисекунды системных
 *   часов. СПРАВОЧНО, не порядок: часы устройства человек может перевести, и
 *   монотонности у них нет. Сортировка архива делается по [archiveIndex]
 *   всегда.
 *
 *   Все ходы одной архивации несут одну и ту же метку — это время закрытия
 *   ленты, а не время хода. Времени самого хода в проекте не хранит никто:
 *   [JournalTurn] его не несёт. Так что восстановить, когда именно был
 *   разговор, по архиву нельзя — можно только узнать, когда его закрыли.
 */
@Entity(
    tableName = "journal_archive_turns",
    primaryKeys = ["archiveIndex", "turnIndex"],
)
data class JournalArchiveTurn(
    val archiveIndex: Int,
    val turnIndex: Int,
    val userContent: String,
    val agentContent: String,
    val question: String,
    val recordsJson: String,
    val promptTokens: Int,
    val fingerprint: String,
    val archivedAt: Long,
)

/**
 * Доступ к архиву закрытых разговоров.
 *
 * ТИПОВАЯ ГРАНИЦА. Здесь нет ни одной функции, возвращающей [JournalTurn], и
 * появиться такой не должно. В этом весь смысл отдельного DAO: сборщик
 * промпта принимает активный ход, а получить его отсюда попросту нечем.
 *
 * ФУНКЦИИ НЕ `suspend` — по той же причине, что в [JournalTurnDao]: `suspend`
 * в Room требует зависимости `room-ktx`, которую эта база намеренно не тянет.
 * Плата та же: вызовы блокируют поток, база собрана без разрешения работать в
 * главном, значит вызывающий обязан уйти в поток ввода-вывода сам. Не сделает
 * — упадёт при первом обращении, то есть промах громкий.
 *
 * ЧТЕНИЯ ХОДОВ ЗДЕСЬ НЕТ. Ни выборки текстов, ни выборки одной архивации:
 * читателя у архива сегодня нет ни одного, а функция без вызывающего со
 * временем начинает выглядеть проверенной, не будучи ею. Появится замер —
 * появится и запрос, написанный под его настоящую надобность, а не под
 * догадку о ней.
 *
 * ОТДЕЛЬНОГО ИНДЕКСА НЕТ. Составной ключ `(archiveIndex, turnIndex)` уже даёт
 * указатель по первому столбцу, поэтому выборка одной архивации, когда она
 * понадобится, обойдётся без него.
 */
@Dao
interface JournalArchiveDao {

    /**
     * Кладёт ходы одной архивации.
     *
     * СТОЛКНОВЕНИЕ КЛЮЧА РОНЯЕТ ВЫЗОВ, а не переписывает строку. Это отличие
     * от [JournalTurnDao.insert], и оно намеренное: там повторная запись того
     * же хода — обычное дело и ронять сохранение из-за неё нельзя, здесь же
     * совпадение пары `(архивация, ход)` означает, что номер архивации выдан
     * дважды. Тихая замена в этом случае затёрла бы чужой закрытый разговор —
     * ровно ту потерю, ради устранения которой таблица и заведена. Отказ
     * откатывает перенос целиком, и активная лента остаётся на месте.
     */
    @Insert
    fun insertAll(rows: List<JournalArchiveTurn>)

    /**
     * Сколько ходов лежит в архиве всего, по всем архивациям.
     *
     * Для показа человеку рядом с числом активных ходов. Раздельно, а не
     * суммой: сумма скрыла бы, что активная лента пуста.
     */
    @Query("SELECT COUNT(*) FROM journal_archive_turns")
    fun count(): Int

    /**
     * Номер, которым следует пометить следующую архивацию.
     *
     * На пустой таблице даёт ноль. Считается запросом, а не хранится
     * указателем: указатель — второе место, где живёт одна и та же величина,
     * и разойтись они могут молча. Вызывать это обязательно ВНУТРИ той же
     * транзакции, что и вставка, иначе между вычислением и записью может
     * влезть другая архивация и обе получат один номер.
     */
    @Query("SELECT COALESCE(MAX(archiveIndex), -1) + 1 FROM journal_archive_turns")
    fun nextArchiveIndex(): Int
}
