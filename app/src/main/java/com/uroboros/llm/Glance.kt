package com.uroboros.llm

import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

/**
 * Взгляд агента на свои приборы: агент сам просит показать их, код показывает
 * доску — то, что владелец видит в «Подробно», — на один ход, и в ленту она не
 * ложится. В ленте остаются вопрос и ответ.
 *
 * ПОЧЕМУ ТАК, А НЕ ДОСКОЙ В ЛЕНТЕ. Лента только дописывается: снимок приборов,
 * положенный в неё, остался бы там навсегда, и через час модель прочла бы
 * старую температуру как нынешнюю. Целиком на каждом ходе доска стоила бы
 * сотен токенов. Показ по просьбе стоит обсчёта доски только на том ходе, где
 * она нужна, и всегда свежий.
 *
 * ФОРМА — РОДНАЯ ДЛЯ МОДЕЛИ. Qwen2.5 обучена вызывать инструменты: в
 * системном сообщении — описание в `<tools>`, модель пишет `<tool_call>…`,
 * ответ инструмента подаётся репликой собеседника в обёртке `<tool_response>`.
 * Ровно так шаблон модели собирает роль `tool`; движок эту роль сам не
 * пропускает (см. `parse_messages_json` в `gguf_lib.cpp`), поэтому реплика
 * собирается здесь — это те же токены. Своя метка вместо родной формы
 * держалась бы на том, чему модель не учили.
 *
 * Как ход ведёт вызов — у ConversationTurns (остановка выдачи на вызове,
 * второй проход с доской, лестница перехвата поверх второго прохода).
 *
 * ЧЕГО НЕ УМЕЕТ.
 *  - Решает модель: не позовёт — назовёт число из головы. Описание прямо
 *    называет, о чём спрашивают, включая вопросы «да/нет» о теле, — это и есть
 *    способ поймать себя на «не глядел»; без такой фразы мимо проходили именно
 *    вопросы вида «ты не перегреваешься?».
 *  - Стена обращается к модели на «ты», и в зеркальных вопросах («ты не
 *    перегреваешься?») ответ иногда выходит в том же лице: «Ты не
 *    перегреваешься». Число и смысл при этом верны. Доска от первого лица
 *    этого не лечит — лечится только лицом стены.
 *  - Следующий ход доски не видит: «а батарея?» без нового взгляда агент
 *    ответит по своему прошлому ответу.
 *  - Строка «Ход» на доске — числа прошлого хода.
 *  - Инструмент один. Общей системы инструментов нет: появится второй — тогда
 *    и общее.
 */
object Glance {

    /** Имя инструмента — по нему вызов и узнаётся. */
    const val TOOL_NAME = "look_at_instruments"

    /** Начало вызова в выдаче модели. */
    const val CALL_OPEN = "<tool_call>"

    /**
     * Что показывают приборы. Перечень назван целиком: на что описание не
     * указывало (модель, контекст, вопросы «да/нет» о нагреве), туда модель не
     * глядела и отвечала из головы.
     */
    private const val TOOL_DESCRIPTION =
        "Мои приборы прямо сейчас: точные дата, день недели и время; на какой модели я работаю " +
            "и размер контекста; температура и заряд телефона; нагрев (зона сторожа); заполнение " +
            "ленты; скорость; токены последнего хода; сколько записей в памяти. Любой вопрос о " +
            "времени и дате, о моём теле, железе, нагреве, заряде или о любом числе про меня — " +
            "сначала смотрю сюда, даже если ответ «да» или «нет» (например: «ты не " +
            "перегреваешься?», «батарея не садится?»): сам я этого не знаю."

    /**
     * Описание инструмента для стены — слово в слово тем текстом, каким его
     * ставит шаблон Qwen2.5 при переданных инструментах. Английский — потому
     * что так модель училась; описание самого инструмента — по-русски.
     * Стоит последним в стене (см. BuildSelfDescription.compose).
     */
    val WALL_BLOCK: String =
        "# Tools\n\nYou may call one or more functions to assist with the user query.\n\n" +
            "You are provided with function signatures within <tools></tools> XML tags:\n<tools>\n" +
            "{\"type\": \"function\", \"function\": {\"name\": \"$TOOL_NAME\", " +
            "\"description\": \"$TOOL_DESCRIPTION\", " +
            "\"parameters\": {\"type\": \"object\", \"properties\": {}}}}" +
            "\n</tools>\n\nFor each function call, return a json object with function name and " +
            "arguments within <tool_call></tool_call> XML tags:\n<tool_call>\n" +
            "{\"name\": <function-name>, \"arguments\": <args-json-object>}\n</tool_call>"

    /**
     * Реплика агента с вызовом — в том виде, в каком её пишет модель. Выдача
     * обрывается на начале вызова, поэтому хвост вызова ставится здесь, а
     * текст до вызова (если модель что-то сказала прежде) сохраняется.
     */
    fun callMessage(before: String): String =
        before.trimEnd().let { if (it.isEmpty()) "" else "$it\n" } +
            "$CALL_OPEN\n{\"name\": \"$TOOL_NAME\", \"arguments\": {}}\n</tool_call>"

    /** Первая строка доски: чья она. */
    const val DESK_HEADER = "Мои приборы сейчас:"

    /**
     * Ответ инструмента — реплика собеседника в обёртке, как её ставит шаблон.
     * [desk] — строки доски как в «Подробно»; пустая — приборы не видны
     * (ход начал агент сам, экрана нет), и это сказано словами, а не пустотой.
     */
    fun response(desk: String, now: Long = System.currentTimeMillis()): String {
        val body = desk.ifBlank { "Приборы мне сейчас не видны." }
        return "<tool_response>\n$DESK_HEADER\n${timeLine(now)}\n$body\n</tool_response>"
    }

    /** Точное время с календарём: «Сейчас: четверг, 1 октября 2026, 20:14». */
    fun timeLine(now: Long): String =
        "Сейчас: " + SimpleDateFormat("EEEE, d MMMM yyyy, HH:mm", Locale("ru")).format(Date(now))
}
