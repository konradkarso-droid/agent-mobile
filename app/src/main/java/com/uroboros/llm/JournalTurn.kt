package com.uroboros.llm

import androidx.room.Dao
import androidx.room.Entity
import androidx.room.Insert
import androidx.room.OnConflictStrategy
import androidx.room.PrimaryKey
import androidx.room.Query

/**
 * Один ход разговора на диске.
 *
 * ЗАЧЕМ. Лента ([ConversationJournal]) живёт в памяти процесса и умирает
 * вместе с приложением. Это касается не только показа: снимок состояния
 * движка (контрольная точка) поднимается с обсчитанным началом внутри, и
 * если наш текст при следующем запуске не совпадёт с тем, от которого
 * снимок сделан, движок не найдёт совпадения и выбросит поднятое. То есть
 * без этой таблицы контрольные точки не просто неполны — они бесполезны.
 *
 * ОТДЕЛЬНЫЙ ФАЙЛ БАЗЫ. Лента лежит в `uroboros_journal.db`, а не рядом со
 * стикерами. Причина не в порядке, а в правах: база памяти собрана с
 * деструктивным откатом миграции, то есть будущая ошибка в схеме ленты
 * стёрла бы проверенные записи. Недоверенный канал не должен иметь такой
 * власти над проверенным. Побочно: у ленты своя версия схемы, и менять её
 * можно, не задевая память.
 *
 * ДОСЛОВНОСТЬ. [userContent] и [agentContent] кладутся сюда ровно такими,
 * какими ушли в движок и пришли обратно. Никакой обрезки, чистки пробелов
 * и косметики для экрана: расхождение на один знак обрывает совпадение с
 * обсчитанным началом, а единственным признаком будет выросшее время до
 * первого токена — поломка, о которой ничто не сообщит.
 *
 * @property turnIndex порядковый номер хода с нуля, он же ключ. Порядок
 *   ходов — часть смысла ленты, поэтому читать её всегда с сортировкой по
 *   этому полю, а не полагаться на порядок строк в таблице.
 * @property userContent реплика пользователя целиком: пометка об ответе
 *   без опоры, процитированные записи и сам вопрос — так, как их собрал
 *   [ConversationJournal.composeUserContent].
 * @property agentContent ответ движка дословно.
 * @property question то, что человек набрал руками, без записей. Хранится
 *   отдельно не для удобства: у двух строк два разных читателя — модель
 *   должна видеть записи, человек на экране нет.
 * @property recordsJson участвовавшие записи памяти — массив объектов
 *   `{"text": …, "firstSeenTurn": …}`. Текстовый столбец, а не список
 *   через конвертер типов: конвертер регистрируется на классе базы, то
 *   есть завёл бы связь между двумя файлами там, где её можно не заводить.
 *   Разбор и сборка — на стороне журнала.
 *
 *   Хранятся записи ЦЕЛИКОМ, хотя текст новой записи уже есть внутри
 *   [userContent]: запись, легшая в ленту на первом ходе, на шестом в
 *   реплику не подставляется, но участвовать в ходе не перестаёт, и без
 *   этого столбца шестой ход выглядел бы безопорным.
 * @property promptTokens размер запроса на этом ходе в токенах — по
 *   отчёту движка, не по нашей оценке. Знаки в токены мы пересчитывать не
 *   умеем: замер показал, что прикидка «2.6 знака на токен» завышает на
 *   треть на реальном тексте.
 *
 *   Хранится потому, что после подъёма ленты этого числа взять неоткуда:
 *   движок отдаёт его только по итогам прогона, а до первого ответа
 *   прогона не было. Без него проверка «влезет ли следующий ход» считала
 *   бы занятое место нулевым и пропустила бы ход, на котором движок молча
 *   выбрасывает половину разговора.
 *
 *   Ноль означает «не измерено», а не «пусто»: ход, сохранённый до того,
 *   как движок отчитался. Показывать такой ноль как измеренную величину
 *   нельзя.
 *
 *   Значение по умолчанию описывает строки, легшие ДО появления столбца:
 *   миграция проставляет им ноль, и это про них правда. Тому, кто пишет
 *   новый ход, умолчание не адресовано — число у него есть, и он передаёт
 *   его явно.
 * @property fingerprint отпечаток модели и параметров, от которого движок
 *   считает папку своего кэша. Лента, поднятая при другом отпечатке, не
 *   отвечает ни одной контрольной точке; без этого поля чужая пара
 *   поднялась бы молча, и обе стороны отчитались бы об успехе. Значение
 *   одинаково во всех строках одной ленты — расхождение внутри таблицы
 *   само по себе признак порчи.
 */
@Entity(tableName = "journal_turns")
data class JournalTurn(
    @PrimaryKey val turnIndex: Int,
    val userContent: String,
    val agentContent: String,
    val question: String,
    val recordsJson: String,
    val promptTokens: Int = 0,
    val fingerprint: String,
)

/**
 * Доступ к сохранённой ленте.
 *
 * ФУНКЦИИ НЕ `suspend` СОЗНАТЕЛЬНО. `suspend` в Room требует зависимости
 * `room-ktx` в сборочном файле; обычные функции компилируются при любом
 * её наличии. Плата названа прямо: они блокируют вызвавший поток, а база
 * собрана без разрешения работать в главном потоке, поэтому вызывающий
 * обязан уйти в `Dispatchers.IO` сам. Не сделает — приложение упадёт при
 * первом же обращении, то есть промах громкий, а не тихий.
 *
 * ОТРЕЗАНИЕ ЕСТЬ, ПРАВКИ СЕРЕДИНЫ НЕТ. [deleteFrom] убирает хвост ленты
 * начиная с указанного хода. Только хвост: отрезание с конца оставляет
 * начало ленты дословно тем же, то есть совпадение с обсчитанным началом
 * сохраняется, и движку остаётся дописать разницу. Ход, вынутый из
 * середины, оборвал бы это совпадение и вдобавок оставил дыру в
 * нумерации, от которой подъём отказывает целиком.
 *
 * ОТРЕЗАННЫЙ ХОД ИСЧЕЗАЕТ БЕССЛЕДНО. Хранилища отброшенных ходов нет —
 * решение сознательное, а не забытое. Такой ход был бы размеченным
 * человеком образцом выдумки, и материал этот ценный, но читателя у него
 * сегодня нет ни одного, а таблица без читателя растёт молча. Заводить
 * её стоит в тот день, когда читатель появится; до тех пор плата названа
 * прямо: образцы теряются.
 *
 * Обновления хода нет: ход дописывается один раз и дальше не меняется.
 * [insert] заменяет строку при совпадении ключа только затем, чтобы
 * повторная запись того же хода не роняла сохранение. На этом же держится
 * повторное использование номера после отрезания — освободившийся
 * [JournalTurn.turnIndex] достаётся следующему ходу.
 */
@Dao
interface JournalTurnDao {

    /** Вся лента по порядку. Пустой список означает, что ленты нет. */
    @Query("SELECT * FROM journal_turns ORDER BY turnIndex ASC")
    fun all(): List<JournalTurn>

    /** Число сохранённых ходов — для показа человеку, без чтения текста. */
    @Query("SELECT COUNT(*) FROM journal_turns")
    fun count(): Int

    /**
     * Сколько разных отпечатков лежит в таблице.
     *
     * Ожидается ровно один. Ноль означает пустую ленту, больше одного —
     * порчу: подъём в этом случае отказывает целиком, а не пытается
     * выбрать подходящие строки. Частично поднятая лента хуже пустой —
     * она обещает совпадение, которого нет.
     */
    @Query("SELECT COUNT(DISTINCT fingerprint) FROM journal_turns")
    fun fingerprintCount(): Int

    /** Отпечаток сохранённой ленты; `null`, если ленты нет. */
    @Query("SELECT fingerprint FROM journal_turns LIMIT 1")
    fun fingerprint(): String?

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    fun insert(turn: JournalTurn)

    /**
     * Стирает сохранённую ленту целиком.
     *
     * Вызывается при закрытии ленты человеком и при отказе подъёма.
     * Частичного стирания нет намеренно: ход посреди ленты, удалённый в
     * одиночку, оставил бы дыру в нумерации и в обсчитанном начале.
     */
    @Query("DELETE FROM journal_turns")
    fun clearAll()

    /**
     * Стирает ходы, начиная с [fromIndex] и до конца ленты.
     *
     * Отрезание хвоста, а не выборочное удаление: нумерация после него
     * остаётся сплошной от нуля, и подъём проходит проверку на дыру. Взят
     * диапазон, а не одна строка, по двум причинам. Первая: одна строка —
     * частный случай диапазона, и второй метод под неё был бы копией.
     * Вторая: удаление одной строки из середины даёт как раз ту дыру, от
     * которой подъём отказывает целиком, — диапазон «с этого места и до
     * конца» такой вызов выразить не позволяет.
     *
     * Число стёртых строк возвращается, потому что «стёрто ноль» и
     * «стёрто три» — разные исходы, и первый означает, что стирать было
     * нечего: указан номер за концом ленты. Молча вернуть успех в обоих
     * случаях значило бы, что промах вызывающего ничем себя не выдаст.
     */
    @Query("DELETE FROM journal_turns WHERE turnIndex >= :fromIndex")
    fun deleteFrom(fromIndex: Int): Int
}
