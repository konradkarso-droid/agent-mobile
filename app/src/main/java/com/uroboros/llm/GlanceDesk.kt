package com.uroboros.llm

/**
 * Доска приборов — что агент видит, когда сам глянул на приборы ([Glance]).
 * Одна на всех, кто её показывает: экран (MainActivity.deskSummary) и чаты
 * телеграма (gate.link.ChatLink). Разное у них — только [Trust]: где агент
 * сейчас говорит и с кем.
 *
 * ПОЧЕМУ ДОВЕРИЕ РЕШАЕТ КОД, А НЕ МОДЕЛЬ. Модель вправе пересказать собеседнику
 * любую строку доски, и удержать её от этого нечем: строка «не говори» — толчок,
 * а не рычаг. Поэтому то, чего в этом месте говорить нельзя, на доску не
 * ставится вовсе.
 *
 * ЧТО ГДЕ (решение владельца):
 *  - [Trust.OWNER] — чат приложения, за замком экрана: всё — тело, лента
 *    экрана, модель и контекст, число записей, скорость, обещания;
 *  - [Trust.OUTSIDE] — телеграм: тело, число записей (число, не содержание),
 *    скорость, обещания. Модели и контекста нет — имя модели помогло бы
 *    подбирать к ней уловки заранее, на своей копии весов; ленты экрана нет —
 *    это разговоры владельца. Что описание приборов в стене их обещает, а
 *    здесь их нет, сказано словами ([NOT_HERE]), — иначе модель назвала бы их
 *    наугад.
 * Обещания приходят уже отобранными для места: в телеграме — только этого
 * чата (gate.ChatPromises.ofChat). Отбирает зовущий, потому что «этот чат»
 * знает только он; доска лишь не показывает ничего сверх поданного.
 *
 * Время ставит сама обёртка ответа инструмента (Glance.response).
 *
 * ЧЕГО НЕ УМЕЕТ: показание — на момент взгляда; следующий ход доски не видит.
 *
 * Чистый объект.
 */
object GlanceDesk {

    /** Где агент сейчас говорит. */
    enum class Trust {
        /** Чат приложения, за замком экрана. */
        OWNER,

        /** Телеграм: собеседником может быть кто угодно. */
        OUTSIDE,
    }

    /**
     * Показания для доски. [body] — строка тела (safety.BodyLine); [ribbon] —
     * строка ленты экрана; [model] — «Модель: …, контекст N»; [records] — число
     * записей памяти, null — не прочиталось; [speed] — ток/с прошлого ответа в
     * этом месте, null — не было; [promises] — строки обещаний этого места.
     */
    data class Readings(
        val body: String,
        val ribbon: String? = null,
        val model: String? = null,
        val records: Int?,
        val speed: String?,
        val promises: List<String>,
    )

    /** Строка о том, чего в телеграме нет, хотя описание приборов в стене это обещает. */
    const val NOT_HERE = "Модель, контекст и заполнение ленты здесь не называю."

    /** Строка числа записей. */
    fun recordsLine(count: Int): String = "Память: записей $count"

    /** Доска строками, по порядку: что видит агент в месте [trust]. */
    fun of(r: Readings, trust: Trust): String = when (trust) {
        Trust.OWNER -> listOfNotNull(body(r), r.ribbon, r.model, records(r), speed(r)) + r.promises
        Trust.OUTSIDE -> listOfNotNull(body(r), records(r), speed(r)) + r.promises + NOT_HERE
    }.joinToString("\n")

    private fun body(r: Readings) = r.body
    private fun records(r: Readings) = r.records?.let(::recordsLine) ?: "Память: число записей сейчас не прочиталось."
    private fun speed(r: Readings) = r.speed?.let { "Последний ход: выдача $it ток/с" }
}
