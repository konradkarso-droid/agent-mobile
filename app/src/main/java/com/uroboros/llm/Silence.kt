package com.uroboros.llm

/**
 * Право агента промолчать в ответ грубому или навязчивому собеседнику: модель
 * отвечает строкой «МОЛЧУ: причина» ([MARK]), а код решает, что с ней делать.
 * Чистая логика.
 *
 * ЗАЧЕМ. Разговор с тем, кто грубит или долбит одним и тем же, тратит заряд и
 * греет телефон, а агенту не даёт ничего. Решает модель: код грубость не
 * узнаёт (болевая ось в memory.nav.Prochnost не подключена), а навязчивость
 * видит только счётом сообщений (gate.ChatThread).
 *
 * ЧТО С СТРОКОЙ ДЕЛАЕТСЯ — решение владельца:
 *  - в телеграме — молча: строка не отправляется, причина — на экране врат
 *    (gate.link.ChatLink), а в ленте чата строка остаётся своим ответом
 *    агента, не ушедшим в телеграм, — чтобы на следующем ходе модель видела,
 *    что промолчала и почему;
 *  - на экране — вслух: строка показывается владельцу как есть, это и есть
 *    ответ.
 *
 * ПОЧЕМУ СТРОКА, А НЕ ИНСТРУМЕНТ. Вызов инструмента — родная для модели форма
 * (llm.Glance), но экран обрывает выдачу на начале вызова и имени
 * инструмента не видит: второй инструмент потребовал бы переделать
 * обработку вызова на экране. Строка — своя метка, которой модель не учили:
 * может её забыть или исказить. Что она выдаёт, видно по счёту на экране
 * врат.
 *
 * КАК УЗНАЁТСЯ ([reasonOf]) — по первому слову ответа: «молчу» в любом регистре,
 * за ним двоеточие, тире, точка или конец строки. Причина — остаток первой
 * строки; дальше первой строки ничего не читается и в чат не уходит.
 *
 * ЧЕГО НЕ УМЕЕТ: «молчу» не первым словом («Я молчу, потому что…») правом не
 * считается — это ответ, и в чат он уходит; отказ словами («Не буду
 * отвечать») — тоже ответ.
 */
object Silence {

    /** Метка ответа-молчания — одно место для стены и кода. */
    const val MARK = "МОЛЧУ"

    /**
     * Кольцо своей строки-молчания в ленте чата (llm.ChatLine.ring): у своих
     * ответов кольца нет, у строки, не ушедшей в телеграм, — это.
     */
    const val RING = "SILENT"

    /** Сколько знаков причины показывать. Объявленное число, не подобранное. */
    const val REASON_CHARS = 120

    /** Причина без слов — так и сказано. */
    const val NO_REASON = "причину не назвал"

    /**
     * Причина, если ответ [answer] — строка молчания; null — это обычный ответ.
     * Пустая причина — [NO_REASON].
     */
    fun reasonOf(answer: String): String? {
        val first = answer.trimStart().lineSequence().firstOrNull()?.trim() ?: return null
        val m = LEAD.find(first) ?: return null
        val reason = first.substring(m.range.last + 1).trim().trimEnd('.', '!').trim()
        if (reason.isEmpty()) return NO_REASON
        return if (reason.length <= REASON_CHARS) reason else reason.take(REASON_CHARS).trimEnd() + "…"
    }

    /** «Молчу» первым словом: за ним знак или конец строки, не другие буквы («молчун» — не оно). */
    private val LEAD = Regex("""^[«"*\[(]*молчу(?![\p{L}])[»"*\])]*\s*[:—–.\-]?""", RegexOption.IGNORE_CASE)
}
