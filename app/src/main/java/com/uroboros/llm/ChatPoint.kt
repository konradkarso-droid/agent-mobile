package com.uroboros.llm

/**
 * Свой снимок ленты у чата телеграма: когда писать его на диск и когда
 * поднимать. Чистая логика: файлы и движок — у LlmEngine.
 *
 * ЗАЧЕМ. Модель с Mamba-слоями берёт готовым только начало запроса, снятое
 * снимком (`gguf_lib.cpp`, «СНИМОК ЛЕНТЫ»). Без своего снимка ход чата после
 * хода экрана или судьи считает окно чата заново от стены.
 *
 * СЛОТ ОДИН. Снимок ленты в движке один на процесс: чей последний, того и
 * снимок. Второго слота в памяти нет и не будет: 7B-модель и так на грани
 * памяти телефона. Поэтому у каждого чата свой файл на диске, а слот переходит
 * из рук в руки ([before]):
 *  - перед чужой работой — экран, судья, другой чат — снимок чата, если он
 *    этого чата и ещё не на диске, пишется в файл этого чата;
 *  - перед ходом чата, если в движке не его состояние, поднимается его файл.
 * Точка экрана живёт по своим правилам (LlmEngine.conversationDisplaced);
 * здесь — только чаты.
 *
 * ЧЕЙ СНИМОК В СЛОТЕ ([State.owned]) — по строке лога хода ([Outcome]): снят
 * на этом ходе, граница та же или поднят из файла этого чата — его. Ход без
 * снятия (прошлых ходов нет, граница позади обсчитанного) оставляет в слоте
 * прежний снимок, возможно чужой, и писать его под именем чата нельзя: файл
 * чата получил бы снимок экрана. Вреда ответу от этого не было бы — снимок
 * поднимается, только если совпал с началом запроса токен в токен, — но
 * сотни мегабайт записи впустую.
 *
 * ФАЙЛОВ — не больше [MAX_FILES]: снимок модели 7B весит больше сотни
 * мегабайт. Стираются самые давние ([extra]).
 *
 * ЧЕГО НЕ УМЕЕТ:
 *  - снимок пишется на диск лениво — когда движок уходит к другому; умер
 *    процесс, пока снимок только в памяти, — следующий ход чата посчитает окно
 *    заново;
 *  - у модели без Mamba-слоёв строки снимка в логе нет, и точка чата не
 *    пишется: после чужой работы чат считается заново, как и без этого
 *    механизма;
 *  - чатов больше, чем файлов, — давний чат снова считается заново;
 *  - каждая смена хозяина слота — запись и чтение файла: секунды и износ
 *    памяти телефона.
 */
object ChatPoint {

    /** Объявленное число, не подобранное: сколько чатов держат снимок на диске. */
    const val MAX_FILES = 2

    /**
     * Что в движке: [chat] — ключ чата, чьё состояние сейчас там (null — не
     * чата); [owned] — снимок в слоте этого чата; [onDisk] — тот же снимок уже
     * лежит в его файле.
     */
    data class State(val chat: String? = null, val owned: Boolean = false, val onDisk: Boolean = false)

    /** Что сказал движок о снимке на ходе чата. */
    enum class Outcome {
        /** Снят на границе прошлых ходов этого хода. */
        TAKEN,

        /** Не снят: граница та же, и снимок с ней уже в слоте. */
        SAME,

        /** Не снят по другой причине — в слоте прежний. */
        NOT_TAKEN,

        /** Строки нет: модель без Mamba-слоёв или ход не дошёл до обсчёта. */
        NONE,
    }

    /** Перед запросом: чей снимок записать ([save]) и чей поднять ([lift]); null — ничего. */
    data class Before(val save: String?, val lift: String?)

    /** Что сделать перед запросом чата [incoming]; null — запрос не чата. */
    fun before(s: State, incoming: String?): Before {
        val leaving = s.chat?.takeIf { it != incoming }
        return Before(
            save = leaving?.takeIf { s.owned && !s.onDisk },
            lift = incoming?.takeIf { it != s.chat },
        )
    }

    fun afterSave(s: State, ok: Boolean): State = if (ok) s.copy(onDisk = true) else s

    /** Подъём файла чата [chat]: удался — в слоте его снимок, он же на диске; нет — движок пуст. */
    fun afterLift(chat: String, ok: Boolean): State = if (ok) State(chat, owned = true, onDisk = true) else State()

    /** Запрос не чата начался: состояние в движке больше не чата. */
    fun otherStarted(): State = State()

    /** Ход чата [chat] кончился; [outcome] — что сказал движок о снимке. */
    fun afterChat(s: State, chat: String, outcome: Outcome): State {
        val same = s.chat == chat
        return when (outcome) {
            Outcome.TAKEN -> State(chat, owned = true, onDisk = false)
            Outcome.SAME -> State(chat, owned = true, onDisk = same && s.onDisk)
            Outcome.NOT_TAKEN, Outcome.NONE -> State(chat, owned = same && s.owned, onDisk = same && s.onDisk)
        }
    }

    /** Имена файлов, которые стереть: всё сверх [max] самых свежих. [files] — имя и время записи. */
    fun extra(files: List<Pair<String, Long>>, max: Int = MAX_FILES): List<String> =
        files.sortedByDescending { it.second }.drop(max).map { it.first }
}
