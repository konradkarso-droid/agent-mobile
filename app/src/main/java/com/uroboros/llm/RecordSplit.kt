package com.uroboros.llm

/**
 * Записи хода, разрезанные на подпись и содержание, и прибор «Записи:» в
 * «Подробно».
 *
 * ЗАЧЕМ. Это мерка перед склейкой заранее обсчитанных записей (замысел и
 * границы — в `record_splice.h` в нативной части). Склейка берёт готовым
 * только содержание записи, а подпись («С твоих слов в прошлом разговоре, на
 * днях:») считает свежей в каждом ходе: подпись называет время и стареет, а
 * содержание нет. Сколько при этом остаётся считать заново, зависит от длины
 * подписей и записей на настоящих ходах — это и показывает прибор.
 *
 * Ход сейчас обсчитывается целиком, как и без прибора: движок только режет
 * запрос и считает токены.
 *
 * ЧЕГО НЕ УМЕЕТ: подпись находится по первому «: » в строке. Строка без
 * подписи, но с «: » внутри разрежется не там. Для счёта и для склейки это
 * безвредно — разрез идёт по точному тексту, и склеенный запрос равен
 * исходному, — но подписью тогда будет названо начало такой строки.
 */
object RecordSplit {

    /** Строка вспоминания: подпись (с двоеточием) и содержание (с пробелом в начале). */
    data class Line(val sig: String, val content: String)

    /**
     * Строки вспоминания в том виде, в каком их режет движок. Строка без «: »
     * (шапка портрета «О собеседнике я знаю только это:») идёт целиком
     * содержанием с пустой подписью. Пустые строки (разделитель между
     * портретом и остальными записями) пропускаются: это перенос, а не запись.
     */
    fun lines(recall: String): List<Line> = recall.split('\n')
        .filter { it.isNotEmpty() }
        .map { line ->
            val at = line.indexOf(SIG_END)
            if (at < 0) Line("", line) else Line(line.substring(0, at + 1), line.substring(at + 1))
        }

    /** Отчёт движка о разрезе одного хода (см. `record_report` в `gguf_lib.cpp`). */
    data class Report(
        val lines: Int = 0,
        val sigTokens: Int = 0,
        val contentTokens: Int = 0,
        val seamTokens: Int = 0,
        val seamWholeTokens: Int = 0,
        /** Почему не режется; null — разрезано. */
        val why: String? = null,
    )

    /**
     * Строка прибора. [report] null — в ходе записей не было (или движок плана
     * не получил).
     *
     * Два числа «свежими» — два способа хранить кусок, чтобы выбирать по
     * настоящим ходам:
     *  - «подпись отдельно» — свежими считаются подписи и швы содержаний;
     *  - «с подписью» — только швы, но такой кусок умирает при каждой смене
     *    подписи («вчера» → «на днях»).
     */
    fun meterLine(report: Report?): String {
        if (report == null) return "Записи: в этом ходе записей не было"
        report.why?.let { return "Записи: не режутся — $it" }
        val all = report.sigTokens + report.contentTokens
        val apart = report.sigTokens + report.seamTokens
        return "Записи: ${report.lines} · подписи ${report.sigTokens} ток. · " +
            "содержание ${report.contentTokens} ток. · свежими при склейке: " +
            "подпись отдельно ${share(apart, all)}, с подписью ${share(report.seamWholeTokens, all)} · " +
            "склейки ещё нет — записи обсчитаны целиком"
    }

    private fun share(part: Int, all: Int): String =
        if (all <= 0) "$part ток." else "$part ток. (${(part * 100 + all / 2) / all} %)"

    private const val SIG_END = ": "
}
