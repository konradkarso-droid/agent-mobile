package com.uroboros.llm

import android.content.Context
import androidx.room.Database
import androidx.room.Room
import androidx.room.RoomDatabase
import androidx.room.migration.Migration
import androidx.sqlite.db.SupportSQLiteDatabase

/**
 * База под разговор — отдельный файл, не тот, в котором память.
 *
 * Таблиц здесь две: активная лента ([JournalTurn]) и архив закрытых
 * разговоров ([JournalArchiveTurn]). Они в ОДНОЙ базе намеренно: закрытие
 * разговора переносит ходы из первой во вторую и очищает первую, и эти два
 * действия обязаны быть неделимы. Через два файла атомарности нет — там
 * понадобился бы собственный журнал переноса, чтобы отличить «перенесено» от
 * «перенесено наполовину».
 *
 * ПОЧЕМУ ОТДЕЛЬНО ОТ ПАМЯТИ. Дело не в порядке, а в правах. База памяти
 * (`uroboros_memory.db`) собрана с деструктивным откатом миграции: подъём
 * её версии без написанной миграции стирает всё, включая проверенные
 * записи. Держи лента свою таблицу там же — будущая ошибка в схеме ленты
 * забрала бы с собой память. Недоверенный канал не должен иметь такой
 * власти над проверенным.
 *
 * Побочные выгоды: у ленты своя версия схемы, менять её можно, не задевая
 * память; закрытие ленты не может задеть стикеры по ошибке в запросе.
 *
 * ДЕСТРУКТИВНОГО ОТКАТА ЗДЕСЬ НЕТ — сознательно, в отличие от базы памяти.
 * Он стирает молча, а этот файл единственное место, где ответы агента вообще
 * хранятся. Плата названа прямо: если однажды поднять [SCHEMA_VERSION] и не
 * написать миграцию, база не откроется вовсе. Это громкий отказ вместо тихой
 * потери.
 *
 * ЧТО ОБЯЗАН СДЕЛАТЬ ВЫЗЫВАЮЩИЙ. Обращение к базе может бросить — и при
 * несовпадении схемы, и при испорченном файле. Лента вещь необязательная:
 * без неё приложение работает, просто разговор не переживает выгрузку.
 * Поэтому вызывающий ловит отказ, продолжает с пустой лентой и говорит об
 * этом человеку словами. Падать целиком из-за необязательной части нельзя,
 * молчать о её пропаже — тоже.
 *
 * Функции DAO не `suspend` (причина в [JournalTurnDao]), значит любое
 * обращение блокирует поток. Разрешения работать в главном потоке база не
 * получает намеренно: промах будет громким.
 *
 * Файл базы лежит во внутреннем хранилище приложения и подпадает под
 * `res/xml/data_extraction_rules.xml`, где из выгрузки в облако и переноса
 * на другое устройство исключены все домены. Отдельного правила под этот
 * файл не нужно.
 */
@Database(
    entities = [JournalTurn::class, JournalArchiveTurn::class],
    version = JournalDatabase.SCHEMA_VERSION,
    exportSchema = false
)
abstract class JournalDatabase : RoomDatabase() {

    abstract fun journalTurnDao(): JournalTurnDao

    /**
     * Доступ к архиву. Отдельный DAO, а не функции в [JournalTurnDao]:
     * закрытый ход не должен иметь возможности попасть туда, где ждут
     * активный, и проверяет это компилятор, а не внимательность.
     */
    abstract fun journalArchiveDao(): JournalArchiveDao

    companion object {

        /**
         * Версия схемы разговора. Считается отдельно от версии базы памяти —
         * это разные файлы, и совпадение чисел было бы случайным.
         *
         * При подъёме числа сюда же добавляется миграция: без неё база не
         * откроется (деструктивного отката здесь нет намеренно, см. выше).
         */
        const val SCHEMA_VERSION = 3

        /**
         * Имя файла. Отличается от `uroboros_memory.db` не только словом:
         * это два разных файла на диске, и стереть один, не тронув другой,
         * можно средствами системы.
         */
        const val FILE_NAME = "uroboros_journal.db"

        /**
         * Версия 2: столбец `promptTokens` — размер запроса на ходе по
         * отчёту движка.
         *
         * Понадобился, когда лента научилась подниматься с диска: числа
         * взять стало неоткуда, движок отдаёт его только по итогам
         * прогона. Без него проверка «влезет ли следующий ход» считала бы
         * занятое место нулевым.
         *
         * Ноль существующим строкам — правда, а не заглушка: они легли,
         * когда столбца не было, и что в них стояло, никому не известно.
         * Ноль означает «не измерено» и так и показывается на экране.
         *
         * Миграция настоящая, а не пересоздание таблицы: деструктивного
         * отката у этой базы нет намеренно, и заводить его ради одного
         * столбца значило бы отменить это решение ради удобства.
         */
        val MIGRATION_1_2 = object : Migration(1, 2) {
            override fun migrate(db: SupportSQLiteDatabase) {
                db.execSQL(
                    "ALTER TABLE `journal_turns` " +
                        "ADD COLUMN `promptTokens` INTEGER NOT NULL DEFAULT 0"
                )
            }
        }

        /**
         * Версия 3: таблица `journal_archive_turns` — архив закрытых
         * разговоров ([JournalArchiveTurn]).
         *
         * Понадобилась, когда закрытие разговора человеком перестало быть
         * удалением. Раньше нажатие стирало строки ленты, и ответы агента
         * исчезали с устройства целиком; теперь они переносятся сюда.
         *
         * Только создание таблицы: существующие строки `journal_turns` эта
         * миграция не читает и не трогает. Активная лента переживает подъём
         * версии как обычно, а архив у неё поначалу пуст — и это правда, а
         * не потеря: до появления таблицы закрытые разговоры не хранились
         * нигде, восстанавливать нечего.
         *
         * Текст запроса должен слово в слово отвечать [JournalArchiveTurn]:
         * Room при открытии сверяет настоящую схему с ожидаемой и при
         * расхождении отказывается открывать базу. Отсюда обратные кавычки,
         * `NOT NULL` у каждого столбца (в сущности нет ни одного
         * необязательного поля) и составной ключ ровно в том порядке, в
         * каком он объявлен в `primaryKeys`.
         *
         * `IF NOT EXISTS` — не перестраховка на случай повторного запуска
         * миграции (Room её дважды не запускает), а та же форма, которую
         * порождает сам Room при создании базы с нуля. Две несовпадающие
         * формы одного `CREATE TABLE` со временем разъезжаются, и заметно
         * это становится только на устройстве, где база уже старая.
         */
        val MIGRATION_2_3 = object : Migration(2, 3) {
            override fun migrate(db: SupportSQLiteDatabase) {
                db.execSQL(
                    "CREATE TABLE IF NOT EXISTS `journal_archive_turns` (" +
                        "`archiveIndex` INTEGER NOT NULL, " +
                        "`turnIndex` INTEGER NOT NULL, " +
                        "`userContent` TEXT NOT NULL, " +
                        "`agentContent` TEXT NOT NULL, " +
                        "`question` TEXT NOT NULL, " +
                        "`recordsJson` TEXT NOT NULL, " +
                        "`promptTokens` INTEGER NOT NULL, " +
                        "`fingerprint` TEXT NOT NULL, " +
                        "`archivedAt` INTEGER NOT NULL, " +
                        "PRIMARY KEY(`archiveIndex`, `turnIndex`)" +
                        ")"
                )
            }
        }

        @Volatile
        private var INSTANCE: JournalDatabase? = null

        fun getInstance(context: Context): JournalDatabase {
            return INSTANCE ?: synchronized(this) {
                INSTANCE ?: Room.databaseBuilder(
                    context.applicationContext,
                    JournalDatabase::class.java,
                    FILE_NAME
                ).addMigrations(MIGRATION_1_2, MIGRATION_2_3)
                 .build().also { INSTANCE = it }
            }
        }
    }
}
