/**
 * Размер окна контекста вынесен на уровень файла, а не оставлен в
 * приватном `companion object` класса, 28.08.2026.
 *
 * Причина: экран считает по нему заполненность ленты разговора, а
 * приватный companion наружу не виден — сборка падала с «Cannot access
 * 'Companion'». Открывать companion целиком значило бы выставить наружу
 * и остальные настройки загрузки, которые никого снаружи не касаются.
 * Наружу вынесено ровно одно число — то, о котором спрашивают.
 *
 * Дублировать 8192 на стороне экрана было нельзя: два места разошлись бы
 * молча, и счётчик показывал бы заполненность от несуществующего окна.
 */
/**
 * Размер окна контекста — сколько токенов модель держит перед глазами
 * одновременно: системная стена, весь разговор и ответ, всё вместе.
 *
 * ЗАКРЫТЫЙ ЭКСПЕРИМЕНТ, 27.08.2026 — оставлено 8192. Движок число
 * принял (`ctx=8192` в логе загрузки). Заплатили 44 МБ памяти (пик
 * 1487 → 1531 МБ на коротком запросе) и ноль скорости (155.8 → 156.2
 * мс на токен). На восьмигигабайтном телефоне это цена, которой можно
 * пренебречь.
 *
 * ПОДОЗРЕНИЕ, КОТОРОЕ БЫЛО СНЯТО. В ту же ночь показалось, что
 * удвоение контекста сломало запись кэша на диск. Не сломало:
 * причина — условие `n_common == 0` внутри библиотеки, см.
 * [PROMPT_CACHE_GENERATION]. Смена контекста лишь завела новую папку
 * кэша и тем самым выдала себя за виновника.
 *
 * Дальше двигать не советую, и не из-за цены. Узким местом стал не
 * размер окна, а способность 3B-модели длинным окном пользоваться и
 * терпение человека: генерация замедляется с длиной запроса (156 мс на
 * токен при 311 токенах, 186 при 1687, 277 при 2694 — последнее
 * измерено на разогретом до 36.5 °C телефоне, вклад нагрева не
 * отделён). 16384 записать как доступное и не трогать.
 *
 * Почему вообще тронуто. До этой правки сюда шло `params.contextSize`,
 * то есть 4096 — число, которое выбрали не мы. Библиотека смотрит на
 * объём памяти телефона, относит устройство к какому-то классу и
 * выдаёт значение сама. Мы собирались проектировать журнал разговора
 * вокруг этой четвёрки, ни разу не попробовав её подвинуть, — ровно та
 * ошибка, за которую забракован `DEVICE.md`: чужое число, принятое за
 * своё.
 *
 * Что это даёт. Бюджет журнала считается так: контекст минус системная
 * стена (около 275 токенов по замеру 27.08) минус потолок ответа (512).
 * При 4096 на разговор остаётся около 3300 токенов — шесть ходов, если
 * ответы длинные, восемнадцать, если короткие. Удвоение контекста
 * удваивает и это число напрямую.
 *
 * ЧЕМ МОЖЕМ ПЛАТИТЬ — три подозрения, все проверяются одним прогоном:
 * 1. Память. Хранилище обсчитанного (KV-кэш) растёт линейно с
 *    контекстом. Точная формула здесь НЕ приводится намеренно:
 *    выдуманное число хуже отсутствующего, а на экране есть настоящее.
 *    Отправная точка — пик 1487 МБ при 4096 на телефоне с 8 ГБ.
 * 2. Скорость генерации. Она упирается в память (замер потоков:
 *    прибавка исчезает между 3 и 4 потоками), а более просторное
 *    хранилище означает больше обращений к ней. База: 155-183 мс на
 *    токен.
 * 3. Файл кэша стены. Вырастет; сколько — увидим строкой «Кэш стены».
 *
 * Ещё одна возможность, которую замер закрывает попутно: библиотека
 * может не согласиться с заданным числом. Тогда в строке `Движок:`
 * останется `ctx=4096`, и это будет видно ДО всяких секундомеров.
 *
 * ОТКАТ — одно слово: вернуть сюда 4096. Значение входит в отпечаток
 * папки кэша ([loadIdentity]), поэтому смена безопасна: состояние от
 * другого контекста подхвачено не будет, кэш просто пересоберётся в
 * своей папке. Первый запуск после правки платит полную цену обсчёта
 * стены заново — мерить надо на втором и третьем.
 */
const val CONTEXT_SIZE = 8192


class LlmEngine(
    private val context: Context,
    private val watchdog: DeviceSafetyWatchdog
) {

    private val engine = GGMLEngine()

    /**
     * Сколько байт занял бы снимок состояния движка, если сохранить его на
     * диск прямо сейчас. Ноль, если модель не загружена.
     *
     * Заведено 28.08.2026 ради одного решения. Разговор переживает поворот
     * экрана, но не выгрузку приложения: при возвращении лента считается
     * заново, а это минуты. Способов два — держать процесс постоянным
     * уведомлением (2.2 ГБ памяти круглосуточно, и на MIUI не гарантия) или
     * писать состояние на диск и поднимать при запуске. Второй лучше во
     * всём, кроме размера файла: если снимок весит сотни мегабайт, запись
     * при каждом уходе будет заметной.
     *
     * Отсюда и это число: оно решает спор фактом, а не прикидкой. Наша
     * оценка «16 КБ на токен» ни разу не проверялась.
     *
     * Считает библиотека, не мы. Сама по себе величина ничего не пишет и
     * не сохраняет — только отвечает на вопрос «сколько бы вышло».
     */
    val stateSizeBytes: Long get() = engine.getStateSize()

    /** Папка кэша системного промпта для текущей модели, либо null — если создать не удалось. */
    private var promptCacheDir: File? = null

    /**
     * Подтвердил ли движок приём папки кэша. Ответ спрашивается один раз, в
     * момент установки папки, и хранится здесь.
     *
     * Почему полем, а не поиском по логу в момент показа. Строка о приёме
     * папки печатается ровно один раз — при загрузке модели, — а лог движка
     * живёт в кольцевом буфере и по мере разговора теряет начало (см.
     * [lastEngineLogLine]). Поиск задним числом рано или поздно переставал бы
     * её находить и рапортовал бы о неполадке при исправно работающем кэше.
     * То есть прибор врал бы тем громче, чем дольше идёт работа, — а именно
     * долгая работа и есть тот случай, ради которого на него смотрят.
     */
    private var promptCacheAcknowledged = false

    /**
     * Отпечаток текущей загрузки — имя папки кэша системной стены.
     *
     * Заново здесь ничего не считается: это имя уже созданной папки, то
     * есть ровно та строка, которую [applyPromptCache] вывел из метаданных
     * модели, текста системной стены и параметров загрузки. Второе место
     * вычисления того же отпечатка разошлось бы с первым молча.
     *
     * Зачем наружу. Сохранённая на диск лента разговора обязана знать, при
     * какой загрузке она набрана: поднятая при других метаданных или
     * параметрах, она не отвечает ни одному сохранённому состоянию движка,
     * и совпадения с обсчитанным началом у неё не будет. Без этой привязки
     * чужая пара поднялась бы, и обе стороны отчитались бы об успехе.
     *
     * `null`, пока модель не загружена или папку создать не удалось.
     * Привязывать ленту в этом случае не к чему — значит поднимать её
     * нельзя, и сохранять её как пригодную для подъёма тоже.
     */
    val loadFingerprint: String? get() = promptCacheDir?.name

    val isLoaded: Boolean get() = engine.isLoaded

    suspend fun loadModel(modelPath: String): Boolean {
        val params = GGMLEngine.getRecommendedParams(context)
        applyThreadMode()
        val ok = engine.load(
            path = modelPath,
            contextSize = CONTEXT_SIZE,
            threads = params.threads,
            batchSize = params.batchSize,
            flashAttn = FLASH_ATTENTION,
            useMmap = params.useMmap,
            useMlock = params.useMlock,
            cacheTypeK = KV_CACHE_TYPE,
            cacheTypeV = KV_CACHE_TYPE,
        )
        if (ok) {
            val file = File(modelPath)
            configureAfterLoad(
                sourceIdentity = file.name + ":" + file.length(),
                loadIdentity = loadIdentity(
                    contextSize = CONTEXT_SIZE,
                    flashAttn = FLASH_ATTENTION,
                    cacheTypeK = KV_CACHE_TYPE,
                    cacheTypeV = KV_CACHE_TYPE,
                    generation = PROMPT_CACHE_GENERATION,
                ),
            )
        }
        return ok
    }

    suspend fun loadModelFromUri(uri: Uri): Boolean {
        val params = GGMLEngine.getRecommendedParams(context)
        applyThreadMode()
        val ok = engine.load(
            context = context,
            uri = uri,
            contextSize = CONTEXT_SIZE,
            threads = params.threads,
            batchSize = params.batchSize,
            flashAttn = FLASH_ATTENTION,
            useMmap = params.useMmap,
            useMlock = params.useMlock,
            cacheTypeK = KV_CACHE_TYPE,
            cacheTypeV = KV_CACHE_TYPE,
        )
        if (ok) {
            configureAfterLoad(
                sourceIdentity = uri.toString(),
                loadIdentity = loadIdentity(
                    contextSize = CONTEXT_SIZE,
                    flashAttn = FLASH_ATTENTION,
                    cacheTypeK = KV_CACHE_TYPE,
                    cacheTypeV = KV_CACHE_TYPE,
                    generation = PROMPT_CACHE_GENERATION,
                ),
            )
        }
        return ok
    }

    /**
     * Единственное место, где настраивается уже загруженная модель.
     *
     * Раньше этот блок стоял дословно в обоих путях загрузки — по пути к файлу
     * и по выданному системой доступу к папке. Расхождение между двумя копиями
     * было бы поломкой того сорта, который не видно: один способ открыть модель
     * работал бы настроенным, другой — нет, а на экране оба выглядят одинаково.
     * Штраф за повтор токена уже пришлось выносить в константу по этой же
     * причине; здесь та же мера, только целиком.
     *
     * Порядок вызовов сохранён ровно как был. Он не случаен: системная стена
     * задаётся ПОСЛЕ базовых параметров сэмплера и один раз на загрузку, а не
     * на каждый запрос, — иначе движок не сможет переиспользовать уже
     * обсчитанное начало запроса.
     *
     * @param sourceIdentity откуда взялась модель — имя и размер файла либо
     *        строка выданного доступа. Участвует в имени папки кэша, см.
     *        [applyPromptCache].
     * @param loadIdentity параметры, с которыми модель фактически загружена,
     *        см. [loadIdentity]. Тоже участвует в имени папки кэша.
     */
    private fun configureAfterLoad(sourceIdentity: String, loadIdentity: String) {
        applyPromptCache(sourceIdentity, loadIdentity)
        engine.setSampling(temperature = 0.7f, topK = 40, topP = 0.9f, minP = 0.05f, mirostat = 0)
        engine.updateSamplerParams(SAMPLER_PARAMS_JSON)
        // BIBLE soft-wall: задаётся один раз при загрузке (static), не на каждый
        // generateFlow-вызов — сохраняет KV-cache prefix reuse в native-движке.
        engine.setSystemPrompt(BibleSoftWall.TEXT)
        applyStreamingLatency()
    }

    /**
     * Кэш обсчитанной системной стены на диске.
     *
     * Зачем. Системная стена — это больше тысячи токенов, и при каждом холодном
     * запуске движок считал её заново, около полутора минут. Библиотека умеет
     * сохранять уже посчитанное состояние на диск и поднимать его при следующем
     * запуске; надо только указать ей папку. Сохранение и восстановление она
     * делает сама, на пути генерации, — звать нам нечего.
     *
     * Почему папка своя на каждую модель. В имени файла кэша библиотека
     * использует отпечаток ТОЛЬКО текста системной стены. Модели в ключе нет.
     * Значит, поменяв модель и оставив стену прежней, мы получили бы совпадение
     * имён и поднятое состояние от чужой модели. Ошибка была бы молчаливой —
     * ни строки на экране, просто ответы не те. Поэтому модель разводится по
     * папкам нами.
     *
     * Из чего складывается имя папки: метаданные загруженной модели (название,
     * число параметров, размер, тип квантования), имя и размер исходного файла
     * и параметры загрузки ([loadIdentity]). Метаданные берутся у уже
     * загруженной модели, поэтому имя папки одинаково независимо от способа
     * открытия. Имя файла нужно вдобавок к ним: две сборки одной и той же
     * модели (например, обычная и с аблитерацией) вполне могут нести
     * одинаковые метаданные, а различаются именно файлом.
     *
     * Папки прежних моделей удаляются здесь же. Иначе несколько экспериментов
     * с квантованием оставили бы на телефоне по нескольку десятков мегабайт
     * каждый, и никто бы об этом не узнал.
     *
     * Не `cacheDir`, а `filesDir` — намеренно. Содержимое `cacheDir` система
     * вправе стереть при нехватке места; кэш то работал бы, то нет, без всякого
     * следа. `filesDir` система сама не трогает.
     */
    private fun applyPromptCache(sourceIdentity: String, loadIdentity: String) {
        promptCacheDir = null
        promptCacheAcknowledged = false

        val fingerprint = shortHash(
            (engine.getModelInfoJson() ?: "") + "|" + sourceIdentity + "|" + loadIdentity
        )
        val root = File(context.filesDir, PROMPT_CACHE_ROOT)
        val dir = File(root, fingerprint)

        if (!dir.isDirectory && !dir.mkdirs()) return

        // Папки других моделей больше не нужны.
        root.listFiles()?.forEach { old ->
            if (old.isDirectory && old.name != fingerprint) old.deleteRecursively()
        }

        promptCacheDir = dir
        engine.setPromptCacheDir(dir.absolutePath)

        // Спрашиваем немедленно: строка только что напечатана и лежит в хвосте
        // лога. Через сотню-другую ходов её там уже не будет.
        promptCacheAcknowledged = lastEngineLogLine(PROMPT_CACHE_LOG_MARKER) != null
    }

    /**
     * Параметры загрузки одной строкой — для имени папки кэша.
     *
     * Зачем. На диске лежит не текст, а обсчитанное состояние внимания модели
     * по системной стене. Его раскладка зависит от того, с какими параметрами
     * модель загружена: сколько места отведено под контекст, каким способом
     * считается внимание, сколькими байтами записана каждая ячейка. Поменяй
     * любой из них — и сохранённое, поднятое как есть, окажется разобрано не
     * по тем границам.
     *
     * Чем это опасно именно здесь. Библиотека складывает имя файла кэша из
     * отпечатка ОДНОГО ТОЛЬКО текста стены. Стена при смене параметров не
     * меняется, значит имя совпадёт, значит прежний файл будет подхвачен
     * молча. На экране не появится ни строки: либо ответы поедут, либо
     * приложение упадёт, и ни то ни другое не покажет причину. Поэтому
     * параметры разводятся по папкам нами — так же, как раньше пришлось
     * разводить модели.
     *
     * Правило, которое легко нарушить незаметно: сюда передаётся то, что
     * ФАКТИЧЕСКИ ушло в load(), а не то, что предложила библиотека. Стоит
     * задать какой-нибудь параметр своей константой в load(), а сюда оставить
     * `params.` — и отпечаток перестанет замечать собственную же правку. Кэш
     * останется в прежней папке, то есть случится ровно та беда, ради которой
     * всё это и написано. Поэтому в обоих местах стоит одно и то же значение.
     *
     * Что берётся и почему только это:
     * - размер контекста — задаёт объём самого хранимого состояния;
     * - способ подсчёта внимания (`flashAttn`) — может менять его раскладку;
     * - типы сжатия ключей и значений — задают ширину каждой ячейки;
     * - поколение ([PROMPT_CACHE_GENERATION]) — единственное здесь, что не
     *   является параметром загрузки. Оговорка намеренная, объяснение — в
     *   пояснении к самой константе. Коротко: другого способа завести чистую
     *   папку кэша у нас нет, а он необходим.
     *
     * Что НЕ берётся намеренно: число потоков и размер пачки обсчёта. Они
     * влияют на порядок сложения чисел, а не на форму результата, — поднятое
     * состояние остаётся пригодным. Включи мы их в отпечаток, каждый замер
     * скорости стирал бы двадцать мегабайт кэша и платил бы за них заново, без
     * всякой пользы.
     *
     * Типы значений здесь не названы намеренно. Они принадлежат библиотеке,
     * её исходников у нас перед глазами нет, а угаданное имя чужого типа —
     * это поломка сборки, о которой узнаёшь через шестнадцать минут. Знать их
     * и не требуется: строка собирается из значений как они есть, своим
     * текстовым видом.
     * Точное написание неважно — важно лишь, чтобы одинаковая загрузка давала
     * одинаковую строку, а разная разную. Если библиотека когда-нибудь сменит
     * написание, отпечаток сменится тоже и кэш пересоберётся: это безопасная
     * сторона ошибки — лишняя работа, а не чужое состояние.
     */
    private fun loadIdentity(
        contextSize: Any?,
        flashAttn: Any?,
        cacheTypeK: Any?,
        cacheTypeV: Any?,
        generation: Any?,
    ): String = "ctx=$contextSize|fa=$flashAttn|k=$cacheTypeK|v=$cacheTypeV|gen=$generation"

    /**
     * Что происходит с кэшем системной стены, человеческими словами.
     *
     * Нужно потому, что задающий метод библиотеки не возвращает ничего: он молча
     * ничего не делает и при недоступной папке, и при пустой системной стене.
     * Отличить «работает» от «молчит» можно двумя способами, оба здесь:
     * файл кэша, появившийся на диске после первого ответа, и ответ движка,
     * записанный в [promptCacheAcknowledged] в момент установки папки.
     *
     * Ответ берётся из поля, а не ищется в логе заново, — причина изложена у
     * самого поля. Коротко: искомая строка со временем вытесняется из лога, и
     * поиск задним числом сообщал бы о поломке там, где всё цело.
     *
     * Считаются только файлы, лежащие в папке непосредственно. Подпапки
     * пропускаются намеренно: в одной из них живёт наша контрольная точка
     * ([checkpointFile]), и она весит больше самого кэша. Попади она в этот
     * счёт — одна строка на экране говорила бы про два разных предмета сразу,
     * и рост любого из них выглядел бы одинаково.
     */
    fun getPromptCacheReport(): String {
        val dir = promptCacheDir
            ?: return "Кэш стены: ПАПКА НЕ СОЗДАНА — обсчёт будет каждый раз заново"

        val files = dir.listFiles()?.filter { it.isFile } ?: emptyList()
        val bytes = files.sumOf { it.length() }
        val confirmed = promptCacheAcknowledged

        val state = when {
            files.isEmpty() -> "пуст (заполнится после первого ответа)"
            else -> "${files.size} ф., ${bytes / (1024 * 1024)} МБ"
        }
        val engineSays = if (confirmed) "движок папку принял" else "движок о папке не сообщил"

        return "Кэш стены: $state · $engineSays · ${dir.name}"
    }

    /**
     * Готовая строка о последней попытке сохранить или поднять контрольную
     * точку — то, что показывается на экране.
     *
     * Строка складывается В МОМЕНТ действия, а не при показе, и это не вопрос
     * оформления. Причину отказа и число токенов знает только лог движка, а он
     * теряет начало по мере разговора (см. [lastEngineLogLine]). Собранная
     * позже строка была бы тем беднее, чем позже на неё посмотрели.
     *
     * Пустой не бывает никогда. «Не пробовали» — такое же состояние, как
     * «сохранена»: механизм, который молчит, неотличим от механизма, которого
     * нет.
     */
    private var checkpointReport: String = "Точка: не пробовали"

    /** Строка о последней попытке сохранить или поднять контрольную точку. */
    fun getStateCheckpointReport(): String = checkpointReport

    /**
     * Файл контрольной точки для нынешней загрузки, либо null — если папки
     * кэша нет, а значит и привязать точку не к чему.
     *
     * Точка лежит ВНУТРИ папки кэша стены, в подпапке. Так достаются даром две
     * вещи, каждую из которых иначе пришлось бы писать своими руками:
     *
     * - имя папки уже является отпечатком загрузки (модель, её файл, параметры,
     *   поколение — см. [applyPromptCache] и [loadIdentity]). Точка от другой
     *   модели или других параметров физически лежит по другому пути, поэтому
     *   поднять чужое состояние нельзя. Библиотека сама такой защиты не даёт:
     *   она проверяет соответствие модели никак;
     * - уборка уже написана. [applyPromptCache] удаляет папки всех прежних
     *   отпечатков целиком, вместе с их подпапками. Второй механизм уборки —
     *   это второе место, где та же мысль записана, и он неизбежно разойдётся
     *   с первым.
     *
     * Подпапка, а не файл рядом с кэшем: [getPromptCacheReport] считает
     * мегабайты файлов в папке, а точка тяжелее самого кэша и исказила бы этот
     * счёт.
     *
     * Папку здесь НЕ создаём: функция отвечает на вопрос, а не действует. Её
     * зовёт и запись, и отчёт о состоянии диска, а отчёт, оставляющий после
     * себя папку, — это прибор, меняющий то, что измеряет.
     */
    private fun checkpointFile(): File? {
        val dir = promptCacheDir ?: return null
        return File(File(dir, CHECKPOINT_SUBDIR), CHECKPOINT_FILE_NAME)
    }

    /**
     * Что лежит на диске — вторая строка о точке, независимая от первой.
     *
     * Зачем отдельно от [getStateCheckpointReport]. Та рассказывает о
     * последней ПОПЫТКЕ и живёт в памяти процесса: после перезапуска она
     * честно говорит «не пробовали». Но «не пробовали, потому что запустились
     * только что» и «не пробовали ни разу в жизни» — на экране одно и то же,
     * а разница между ними и есть всё, что мы хотим знать о записи при уходе
     * в фон: успела она в прошлый раз или нет.
     *
     * Поэтому каналов два, и сливать их нельзя: один про действие, другой про
     * диск. Возраст, а не время записи, потому что вопрос к точке всегда один
     * — насколько она отстала от разговора.
     *
     * ОТСТАВАНИЕ НЕ ДЕЛАЕТ ТОЧКУ НЕВЕРНОЙ. Движок сверяет пришедший запрос с
     * поднятым состоянием потокенно и досчитывает несовпавший хвост. Отставшая
     * точка стоит пересчёта нескольких ходов, а не неправильного ответа.
     */
    fun getStateCheckpointDiskReport(): String {
        val file = checkpointFile()
            ?: return "Точка на диске: неизвестно — папка кэша не создана"
        if (!file.isFile) return "Точка на диске: нет"
        val age = System.currentTimeMillis() - file.lastModified()
        return "Точка на диске: ${humanBytes(file.length())}, ${humanAge(age)}"
    }

    /**
     * Записать обсчитанное состояние движка на диск.
     *
     * Зачем. Разговор переживает поворот экрана, но не выгрузку приложения:
     * при возвращении вся лента считается заново, а это минуты. На диске же
     * лежит не текст, а уже обсчитанное внимание модели по всей ленте, и
     * поднять его стоит секунд.
     *
     * ЧЕГО ЭТА ФУНКЦИЯ НЕ ДЕЛАЕТ. Она не решает, когда сохраняться, и не
     * связана с лентой разговора. Точка без сохранённой ленты бесполезна: при
     * следующем запуске короткий вопрос не совпадёт с поднятым состоянием, и
     * движок сотрёт поднятое как непригодный префикс. Связывать одно с другим —
     * работа того, кто зовёт, а не эта.
     *
     * КОГДА ДВИЖОК ОТКАЗЫВАЕТ, и это не поломка, а защита. Он пишет вместе с
     * состоянием список токенов и требует, чтобы длина списка совпадала с
     * числом обсчитанного. Список чистится, когда движок сам подрезает контекст
     * посреди генерации, а счётчик остаётся большим — сохранённая в такой
     * момент точка поднялась бы молча и неверной. Отказ здесь честнее.
     *
     * Замена не на месте: пишем во временный файл и переименовываем. Иначе
     * между стиранием прежней точки и записью новой есть промежуток, в котором
     * точки нет вовсе, — а прерваться на нём может что угодно, от выгрузки до
     * нехватки места. Если переименовать не удалось, прежняя точка остаётся
     * целой, и на экране написано именно это.
     *
     * Идёт на своём потоке: файл весит десятки мегабайт, а вызов внутри
     * библиотеки к тому же ждёт, пока закончится генерация.
     *
     * @return получилось ли. Причина неудачи — в [getStateCheckpointReport].
     */
    suspend fun saveStateCheckpoint(): Boolean = withContext(Dispatchers.IO) {
        if (!engine.isLoaded) {
            checkpointReport = "Точка: ОТКАЗ — модель не загружена"
            return@withContext false
        }

        val target = checkpointFile()
        if (target == null) {
            checkpointReport = "Точка: ОТКАЗ — папка кэша не создана, привязать точку не к чему"
            return@withContext false
        }

        val temp = File(target.parentFile, target.name + CHECKPOINT_TEMP_SUFFIX)
        val parent = target.parentFile
        if (parent != null && !parent.isDirectory && !parent.mkdirs()) {
            checkpointReport = "Точка: ОТКАЗ — не удалось создать папку для точки"
            return@withContext false
        }

        val ok = runCatching { engine.stateSaveToFile(temp.absolutePath) }.getOrDefault(false)

        if (!ok) {
            temp.delete()
            val why = lastEngineLogLine(STATE_SAVE_REFUSED_FRAGMENT) ?: "лог молчит"
            checkpointReport = "Точка: ОТКАЗ при записи · $why"
            return@withContext false
        }

        // Строка ищется по уже известному исходу, а не наоборот. Иначе удачная
        // попытка, случившаяся раньше в этом же запуске, подписалась бы под
        // нынешним отказом.
        val note = lastEngineLogLine(STATE_SAVE_OK_FRAGMENT) ?: "лог молчит"

        if (!temp.renameTo(target)) {
            temp.delete()
            checkpointReport = "Точка: ОТКАЗ — не удалось заменить прежнюю, старая цела"
            return@withContext false
        }

        checkpointReport = "Точка: сохранена, ${humanBytes(target.length())} · $note"
        true
    }

    /**
     * Поднять состояние движка с диска.
     *
     * ЧЕГО ЭТА ФУНКЦИЯ НЕ ДЕЛАЕТ, и это важно ровно так же, как у записи. Она
     * поднимает состояние движка и ничего не знает о ленте разговора. Поднятое
     * состояние живёт до первого же запроса: движок сверяет пришедший запрос с
     * поднятым началом, и если совпадения нет — стирает поднятое и считает
     * заново. То есть поднимать точку в отрыве от ленты бессмысленно, а
     * поднять ленту в отрыве от точки просто дорого. Пару обязан составить
     * тот, кто зовёт.
     *
     * Отсутствие точки на диске — не отказ и не поломка, а обычное первое
     * состояние; на экране оно так и называется.
     *
     * @return получилось ли. Подробность — в [getStateCheckpointReport].
     */
    suspend fun restoreStateCheckpoint(): Boolean = withContext(Dispatchers.IO) {
        if (!engine.isLoaded) {
            checkpointReport = "Точка: ОТКАЗ — модель не загружена"
            return@withContext false
        }

        val source = checkpointFile()
        if (source == null) {
            checkpointReport = "Точка: ОТКАЗ — папка кэша не создана, привязать точку не к чему"
            return@withContext false
        }
        if (!source.isFile) {
            checkpointReport = "Точка: на диске нет"
            return@withContext false
        }

        val ok = runCatching { engine.stateLoadFromFile(source.absolutePath) }.getOrDefault(false)

        if (ok) {
            val note = lastEngineLogLine(STATE_LOAD_OK_FRAGMENT) ?: "лог молчит"
            checkpointReport = "Точка: поднята · $note"
        } else {
            val why = lastEngineLogLine(STATE_LOAD_FAILED_FRAGMENT) ?: "лог молчит"
            checkpointReport = "Точка: ОТКАЗ при подъёме · $why"
        }
        ok
    }

    /** Размер файла словами, которые читаются с экрана без пересчёта в уме. */
    private fun humanBytes(bytes: Long): String =
        if (bytes >= 1024L * 1024L) "${bytes / (1024L * 1024L)} МБ" else "${bytes / 1024L} КБ"

    /**
     * Возраст файла словами. Единица укрупняется с ростом: точность в минутах
     * нужна на свежей точке и не нужна на трёхдневной, а «4320 минут назад»
     * читатель всё равно переводит в дни сам.
     */
    private fun humanAge(millis: Long): String {
        val minutes = millis / 60_000L
        return when {
            minutes < 1L -> "только что"
            minutes < 60L -> "$minutes мин назад"
            minutes < 60L * 24L -> "${minutes / 60L} ч назад"
            else -> "${minutes / (60L * 24L)} дн назад"
        }
    }

    /**
     * Токены выдаются наружу порциями: движок копит текст в буфере и вызывает
     * обратный вызов, только когда буфер набрался. Умолчание — 256 байт, оно
     * рассчитано на межпроцессное общение через Binder, где каждый вызов стоит
     * десятки микросекунд. У нас библиотека работает прямым вызовом внутри
     * своего же процесса, и платить этой ценой не за что.
     *
     * Что это меняло на практике: короткий ответ помещался в одну-две порции,
     * поэтому на экране 11 секунд не появлялось ничего, а потом ответ возникал
     * целиком. Выглядело как «медленно», хотя генерация всё это время шла.
     * Побочный эффект был хуже самой задержки: наш секундомер мерил не скорость
     * генерации, а момент доставки, и его числа были бессмысленны.
     *
     * 64 — значение, рекомендованное документацией библиотеки ровно для этого
     * случая (прямой JNI внутри процесса, наименьшая задержка).
     */
    private fun applyStreamingLatency() {
        engine.setTokenBatchSize(STREAMING_BATCH_BYTES)
    }

    /**
     * Профиль потоков движка.
     *
     * До этой правки не вызывался никогда, поэтому работало умолчание —
     * "баланс", а оно на восьмиядерном процессоре отдавало генерации всего два
     * потока (обсчёту запроса — четыре). Это было видно в логе загрузки как
     * threads_gen=2, но принималось за свойство железа, пока строку не вывели
     * на экран.
     *
     * Вызывается ПЕРЕД load() намеренно. Документация библиотеки разрешает
     * менять профиль на ходу, так что технически момент неважен, — но если
     * настройка успевает до загрузки, движок печатает фактическое число
     * потоков в своей же строке лога. То есть результат правки виден числом,
     * а не подтверждается нашим словом.
     *
     * Оговорка из документации, которая нас пока не касается: VLM-проектор
     * запоминает число потоков при своей инициализации и на смену профиля не
     * реагирует. Когда дойдём до картинок, его придётся перезагружать.
     *
     * ЗАКРЫТЫЙ ЭКСПЕРИМЕНТ, 26.08.2026 — не повторять. Пробовали задать число
     * потоков напрямую в load() вместо params.threads, чтобы поднять генерацию
     * с трёх потоков до четырёх. Параметр подействовал, лог показал
     * threads_gen=4 threads_batch=4. Скорость не изменилась ВООБЩЕ: 174.9 и
     * 172.2 мс на токен против прежних 174.7-183.0, то есть внутри разброса.
     *
     * Что это значит и почему прежний вывод был неполон. С двух потоков на три
     * скорость росла почти линейно, и отсюда был сделан вывод «упора в память
     * нет». Верным он оказался только на том отрезке: между тремя и четырьмя
     * потоками прибавка исчезла целиком. Потолок найден, и он между 3 и 4.
     *
     * Почему откатили, хотя вреда на замере не видно. Одно это число задаёт
     * потоки и генерации, и обсчёту запроса, поэтому четвёртый поток генерации
     * стоил обсчёту падения с восьми потоков до четырёх. Сегодня обсчитывать
     * почти нечего — системная стена поднимается из кэша, остаётся текст
     * вопроса, — но журнал разговора добавит в запрос сотни токенов, которые
     * кэшем не покрыты. То есть мы заплатили бы вдвое дороже за обсчёт ровно
     * тогда, когда обсчёт станет заметен, и купили бы на это ноль.
     *
     * ПЕРЕОТКРЫВАЛСЯ 26.08.2026 по другой мишени — обсчёт запроса вместо
     * генерации — и снова закрыт, отрицательно. Подробности и числа в
     * [THREADS_OVERRIDE]. Записанное выше остаётся верным.
     */
    private fun applyThreadMode() {
        engine.setThreadMode(THREAD_MODE_PERFORMANCE)
    }

    /**
     * Обёртка над генерацией, которая физический watchdog реально исполняет:
     * FATIGUE — задержка между токенами; CRITICAL или истёкший хард-таймаут —
     * генерация останавливается до выхода из опасной зоны. Модель не участвует
     * в этом решении (Bible principle #1).
     *
     * Почему многоходовой вызов, а не одиночный. В нативном коде библиотеки
     * сохранение и восстановление кэша системной стены на диске вызываются
     * ТОЛЬКО внутри многоходовой ветки. Одиночная генерация до них не доходит
     * вовсе — установленную папку она принимает, но не использует. Это было
     * видно на замере: строка кэша осталась пустой после трёх холодных
     * запусков, а обсчёт стены каждый раз стоил полторы минуты заново.
     *
     * Снаружи ничего не изменилось: подпись та же, вызывающие места не
     * трогались. Разговор здесь по-прежнему одноходовый — одно сообщение
     * пользователя. Многоходовость понадобится журналу разговора; здесь она
     * появилась раньше срока, потому что дисковый кэш живёт только в ней.
     */
    fun generateFlow(prompt: String, maxTokens: Int = 512): Flow<GenerationEvent> =
        guardedFlow(singleUserMessage(prompt), maxTokens)

    /**
     * Тот же прогон, но запросом идёт вся лента разговора, а не одна
     * реплика: пары «роль — текст» в том порядке, в каком их отдаёт
     * [ConversationJournal.messagesFor].
     *
     * Отдельная функция, а не смена подписи у [generateFlow], намеренно.
     * Старый путь зовёт не только экран — его же использует агентский
     * цикл, и правка подписи молча утащила бы за собой места, которых
     * сейчас никто не смотрит. Два входа, одна обёртка, ноль риска для
     * работающего.
     *
     * Системной стены здесь нет: движок сам ставит её первым сообщением,
     * если в массиве нет роли `system` (см. `gguf_lib.cpp` ~1700).
     * Положить её сюда значило бы посчитать её дважды и промахнуться
     * мимо собственного дискового кэша.
     */
    fun generateConversationFlow(
        messages: List<Pair<String, String>>,
        maxTokens: Int = 512,
    ): Flow<GenerationEvent> = guardedFlow(conversationMessages(messages), maxTokens)

    /**
     * Обёртка над генерацией, общая для обоих входов.
     *
     * Стояла раньше прямо в теле [generateFlow]. Вынесена, когда входов
     * стало два: скопированный блок сторожа разошёлся бы со временем
     * молча — один путь остался бы под присмотром, другой нет, а на
     * экране оба выглядят одинаково. Та же мера, что и с
     * [configureAfterLoad], и по той же причине.
     */
    private fun guardedFlow(messagesJson: String, maxTokens: Int): Flow<GenerationEvent> = flow {
        watchdog.markInferenceStarted()
        try {
            engine.generateMultiTurnFlow(messagesJson, maxTokens).collect { event ->
                val zone = watchdog.zone.value

                if (zone == SafetyZone.CRITICAL || watchdog.shouldForceCooldown()) {
                    engine.stopGeneration()
                    watchdog.resetInferenceTimer()
                    return@collect
                }

                if (zone == SafetyZone.FATIGUE) {
                    delay(100)
                }

                emit(event)
            }
        } finally {
            watchdog.resetInferenceTimer()
        }
    }

    fun stopGeneration() {
        engine.stopGeneration()
        watchdog.resetInferenceTimer()
    }

    /**
