         * будущем, а не на измерении. Включённая опция, которая ничего не
         * дала, — сознательный долг: не окупилась, но ломать может.
         *
         * Что это. Обычный подсчёт внимания раскладывает в памяти большую
         * промежуточную таблицу «каждый токен против каждого» и потом читает её
         * обратно. Чем длиннее запрос, тем крупнее таблица и тем больше времени
         * уходит не на счёт, а на возню с памятью. Этот режим ту таблицу
         * целиком не создаёт: считает по кускам и складывает на ходу.
         * Арифметика та же, обращений к памяти меньше.
         *
         * Почему именно сейчас. Предыдущий замер показал, что упор у нас между
         * тремя и четырьмя потоками: четвёртый поток не дал ничего. Похоже на
         * упор в память, а этот режим бьёт ровно туда — он не добавляет
         * вычислителей, он сокращает походы за данными.
         *
         * ЗАМЕРЕНО 26.08.2026 — выигрыша нет. 174.2 и 174.4 мс на токен
         * против базы 174.7-183.0, то есть внутри разброса. По пику памяти
         * сказать нельзя ничего: он скакал 1703 / 1901 / 2095 МБ внутри одного
         * и того же опыта, и любая разница в нём тонет. Полная пересборка
         * стены (1075 токенов) заняла 101.4 с против прежних 95-108 — тоже без
         * изменений, но этот замер режим и не проверяет: там время уходит на
         * подъём модели с диска, а не на счёт.
         *
         * Почему всё-таки включено. Режим сокращает не вычисления, а обращения
         * к памяти, и заметен он на ДЛИННЫХ обсчитываемых запросах. Сегодня
         * обсчитывать нечего: стена приходит из кэша, остаётся десяток токенов
         * вопроса — то есть опыт поставлен на длине, где этот режим не может
         * себя показать по существу. Журнал разговора добавит в запрос сотни
         * некэшированных токенов, и тогда замер станет осмысленным. Это
         * ставка, а не вывод: если и на журнале выйдет ноль — выключать.
         *
         * Риск, названный прямо. Документация библиотеки предупреждает: на
         * части ARM-устройств этот режим падает в связке со сжатым KV-кэшем, а
         * у нас как раз `q8_0`. У нас не упал — холодная пересборка и три
