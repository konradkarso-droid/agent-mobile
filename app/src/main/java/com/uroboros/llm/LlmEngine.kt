        /**
         * Ширина ячейки KV-кэша — того самого хранилища, где лежит уже
         * обсчитанное начало запроса.
         *
         * ЗАКРЫТЫЙ ЭКСПЕРИМЕНТ, 26.08.2026 — не повторять. Проверялась одна
         * догадка: не сжатие ли ячеек делает обсчёт запроса таким медленным.
         * Пробовали `f16` (без сжатия). Результат отрицательный, вернули
         * `q8_0`.
         *
         * Из-за чего вообще возникло подозрение. Обсчёт запроса идёт со
         * скоростью около 10 токенов в секунду, генерация — около 5.4. То есть
         * обсчёт быстрее генерации всего в 1.8 раза, а должен быть быстрее в
         * десятки: генерация обязана прочитать все два гигабайта весов ради
         * КАЖДОГО следующего токена, а обсчёт читает те же два гигабайта ОДИН
         * РАЗ на всю пачку и пропускает через них сразу сотни токенов. Похоже,
