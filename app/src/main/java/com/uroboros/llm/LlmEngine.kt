         * отпечаток сменился бы, папка стала бы пустой, длинный запрос снова
         * оказался бы первым и записался. Мы прочитали бы это как «виноват
         * контекст» и откатили бы здоровое. Совпадение догадки с наблюдением
         * не является доказательством, если у наблюдения есть вторая причина.
         *
         * Почему рычагом стало поколение, а не удаление папки своими руками.
         * Удаление — операция, которая при ошибке в пути стирает не то;
         * поколение же меняет ИМЯ папки, а прежняя удаляется уже написанным
         * кодом ([applyPromptCache] чистит всё, что не совпало с нынешним
         * отпечатком). Плюс значение видно на экране в строке «Кэш стены»
         * последними знаками имени папки, то есть смену можно проверить
         * глазами, а не поверить на слово.
         *
         * Оговорка про правило отпечатка. Пояснение к [loadIdentity] требует
         * передавать туда то, что фактически ушло в `load()`. Поколение — не
         * параметр загрузки, и это единственное исключение. Оно безопасно
         * ровно в ту сторону, в какую и должно: лишняя пересборка кэша, а не
         * поднятое чужое состояние.
         *
         * КАК ПОЛЬЗОВАТЬСЯ. Поднять число, собрать, установить — и первым же
