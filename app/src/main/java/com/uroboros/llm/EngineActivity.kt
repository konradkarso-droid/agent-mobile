package com.uroboros.llm

import java.util.concurrent.atomic.AtomicInteger

/**
 * Занята ли модель сейчас и когда она в последний раз закончила работу.
 *
 * ЗАЧЕМ. Агент ложится спать, когда вокруг тихо: никто не говорит с ним, цикл
 * не идёт, судья не разбирает. Все три идут через одну обёртку генерации
 * движка, поэтому «тихо» меряется здесь, в одном месте, а не собирается из
 * признаков экрана, цикла и службы по отдельности.
 *
 * ПОЧЕМУ НЕ У СТОРОЖА. Сторож тоже отмечает начало генерации, но для потолка
 * непрерывной работы, то есть для безопасности. Сон — не безопасность, а
 * побуждение. Сидя на отметке сторожа, сон молча менялся бы от любой правки
 * потолка, и наоборот: нужды сна тянули бы за собой предохранитель.
 *
 * ЧЕГО НЕ УМЕЕТ:
 *  - видит только генерацию. Разговор, в котором человек читает ответ и
 *    думает над следующей репликой, для него тишина — поэтому порог тишины у
 *    того, кто решает спать, меряется десятками минут, а не секундами;
 *  - живёт в памяти процесса: после комы процесс новый, и о прошлой работе
 *    здесь ничего нет — [lastEndedAtMs] снова null;
 *  - не знает, чем занята модель, — только что занята.
 */
class EngineActivity(private val clock: () -> Long = System::currentTimeMillis) {

    private val running = AtomicInteger(0)

    @Volatile
    private var lastEnded: Long? = null

    /** Генерация началась. Каждому вызову обязан ответить ровно один [end]. */
    fun begin() {
        running.incrementAndGet()
    }

    /**
     * Генерация кончилась — любым путём. Отметка времени ставится ДО снятия
     * занятости: тот, кто увидел «не занята», видит и время конца.
     */
    fun end() {
        lastEnded = clock()
        running.decrementAndGet()
    }

    val busy: Boolean get() = running.get() > 0

    /** Когда закончилась последняя генерация; null — в этом процессе не было ни одной. */
    val lastEndedAtMs: Long? get() = lastEnded
}
