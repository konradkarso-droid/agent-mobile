package com.uroboros.llm

/**
 * Лента разговора — недоверенный журнал ходов, который уходит в модель
 * вместе с каждым новым вопросом.
 *
 * ЧТО ЭТО НЕ. Это не память. Память — проверенные записи с происхождением,
 * они живут в своём слое и попадают сюда лишь как цитаты внутри реплики
 * пользователя. Лента не дозревает в память и не пересказывается моделью
 * в записи: недоверенное не отмывается временем.
 *
 * ФОРМА. Массив сообщений с ролями (`user` / `assistant`), а не текст
 * внутри одной реплики. Выбрано 27.08.2026 после разбора
 * `gguf_lib/src/main/cpp/gguf_lib.cpp`: рамку агентской реплики ставит
 * шаблон модели внутри движка, и ставит ОДИНАКОВО при генерации и при
 * следующей подаче. Своя рамка («Ты ответил: «…») оказалась бы внутри
 * пользовательской реплики — движок обернул бы её собственными
 * разделителями ролей, и модель прочитала бы её как часть вопроса.
 *
 * ТОЛЬКО ДОПИСЫВАНИЕ В КОНЕЦ. Любая правка уже уложенного текста сдвигает
 * всё, что за ним, и обрывает совпадение с обсчитанным началом — а это
 * минуты пересчёта на каждом ходе. Скользящее окно исключено по этой же
 * причине. Отрезание хвоста ([dropLastTurn]) правкой уложенного текста не
 * является: начало ленты остаётся дословно тем же, и совпадение с ним
 * уцелевает.
 *
 * ДОСЛОВНОСТЬ. Текст кладётся сюда ровно таким, каким ушёл в движок и
 * пришёл обратно: без обрезки, без чистки пробелов, без косметики для
 * экрана. Расхождение на один знак обрывает совпадение в этом месте, и
 * единственным признаком будет выросшее «до 1-го токена» — то есть
 * поломка, о которой ничто не сообщит. Поэтому текст для показа человеку
 * и текст для ленты не должны быть одной переменной.
 *
 * ГДЕ ЖИВЁТ. Один экземпляр на процесс ([shared]): переживает поворот
 * экрана и любое другое пересоздание активности, умирает вместе с
 * приложением.
 *
 * ТЕКСТ ленты выгрузку пережить может — его сохраняет `JournalStore`, а
 * [restore] поднимает обратно. ОБСЧИТАННОЕ НАЧАЛО не переживает: снимок
 * состояния движка это контрольные точки, и половина их на стороне Kotlin
 * не написана. Разница дорогая и её надо понимать: поднятая лента даёт
 * разговор на экране и в подаче модели, но первый же ход после
 * перезапуска оплачивает полный пересчёт всей ленты — при паре тысяч
 * токенов это около минуты, при полной ленте минуты. Поэтому РЕШЕНИЕ,
 * поднимать ли ленту, принимается снаружи и не здесь.
 *
 * Постоянное уведомление, стоявшее здесь раньше, ОТВЕРГНУТО: оно держало
 * бы 2.2 ГБ круглосуточно, на MIUI не гарантирует выживание процесса без
 * ручной настройки автозапуска и не переживает перезагрузку.
 *
 * ПОЧЕМУ ОДИНОЧКА, А НЕ ViewModel. ViewModel — правильное место, но оно
 * может потребовать строки в сборочном файле, а проверить это с телефона
 * нельзя: цена ошибки — красная сборка и потерянный заход. Одиночка даёт
 * то же самое время жизни без единой новой зависимости. Переезд в
 * ViewModel — отдельная правка, когда до сборочного файла дойдут руки.
 */
class ConversationJournal {

    /**
     * Один ход. `userContent` — то, что ушло в реплике пользователя
     * ЦЕЛИКОМ, вместе с процитированными записями памяти; `agentContent` —
     * то, что выдал движок; `question` — то, что человек набрал руками.
     *
     * Записи хранятся внутри реплики, а не отдельным полем, намеренно:
     * при следующей подаче в модель уйдёт ровно эта строка, и хранить её
     * разобранной на части значило бы собирать её заново каждый раз — то
     * есть завести второе место, где текст может разойтись с обсчитанным.
     *
     * А вот `question` отдельно нужен, и это не то же самое дублирование.
     * У двух строк два разных читателя: модель должна видеть записи,
     * человек на экране — нет, иначе разговор утонет в цитатах, которые
     * он не писал. Та же мера, что `sourceLabel` рядом с
     * `provenancePhrase`: одна величина, два читателя, две функции.
     * Хранить их в одном ходе, а не в двух списках, важно — два списка
     * разошлись бы молча.
     */
    data class Turn(
        val userContent: String,
        val agentContent: String,
        val question: String,
        val records: List<RecordUse> = emptyList(),
    )

    /**
     * Одна запись памяти, участвовавшая в ходе, — для показа человеку.
     *
     * Зачем вообще хранить. На экране настоящее воспоминание и выдумка
     * выглядят ОДИНАКОВО: провенанс уходит в модель внутри реплики, а
     * человек видит только ответ. Замечено 28.08.2026 на живом разговоре —
     * «вспоминаю, что цвета радуги обычно перечислены как…» и «вспоминаю,
     * что круг — это замкнутый полигон с четырьмя вершинами» отличались
     * только тем, что за первым стояла запись, а за вторым ничего.
     * Отличить их можно было, только спрашивая модель её же словами.
     *
     * [firstSeenTurn] — номер хода, на котором эта запись легла в ленту
     * ВПЕРВЫЕ. Он нужен из-за отсева повторов: на шестом ходе отбор может
     * найти нужную запись, а подставлено будет ноль — она лежит с первого
     * хода и всё это время видна модели. Без этого числа экран сказал бы
     * «записей нет», и верный ответ прочитался бы как выдумка. Признак
     * «новая» отдельным полем НЕ хранится: он выводится сравнением с
     * номером самого хода, а два поля об одном разошлись бы молча.
     */
    data class RecordUse(
        val text: String,
        val firstSeenTurn: Int,
    )

    private val turns = mutableListOf<Turn>()

    /**
     * Записи, уже лежащие в ленте: строка → номер хода, на котором она
     * легла впервые.
     *
     * Ключ — сама готовая строка целиком, а не идентификатор записи: так
     * сравнение точное и не зависит от того, есть ли у записи
     * идентификатор и не поменялся ли её текст.
     *
     * Было множеством, стало отображением 28.08.2026: множество отвечало
     * на вопрос «лежит ли», а для показа человеку нужен ответ на вопрос
     * «с какого хода лежит».
     */
    private val placedRecords = mutableMapOf<String, Int>()

    /**
     * Вызывается после того, как ход закрыт: номер хода и он сам.
     *
     * Через это лента попадает на диск. Оповещение, а не прямой вызов
     * хранилища, по двум причинам. Первая: класс остаётся чистым Kotlin,
     * без базы и `Context`, и проверяется юнит-тестом. Вторая, важнее:
     * иначе рядом с каждым [appendTurn] пришлось бы не забыть вызвать
     * сохранение, а забытое место молчит — ход остался бы только в памяти
     * процесса, и обнаружилось бы это лишь после перезапуска.
     *
     * Ставится один раз тем, кто держит и ленту, и хранилище. При подъёме
     * ([restore]) НЕ вызывается: поднятое уже лежит на диске.
     */
    var onTurnAppended: ((Int, Turn) -> Unit)? = null

    /**
     * Вызывается после [clear].
     *
     * Нужен затем же: лента, стёртая в памяти, не должна оставаться на
     * диске — иначе следующий запуск поднимет разговор, который человек
     * только что закрыл.
     */
    var onCleared: (() -> Unit)? = null

    /**
     * Размер последнего ушедшего запроса в токенах — по отчёту движка,
     * не по нашей оценке.
     *
     * Знаки в токены мы пересчитывать не умеем: замер 28.08 показал, что
     * оценка «2.6 знака на токен» завышает на треть на реальном тексте
     * стены. Движок же отдаёт настоящее число в метриках
     * (`tokensEvaluated` — полный размер запроса, не только новая часть,
     * см. `gguf_lib.cpp` ~1816). Задним числом — да, но числом верным, и
     * ошибка на следующий ход равна длине нового вопроса.
     */
    var lastPromptTokens: Int = 0
        private set

    val turnCount: Int get() = turns.size

    val isEmpty: Boolean get() = turns.isEmpty()

    /** Копия ленты для показа человеку. Модели уходит [messagesFor]. */
    fun history(): List<Turn> = turns.toList()

    /**
     * Отбрасывает записи, которые в ленте уже лежат.
     *
     * Зачем. Отбор подтягивает до пяти записей на КАЖДЫЙ вопрос, а лента
     * только растёт — значит без этой проверки одна и та же запись легла
     * бы в неё по пятому разу. Считано 28.08: пять записей это около 200
     * токенов, то есть ход подорожал бы со 125 до 325 и лента кончилась
     * бы к двадцатому ходу вместо шестидесятого. При этом повтор одной и
     * той же записи подряд не делает её понятнее.
     *
     * Цена решения названа прямо: запись, легшая на первом ходе, к
     * двадцатому окажется далеко от вопроса и будет звучать глуше, чем
     * свежая. Запасной ход на этот случай спроектирован и НЕ сделан —
     * см. [reinsertionIsNotImplemented].
     */
    fun unseenRecords(rendered: List<String>): List<String> =
        rendered.filterNot { it in placedRecords }

    /**
     * Реплика пользователя целиком: пометка об ответе без опоры (если
     * нужна), процитированные записи, вопрос — блоки через пустую строку.
     *
     * ОТВЕТ БЕЗ ОПОРЫ. Если на прошлом ходе отбор не дал ни одной записи,
     * ответ на него взялся только из самой модели. Дальше он лежит в ленте
     * как обычная реплика ассистента — то есть в позиции наибольшего
     * доверия, где ни память, ни RiskTrigger его уже не видят: те стоят на
     * пути записи в базу, а лента в базу не идёт. Поэтому факт называется
     * здесь, и с этого хода он остаётся в ленте рядом с ответом.
     *
     * Пометка стоит в реплике ПОЛЬЗОВАТЕЛЯ, а не в ответе агента, и это
     * главное в её устройстве: в собственных репликах модели она не
     * появляется ни разу, значит подражать нечему. Та же причина, по
     * которой провенанс записи оформлен фразой «Пользователь сказал», а не
     * меткой — работу делает грамматика.
     *
     * Условие — ПУСТОЙ список записей прошлого хода, а не отсутствие новых.
     * Запись, легшая на первом ходе, на шестом не подставляется повторно,
     * но модели всё это время видна, и опорой быть не перестаёт (см.
     * [RecordUse.firstSeenTurn]).
     *
     * Чего пометка не делает: она ничего не останавливает и выдумывать не
     * мешает. Она удерживает ленту правдивой, чтобы неподтверждённый ответ
     * не превращался дальше в установленный факт из собственных прежних
     * слов модели.
     *
     * Заголовка над записями нет и не будет: прежний «Контекст из
     * памяти:» модель читала как тему разговора и принималась рассуждать
     * о своей памяти вообще. Слова «Вопрос:» тоже нет — на вопрос «чья
     * это речь» теперь отвечает роль сообщения, и дублировать её текстом
     * значило бы платить за один и тот же смысл дважды.
     *
     * Пояснение словами («это записи, а не твои реплики… если ответа нет,
     * скажи прямо») было написано и снято до первого прогона: три
     * предложения стоят около полусотни токенов В КАЖДОМ запросе, а
     * работу, ради которой они писались, делает грамматика самой строки
     * записи. Проверяем сначала голую форму: если её хватит, выигрыш
     * бесплатный, если нет — будет точно известно, чего не хватило.
     * Ставить всё разом нельзя: тогда при успехе неизвестно, что именно
     * сработало.
     *
     * Местоимение внутри записи НЕ переписывается («мой» не превращается
     * в «ваш») сознательно: это правка слов пользователя. Система вправе
     * помнить неточно, но не вправе перепутать, кто что сказал. Вместо
     * переписывания — кавычки, которыми в языке и отделяют чужую речь от
     * своей.
     *
     * Текст этого пояснения перенесён сюда 28.08.2026 из `buildPrompt`
     * в `MainActivity`: с появлением ленты та функция осталась без
     * вызывающих и была удалена, а история её решений относится теперь к
     * этому месту.
     */
    fun composeUserContent(records: List<String>, question: String): String {
        val blocks = ArrayList<String>(3)
        if (turns.lastOrNull()?.records?.isEmpty() == true) blocks += ANSWER_WITHOUT_SUPPORT
        if (records.isNotEmpty()) blocks += records.joinToString("\n")
        blocks += question
        return blocks.joinToString("\n\n")
    }

    /**
     * Лента в виде пар «роль — текст», в том порядке, в каком уйдёт в
     * движок. Последней стоит текущая реплика пользователя.
     *
     * Системной стены здесь нет: она задана отдельно при загрузке модели,
     * и именно от её текста движок считает имя файла дискового кэша.
     * Продублировать её здесь значило бы посчитать её дважды и
     * промахнуться мимо собственного кэша.
     */
    fun messagesFor(currentUserContent: String): List<Pair<String, String>> {
        val out = ArrayList<Pair<String, String>>(turns.size * 2 + 1)
        for (turn in turns) {
            out += ROLE_USER to turn.userContent
            out += ROLE_ASSISTANT to turn.agentContent
        }
        out += ROLE_USER to currentUserContent
        return out
    }

    /**
     * Поднимает сохранённую ленту.
     *
     * Принимает готовые ходы — проверять, можно ли им верить, здесь нечем:
     * отпечаток загрузки, целость нумерации и сохранность записей знает
     * хранилище, оно же и отказывает. Сюда приходит либо целая лента, либо
     * ничего.
     *
     * Отображение уложенных записей заново НЕ строится по тексту: у
     * каждой записи уже есть номер хода первой укладки, и он же
     * авторитетен. Пересчитать его здесь значило бы завести второе мнение
     * о том же, а разошлись бы они молча.
     *
     * [onTurnAppended] не вызывается: поднятое уже на диске.
     *
     * Счётчик [lastPromptTokens] остаётся нулевым — настоящее число
     * приходит от движка после первого же хода. До тех пор [roomLeft]
     * завышает запас; врать в безопасную сторону здесь нельзя, поэтому
     * решение о показе заполненности до первого ответа принимает экран.
     *
     * @return `false`, если лента не пуста. Подъём поверх живого разговора
     *         сбил бы нумерацию ходов, а с ней и совпадение с обсчитанным
     *         началом.
     */
    fun restore(saved: List<Turn>): Boolean {
        if (turns.isNotEmpty()) return false
        turns += saved
        for (turn in saved) {
            for (use in turn.records) {
                val known = placedRecords[use.text]
                if (known == null || use.firstSeenTurn < known) {
                    placedRecords[use.text] = use.firstSeenTurn
                }
            }
        }
        return true
    }

    /**
     * Закрывает ход: реплика пользователя и ответ уходят в ленту, а
     * процитированные записи помечаются как уложенные.
     *
     * Вызывать ТОЛЬКО когда ответ действительно получен. Ход, на котором
     * движок выдал ноль токенов, ходом разговора не является — это отказ
     * движка, и в записи разговора ему места нет. Последствие названо
     * прямо: лента после такого отказа не выросла, значит повторная
     * отправка того же вопроса даст тот же запрос до последнего знака и
     * тот же ноль. Человеку нужно сказать об этом словами и дать
     * изменить вопрос самому; дописывать знак за него нельзя — тогда в
     * движок уйдёт не то, что он набрал, и разойдётся с тем, что попадёт
     * в ленту.
     */
    fun appendTurn(
        userContent: String,
        agentContent: String,
        question: String,
        records: List<String>,
    ) {
        val index = turns.size
        // Новизну считает журнал, а не вызывающий. Вызывающему для запроса
        // нужен тот же ответ ([unseenRecords]), и если считать его дважды в
        // двух местах, экран однажды разойдётся с тем, что ушло в модель.
        // Здесь отображение ещё хранит состояние ДО этого хода, поэтому
        // отсутствие ключа и означает «новая».
        val uses = records.map { RecordUse(it, placedRecords[it] ?: index) }
        turns += Turn(userContent, agentContent, question, uses)
        // putIfAbsent по смыслу: первый ход, на котором запись легла, не
        // должен переписываться позднейшими попаданиями той же строки.
        for (record in records) placedRecords.getOrPut(record) { index }
        onTurnAppended?.invoke(index, turns.last())
    }

    /** Число из отчёта движка. Ставится после каждого прогона. */
    fun notePromptTokens(tokens: Int) {
        if (tokens > 0) lastPromptTokens = tokens
    }

    /**
     * Убирает последний ход из ленты.
     *
     * ЗАЧЕМ. До появления сохранения выдумка агента о собеседнике умирала
     * вместе с процессом. Теперь она переживает перезапуск и с каждым
     * ходом уходит глубже в ленту, где стоит в позиции наибольшего доверия
     * — как сказанное самой моделью раньше. Отрезать её должен человек:
     * формального признака выдумки у ленты нет.
     *
     * ТОЛЬКО ПОСЛЕДНИЙ, И ЭТО ГРАНИЦА, А НЕ УПРОЩЕНИЕ. Отрезание с конца
     * оставляет начало ленты дословно тем же, поэтому совпадение с
     * обсчитанным началом уцелевает и движку остаётся дописать разницу.
     * Ход, вынутый из середины, сдвинул бы весь текст за собой — то есть
     * полный пересчёт, о котором ничто не сообщит, кроме выросшего времени
     * до первого токена.
     *
     * ОТМЕТКИ ЗАПИСЕЙ СНИМАЮТСЯ ВМЕСТЕ С ХОДОМ. Записи, легшие в ленту
     * ВПЕРВЫЕ на этом ходе, перестают считаться уложенными. Без этого
     * [unseenRecords] отбрасывала бы их и дальше, и запись, чей
     * единственный след стёрт, не попала бы в ленту больше никогда — при
     * том, что в базе она есть и отбор её находит. Снимаются ровно те
     * ключи, чей номер равен номеру отрезаемого хода: [RecordUse.firstSeenTurn]
     * хранит САМУЮ РАННЮЮ укладку, значит совпадение с последним номером и
     * означает «легла здесь и больше нигде».
     *
     * СЧЁТЧИК ТОКЕНОВ ОБНУЛЯЕТСЯ. [lastPromptTokens] описывает запрос, в
     * который отрезанный ход входил, и после отрезания он завышает.
     * Пересчитать его нечем: настоящее число приходит только от движка по
     * итогам прогона. Ноль здесь означает «не измерено» — то же, что
     * после [restore], и показывается на экране так же.
     *
     * ОПОВЕЩЕНИЯ ЗДЕСЬ НЕТ, в отличие от [appendTurn]. Порядок обратный:
     * сначала правится диск, потом память процесса. При отказе диска
     * лента остаётся нетронутой и оба хранилища по-прежнему говорят одно;
     * оповещение после факта задало бы обратный порядок. Значит вызывающий
     * обязан сперва получить успех от хранилища и только потом звать это.
     *
     * ЧЕГО НЕ ДЕЛАЕТ: не отменяет записи, сохранённые в память на том ходе
     * — лента и память разные слои; не отрезает середину; не даёт
     * переспросить — повторную отправку вопроса набирает человек.
     *
     * @return отрезанный ход, либо `null`, если лента пуста.
     */
    fun dropLastTurn(): Turn? {
        val index = turns.size - 1
        if (index < 0) return null
        val dropped = turns.removeAt(index)
        placedRecords.entries.removeAll { it.value == index }
        lastPromptTokens = 0
        return dropped
    }

    /**
     * Сколько токенов остаётся до края, если следующий ответ займёт
     * [answerLimit], а вопрос будет самым коротким.
     *
     * Край — не размер окна. При `n_past >= n_ctx - 1` движок сам,
     * посреди генерации, выбрасывает половину всего между стеной и
     * концом и ничего об этом не сообщает (`try_context_shift`,
     * `gguf_lib.cpp` ~1004). То есть до потолка доходить нельзя вовсе.
     *
     * ОТВЕЧАЕТ НА ОДИН ВОПРОС: поместится ли сюда хоть что-нибудь.
     * Ноль и меньше означают, что не поместится даже короткий вопрос, и
     * лечение у этого одно — закрыть разговор. Влезет ли КОНКРЕТНЫЙ текст,
     * отвечает [maxContentChars], и лечение там другое: укоротить.
     * Две неудачи не сводятся в одну величину намеренно — совет закрыть
     * разговор там, где хватило бы сократить одно сообщение, стоил бы
     * человеку всего разговора.
     */
    fun roomLeft(contextSize: Int, answerLimit: Int): Int =
        contextSize - MIN_QUESTION_TOKENS - answerLimit - lastPromptTokens

    /**
     * Сколько знаков реплики пользователя мы пускаем при нынешней
     * занятости.
     *
     * Считается по объявленной черте [CHARS_PER_TOKEN_FLOOR] — это не
     * предсказание веса текста, а наше собственное правило, и потому число
     * точное: столько знаков пустим, столько нет.
     *
     * МЕРИТЬ НАДО ДЛИНУ ВСЕЙ РЕПЛИКИ, а не набранного вопроса. В движок
     * уходит то, что собрал [composeUserContent]: вопрос плюс подложенные
     * записи памяти плюс пометка об ответе без опоры. Считать один вопрос
     * значило бы недосчитывать ровно на тех ходах, где отбор что-то нашёл.
     *
     * [MIN_QUESTION_TOKENS] здесь НЕ вычитается. Он стоит вместо длины
     * вопроса, пока она неизвестна; здесь она известна, и подстановка
     * заменяется настоящей величиной, а не складывается с ней.
     *
     * Ноль означает, что не влезет ничего — тот же случай, что даёт
     * [roomLeft] <= 0, и спрашивать надо сперва его.
     */
    fun maxContentChars(contextSize: Int, answerLimit: Int): Int {
        val tokens = contextSize - answerLimit - lastPromptTokens
        if (tokens <= 0) return 0
        return (tokens * CHARS_PER_TOKEN_FLOOR).toInt()
    }

    /** Заполненность ленты в процентах — для показа человеку. */
    fun fillPercent(contextSize: Int): Int =
        if (contextSize <= 0) 0 else (lastPromptTokens * 100 / contextSize)

    /**
     * Стирает ленту целиком.
     *
     * Сегодня это единственный выход при заполнении, и он честный ровно
     * настолько, насколько человека предупредили заранее. Укладка —
     * перенос разговора в память записями — спроектирована, но не
     * написана; пока её нет, закрытие ленты означает, что собеседник
     * обнуляется. Поэтому вызывать это молча, по счётчику, нельзя:
     * решение принимает человек.
     */
    fun clear() {
        turns.clear()
        placedRecords.clear()
        lastPromptTokens = 0
        onCleared?.invoke()
    }

    /**
     * Запасной ход, спроектированный и сознательно НЕ написанный.
     *
     * Если отбор снова вернул запись, а лежит она в ленте далеко позади,
     * её можно положить ЕЩЁ РАЗ, рядом с вопросом. Это дописывание в
     * конец, совпадение не рвётся, и первая копия остаётся на месте —
     * то есть ответ, стоявший на записи, не остаётся без опоры.
     *
     * Не сделано намеренно, по двум причинам. Первая: модель уверенно
     * держала факт на 2694 токенах, трижды подряд, — а вся лента при
     * коротких ответах укладывается в те же тысячи, значит «далеко» в
     * нашем масштабе может не значить «глухо» вовсе. Вторая: ставить
     * два лечения разом нельзя, при успехе не будет известно, что
     * сработало.
     *
     * Признак, по которому включать, назван заранее, чтобы потом его не
     * подгонять: на ленте ходов в двадцать спросить о том, что лежит в
     * записи с первых ходов. Ответит — вставка не нужна. Не ответит или
     * начнёт выдумывать — нужна.
     */
    private val reinsertionIsNotImplemented = Unit

    companion object {
        const val ROLE_USER = "user"
        const val ROLE_ASSISTANT = "assistant"

        /**
         * Пометка об ответе, под которым не было ни одной записи памяти.
         * Ставится в начало следующей реплики пользователя — см.
         * [composeUserContent].
         *
         * Утверждение о положении дел, а не указание. «Не полагайся на
         * прошлый ответ» было бы инструкцией, то есть мягким сигналом,
         * который модель взвешивает против цели ответить; такому в проверках
         * места нет. Здесь же сказано только то, что было.
         */
        const val ANSWER_WITHOUT_SUPPORT =
            "Прошлый ответ ты дал без записей из памяти."

        /**
         * Единственная лента на процесс.
         *
         * Заведена 28.08.2026 по факту поломки. В пояснении выше было
         * написано «переживает поворот экрана», а в `MainActivity` лента
         * лежала обычным полем активности — поворот пересоздаёт активность
         * и заводит новую пустую ленту. Текст обещал одно, код делал
         * другое; разошлись они молча, и увидеть это можно было только
         * повернув телефон.
         *
         * Одиночка, а не `ViewModel`, по прежней причине: `ViewModel`
         * может потребовать строки в сборочном файле, а проверить её с
         * телефона нельзя. Время жизни у них здесь одинаковое — процесс.
         *
         * Что это НЕ чинит: выгрузку приложения. Умер процесс — умерла
         * лента. Лечится постоянным уведомлением, оно в очереди.
         */
        val shared = ConversationJournal()

        /**
         * Минимум под самый короткий осмысленный вопрос, плюс рамки ролей.
         *
         * ЭТО ПОРОГ «ЛЕНТА КОНЧИЛАСЬ», А НЕ ЗАПАС ПОД ЛЮБОЙ ВОПРОС. Раньше
         * величина стояла вместо длины ещё не набранного вопроса и была
         * оценкой сверху: замеренные вопросы шли по 26–43 знака, то есть
         * десятки токенов. Допущение сломалось на вставке в 2889 знаков —
         * двести токенов запаса против неё ничего не значат, проверка
         * пропустила запрос, и движок вернул ноль.
         *
         * Роль теперь другая и узкая: остатка меньше этой величины означает,
         * что не поместится даже короткий вопрос, и лечится это только
         * закрытием разговора. Длину настоящего вопроса меряет
         * [maxContentChars], и она эту величину НЕ прибавляет к себе —
         * заменяет.
         */
        const val MIN_QUESTION_TOKENS = 200

        /**
         * Черта: сколько знаков считаем за один токен, когда решаем,
         * влезет ли текст.
         *
         * ЭТО ОБЪЯВЛЕННАЯ ГРАНИЦА, А НЕ ЗАМЕР. Переводить знаки в токены мы
         * не умеем и не беремся: движок отдаёт настоящее число только по
         * итогам прогона, а посчитать текст заранее его API не позволяет —
         * токенизация наружу не выведена. Замер на реальном тексте дал
         * около двух знаков на токен; здесь взято полтора, то есть с
         * запасом в четверть, и запас этот назначен, а не измерен.
         *
         * ПОЧЕМУ НЕ ОСТОРОЖНЕЕ. Один знак на токен дал бы запас вдвое, но
         * отнял бы длинные вставки на любой непустой ленте. Цена промаха в
         * обе стороны сегодня одинаковая и громкая: слишком тесная черта —
         * отказ словами и укороченный вопрос, слишком свободная — один
         * потерянный ход и сообщение, называющее причину. Тихой порчи нет
         * ни в одну сторону, значит покупать запас вдвое нечем.
         *
         * ЧЕГО ЧЕРТА НЕ УМЕЕТ. Она неточна намеренно и иногда отклонит
         * текст, который влез бы. Это цена, а не недоделка. На знаках, что
         * дробятся мельче обычного — код, редкие знаки, смесь языков, — она
         * может, наоборот, недосчитать; тогда ход пропадёт, и человек
         * увидит сообщение о нулевом ответе.
         *
         * ИЗМЕРЯТЬ ОТНОШЕНИЕ НА ХОДУ МЫ НЕ СТАЛИ, хотя это возможно: движок
         * отдаёт размер запроса каждый ход, длина ленты в знаках известна,
         * деление дало бы отношение для этой модели и этого языка. Отклонено
         * сознательно — оба промаха уже видны человеку на экране, и механизм,
         * который не делает видимым ни одного нового промаха, лишний.
         * Записано здесь, чтобы предложение не всплыло снова как новое.
         */
        const val CHARS_PER_TOKEN_FLOOR = 1.5
    }
