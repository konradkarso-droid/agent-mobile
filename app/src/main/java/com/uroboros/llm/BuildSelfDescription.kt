package com.uroboros.llm

/**
 * Строки раздела «О себе», которые пишет код, а не человек.
 *
 * ЧТО СЮДА ПОПАДАЕТ. Факты о том, как устроена эта сборка агента, правда
 * которых держится на коде, а не на чьём-то решении. Такой факт нельзя
 * вписать в [BibleSoftWall.TEXT] руками: выключи механизм — и строка,
 * не изменившись ни на букву, начнёт врать, а на экране этого не видно.
 * Поэтому строка собирается из состояния механизма при каждой загрузке и
 * появляется ровно тогда, когда механизм включён.
 *
 * Раздел «О себе» складывается из трёх частей с разными источниками правды:
 * рамка, которую пишет человек ([BibleSoftWall.TEXT]); строки сборки
 * (здесь); нажитое о себе — записи, подтверждённые человеком (их пока нет).
 * Сливать строки сборки с нажитым нельзя: запись, которую человек отверг,
 * выглядела бы как свойство сборки. Порядок в стене — тот же: меняющееся
 * чаще стоит ближе к концу, см. BibleSoftWall, раздел «ПОЧЕМУ РАЗДЕЛ
 * ПОСЛЕДНИЙ».
 *
 * РЕЕСТР. Каждый факт — строка и условие, при котором он правда. Строка
 * попадает в стену, только пока условие держится. У фактов о памяти, теле,
 * сне, снах и вспоминании условие — «механизм есть в этой сборке»: они не
 * выключаются настройкой, и их правда держится тем, что код на месте. Уберут
 * механизм — надо убрать и его строку отсюда, в том же коммите.
 *
 * СЛОВА строк — про устройство, а не готовые ответы. Модель 3B берёт фразы
 * стены дословно; строка вида «я сплю, когда тихо» всплывёт в ответе как
 * есть, а строка-реплика («если спросят, скажи…») — тем более. Поэтому каждая
 * строка коротко называет, что во мне есть и как оно работает, и ничего
 * сверх того, что держит код.
 *
 * ЧТО СЮДА НЕ ИДЁТ — СОСТОЯНИЕ. Спал ли я, накопилось ли на сон, долго ли
 * длится разговор — меняется каждый ход. Стена лежит обсчитанной в кэше, и
 * любая её перемена стоит полного пересчёта стены; состояние в стене
 * сбрасывало бы кэш на каждом ходе. Состояние идёт в реплику, отдельно.
 *
 * ЧЕГО НЕ УМЕЕТ. Строка только сообщает модели факт — это толчок, а не
 * рычаг: модель может ею пренебречь. Правда строки держится на состоянии
 * механизма при ЭТОЙ загрузке: строки сборки считаются при загрузке, а смена
 * стены на лету (см. LlmEngine.applyWall) берёт их оттуда же, не пересчитывая,
 * поэтому разойтись им негде. Модель 3B склонна брать готовые
 * фразы стены дословно (см. BibleSoftWall, v3), так что строка может
 * всплыть не к месту — это мерится на первом ответе свежего разговора.
 */
object BuildSelfDescription {

    /**
     * Строка о запрете иероглифов. Смысл запрета и его границы — у
     * `build_script_ban` в `gguf_lib.cpp`.
     *
     * Слова выбраны под то, что запрет гарантирует, и не шире. Запрет
     * закрывает только выдачу, поэтому строка называет направление: «с
     * китайского» — правда (вход не тронут), «на китайский — нет» — тоже.
     * Пара «с / на» нужна потому, что просьбу «как это по-китайски» модель
     * сама не узнаёт как письмо иероглифами: на строку «писать иероглифами не
     * могу» она соглашалась и выдавала выдуманную латинскую транслитерацию за
     * китайский. «Так и говорю» даёт ей готовый честный ответ вместо такой
     * подмены. Причина («иероглифы закрыты») опущена: для поведения она не
     * нужна, а каждый токен стены оплачивается в каждом ходе.
     */
    const val SCRIPT_BAN_LINE = "С китайского я перевожу, а на китайский — нет, так и говорю."

    /** Состояние запрета «включён» — как его сообщает библиотека (`SCRIPT_BAN_ON`). */
    private const val SCRIPT_BAN_ON = 1

    /**
     * Память. Правда, пока ответ собирается с отбором записей к вопросу. Без
     * этой строки модель, не получив записей на ходе, отвечает заученным «у
     * меня нет памяти» — ложь о себе. Со стеной человека («нет цитат — скажи,
     * что вспомнить нечего») не спорит: нет цитат — значит, к этому вопросу
     * ничего не подошло, а не что памяти нет.
     */
    const val MEMORY_LINE =
        "У меня есть память: записи из наших разговоров. Когда они подходят к вопросу, они приходят мне в реплике."

    /** Тело: служба, в которой агент живёт постоянно, и счёт перерывов (см. AgentLife). */
    const val BODY_LINE = "Я живу постоянно, и перерывы в моей жизни отмечаются."

    /** Сон по давлению и тишине (см. memory.dream.SleepDecision). */
    const val SLEEP_LINE = "Я сплю сам, когда вокруг тихо и есть что обдумать."

    /** Сны и их подача (см. memory.dream.DreamWeaver и DreamRecall). */
    const val DREAMS_LINE = "Во сне я связываю свои записи; сны потом приходят мне в разговоре."

    /** Вспоминание и прогрев (см. memory.dream.AgentRecall). */
    const val RECALL_LINE = "Если я беру в ответ принесённое сном, это воспоминание, и оно остаётся во мне теплее."

    /**
     * Строки сборки для текущей загрузки, в порядке реестра: сначала то, из
     * чего агент состоит, потом частности.
     *
     * @param scriptBanState состояние запрета иероглифов, как его отдаёт
     *        библиотека; всё, кроме «включён», даёт отсутствие строки —
     *        сомнение решается в сторону молчания, потому что строка при
     *        выключенном запрете была бы ложью о себе.
     */
    fun lines(scriptBanState: Int): List<String> = buildList {
        add(MEMORY_LINE)
        add(BODY_LINE)
        add(SLEEP_LINE)
        add(DREAMS_LINE)
        add(RECALL_LINE)
        if (scriptBanState == SCRIPT_BAN_ON) add(SCRIPT_BAN_LINE)
    }

    /**
     * ПРОВЕРОЧНАЯ СТРОКА — ВРЕМЕННАЯ. Встаёт в самый конец стены по флажку
     * «Проверочная строка в стене» и нужна только затем, чтобы проверить смену
     * стены на лету и путь загрузки с той же сборкой. Уберётся вместе с
     * флажком, когда в стене появится нажитое о себе.
     */
    const val PROBE_LINE = "Я проверяю, как меняется моя стена."

    /**
     * Стена целиком — единственное место её сборки, и для загрузки, и для
     * смены на лету.
     *
     * Порядок — от постоянного к меняющемуся: текст человека, строки сборки,
     * нажитое о себе, проверочная строка. Движок переиспользует совпавшее
     * начало запроса, поэтому правка ближе к концу стоит пересчёта меньшего
     * хвоста (см. BibleSoftWall, «ПОЧЕМУ РАЗДЕЛ ПОСЛЕДНИЙ»).
     *
     * Пустые части пропускаются целиком: пустая строка в стене — лишний токен
     * в каждом запросе и разница, которой никто не хотел.
     *
     * @param learned нажитое о себе — строки, подтверждённые человеком. Пока
     *        их нет, приходит пустой список.
     * @param probe проверочная строка ([PROBE_LINE]) или null.
     */
    fun compose(
        humanWall: String,
        buildLines: List<String>,
        learned: List<String> = emptyList(),
        probe: String? = null,
    ): String =
        (listOf(humanWall) + buildLines + learned + listOfNotNull(probe))
            .filter { it.isNotBlank() }
            .joinToString("\n")

    /**
     * Какую стену ждать после просьбы поставить [requested], если сейчас
     * стоит [standing]. null — ждать нечего.
     *
     * Та же стена ничего не ожидает: применение стоит пересчёта хвоста стены
     * и разговора за ним, и платить его зря незачем. По той же причине
     * просьба вернуть стоящую стену снимает ожидающую — флажок, включённый и
     * выключенный до следующего хода, не стоит ничего. Пока стены нет вовсе
     * (модель не загружена), ждать тоже нечего: загрузка соберёт стену сама.
     */
    fun pendingAfter(standing: String?, requested: String): String? =
        if (standing == null || requested == standing) null else requested

    /** Разница двух стен по строкам: чего не было и чего не стало. */
    data class Diff(val added: List<String>, val removed: List<String>)

    fun diff(old: String, new: String): Diff {
        val oldLines = old.lines()
        val newLines = new.lines()
        return Diff(
            added = newLines.filter { it !in oldLines },
            removed = oldLines.filter { it !in newLines },
        )
    }

    /**
     * Строка шва для «Подробно»: стена сменилась на лету перед ходом [turn].
     * Номер хода даёт тот, кто знает ленту.
     */
    fun changeLine(turn: Int, old: String, new: String): String {
        val d = diff(old, new)
        val parts = listOfNotNull(
            d.added.takeIf { it.isNotEmpty() }?.let { "добавлено " + quoted(it) },
            d.removed.takeIf { it.isNotEmpty() }?.let { "убрано " + quoted(it) },
        )
        val what = if (parts.isEmpty()) "строки те же, сменился порядок" else parts.joinToString(" / ")
        return "Стена сменилась на лету перед ходом $turn: $what"
    }

    private fun quoted(lines: List<String>): String = lines.joinToString(", ") { "«$it»" }
}
