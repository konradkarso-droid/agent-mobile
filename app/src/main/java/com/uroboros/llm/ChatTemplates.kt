package com.uroboros.llm

/**
 * Свой шаблон разговора вместо шаблона из файла модели — для моделей, чей
 * шаблон теряет то, что подаёт код.
 *
 * FALCON-H1. Шаблон в файле модели выводит первое системное сообщение (стену)
 * и выбрасывает все остальные системные. Код подаёт системными посреди ленты
 * строки о себе и о ночи прошлых ходов (ConversationJournal.messagesFor) и
 * просьбу третьей ступени лестницы (AnswerLadder) — с шаблоном модели они до
 * неё не доходят. Свой шаблон выводит каждое сообщение в той же разметке, что
 * шаблон модели (`<|im_start|>роль`, перевод строки, текст, `<|im_end|>`,
 * перевод строки), с тем же началом (`bos_token`) и тем же приглашением к
 * ответу. Поэтому запрос без системных посреди ленты — и стена с ним — выходит
 * знак в знак как у шаблона модели, и снимок стены на диске остаётся годен.
 * Переводы строк внутри кавычек — настоящие, как в шаблоне модели: так их
 * разбирает и разбор шаблонов этого движка.
 *
 * Ветки инструментов шаблона модели здесь нет: инструментов движку код не
 * передаёт, описание приборов стоит в стене текстом (Glance.WALL_BLOCK).
 *
 * Шаблон ставит движку LlmEngine после каждой загрузки, а для прочих моделей
 * снимает: свой шаблон в движке переживает загрузку другой модели.
 *
 * ЧЕГО НЕ УМЕЕТ:
 *  - модель узнаётся по архитектуре из файла (`general.architecture`), а не по
 *    самому шаблону: модель той же архитектуры с другой разметкой получила бы
 *    чужую. Сверка TemplateCheck этого не увидит — сообщения дойдут, — видно
 *    только по ответам;
 *  - Falcon-H1 не учена на системных сообщениях посреди разговора: как она их
 *    читает, мерено не было;
 *  - прочие модели идут со своим шаблоном; теряет ли он что-нибудь,
 *    показывает TemplateCheck.
 *
 * Чистый объект.
 */
object ChatTemplates {

    /** Архитектура Falcon-H1 в файле модели (`general.architecture`). */
    const val FALCON_H1 = "falcon-h1"

    /** Каждое сообщение, системные посреди ленты тоже, в разметке шаблона Falcon-H1. */
    const val ALL_MESSAGES = "{{bos_token}}{% for message in messages %}" +
        "{{'<|im_start|>' + message['role'] + '\n' + message['content'] + '<|im_end|>' + '\n'}}" +
        "{% endfor %}{% if add_generation_prompt %}{{ '<|im_start|>assistant\n' }}{% endif %}"

    /** Свой шаблон для модели архитектуры [architecture]; null — шаблон из файла модели. */
    fun forArchitecture(architecture: String?): String? = if (architecture == FALCON_H1) ALL_MESSAGES else null

    /** Чей шаблон собирает запрос, словами для прибора (TemplateCheck.line). */
    fun sourceWords(architecture: String?): String =
        if (forArchitecture(architecture) != null) "свой, $architecture" else "из файла модели"
}
