package com.uroboros.llm

import android.content.Context
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.sync.Mutex
import kotlinx.coroutines.sync.withLock
import kotlinx.coroutines.withContext
import org.json.JSONArray
import org.json.JSONObject

/**
 * Сохранение и подъём ленты разговора.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ КЛАСС. [ConversationJournal] — чистый Kotlin, без единого
 * андроидного обращения: так он проверяется юнит-тестом и не тянет за собой
 * ни базу, ни `Context`. Всё, что знает про Android, собрано здесь. Лента об
 * этом классе не знает; связывает их тот, кто держит оба.
 *
 * ГДЕ ГРАНИЦА ОТВЕТСТВЕННОСТИ. Здесь решается, ЧТО лежит на диске и МОЖНО
 * ЛИ этому верить. Здесь же не решается, что делать с отказом: [load]
 * возвращает исход, а показывает его человеку и выбирает поведение
 * вызывающий.
 *
 * ПОТОК. Функции DAO блокирующие (причина в [JournalTurnDao]), поэтому
 * каждая функция здесь уходит в [Dispatchers.IO] сама. Вызывающему думать
 * о потоке не надо — иначе об этом пришлось бы помнить в каждом месте
 * вызова, а забытое место падало бы только на живом устройстве.
 *
 * ОТКАЗЫ НЕ БРОСАЮТСЯ НАРУЖУ. Лента — часть необязательная: без неё
 * приложение работает, просто разговор не переживает выгрузку. Поэтому
 * любая беда с базой превращается в [LoadResult.Refused] со словами, а не
 * в падение. Молчать о пропаже при этом нельзя — на то и слова.
 *
 * ОПЕРАЦИИ ВЫСТРОЕНЫ В ОДИН ПОРЯДОК. Все обращения к базе проходят через
 * [gate], и каждое берёт его ПЕРВЫМ действием — до [Dispatchers.IO] и до
 * любой другой приостановки. Порядок нужен потому, что дописывание хода и
 * стирание ленты приходят сюда из независимых корутин: без общей очереди
 * запоздавшее дописывание воскрешает уже закрытый разговор, а запоздавшее
 * стирание уносит ход нового. Оба исхода тихие — на экране их не видно.
 *
 * Захват именно первым действием существен. Взятый после перехода в поток
 * ввода-вывода, он упорядочил бы не вызовы, а их случайное прибытие в пул
 * потоков: очередь была бы честной и бессмысленной.
 */
class JournalStore(context: Context) {

    /**
     * Сама база, а не только DAO: [archive] переносит ходы и очищает
     * активную таблицу одной транзакцией, а транзакцию открывает база.
     */
    private val db = JournalDatabase.getInstance(context)

    private val dao = db.journalTurnDao()

    private val archiveDao = db.journalArchiveDao()

    /**
     * Очередь обращений к базе ленты.
     *
     * Честная (FIFO): ожидающие получают доступ в порядке, в котором его
     * попросили. Поэтому порядок операций задаётся тем, кто раньше вошёл
     * сюда, — и только этим.
     *
     * ЧЕГО ЭТО НЕ ДАЁТ. Порядок входа сюда совпадает с порядком, в котором
     * вызывающий начал операции, лишь пока между началом и вызовом нет
     * приостановок. Вызывающий, успевший чего-то подождать перед обращением
     * к ленте, встаёт в очередь позже — и получает не тот порядок, на
     * который рассчитывал. Здесь этого не видно и проверить это отсюда
     * нечем.
     *
     * СОСТАВНЫМ ОПЕРАЦИЯМ — ОДИН ЗАХВАТ. Действие вроде «перенести ленту в
     * архив и очистить активную» пишется ОДНОЙ открытой функцией, которая
     * берёт [gate] один раз и дальше обращается к DAO напрямую. Собирать
     * такое действие вызовом соседних функций этого класса нельзя: захват
     * не повторный, и второй заход по тому же пути не упадёт и не вернёт
     * ошибку, а остановится навсегда — в том самом месте, которое отвечает
     * за сохранность разговора.
     */
    private val gate = Mutex()

    /**
     * Исход подъёма. Три состояния, а не два: «поднято», «сохранённого нет»
     * и «отказано, вот почему» — иначе пустой экран после запуска
     * неотличим от сломанного сохранения.
     */
    sealed interface LoadResult {

        /**
         * Лента поднята целиком.
         *
         * @property promptTokens размер последнего ушедшего запроса в
         *   токенах — та же величина, что держит живая лента. Ноль
         *   означает «не измерено»: ход сохранён до того, как движок
         *   отчитался, либо лежит с версии, где столбца не было.
         *   Показывать такой ноль как измеренную величину нельзя.
         */
        data class Restored(
            val turns: List<ConversationJournal.Turn>,
            val promptTokens: Int,
        ) : LoadResult

        /** Сохранённого разговора нет. Это не поломка. */
        object Empty : LoadResult

        /**
         * Подъём отменён. [reason] — готовая фраза для показа человеку:
         * система обязана давать признак, читаемый без знания
         * программирования.
         */
        data class Refused(val reason: String) : LoadResult
    }

    /**
     * Исход отрезания. Три состояния, как и у подъёма: «отрезано столько-то»,
     * «отрезать было нечего» и «отказано, вот почему».
     *
     * Средний случай отделён от первого намеренно. Ноль стёртых строк
     * означает, что на диске этого хода уже нет, то есть лента в памяти и
     * лента на диске разошлись. Слить его с успехом значило бы, что
     * расхождение двух хранилищ выглядит на экране как обычная работа.
     */
    sealed interface DropResult {

        /** Отрезано [count] ходов, все с конца. */
        data class Dropped(val count: Int) : DropResult

        /** Стирать было нечего: на диске такого хода нет. */
        object Empty : DropResult

        /** Отрезание отменено. [reason] — готовая фраза для человека. */
        data class Refused(val reason: String) : DropResult
    }

    /**
     * Исход закрытия разговора. Три состояния по тому же правилу, что у
     * подъёма и отрезания.
     */
    sealed interface ArchiveResult {

        /**
         * Разговор закрыт: [count] ходов перенесены в архив под номером
         * [archiveIndex], активная лента пуста.
         */
        data class Archived(val count: Int, val archiveIndex: Int) : ArchiveResult

        /**
         * Закрывать было нечего: активная лента и так пуста.
         *
         * Отделено от успеха намеренно. Номер архивации при этом НЕ
         * тратится: пустая архивация оставила бы в нумерации промежуток,
         * за которым не стоит ни одного разговора, и будущий читатель
         * архива счёл бы его потерей.
         */
        object Empty : ArchiveResult

        /**
         * Закрытие отменено. [reason] — готовая фраза для человека, и она
         * обязана сказать главное: разговор остался на месте.
         */
        data class Refused(val reason: String) : ArchiveResult
    }

    /**
     * Сколько ходов лежит на диске: [active] в активной ленте, [archived] в
     * архиве закрытых разговоров.
     *
     * Два числа, а не сумма: сумма скрыла бы, что активная лента пуста, —
     * то есть ровно то, что человеку и надо видеть после закрытия.
     */
    data class Counts(val active: Int, val archived: Int)

    /**
     * Поднимает сохранённую ленту, если ей можно верить.
     *
     * @param currentFingerprint отпечаток текущей загрузки
     *        ([LlmEngine.loadFingerprint]); `null`, пока модель не
     *        загружена или папка кэша не создана.
     *
     * ПОДНИМАЕТСЯ ТОЛЬКО ЦЕЛИКОМ. Любое из проверяемых условий отменяет
     * подъём полностью, без попытки взять уцелевшую часть. Причина не в
     * строгости: половина ленты обещает движку совпадение с обсчитанным
     * началом, которого у неё нет, и расплата за это — молчаливый пересчёт
     * всего разговора, о котором ничто не сообщит.
     *
     * ПРИ ОТКАЗЕ ТАБЛИЦА НЕ СТИРАЕТСЯ. Часть причин временные: модель ещё
     * не загрузилась, файл не прочитался. Стирание же необратимо, и им
     * нельзя отвечать на состояние, которое может смениться само. Чистит
     * ленту человек, закрывая разговор.
     */
    suspend fun load(currentFingerprint: String?): LoadResult = gate.withLock {
        withContext(Dispatchers.IO) {
            val rows = runCatching { dao.all() }.getOrElse {
                return@withContext LoadResult.Refused(
                    "Сохранённый разговор не читается — начинаем с чистой ленты."
                )
            }

            if (rows.isEmpty()) return@withContext LoadResult.Empty

            val stored = rows.first().fingerprint

            if (rows.any { it.fingerprint != stored }) {
                return@withContext LoadResult.Refused(
                    "Сохранённый разговор собран из разных запусков — поднимать его нельзя."
                )
            }

            if (stored.isBlank()) {
                return@withContext LoadResult.Refused(
                    "Сохранённый разговор записан без привязки к модели — поднимать его нельзя."
                )
            }

            if (currentFingerprint == null) {
                return@withContext LoadResult.Refused(
                    "Модель ещё не загружена — сохранённый разговор пока не поднять."
                )
            }

            if (stored != currentFingerprint) {
                return@withContext LoadResult.Refused(
                    "Сохранённый разговор записан при другой модели или других параметрах."
                )
            }

            // Дыра в нумерации означает, что часть ходов не дописалась. Такая
            // лента уйдёт в движок с пропуском посередине — то есть без
            // совпадения с обсчитанным началом, и молча.
            if (rows.mapIndexed { i, row -> row.turnIndex == i }.any { !it }) {
                return@withContext LoadResult.Refused(
                    "В сохранённом разговоре не хватает ходов — поднимать его нельзя."
                )
            }

            val turns = ArrayList<ConversationJournal.Turn>(rows.size)
            for (row in rows) {
                val records = parseRecords(row.recordsJson)
                    ?: return@withContext LoadResult.Refused(
                        "Сохранённый разговор повреждён — поднимать его нельзя."
                    )
                turns += ConversationJournal.Turn(
                    userContent = row.userContent,
                    agentContent = row.agentContent,
                    question = row.question,
                    records = records,
                )
            }

            // Число берётся у ПОСЛЕДНЕГО хода: это размер последнего ушедшего
            // запроса, то есть ровно то, что означает счётчик живой ленты.
            // Числа промежуточных ходов лежат в строках и пригодятся при
            // разборе роста ленты, но счётчику отвечает только последнее.
            LoadResult.Restored(turns, rows.last().promptTokens)
        }
    }

    /**
     * Дописывает один ход.
     *
     * @param promptTokens размер запроса на этом ходе по отчёту движка.
     *        Вызывающий обязан снять его ДО закрытия хода: счётчик ленты
     *        обновляется отдельным вызовом, и если сделать это после,
     *        в строку уйдёт число предыдущего хода — расхождение на один
     *        ход, которое ничем себя не выдаст.
     * @param fingerprint отпечаток текущей загрузки; `null` кладётся пустой
     *        строкой. Ход при этом сохраняется — он нужен для показа
     *        человеку и для будущего замера, — но лента с пустым отпечатком
     *        подъёму не подлежит: привязать её не к чему. Сохранение и
     *        подъём здесь намеренно расходятся в условиях: пропустить ход
     *        при записи невосстановимо, а лишний отказ при подъёме стоит
     *        одного пересчёта.
     *
     * @return `false`, если запись не удалась. Вызывающий обязан сказать об
     *         этом человеку: дальше лента на диске будет неполной, а значит
     *         при следующем запуске подъём откажет по дыре в нумерации.
     */
    suspend fun append(
        index: Int,
        turn: ConversationJournal.Turn,
        promptTokens: Int,
        fingerprint: String?,
    ): Boolean = gate.withLock {
        withContext(Dispatchers.IO) {
            runCatching {
                dao.insert(
                    JournalTurn(
                        turnIndex = index,
                        userContent = turn.userContent,
                        agentContent = turn.agentContent,
                        question = turn.question,
                        recordsJson = renderRecords(turn.records),
                        promptTokens = promptTokens,
                        fingerprint = fingerprint ?: "",
                    )
                )
            }.isSuccess
        }
    }

    /**
     * Отрезает хвост сохранённой ленты, начиная с хода [fromIndex].
     *
     * ТОЛЬКО ХВОСТ. Начало ленты остаётся дословно прежним, поэтому
     * совпадение с обсчитанным началом сохраняется, а нумерация — сплошной
     * от нуля. Правки середины здесь нет и быть не может: дыра в нумерации
     * отменяет следующий подъём целиком.
     *
     * ОТРИЦАТЕЛЬНЫЙ НОМЕР ОТКЛОНЯЕТСЯ. Запрос стирает всё, у чего номер не
     * меньше указанного, значит `-1` вычистил бы ленту целиком — и без
     * ведома человека, который просил убрать один ход. Стирания ленты в
     * этом классе больше нет ни одного: закрытие разговора её переносит, а
     * не уничтожает, — и открывать окольную дорогу к утраченной операции
     * через промах в аргументе нельзя тем более. Проверка стоит здесь, а не
     * у вызывающего: вызывающих со временем становится несколько, и забытое
     * место молчит.
     *
     * ПОРЯДОК ОТНОСИТЕЛЬНО ПАМЯТИ ПРОЦЕССА. Сначала диск, потом лента в
     * памяти. При отказе диска лента остаётся нетронутой, и оба хранилища
     * по-прежнему говорят одно; обратный порядок при том же отказе оставил
     * бы на диске ход, которого в памяти уже нет, — и разошлись бы они
     * молча, до следующего запуска.
     *
     * ОТРЕЗАННЫЙ ХОД В АРХИВ НЕ ИДЁТ. Архив собирает разговоры, закрытые
     * целиком; отрезание же — правка ленты, которая продолжается, и ход
     * убирают из неё именно затем, чтобы его не было. Свести оба действия в
     * одно хранилище значило бы сложить в одну таблицу материал с разным
     * смыслом. Плата названа прямо и не изменилась: отрезанный ход исчезает
     * бесследно.
     *
     * @return сколько ходов стёрто, либо причина отказа словами.
     */
    suspend fun dropFrom(fromIndex: Int): DropResult = gate.withLock {
        withContext(Dispatchers.IO) {
            if (fromIndex < 0) {
                return@withContext DropResult.Refused(
                    "Отрезать нечего: указан номер хода до начала ленты."
                )
            }
            val removed = runCatching { dao.deleteFrom(fromIndex) }.getOrElse {
                return@withContext DropResult.Refused(
                    "Сохранённый разговор не правится — ход остался на диске."
                )
            }
            if (removed > 0) DropResult.Dropped(removed) else DropResult.Empty
        }
    }

    /**
     * Закрывает разговор: переносит ленту в архив и очищает активную
     * таблицу.
     *
     * ЭТО НЕ УДАЛЕНИЕ. Ходы остаются на устройстве, в
     * `journal_archive_turns`, под собственным номером архивации. Отсюда и
     * разница в осторожности: удаление необратимо и требовало подтверждения
     * человека, перенос не разрушает ничего.
     *
     * ЧЕГО ЭТО НЕ ДАЁТ. Материал остаётся ТОЛЬКО на этом устройстве:
     * потерянный телефон уносит архив вместе с лентой. Копия наружу —
     * отдельное ручное действие человека, частью закрытия она не является.
     *
     * ОДНА ТРАНЗАКЦИЯ, ЧЕТЫРЕ ДЕЙСТВИЯ. Прочитать ходы, взять номер
     * архивации, вставить, очистить. Неделимость здесь не про порядок, а
     * про то, что промежуточных состояний быть не должно: очистка без
     * вставки — та самая безвозвратная потеря, вставка без очистки — один
     * разговор в двух местах сразу. Отказ на любом шаге откатывает всё, и
     * активная лента остаётся ровно такой, какой была.
     *
     * Номер архивации берётся ВНУТРИ транзакции, а не до неё: между
     * вычислением и вставкой иначе может влезть другое закрытие, и оба
     * разговора получили бы один номер. Очередь [gate] это и так
     * предотвращает, но она защищает только от вызовов через этот класс, а
     * транзакция — от всего остального.
     *
     * ПОЧЕМУ ЭТО ОДНА ФУНКЦИЯ, А НЕ ВЫЗОВ СОСЕДНИХ. [gate] не повторный,
     * поэтому собранное из нескольких открытых функций этого класса
     * действие остановилось бы навсегда на втором захвате — не упало бы и
     * не вернуло ошибку, а именно замерло, в том самом месте, которое
     * отвечает за сохранность разговора. Причина подробнее в KDoc самого
     * [gate].
     *
     * ПОРЯДОК ОТНОСИТЕЛЬНО ПАМЯТИ ПРОЦЕССА тот же, что у [dropFrom]:
     * сначала диск, потом лента в памяти. При отказе диска оба хранилища
     * по-прежнему говорят одно.
     *
     * @return сколько ходов закрыто и каким номером, либо «закрывать было
     *         нечего», либо причина отказа словами.
     */
    suspend fun archive(): ArchiveResult = gate.withLock {
        withContext(Dispatchers.IO) {
            runCatching {
                db.runInTransaction<ArchiveResult> {
                    val rows = dao.all()
                    if (rows.isEmpty()) return@runInTransaction ArchiveResult.Empty

                    val archiveIndex = archiveDao.nextArchiveIndex()
                    val archivedAt = System.currentTimeMillis()

                    // Строки переносятся как есть, без разбора recordsJson:
                    // разбор при переносе дал бы порче одного хода власть
                    // отменить закрытие всего разговора.
                    archiveDao.insertAll(
                        rows.map { row ->
                            JournalArchiveTurn(
                                archiveIndex = archiveIndex,
                                turnIndex = row.turnIndex,
                                userContent = row.userContent,
                                agentContent = row.agentContent,
                                question = row.question,
                                recordsJson = row.recordsJson,
                                promptTokens = row.promptTokens,
                                fingerprint = row.fingerprint,
                                archivedAt = archivedAt,
                            )
                        }
                    )
                    dao.clearAll()

                    ArchiveResult.Archived(rows.size, archiveIndex)
                }
            }.getOrElse {
                ArchiveResult.Refused(
                    "Разговор закрыть не удалось — на диске всё осталось как было."
                )
            }
        }
    }

    /**
     * Оба числа диска разом: активная лента и архив.
     *
     * ОДИН ЗАХВАТ НА ДВА ЧИСЛА. Прочитай их порознь — между чтениями могло
     * бы пролезть закрытие разговора, и на экран попала бы пара, которой на
     * диске не было ни в один момент: ходов 2, в архиве 0. Расхождение
     * редкое и совершенно невидимое, а очередь [gate] заведена ровно затем,
     * чтобы такие исходы не были невидимыми.
     *
     * ЧТЕНИЕ СТОИТ В ТОЙ ЖЕ ОЧЕРЕДИ, ЧТО И ЗАПИСИ, хотя ничего не меняет:
     * иначе счётчик успевал бы обогнать только что начатую запись и показать
     * число, которое на диске не побывало. Ждать при этом почти нечего —
     * операции здесь занимают миллисекунды.
     *
     * ОТКАЗ ЧТЕНИЯ — `null`, А НЕ НУЛИ. Погасить его нулями было бы дёшево,
     * но показать «в архиве 0» сразу после закрытия разговора значило бы
     * объявить потерю обычной работой. Пусть человек увидит «не читается».
     */
    suspend fun counts(): Counts? = gate.withLock {
        withContext(Dispatchers.IO) {
            runCatching { Counts(dao.count(), archiveDao.count()) }.getOrNull()
        }
    }

    /**
     * Записи хода в JSON. Сборка — на `JSONArray`, а не склейкой строк:
     * экранирование кавычек и переносов тогда на библиотеке, а не на нас.
     * Тем же приёмом собирается лента для движка.
     */
    private fun renderRecords(records: List<ConversationJournal.RecordUse>): String {
        val array = JSONArray()
        for (record in records) {
            array.put(
                JSONObject()
                    .put(KEY_TEXT, record.text)
                    .put(KEY_FIRST_SEEN, record.firstSeenTurn)
            )
        }
        return array.toString()
    }

    /**
     * Разбор записей хода. `null` означает порчу — и отменяет подъём всей
     * ленты, а не одного хода. Ход, потерявший свои записи, выглядел бы
     * безопорным, и верный ответ на нём прочитался бы как выдумка.
     */
    private fun parseRecords(json: String): List<ConversationJournal.RecordUse>? =
        runCatching {
            val array = JSONArray(json)
            val out = ArrayList<ConversationJournal.RecordUse>(array.length())
            for (i in 0 until array.length()) {
                val item = array.getJSONObject(i)
                out += ConversationJournal.RecordUse(
                    text = item.getString(KEY_TEXT),
                    firstSeenTurn = item.getInt(KEY_FIRST_SEEN),
                )
            }
            out
        }.getOrNull()

    private companion object {
        const val KEY_TEXT = "text"
        const val KEY_FIRST_SEEN = "firstSeenTurn"
    }
}
