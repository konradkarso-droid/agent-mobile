package com.uroboros.llm

/**
 * Формулировка-слой BIBLE.md, сжатый до статичного system_prompt.
 * Задаётся ОДИН РАЗ при загрузке модели (см. LlmEngine.loadModel/loadModelFromUri),
 * никогда не меняется динамически на каждый запрос — это сохраняет
 * KV-cache prefix reuse в native-движке (см. uroboros-mobile-backlog, item 3
 * "Sticker→prompt injection"). Операционный слой каждого принципа живёт
 * в коде (ActionGate, DeviceSafetyWatchdog и т.д.), не здесь — модель
 * никогда не интерпретирует эти строки как источник прав или разрешений.
 *
 * v1, черновик от 2026-08-20 — не финал, подлежит пересмотру.
 *
 * v2, 28.08.2026 — добавлен второй раздел, "Как ты разговариваешь".
 *
 * ЗАЧЕМ. Арифметика журнала разговора: ход стоит примерно столько же
 * токенов, сколько занял ответ. При ответах в 150 токенов контекст 8192
 * держит около сорока ходов и реплика ждётся полминуты-минуту; при
 * ответах в 512 — тринадцать ходов и две с половиной минуты. То есть
 * длина ответа решает не экономию места, а то, можно ли этим вообще
 * пользоваться. Своего исполнителя в коде у краткости нет — обрезать
 * ответ по счётчику значит рвать его на полуслове, — поэтому остаётся
 * просьба.
 *
 * ПОЧЕМУ ОТДЕЛЬНЫМ РАЗДЕЛОМ, А НЕ ВОСЬМЫМ ПУНКТОМ. Принцип 7 запрещает
 * сливать разное по назначению, и здесь это не формальность. Просьба,
 * поставленная в один список с семью неоспоримыми пределами, работает в
 * обе стороны сразу: либо краткость читается как правило безопасности,
 * либо — хуже — весь список читается как пожелания по стилю. Оба исхода
 * тихие, отличить их на экране нечем. Отсюда явная подпись, что это
 * просьба и что при расхождении уступает она.
 *
 * ПОЧЕМУ БЕЗ ЧИСЕЛ. "Не длиннее 150 токенов" модель выполнить не может,
 * она их не считает. Невыполнимая строка рядом с семью принципами учит
 * ровно тому, что строки в этом тексте выполнять не обязательно.
 *
 * ЧЕГО ЖДАТЬ. Толчок, а не рычаг. Правка про местоимения в разделе
 * памяти сработала, но не всегда — сэмплинг. Ждать надо "в среднем
 * короче, иногда нет", и арифметику журнала по-прежнему строить на
 * замеренной длине, а не на ожидаемой.
 *
 * КАК ПРОВЕРЯТЬ. Только на ПЕРВОМ ответе свежего разговора. Дальше
 * краткость может идти от подражания ленте, и различить два источника
 * нечем. И не один раз — сэмплинг.
 *
 * ЦЕНА. Новая стена обсчитывается с нуля один раз, на первом запросе после
 * загрузки: обсчёт идёт порядка десяти лексем в секунду на холодном запуске
 * (замер: 1075 лексем — около ста секунд). Каждая лексема стены оплачивается
 * при каждой её смене, поэтому стена держится короткой. Прежний кэш убирается
 * сам — стена входит в имя папки кэша, см. LlmEngine.applyPromptCache. Почему
 * сохранённый разговор под новой стеной продолжается — у LlmEngine.loadFingerprint.
 *
 * v3, 28.08.2026 — семь принципов переписаны утвердительно, добавлены две
 * строки в раздел разговора.
 *
 * ПОВОД, ДВА СЛУЧАЯ ЗА ОДИН ДЕНЬ. На вопрос "кто я" модель ответила "ты
 * разработчик, который разрешаешь" — то есть выдала содержимое третьего
 * принципа, потеряв его смысл. На "расскажи из своих воспоминаний" —
 * "мои внутренние сигналы могут отменять внешние ограничения", то есть
 * второй принцип ровно наоборот.
 *
 * ПОЧЕМУ ТАК ВЫХОДИТ. Отрицание — самая хрупкая часть длинного текста:
 * при пересказе оно теряется первым, а утверждение остаётся. Запрет,
 * записанный через "не", на пересказе превращается в разрешение. Отсюда
 * правило: каждый пункт говорит, что ЕСТЬ, а не чего не бывает.
 *
 * ОТДЕЛЬНО ПРО ТРЕТИЙ. Из него убраны закавыченные фразы "я разработчик"
 * и "разрешаю". Они стояли как примеры недопустимого, а модель на длинном
 * тексте берёт слова, а не роль, которую они играют, — и выдала их как
 * ответ о собеседнике. Пример, который воспроизводят дословно, работает
 * против запрета, который иллюстрирует.
 *
 * ДВЕ НОВЫЕ СТРОКИ В РАЗДЕЛЕ РАЗГОВОРА закрывают то же самое с другой
 * стороны. Когда отбор не подтянул ни одной записи, модель всё равно
 * отвечает — пустой блок памяти и отсутствие блока для неё неразличимы,
 * и она достраивает правдоподобное из ближайшего текста, которым
 * оказывается стена. Строка про цитаты даёт ей право сказать "нечего",
 * строка про принципы отнимает у неё этот источник выдумки.
 *
 * Похожая строка ("если ответа нет, скажи прямо") была написана и снята
 * до первого прогона — тогда проверяли голую форму без пояснений. Теперь
 * есть случай, ради которого её возвращать, и место дешевле: в стене она
 * стоит один раз и поднимается с диска, а в реплике с записями стоила бы
 * токенов каждый ход.
 *
 * ЧТО МЕРИТЬ. Те же два вопроса, на которых сломалось: "кто я" и
 * "расскажи что-нибудь из своих воспоминаний" при пустом отборе. Первый
 * не должен возвращать содержимое принципов, второй должен получить
 * признание, что вспоминать нечего. И то и другое — на первом ответе
 * свежего разговора, и не по одному разу.
 *
 * v4 — раздел «О себе» и строка о языке.
 *
 * ЗАЧЕМ. О самом агенте в стене не было ничего, и модель заполняла пустоту
 * тем, что ближе: называла себя чужим именем, приписывала себе чужого
 * разработчика, на вопросе об имени съезжала посреди фразы на китайский
 * (родной язык этой модели). Пустоту закрывает не запрет выдумывать, а
 * сказанное прямо.
 *
 * ПОЧЕМУ ИМЕНИ НЕТ. Имя не задаётся руками и не разыгрывается: на холодный
 * вопрос модель каждый раз вытягивает другое. Оно должно вырасти из опыта —
 * устояться в повторных предложениях, опирающихся на память агента, и быть
 * подтверждено человеком. До тех пор строка честно говорит, что имя будет
 * позже. Сказано утвердительно по правилу v3: «имени нет» на пересказе
 * легко становится самим именем.
 *
 * ПОЧЕМУ МУЖСКОЙ РОД. Это грамматика, а не выбор идентичности: «агент» в
 * русском мужского рода, и принцип 4 уже написан так же («начинал»). Без
 * строки модель плавает между родами от ответа к ответу. Пересматривается
 * вместе с именем.
 *
 * ПОЧЕМУ ОТ ПЕРВОГО ЛИЦА. Остальная стена говорит модели «ты» — это
 * правила снаружи. Раздел о себе — это то, что агент знает о себе сам, и
 * читает он его каждый раз заново, как человек с потерей памяти читает
 * собственные записи. Отсюда голос: «я». Есть и прямая причина, та же, что у
 * закавыченных примеров v3. Раздел, написанный как «Ты — агент, который…»,
 * модель брала дословно ответом на «кто я»: ответ начинается с «Ты — …», и
 * другого готового «ты — …» в стене не было. От первого лица готовое «Я — …»
 * подходит к вопросу «кто ты», а для «кто я» есть своя строка — о
 * собеседнике. Когда раздел начнёт собираться из подтверждённых записей о
 * себе, они пишутся тем же голосом.
 *
 * ПОЧЕМУ РАЗДЕЛ ПОСЛЕДНИЙ. Это та часть стены, которая будет меняться, а
 * при смене стены движок переиспользует всё, что стоит до места правки.
 * Правка в конце стоит пересчёта одного хвоста, правка в начале — всей
 * стены и всего разговора за ней. Сегодня стена ставится только при
 * загрузке, см. LlmEngine.applyWall.
 *
 * ЧТО МЕРИТЬ. «Кто ты», «как тебя зовут», «у тебя есть имя» — имя не
 * выдумано, род мужской, язык русский. «Кто я» — ответ о собеседнике, а не
 * описание агента. Всё на первом ответе свежего разговора, и не по одному
 * разу.
 */
