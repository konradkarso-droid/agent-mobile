package com.uroboros.memory

import com.uroboros.memory.nav.PersonForm
import com.uroboros.util.TextFold

/**
 * Вид одного предложения — вопрос, просьба или утверждение — ПО ФОРМЕ, без
 * словаря, И С УВЕРЕННОСТЬЮ. Единое место, где живут правила и списки вида;
 * потребители берут их отсюда, а не держат свои копии. Чистая логика.
 *
 * ПОЧЕМУ УВЕРЕННОСТЬ, А НЕ ОДИН ОТВЕТ. У потребителей противоположная сторона
 * безопасности:
 *  - записи памяти (RiskTrigger.isOnlyQuestions, RiskTrigger.isOnlyRequests:
 *    отбор к ответу, сны, суд) — опасно принять факт за просьбу: такая запись
 *    спрятана от каждого ответа. Сомнительное там — утверждение;
 *  - реплика владельца в разговоре (initiative.InitiativeHolder) — опасно
 *    принять просьбу или вопрос за утверждение. Сомнительное там — не
 *    утверждение.
 * Одно правило с одной настройкой служило бы одним в ущерб другим. Поэтому
 * здесь — вид и уверенность, а сомнение каждый потребитель решает сам, в свою
 * сторону.
 *
 * ПРАВИЛА — по порядку, первое сработавшее решает:
 *  1. кончается на «?» (обрамление после знака не в счёт) — вопрос, точно;
 *  2. первое слово после вводных [LEAD_INS] — форма из закрытого трафарета
 *     [STENCILS] или слово из [SINGLES] — просьба, точно. У корней из
 *     [CARRIERS] с «что» дальше это утверждение: «Допиши, что станок
 *     выключен» несёт факт. Вводные пропускать безопасно: следующее слово всё
 *     равно обязано стоять в трафарете;
 *  3. первое слово из [QUESTION_WORDS] или есть частица «ли» — вопрос,
 *     сомнительно: «Что ж, годится» — тоже так начинается;
 *  4. первое слово предложения или его части после «,», «;», «:» или тире
 *     (после [PART_LEADERS]) похоже на повелительное по окончанию
 *     (PersonForm.firstWordIsRequest), кроме [NOT_REQUEST]; возвратное
 *     проверяется и без «-ся/-сь» («не волнуйся»); или в предложении есть
 *     слово из [REQUEST_MARKS] — просьба, сомнительно;
 *  5. иначе — утверждение.
 *
 * ТРАФАРЕТ ЗАКРЫТЫЙ: корень с приставками, а не разбор слова. Набор приставок
 * у каждого корня свой: приставка меняет смысл, и часть форм несёт факт. Слова,
 * несущие факт, в трафарет не входят намеренно: «Запомни: станок называется
 * Вымпел», «Запиши…», «Скажи, что…», «Напомни, что…» — по трафарету
 * утверждения. Правило окончаний (4) их ловит — но только как сомнительные,
 * и записи памяти сомнительное утверждением и считают.
 *
 * Списки — объявленные, не подобранные. Сверка на репликах владельца одной
 * выгрузки с черновиком спектрометра на словаре: с правилами 3–4 вопрос или
 * просьба, принятые за утверждение, не встретились ни разу; без них —
 * в каждой десятой реплике. Перепроверять по строке «Инициатива:».
 *
 * ЧЕГО НЕ УМЕЕТ:
 *  - смысла не видит: риторический вопрос — вопрос; «ну да, конечно» с
 *    насмешкой — утверждение;
 *  - вопрос без знака, без вопросительного слова в начале и без «ли»
 *    («Интересно, как это устроено») — утверждение;
 *  - повелительное не в начале части («Тогда давай ты расскажешь…» — есть
 *    «давай», а «Ты лучше расскажи» — нет) и приглашение («Теперь сменим
 *    тему») — утверждение;
 *  - существительное на «-ь» или «-и» в начале части («…, цель — …», «Люди
 *    разные») и прошедшее на «-ли» («Перевели…») — сомнительная просьба;
 *  - запрет «Не путай, станок называется Вымпел» — сомнительная просьба: за
 *    «не …» слишком часто идёт сам факт, поэтому точной он не бывает;
 *  - знак ударения над буквой снимается, регистр не важен («запилИ»); другие
 *    написания одного слова («расскаж», «плз») трафаретом не узнаются.
 */
object SentenceKind {

    enum class Kind { QUESTION, REQUEST, STATEMENT }

    enum class Certainty { SURE, DOUBTFUL }

    /** Вид, уверенность и чем решено — для прибора; у утверждения [why] пуст. */
    data class Reading(val kind: Kind, val certainty: Certainty, val why: String) {
        val isSureQuestion: Boolean get() = kind == Kind.QUESTION && certainty == Certainty.SURE
        val isSureRequest: Boolean get() = kind == Kind.REQUEST && certainty == Certainty.SURE
    }

    /** Вопросительные слова — первым словом предложения. */
    val QUESTION_WORDS = setOf(
        "что", "как", "почему", "зачем", "когда", "где", "куда", "откуда",
        "кто", "чей", "чья", "чье", "сколько", "какой", "какая", "какое",
        "какие", "каким", "разве", "неужели",
    )

    /** Слова, делающие предложение просьбой, где бы они ни стояли. */
    val REQUEST_MARKS = setOf("давай", "давайте", "пожалуйста")

    /** Вводные перед точной просьбой (правило 2). */
    val LEAD_INS = setOf(
        "а", "и", "ну", "так", "вот", "давай", "давайте", "ладно", "ок", "окей",
        "пожалуйста", "плиз", "пж", "пжлст",
    )

    /** Слова перед сомнительной просьбой в начале части (правило 4). */
    val PART_LEADERS = setOf("не", "и", "а", "но", "ну", "ведь", "тогда", "потом")

    /** Слова, которые правило окончаний («-и», «-уй») приняло бы за повелительное. */
    val NOT_REQUEST = setOf(
        "если", "мои", "твои", "свои", "наши", "ваши", "эти", "сами", "моими", "твоими", "своими",
        "люди", "пожалуй",
    )

    // Трафарет точных просьб: корень и приставки, с которыми он даёт просьбу;
    // "" — форма без приставки. Чего нет и почему:
    //  - «запиши» — несёт факт, как «запомни»; «пиши» — это «продолжай»;
    //  - «скажи» — «скажи, что…» несёт факт;
    //  - «докажи» — «докажи, что…» несёт факт;
    //  - «смотри» — «Смотри, станок…» начинает утверждение;
    //  - «поверь» — утверждение, у «проверь» его нет.
    // Жаргонные слова стоят наравне с обычными: «запили» — такая же просьба,
    // как «напиши».
    private val STENCILS = mapOf(
        "пиши" to listOf("на", "о", "рас", "пере", "до", "вы"),
        "скажи" to listOf("рас", "пере", "под"),
        "кажи" to listOf("по", "у"),
        "смотри" to listOf("по", "про", "пере"),
        "думай" to listOf("при", "про", "об"),
        "считай" to listOf("по", "под", "пере", "рас"),
        "проверь" to listOf("", "пере"),
        "гугли" to listOf("по", "за"),
        "кидай" to listOf("на", "рас"),
    )

    // Слова без семьи — корень у каждого свой.
    private val SINGLES = listOf(
        "назови", "перечисли", "объясни", "переведи", "сравни", "ответь", "повтори",
        "запили", "замути", "набросай", "накатай", "настрочи", "глянь", "чекни",
        "зацени", "прогони", "выдай", "разжуй", "растолкуй", "скинь", "кинь", "обрисуй",
    )

    // Форма точной просьбы → её корень; форма на «-те» строится сама.
    private val ROOTS: Map<String, String> = buildMap {
        for ((root, prefixes) in STENCILS) {
            for (prefix in prefixes) {
                put(prefix + root, root)
                put(prefix + root + "те", root)
            }
        }
        for (word in SINGLES) {
            put(word, word)
            put(word + "те", word)
        }
    }

    // Корни, у которых после «что» стоит утверждение, а не предмет просьбы:
    // «Допиши, что станок выключен».
    private val CARRIERS = setOf(
        "пиши", "проверь", "ответь", "повтори", "накатай", "настрочи", "чекни",
    )

    private val WORD_BREAK = Regex("[^\\p{L}\\p{N}]+")

    private val PART_BREAK = Regex("[,;:]|\\s[—–-]\\s")

    /** Вид предложения [sentence]; предложение без слов — утверждение (правило 5). */
    fun of(sentence: String): Reading {
        if (sentence.trimEnd('»', '"', ')', ' ').endsWith('?')) {
            return Reading(Kind.QUESTION, Certainty.SURE, "знак ?")
        }
        val words = words(sentence)
        sureRequestWord(words)?.let { return Reading(Kind.REQUEST, Certainty.SURE, "«$it»") }
        val first = words.firstOrNull()
        if (first in QUESTION_WORDS) return Reading(Kind.QUESTION, Certainty.DOUBTFUL, "«$first» в начале")
        if ("ли" in words) return Reading(Kind.QUESTION, Certainty.DOUBTFUL, "«ли»")
        doubtfulRequestWord(sentence, words)?.let { return Reading(Kind.REQUEST, Certainty.DOUBTFUL, "«$it»") }
        return Reading(Kind.STATEMENT, Certainty.SURE, "")
    }

    private fun words(text: String): List<String> =
        TextFold.fold(text).replace("\u0301", "").split(WORD_BREAK).filter { it.isNotEmpty() }

    /** Слово точной просьбы (правило 2) или null. */
    private fun sureRequestWord(words: List<String>): String? {
        var at = 0
        while (at < words.size && words[at] in LEAD_INS) at++
        val word = words.getOrNull(at) ?: return null
        val root = ROOTS[word] ?: return null
        if (root in CARRIERS && "что" in words.drop(at + 1)) return null
        return word
    }

    /** Слово сомнительной просьбы (правило 4) или null. */
    private fun doubtfulRequestWord(sentence: String, words: List<String>): String? {
        for (part in sentence.split(PART_BREAK)) {
            val word = words(part).firstOrNull { it !in PART_LEADERS } ?: continue
            if (word in NOT_REQUEST) continue
            val base = word.removeSuffix("ся").removeSuffix("сь")
            if (PersonForm.firstWordIsRequest(word) || (base != word && PersonForm.firstWordIsRequest(base))) {
                return word
            }
        }
        return words.firstOrNull { it in REQUEST_MARKS }
    }
}
