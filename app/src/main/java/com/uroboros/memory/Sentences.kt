package com.uroboros.memory

/**
 * Разрезание длинной записи на предложения и склейка одинаковых.
 *
 * ЗАЧЕМ. Записи длиннее потолка судьи (`JudgeRun.MAX_RECORD_CHARS`) не судятся
 * ни с кем: спор с ними не будет найден никогда. Поднимать потолок бесполезно —
 * пара растёт квадратом, а длинная запись содержит не одно утверждение, а
 * десятки. Нужен другой ход: резать запись на части и работать с частями.
 * Здесь только первый слой — границы предложений и повторы; разбор предложения
 * на роли и деление составного предложения на утверждения сюда не входят.
 *
 * ЗАПИСЬ ПРИ ЭТОМ ОСТАЁТСЯ ЦЕЛОЙ. Куски — вид на запись, а не замена ей.
 * Сказанным считается то, что дошло до собеседника, а дошло оно одной штукой;
 * хранить вместо реплики её обломки значит терять невосстановимо.
 *
 * ПОЧЕМУ НУМЕРАЦИЯ ЛОМАЛА ПРЕЖНЮЮ РАЗРЕЗАЛКУ. Граница предложения — знак конца
 * плюс пробел. Номер пункта списка выглядит точно так же: «1. », «2. ». На
 * тексте, набранном списком, половина кусков выходила из одной цифры и точки,
 * а настоящее предложение начиналось со следующего куска. Поэтому здесь режется
 * как прежде, а потом обратно склеивается то, что резать не следовало: кусок из
 * одного номера и кусок, кончающийся сокращением из закрытого списка. Там, где
 * склеивать нечего, разрез получается прежний — это и есть проверка, что
 * починка не поменяла поведение на обычном тексте.
 *
 * ПОЧЕМУ НОМЕР СНИМАЕТСЯ С НАЧАЛА КУСКА. Иначе повторы не склеиваются: одно и
 * то же предложение под номерами 1 и 7 — два разных текста. Номер здесь не
 * содержание, а разметка списка.
 *
 * ЧЕГО НЕ УМЕЕТ:
 *  - список сокращений закрытый. Незнакомое сокращение («илл.», «оз.») по-
 *    прежнему разорвёт предложение надвое. Угадывать сокращение по форме не
 *    пытается: «г.» бывает и концом предложения, и началом «г. Москва», и
 *    формальным признаком их не различить;
 *  - предложение, которое ПРАВДА начинается с числа и точки («1861. Отмена
 *    крепостного права»), лишится этого числа — оно неотличимо от номера
 *    пункта;
 *  - составное предложение остаётся одним куском. «В мастерской стоит станок,
 *    и у него есть подача, шпиндель, станина и кожух» — это пять утверждений, а
 *    кусок один. Деление по частям предложения — следующий слой, не этот;
 *  - склейка повторов сравнивает тексты ТОЧНО, с учётом регистра. «Вымпел» и
 *    «вымпел» остаются двумя кусками, и это намеренно: регистр в названиях
 *    значим, а различать название и слово формально нечем;
 *  - словаря нет вовсе. «Кожух закрывает зону» и «зона закрывается кожухом» —
 *    два разных куска.
 *
 * ПОЧЕМУ НЕ ТРОГАЕТ RiskTrigger. У правила противоречия есть своя разрезалка
 * (`SENTENCE_BREAK` внутри `withoutQuestions`), и она нарочно оставлена как
 * была. Починка нумерации меняет то, что правило считает предложением, а его
 * поведение измерено на прежней разрезалке; сначала перемер, потом слияние.
 * Пока их две, расхождение надо держать в голове — это цена, а не удобство.
 */
object Sentences {

    /** Кусок текста и сколько раз он встретился в записи. */
    data class Piece(val text: String, val count: Int)

    // Граница предложения: знак конца и пробел после него. Тот же признак, что
    // у правила противоречия.
    private val BREAK = Regex("(?<=[.!?…])\\s+")

    // Кусок, состоящий из одного номера пункта: «1.», «12)».
    private val BARE_NUMBER = Regex("^\\d+[.)]$")

    // Номер пункта в начале куска — разметка списка, не содержание.
    private val LEADING_NUMBER = Regex("^\\d+[.)]\\s*")

    private val SPACES = Regex("\\s+")

    // Закрытый список: сокращения, после которых точка не кончает предложение.
    // «г.» и «в.» сюда НЕ входят — они слишком часто стоят концом предложения,
    // и склейка по ним слепила бы больше, чем починила.
    private val ABBREVIATIONS = setOf(
        "т.е.", "т.д.", "т.п.", "т.к.", "им.", "др.", "пр.",
        "см.", "рис.", "табл.", "стр.", "гг.", "вв.", "руб.", "коп.",
    )

    /**
     * Куски-предложения в порядке появления. Пробелы внутри куска сведены к
     * одному, номер пункта снят с начала. Пустых кусков не возвращает.
     */
    fun split(text: String): List<String> {
        val result = mutableListOf<String>()
        var held = ""
        for (raw in BREAK.split(text)) {
            val part = SPACES.replace(raw, " ").trim()
            if (part.isEmpty()) continue
            val joined = if (held.isEmpty()) part else "$held $part"
            val lastWord = part.substringAfterLast(' ').lowercase()
            // Кусок не закончен: это номер пункта или сокращение, а настоящее
            // предложение продолжается в следующем куске.
            if (BARE_NUMBER.matches(part) || lastWord in ABBREVIATIONS) {
                held = joined
                continue
            }
            result += joined
            held = ""
        }
        // Текст кончился на номере или сокращении — отдаём как есть, чтобы
        // ничего не потерять.
        if (held.isNotEmpty()) result += held
        return result.map { LEADING_NUMBER.replace(it, "").trim() }.filter { it.isNotEmpty() }
    }

    /**
     * Одинаковые куски — в один, с числом повторов. Порядок первого появления
     * сохраняется: он и есть порядок записи.
     */
    fun collapse(parts: List<String>): List<Piece> {
        val counts = LinkedHashMap<String, Int>()
        for (part in parts) counts[part] = (counts[part] ?: 0) + 1
        return counts.map { (text, count) -> Piece(text, count) }
    }

    /** Разрезать запись и склеить повторы — то, что нужно вызывающему обычно. */
    fun statements(text: String): List<Piece> = collapse(split(text))
}
