package com.uroboros.memory

/**
 * Запрос «одна запись по номеру» в поле ввода экрана «Показать»: `№75` или
 * `#75`, пробел после знака допустим.
 *
 * ЗАЧЕМ. Отбор по словам и срез по рангу дотягиваются не до всех записей, а
 * убрать ошибочную запись можно только с экрана, где она видна. Номер
 * дотягивается до любой (см. TrustedMediator.getRecord).
 *
 * ГРАНИЦА ОБЪЯВЛЕНА, а не угадывается по тексту:
 *  - голое число («75») — это поиск по словам, а не номер: в памяти лежат
 *    записи с числами («ставка 7,5»), и искать их числом законно;
 *  - знак номера с другими словами («№75 рубанок») — тоже поиск по словам:
 *    вход по номеру показывает ровно одну запись, и смешанный запрос не
 *    может значить одновременно и то и другое;
 *  - запросом по номеру нельзя искать сам текст «№75» в записях. Такой поиск
 *    был бы бесполезен и без этого: знак отсекается при разборе слов.
 *
 * Чего не умеет: номер надо знать. Он печатается у каждой записи на экране
 * «Показать», в списке отвергнутых и в сообщениях об отвержении; записи,
 * которую человек нигде не видел, номер ему взять неоткуда.
 */
object RecordNumber {

    private val PATTERN = Regex("""^\s*[№#]\s*(\d{1,18})\s*$""")

    /** Номер записи, если весь запрос — номер; иначе null. */
    fun parse(query: String?): Long? {
        if (query == null) return null
        val digits = PATTERN.matchEntire(query)?.groupValues?.get(1) ?: return null
        return digits.toLongOrNull()
    }
}
