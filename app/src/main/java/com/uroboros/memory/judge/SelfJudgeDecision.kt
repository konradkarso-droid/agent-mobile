package com.uroboros.memory.judge

/**
 * Когда агент сам берётся за разбор памяти судьёй. Чистое решение: ни базы, ни
 * Android — затем и вынесено, чтобы правила закрепить тестами. Входы собирает
 * тело агента (AgentService) раз в минуту бодрствования.
 *
 * НАЧИНАТЬ СТРОГО. Лишний запуск — нагрев, заряд и ответ, который ждёт, пока
 * судья уступит; пропуск — вердикты придут позже, и только. Поэтому сомнение
 * решается в сторону отказа: без показаний батареи — не судим, не на зарядке —
 * не судим, даже если заряда много.
 *
 * СОН И СУД — РАЗНЫЕ РЕШЕНИЯ. Сон дешёвый и без модели (SleepDecision), суд
 * дорогой и с моделью. Условия и строки у них свои: слитые, они прятали бы
 * отказ суда («не на зарядке») под видом «не спал».
 *
 * Здесь только условия, которые проверяются без чтения памяти. «Есть ли что
 * судить» и загрузка модели идут после них, в теле: одно читает базу, другое
 * стоит гигабайтов и десятков секунд.
 *
 * ЧЕГО НЕ УМЕЕТ:
 *  - тишину меряет от конца последнего обращения к модели, а не от последнего
 *    касания экрана: человек, который читает ответ, для него молчит;
 *  - отдых после прогона живёт в памяти процесса; после комы его нет, и первый
 *    же тихий час на зарядке начнёт суд заново.
 */
object SelfJudgeDecision {

    /**
     * Бюджет одного прогона судьи — общий для кнопки и самостоятельного суда.
     * Прогон продолжаем, так что бюджет — страховка, а не план.
     */
    const val RUN_BUDGET_MS = 7L * 60 * 60 * 1000

    /**
     * Сколько тишины нужно, чтобы начать суд. Объявленное число, не
     * подобранное: суд занимает модель надолго, и начинать его на паузе
     * живого разговора дороже, чем начать на четверть часа позже.
     */
    const val QUIET_MS = 15L * 60 * 1000

    /**
     * Отдых после самостоятельного прогона, кончившегося не по уступке
     * разговору: оборванный по нагреву или бюджету прогон не должен
     * начинаться снова через минуту. Объявленное число.
     */
    const val REST_AFTER_RUN_MS = 30L * 60 * 1000

    data class Inputs(
        val running: Boolean,
        val emergencyStop: Boolean,
        /** Прислал ли сторож хоть одно показание батареи. */
        val powerKnown: Boolean,
        val charging: Boolean,
        /** Отказ сторожа словами (DeviceSafetyWatchdog.longRunBlockReason); null — можно. */
        val watchdogRefusal: String?,
        val engineBusy: Boolean,
        val quietMs: Long,
        /** Сколько ещё отдыхать после прошлого прогона; ноль и меньше — отдых кончился. */
        val restLeftMs: Long,
        /** Выбиралась ли модель хоть раз — иначе загружать нечего. */
        val modelChosen: Boolean,
    )

    /** Почему суд сейчас не начинается, словами; null — условия выполнены. */
    fun refusal(i: Inputs): String? = when {
        i.running -> "идёт разбор"
        i.emergencyStop -> "взведён аварийный стоп"
        !i.powerKnown -> "сторож ещё не прислал показаний батареи"
        !i.charging -> "не на зарядке"
        i.watchdogRefusal != null -> i.watchdogRefusal
        i.engineBusy -> "модель занята"
        i.quietMs < QUIET_MS -> "тихо ${minutes(i.quietMs)} мин из ${minutes(QUIET_MS)}"
        i.restLeftMs > 0 -> "отдыхаю после разбора, ещё ${minutesUp(i.restLeftMs)} мин"
        !i.modelChosen -> "модель ни разу не выбиралась — загружать нечего"
        else -> null
    }

    private fun minutes(ms: Long): Long = ms.coerceAtLeast(0) / 60_000

    private fun minutesUp(ms: Long): Long = (ms + 59_999) / 60_000
}
