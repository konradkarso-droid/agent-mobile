package com.uroboros.memory.judge

/**
 * Отпечатки судей — чем судим: печатного ([JudgeVerdict.loadFingerprint]) и
 * прямого ([JudgeSieveRow], «ОТПЕЧАТОК»). Зачем отпечаток вообще и почему в
 * нём промпт — у [JudgeVerdict.loadFingerprint]; здесь — что в нём значит
 * «модель». Чистый объект: имя и размер файла читает JudgeLauncher.
 *
 * МОДЕЛЬ — ПО ИМЕНИ И РАЗМЕРУ ФАЙЛА, А НЕ ПО АДРЕСУ. Адрес файла на телефоне
 * (content://…) меняется, когда файл выбирают заново или переносят на другой
 * телефон, а сама модель при этом та же. Отпечаток по адресу делал судью
 * «другим» в каждом таком случае, и начало следующего прогона сносило все его
 * вердикты (JudgeVerdictDao.forgetOtherJudges): очередь суда начиналась с
 * нуля. Имя и размер вместе меняются тогда, когда меняется сам файл.
 *
 * ПРЕЖНИЙ ОТПЕЧАТОК ПЕРЕНОСИТСЯ. Отпечаток по адресу ([legacyModel]) — тот же
 * судья, если адрес указывает на тот же файл. Поэтому строки, снятые под ним,
 * переписываются на отпечаток по имени и размеру раньше, чем чужие судьи
 * сносятся (JudgeLauncher.carry), а не теряются.
 *
 * ЧЕГО НЕ УМЕЕТ:
 *  - имя или размер файла не прочитались — модель по адресу, как раньше
 *    ([model]); строка «Судья:» в отчёте прогона говорит об этом;
 *  - другой файл с тем же именем и тем же размером в байтах считается той же
 *    моделью — случай, которым можно пренебречь;
 *  - накладка, подключённая к модели, в отпечаток не входит — и по адресу не
 *    входила;
 *  - вердикты, которых в базе уже нет (снесённые раньше), не возвращает.
 */
object JudgePrint {

    /**
     * Модель для отпечатка: имя и размер файла, если оба известны, иначе адрес
     * [uri] — тот же отпечаток, что был до имени и размера.
     */
    fun model(uri: String, name: String?, size: Long?): String =
        if (name.isNullOrBlank() || size == null || size <= 0) legacyModel(uri) else "$name|$size"

    /** Модель так, как отпечаток считался по адресу файла. */
    fun legacyModel(uri: String): String = uri

    /** Отпечаток печатного судьи: модель и текст его промпта. */
    fun printed(model: String, prompt: String): String =
        Integer.toHexString(model.hashCode()) + "-" + Integer.toHexString(prompt.hashCode())

    /** Отпечаток прямого судьи: модель и версия его направления. */
    fun direct(model: String, version: Int): String =
        Integer.toHexString(model.hashCode()) + "-d" + version
}
