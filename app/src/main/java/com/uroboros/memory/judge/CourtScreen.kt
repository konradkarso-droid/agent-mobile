package com.uroboros.memory.judge

/**
 * Экран суда: чёрный экран поверх экрана блокировки, который не даёт телефону
 * погасить экран, пока агент судит память. Показ — AgentService, сам экран —
 * CourtScreenActivity; здесь — зачем, границы и строка прибора, без Android.
 *
 * ЗАЧЕМ. Прошивка этого телефона замораживает процесс агента, когда экран
 * погашен, а агент в фоне: службе переднего плана, блокировке сна и исключению
 * из оптимизации батареи она не уступает. Прогон суда тогда стоит на одной паре
 * часами и идёт снова, только когда экран зажгут. С горящим экраном агента не
 * замораживают: в руках у человека тот же прогон идёт по паре за секунды.
 * Значит, на время суда экран должен гореть.
 *
 * И ПО КНОПКЕ ТОЖЕ. Нажавший «Разбор памяти» не обязательно остаётся в
 * приложении: отошёл — экран погас, и ночь по кнопке стоит так же, как
 * самостоятельный суд. Поэтому экран бережёт и её — от начала суда до конца
 * всей ночи, включая шаги после суда.
 *
 * КАК. Экран просится через уведомление на весь экран — тем же путём, каким
 * будильник будит телефон, — и только когда экран погашен: при погасшем
 * экране в начале суда и при каждом погасании за время суда. Чёрный, с яркостью
 * [BRIGHTNESS]: на экране этого телефона чёрные точки не светятся. Закрывается
 * сам, когда суд кончился; касание закрывает его раньше.
 *
 * ЧЕГО НЕ УМЕЕТ:
 *  - бережёт только суд: самостоятельный и ночь по кнопке. Шаги ночи, которые
 *    агент доделывает сам, и ответ в телеграме при погасшем экране
 *    замораживаются, как раньше;
 *  - нужно разрешение «уведомления на весь экран»; его может не быть, и тогда
 *    экран не просится вовсе, а строка говорит почему;
 *  - прошивка может не открыть экран и при разрешении — строка тогда скажет
 *    «просил — не открылся»;
 *  - погасил человек экран кнопкой — экран суда зажжётся снова: это и есть
 *    «экран горит, пока идёт суд»;
 *  - состояние живёт в памяти процесса: после комы строки нет.
 *
 * Чистый объект.
 */
object CourtScreen {

    /** Яркость экрана суда, доля от полной. Объявленное число, не подобранное. */
    const val BRIGHTNESS = 0.01f

    /** Цвет надписи на экране суда — тёмно-серый, чтобы не светить. */
    const val TEXT_COLOR = 0xFF2A2A2A.toInt()

    /** Надпись на экране суда: зачем горит и как закрыть. */
    const val TEXT = "Агент разбирает память.\nЭкран не гаснет, пока идёт суд.\nКоснитесь — закрыть."

    /** Отказ в показе, когда разрешения нет. */
    const val NOT_ALLOWED = "разрешение «Уведомления на весь экран» выключено — включить в настройках приложения агента"

    /**
     * Один прогон суда с точки зрения экрана: [startedAt] —
     * начало суда; [refusal] — почему экран не просился (последний отказ);
     * [requests] — сколько раз просился, последний — [lastRequestAt];
     * [opens] — сколько раз экран на деле открылся, первый — [openedAt];
     * [endedAt] — суд кончился.
     */
    data class Run(
        val startedAt: Long,
        val refusal: String? = null,
        val requests: Int = 0,
        val lastRequestAt: Long? = null,
        val opens: Int = 0,
        val openedAt: Long? = null,
        val endedAt: Long? = null,
    ) {
        fun requested(now: Long) = copy(refusal = null, requests = requests + 1, lastRequestAt = now)
        fun opened(now: Long) = copy(opens = opens + 1, openedAt = openedAt ?: now)
        fun ended(now: Long) = if (endedAt != null) this else copy(endedAt = now)
    }

    /**
     * Нужен ли экран суда сейчас: идёт прогон ([running]) и его экран не снят.
     * Не нужен — экран суда закрывается сам (CourtScreenActivity).
     */
    fun needed(running: Boolean, run: Run?): Boolean = running && run != null && run.endedAt == null

    /** Строка прибора. [clock] — время словами. */
    fun line(run: Run?, clock: (Long) -> String): String {
        if (run == null) return "Экран суда: в этом запуске суда не было"
        val end = run.endedAt?.let { ", суд кончился в ${clock(it)}" } ?: ""
        return when {
            run.refusal != null -> "Экран суда: не показан — ${run.refusal}$end"
            run.requests == 0 ->
                "Экран суда: суд с ${clock(run.startedAt)}, экран и так горел — не понадобился$end"
            run.opens == 0 ->
                "Экран суда: просил ${times(run.requests)}, последний раз в ${run.lastRequestAt?.let(clock) ?: "?"}" +
                    " — не открылся$end"
            else ->
                "Экран суда: открыт в ${run.openedAt?.let(clock) ?: "?"}" +
                    (if (run.requests > 1 || run.opens > 1) " · просил ${times(run.requests)}, открывался ${times(run.opens)}" else "") +
                    end
        }
    }

    /** «1 раз», «2 раза», «5 раз». */
    fun times(n: Int): String {
        val tail = n % 100
        val word = when {
            tail in 11..14 -> "раз"
            n % 10 in 2..4 -> "раза"
            else -> "раз"
        }
        return "$n $word"
    }
}
