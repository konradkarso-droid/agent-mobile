package com.uroboros.memory.judge

import androidx.room.Entity

/** Что сказал человек, посмотрев на спорную пару. */
enum class HumanVerdict {
    /** Не смотрел. Начальное состояние всякой строки. */
    UNREVIEWED,

    /** Посмотрел: спор настоящий. */
    CONFIRMED,

    /** Посмотрел: судья промахнулся. */
    MISS,
}

/**
 * Разобранная пара записей: что ответила модель, чем это кончилось и что об
 * этом сказал человек.
 *
 * Строка значит две вещи сразу — «вот вердикт» и «эту пару уже смотрели».
 * Вторая половина и есть то, ради чего таблица заведена: без неё ночной прогон
 * каждый раз начинал бы с начала и пересуживал всю память.
 *
 * ПОЭТОМУ СТРОКИ «НЕ СПОР» НЕ УДАЛЯЮТСЯ. Удалить строку значит не очистить
 * список, а вернуть пару в очередь: судья разберёт её снова и снова покажет.
 * Из списка на экране пара уходит по [humanVerdict], а не по удалению строки.
 *
 * ПАРА НЕУПОРЯДОЧЕНА. Судья спрашивает модель об одной паре дважды, в обоих
 * порядках, поэтому «запись 13 против 15» и «15 против 13» — одно дело, а не
 * два. Чтобы одна пара не легла сюда двумя строками, в [firstId] всегда
 * меньший номер. Кто пишет строку, тот и обязан это соблюсти.
 *
 * НЕПРОЧИТАННЫЕ ОТВЕТЫ СЮДА НЕ ПОПАДАЮТ. Если модель промолчала или заговорила
 * словами, строки не появляется, и пара остаётся в очереди на следующий прогон.
 * Иначе поломка судьи осела бы в хранилище как разобранная пара и больше
 * никогда не пересматривалась. Сколько ответов не прочиталось — дело прибора
 * прогона, а не этой таблицы.
 *
 * СКОЛЬКО ЭТО ВЕСИТ. Строк примерно квадрат от числа записей: полсотни записей —
 * около полутора тысяч строк и сотня килобайт, пятьсот записей — сто двадцать
 * тысяч строк и порядка девяти мегабайт. Комплект всегда один: строки чужих
 * судей и пар с удалёнными записями сносятся в начале каждого прогона, см.
 * JudgeVerdictDao. Дальше этого таблица не растёт, а если память дорастёт до
 * величин, где и один комплект тяжёл, — сужать придётся круг сравниваемых пар,
 * а не чистить хранилище.
 */
@Entity(
    tableName = "judge_verdicts",
    primaryKeys = ["firstId", "secondId", "loadFingerprint"],
)
data class JudgeVerdict(
    /** Номер записи с меньшим id — см. про неупорядоченность пары выше. */
    val firstId: Long,

    /** Номер записи с большим id. */
    val secondId: Long,

    /**
     * Чем судили: короткий отпечаток модели и текста промпта вместе.
     *
     * Входит в ключ, а не лежит рядом справочно. Вердикт — не свойство пары, а
     * показание конкретного судьи: сменилась модель или хоть слово в промпте —
     * и прежние оценки к новому судье не относятся. При смене отпечатка все
     * пары становятся неразобранными, и пересуживание начинается само, без
     * отдельной команды.
     *
     * Именно поэтому отпечаток обязан включать промпт: два промпта,
     * отличавшиеся только пояснениями в скобках, совпали на тех же парах меньше
     * чем в половине ответов.
     *
     * Короткий намеренно. Строка повторяется в каждой строке таблицы, и полная
     * ссылка на файл модели весила бы больше, чем всё остальное вместе, ничего
     * не добавляя: различать надо не содержание, а факт смены.
     */
    val loadFingerprint: String,

    /** Ответ модели, когда первой показали [firstId]. Одна цифра. */
    val forward: String,

    /** Ответ модели, когда первой показали [secondId]. Одна цифра. */
    val backward: String,

    /** Имя значения `MemoryJudge.Verdict`. Спором считается только единица в обоих порядках. */
    val verdict: String,

    val judgedAt: Long,

    /**
     * Сколько заняла пара целиком, оба вопроса.
     *
     * Единственное место, где видна настоящая цена прогона на этом устройстве.
     * Из общего времени её не вывести делением: прогон прерывается нагревом и
     * ждёт остывания, и в среднем по прогону это время размазано.
     */
    val spentMs: Long,

    /**
     * Имя значения [HumanVerdict]. Ровно это поле убирает пару из списка на
     * экране, и оно же — единственный источник доли промахов судьи на живой
     * памяти.
     *
     * Записывается только по действию человека и снимается обратно тем же
     * способом. Обратимость обязательна: человек, листающий полсотни пар
     * подряд, закроет настоящий спор по инерции, и это не должно быть
     * окончательным — ниже него никого нет.
     *
     * Чего это число не значит: «промах» — суждение человека, а не истина.
     * Доля, которая из него вырастет, — доля пар, с которыми человек не
     * согласился.
     */
    val humanVerdict: String = HumanVerdict.UNREVIEWED.name,

    /**
     * Когда посмотрели. Справочно: состояние задаёт [humanVerdict], а не эта
     * отметка. Снимается вместе с ним, чтобы не осталось времени просмотра у
     * непросмотренной пары.
     */
    val reviewedAt: Long? = null,
)
