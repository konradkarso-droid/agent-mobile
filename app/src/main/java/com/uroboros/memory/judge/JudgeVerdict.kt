package com.uroboros.memory.judge

import androidx.room.Entity

/**
 * Разобранная пара записей: что ответила модель и чем это кончилось.
 *
 * Строка здесь значит две вещи сразу — «вот вердикт» и «эту пару уже смотрели».
 * Вторая половина и есть то, ради чего таблица заведена: без неё ночной прогон
 * каждый раз начинал бы с начала и пересуживал всю память заново.
 *
 * ПАРА НЕУПОРЯДОЧЕНА. Судья спрашивает модель об одной паре дважды, в обоих
 * порядках, поэтому «запись 13 против 15» и «15 против 13» — одно и то же дело,
 * а не два. Чтобы одна пара не легла сюда двумя строками, в [firstId] всегда
 * меньший номер. Кто пишет строку, тот и обязан это соблюсти.
 *
 * НЕПРОЧИТАННЫЕ ОТВЕТЫ СЮДА НЕ ПОПАДАЮТ. Если модель промолчала или заговорила
 * словами, строки не появляется, и пара остаётся в очереди на следующий прогон.
 * Иначе поломка судьи осела бы в хранилище как разобранная пара и больше никогда
 * не пересматривалась. Сколько ответов не прочиталось за прогон — дело прибора
 * прогона, а не этой таблицы.
 *
 * ГРАНИЦА РОСТА. Строк здесь примерно квадрат от числа записей: полсотни
 * записей — около тысячи строк, пятьсот записей — сто двадцать тысяч, это уже
 * несколько мегабайт. Далеко, но не бесконечно: когда память вырастет,
 * понадобится либо сужать круг сравниваемых пар, либо забывать старые вердикты.
 * Сегодня не сужаем и не забываем — кроме вердиктов по удалённым записям.
 */
@Entity(
    tableName = "judge_verdicts",
    primaryKeys = ["firstId", "secondId", "loadFingerprint"],
)
data class JudgeVerdict(
    /** Номер записи с меньшим id — см. про неупорядоченность пары выше. */
    val firstId: Long,

    /** Номер записи с большим id. */
    val secondId: Long,

    /**
     * Чем судили: модель, параметры её загрузки и текст промпта вместе.
     *
     * Входит в ключ, а не лежит рядом справочно. Вердикт — это не свойство пары,
     * а показание конкретного судьи: сменилась модель или хоть слово в промпте —
     * и прежние оценки к новому судье не относятся. При смене отпечатка все пары
     * автоматически становятся неразобранными, и пересуживание начинается само,
     * без отдельной команды и без кнопки «очистить».
     *
     * Ровно поэтому отпечаток обязан включать текст промпта: два промпта,
     * отличавшиеся только пояснениями в скобках, совпали на тех же парах меньше
     * чем в половине ответов.
     */
    val loadFingerprint: String,

    /** Ответ модели, когда первой показали [firstId]. Одна цифра. */
    val forward: String,

    /** Ответ модели, когда первой показали [secondId]. Одна цифра. */
    val backward: String,

    /** Имя значения `MemoryJudge.Verdict`. Спором считается только единица в обоих порядках. */
    val verdict: String,

    val judgedAt: Long,

    /**
     * Сколько заняла пара целиком, оба вопроса.
     *
     * Единственное место, где видна настоящая цена прогона на этом устройстве.
     * Из общего времени её не вывести делением: прогон прерывается нагревом и
     * ждёт остывания, и в среднем по прогону это время размазано.
     */
    val spentMs: Long,
)
