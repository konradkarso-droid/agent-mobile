package com.uroboros.memory.judge

import com.uroboros.memory.RiskTrigger

/**
 * Кольцо, в которое пара попала при отборе в суд.
 *
 * Кольца вложены: пара внутреннего кольца заведомо прошла бы и внешнее.
 * Порядок перечисления — порядок суда (см. [JudgeSieve]).
 */
enum class JudgeRing {
    /** Доля общих слов от меньшей записи не ниже [JudgeSieve.INNER_SHARE]. */
    INNER,

    /** Общее значимое слово есть, но доля ниже [JudgeSieve.INNER_SHARE]. */
    OUTER,
}

/**
 * Какие пары записей идут к судье и в каком порядке.
 *
 * ГРАНИЦА ОДНА, И ОНА ОБЪЯВЛЕНА. Пара судится, если у записей есть хотя бы одно
 * общее значимое слово (основа, мерка значимости — RiskTrigger.significantStems).
 * Пара без общих слов не судится вовсе: спорить двум записям, у которых нет
 * общего предмета разговора, не о чем. Эта граница не подбирается и не
 * сдвигается — у неё нет числа.
 *
 * ПОРОГ ВНУТРИ НИЧЕГО НЕ ОТСЕКАЕТ. [INNER_SHARE] делит прошедшие пары на два
 * кольца и решает только две вещи: какое кольцо судится первым и в какой
 * строке экрана пара посчитана. Ни одна пара из-за него не выпадает. Поэтому
 * спор «какой порог верный» здесь не решается подбором: неверный порог
 * переставит очередь, но не потеряет спор.
 *
 * ЗАЧЕМ ДВА КОЛЬЦА, А НЕ ОДНО. На испытательной базе все настоящие споры лежат
 * во внутреннем кольце, внешнее — пары одной темы без спора. Но испытательная
 * база не бой. Внешнее кольцо судится последним и считается на экране отдельно
 * (JudgeLauncher.counters), чтобы по подтверждённым человеком спорам было
 * видно, находит ли оно хоть что-то. Слитые в одну цифру, кольца скрыли бы
 * ответ, ради которого их два: окупается ли внешнее.
 *
 * ОТКУДА 0,5. Доля — от меньшей записи, а не от объединения (жаккар): у записей
 * разной длины объединение топит короткую, и жаккар на 0,5 теряет треть
 * настоящих споров. На испытательной базе в полосе 0,4–0,5 не лежит ни одной
 * пары, так что порог внутри полосы ни на что не влияет; 0,5 — её верхний край.
 *
 * ЧЕГО НЕ УМЕЕТ. Спор, сказанный разными словами («рубанок» / «струг»), общих
 * значимых слов не имеет и не судится никогда. Омоним («инструмент» столярный
 * и «инструменты кибератак») даёт общее слово и пару в суд — лишнюю, но не
 * потерянную: это ошибка в сторону лишней работы, а не пропуска.
 */
object JudgeSieve {

    /** Граница между кольцами. Отсекающей силы не имеет — см. шапку. */
    const val INNER_SHARE = 0.5

    /** Кольцо пары или null — пара не судится. */
    fun ring(first: String, second: String): JudgeRing? =
        ring(RiskTrigger.significantStems(first), RiskTrigger.significantStems(second))

    /**
     * То же по готовым основам. Для обхода многих пар: основы записи считаются
     * один раз, а не в каждой паре заново.
     */
    fun ring(first: Set<String>, second: Set<String>): JudgeRing? {
        val common = first.count { it in second }
        if (common == 0) return null
        val smaller = minOf(first.size, second.size)
        return if (common.toDouble() / smaller >= INNER_SHARE) JudgeRing.INNER else JudgeRing.OUTER
    }
}
