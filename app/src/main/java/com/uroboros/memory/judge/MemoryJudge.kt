package com.uroboros.memory.judge

/**
 * Судья памяти: решает, спорят ли две записи между собой.
 *
 * Зачем. Агент записывает в память то, что ему сказали, и старая запись может
 * оказаться опровергнутой новой: «мой любимый инструмент — рубанок» лежит с
 * прошлого месяца, а сегодня сказано «не рубанок, а стамеска». Сам агент этого
 * не замечает — обе записи лежат рядом и обе попадают в ответ.
 *
 * Как устроено. Пара показывается модели дважды, А против Б и Б против А, и
 * спором считается только единица в обоих порядках. Порядок записей сдвигает
 * ответ: на одной и той же паре модель в разных порядках отвечает по-разному
 * заметно чаще, чем хотелось бы, и односторонний вердикт означал бы не
 * отношение записей, а то, какая из них оказалась первой.
 *
 * Чего механизм не умеет — это замерено, а не предположено:
 *  - Не отличает выдумку от жизни. Две фразы из сочинённой истории он назовёт
 *    спором так же уверенно, как две записи о делах.
 *  - Его уверенность ничего не говорит о правоте: на настоящем споре и на
 *    ложной тревоге модель одинаково убеждена. Отсечь ложные по вероятности
 *    нельзя — порога здесь нет и не будет, и искать его не нужно.
 *  - Ложные тревоги он даёт часто, и их доля зависит от того, что лежит в
 *    памяти. Поэтому вердикт «спорят» — повод показать пару человеку, а не
 *    основание что-либо в памяти менять.
 *
 * Класс ничего не знает ни про базу, ни про модель: пары приносят снаружи,
 * ответ добывает [Llm]. Отсев записей, которые судить не надо (строки цикла),
 * делается там же, где отбираются пары, — здесь судится то, что дали.
 */
object MemoryJudge {

    /**
     * Системное сообщение судьи, дословно.
     *
     * Текст — это и есть механизм, а не его оформление. Промпт, отличавшийся от
     * этого только пояснениями в скобках, дал на тех же парах меньше половины
     * совпадающих ответов. Любая правка формулировки означает другого судью,
     * чьё поведение не измерено, и все прежние числа к нему не относятся.
     *
     * Четвёртый ответ своей работы не выполняет: пары из выдуманной истории,
     * ради которых он и вводился, модель всё равно называет спором. Он оставлен
     * потому, что убрать его — тоже правка промпта, требующая нового замера.
     */
    const val SYSTEM: String =
        "Ты сравниваешь две записи из памяти. Не проверяй, верны ли они на самом деле — " +
            "записи могут быть ошибочными. Оцени только отношение между ними.\n" +
            "Ответь одной цифрой:\n" +
            "1 — записи противоречат друг другу (обе не могут быть верны одновременно)\n" +
            "2 — записи согласуются (говорят одно и то же или одна следует из другой)\n" +
            "3 — записи не связаны\n" +
            "4 — не могу судить (чтобы решить, нужны сведения, которых в записях нет)"

    /** Запрос по одной паре в одном порядке. Формат тоже часть промпта — см. [SYSTEM]. */
    fun request(first: String, second: String): String =
        "Запись А: $first\nЗапись Б: $second\nОтвет:"

    /**
     * Источник ответа модели. Реализация обязана дать три вещи, иначе вердикт
     * ничего не значит:
     *
     *  1. Поставить [SYSTEM] своим системным сообщением. Если вместо него уедет
     *     стена принципов агента, модель будет отвечать не на ту инструкцию.
     *  2. Выдавать жадно. Разговорные настройки выдачи случайны: одна и та же
     *     пара даст разные цифры в разных прогонах, и двойной порядок
     *     перестанет что-либо проверять.
     *  3. Ограничить выдачу одним токеном. Нужна цифра, а не рассуждение.
     *
     * Возвращает то, что сказала модель, как есть — разбирает [digitOf].
     */
    interface Llm {
        suspend fun answer(system: String, request: String): String
    }

    enum class Verdict {
        /** Единица в обоих порядках. Только это едет человеку. */
        DISPUTE,

        /** Модель ответила, но спором пару не назвала. */
        NO_DISPUTE,

        /**
         * Хотя бы в одном порядке ответ не прочитан — модель промолчала или
         * заговорила словами. Пара остаётся непросуженной и будет взята снова.
         *
         * Отдельный исход, а не разновидность [NO_DISPUTE], потому что иначе
         * сломавшийся судья выглядел бы как судья, не нашедший споров, и это
         * различие снаружи было бы уже не восстановить.
         */
        UNREADABLE,
    }

    /** Ответы модели по обоим порядкам и вердикт по ним. */
    data class Judgement(
        val forward: Char?,
        val backward: Char?,
        val verdict: Verdict,
    )

    /**
     * Первая цифра ответа, если она из ожидаемых, иначе null.
     *
     * Ищется первая подходящая цифра во всей строке, а не только в начале:
     * модель может добавить пробел или кавычку. Всё остальное — не ответ.
     */
    fun digitOf(answer: String): Char? = answer.firstOrNull { it in '1'..'4' }

    fun verdictOf(forward: Char?, backward: Char?): Verdict = when {
        forward == null || backward == null -> Verdict.UNREADABLE
        forward == '1' && backward == '1' -> Verdict.DISPUTE
        else -> Verdict.NO_DISPUTE
    }

    /**
     * Просудить пару. Два вызова модели: прямой порядок и обратный.
     *
     * Ошибки вызова наружу не глушатся: прогон должен остановиться и сказать,
     * что оборвался, а не дописать в хранилище вердикты, которых не было.
     */
    suspend fun judge(llm: Llm, first: String, second: String): Judgement {
        val forward = digitOf(llm.answer(SYSTEM, request(first, second)))
        val backward = digitOf(llm.answer(SYSTEM, request(second, first)))
        return Judgement(forward, backward, verdictOf(forward, backward))
    }
}
