package com.uroboros.memory

/**
 * Сверка того, что подаётся модели в одном ходе, — записей между собой и
 * записей с репликой человека, — и фраза, которой найденное расхождение
 * говорится самой модели.
 *
 * ЗАЧЕМ ЭТО ЕСТЬ. Правило противоречия стоит на входе в память и работает на
 * человека: поднимает бит, наполняет очередь, рисует спор на экране. В контекст
 * модели оно не выходило ни одним словом, и наблюдалось, чем это кончается:
 * агенту подали пять прямо противоречащих друг другу записей, и он выбрал одну,
 * ответив ровным голосом, без тени сомнения. Выбор сделала не память — его
 * сделала пустота на месте сведения о споре.
 *
 * ДВЕ ПАРЫ, И ВТОРАЯ ЧАЩЕ ПЕРВОЙ. Спор двух старых записей между собой —
 * редкость. Обычное дело — когда человек говорит сейчас то, что расходится с
 * лежащим в памяти: сверка записей между собой такую пару не видит вовсе, и
 * механизм, знающий только её, молчит ровно там, где нужнее всего.
 *
 * ЧТО ЭТО НЕ. Не вердикт и не отбор. Здесь ничего не прячется, не удаляется и
 * не взвешивается: обе стороны уходят в модель как были, и рядом кладётся факт,
 * что сверка нашла между ними расхождение. Правило противоречия отвечает
 * «спорят или нет» и о сторонах не знает НИЧЕГО — из него невозможно вывести,
 * какая запись верна, поэтому механизм, выбирающий сторону, здесь был бы
 * угадыванием, выдающим себя за вердикт.
 *
 * ПОЧЕМУ УТВЕРЖДЕНИЕ, А НЕ УКАЗАНИЕ. Фраза говорит, что случилось, и не просит
 * ничего сделать. «Не полагайся на одну из них» было бы мягким сигналом,
 * который модель взвешивает против цели ответить — а такому в проверках места
 * нет. Та же мера, по которой провенанс записи оформлен словами «Пользователь
 * сказал», а не меткой: работу делает грамматика.
 *
 * ИСТОЧНИК СТОИТ В ПОДЛЕЖАЩЕМ, и это несущая часть формы. Сказано «сверка
 * нашла расхождение», а не «записи противоречат друг другу»: второе — вывод, и
 * делает его читатель, а не механизм. Модель, прочитавшая «противоречат»,
 * вправе достроить, что одна из записей ложна; прочитавшая «сверка нашла»,
 * знает ровно то, что было сделано, и кем.
 *
 * ЦИТАТЫ, А НЕ НОМЕРА. Нумеровать поданные записи было бы дешевле, но номер на
 * разных ходах означает разные записи — отбор возвращает своё на каждый вопрос.
 * Это тихая подмена, самый дорогой класс ошибок в этом проекте. Цитата стоит
 * десятка токенов и не врёт.
 *
 * РЕПЛИКА, НАОБОРОТ, НЕ ЦИТИРУЕТСЯ, и это не экономия. Она стоит в том же
 * сообщении целиком и своими словами; процитировав её здесь, мы дали бы одному
 * утверждению два вхождения в разных обрамлениях — а два вхождения читаются
 * как два свидетельства, а не как одно сказанное дважды. По этой же причине
 * реплика ложится в память после отбора, а не до (см. вызывающего). Указание
 * на неё поэтому словесное — «ниже», — и держится оно на том, что блок стоит
 * непосредственно перед вопросом (см. `ConversationJournal.composeUserContent`).
 * Переставят блок — указание соврёт, и молча.
 *
 * ГДЕ ЭТО ЖИВЁТ И ПОЧЕМУ НЕ В ЛЕНТЕ. Класс лежит в памяти, рядом с правилом,
 * хотя плод его работы уходит в ленту. Лента объявлена недоверенным журналом и
 * про память не знает; втащив правило туда, мы связали бы два слоя так, что
 * правка правила молча меняла бы поведение ленты.
 *
 * ЧЕГО ЭТОТ МЕХАНИЗМ НЕ УМЕЕТ:
 *  - сверяются ТОЛЬКО переданные тексты и переданная реплика. Запись, которую
 *    отбор на этом ходе не нашёл, в сверку не входит, даже если лежит в ленте с
 *    прошлых ходов и модель её видит;
 *  - пересказ другими словами не берётся вовсе — ни этим правилом, ни любым
 *    другим в проекте. Две записи об одном и том же, сказанные разными словами,
 *    здесь неотличимы от двух записей о разном;
 *  - ПАРА СРАВНИВАЕТСЯ ТОЛЬКО ПОСЛЕ ПОРОГА СХОЖЕСТИ, и для пары с репликой это
 *    решает больше, чем всё остальное здесь. Сработает возражение, повторяющее
 *    запись её же словами с отрицанием («Меркурий НЕ светит алым у полудня»);
 *    возражение, сказанное живьём («да не светит он алым»), до сравнения не
 *    доходит — схожесть около трети при пороге в половину. То есть механизм
 *    покрывает возражение-переписывание, а не возражение-реплику, и обещать
 *    большего нельзя. Порог опустить не выйдет: ниже него ложные срабатывания
 *    начинаются на живом материале сразу, замер стоит у
 *    `RiskTrigger.CONTRADICTION_JACCARD_THRESHOLD`;
 *  - пустая сторона у признака — не поломка, а его устройство (см.
 *    `RiskTrigger.ContradictionMark`);
 *  - [Result.Clean] означает «среди ЭТОГО расхождений нет» и НЕ означает «в
 *    памяти нет спора»: пул здесь — горстка поданных записей, а не память;
 *  - записи, различающиеся только хвостом, дадут две одинаковые цитаты. Случай
 *    не выдуманный: в базе лежат две записи про рубанок с деревянной колодкой,
 *    различающиеся точкой в конце и дефисом против тире. Тогда строка называет
 *    расхождение и не даёт его увидеть — проверяется глазом на экране, где
 *    видны полные тексты;
 *  - ОДНО РАСХОЖДЕНИЕ МОЖЕТ ПРОЗВУЧАТЬ ДВАЖДЫ, в разных ходах и разными
 *    словами. Реплика ложится в память, поэтому спор, названный сегодня парой
 *    «запись и реплика», завтра будет назван парой записей между собой, если
 *    отбор поднимет обе. Это следствие автозаписи, а не сбой; но человек,
 *    увидевший два сообщения об одном споре, без этой строки решит иначе;
 *  - «механизм не звали» тремя исходами НЕ различается. Отсутствие вызова
 *    видно только отсутствием строки на экране вовсе — и потому строка о
 *    сверке там должна стоять всегда, даже когда сверять было нечего.
 */
object DisputeNotice {

    /**
     * Итог сверки. Три значения, а не два, по тому же правилу, что у остальных
     * ступеней проекта: механизм, у которого «нашлось» и «не нашлось» — весь
     * словарь, молчит одинаково и когда ловить нечего, и когда он мёртв.
     */
    sealed class Result {

        /**
         * Сверять было нечего: не набралось ни одной пары. Отдельно от [Clean]
         * потому, что «сравнили и не нашли» и «не сравнивали» — разные события,
         * а на экране они выглядели бы одной пустотой.
         */
        object NothingToCompare : Result()

        /** Сравнили все пары, расхождений не нашлось. */
        object Clean : Result()

        /**
         * Расхождения найдены.
         *
         * @property text готовый блок для реплики пользователя, дословно тот,
         *                что уйдёт в модель.
         * @property pairsFound сколько пар разошлось всего, обоих видов вместе.
         * @property pairsShown сколько из них названо в тексте. Меньше
         *                      [pairsFound] только при обрезке по [MAX_PAIRS].
         */
        data class Found(
            val text: String,
            val pairsFound: Int,
            val pairsShown: Int,
        ) : Result()
    }

    /**
     * Сверяет переданное и собирает блок для реплики.
     *
     * Принимает тексты, а не записи, намеренно: сверка не смотрит ни на
     * провенанс, ни на слой, ни на бит — только на тексты. Чистая функция
     * без базы и без Android, поэтому берётся обычным тестом.
     *
     * @param contents тексты записей, поданных модели в этом ходе.
     * @param utterance текст реплики человека в этом же ходе. Умолчание `null`
     *        означает «реплику не передали» и даёт ровно прежнее поведение —
     *        сверку записей между собой. Умолчание нужно ещё и затем, чтобы
     *        этот файл собирался в своём коммите, до правки вызывающего.
     *
     * ПАРЫ С РЕПЛИКОЙ СЧИТАЮТСЯ ПЕРВЫМИ, и порядок здесь несущий, а не
     * оформительский. Потолок [MAX_PAIRS] один на весь блок; сложи мы пары в
     * обратном порядке, три спора старых записей между собой съедали бы его
     * целиком, и частый случай не уезжал бы в модель именно тогда, когда в
     * памяти много спорного. Редкое вытесняло бы частое тем чаще, чем хуже
     * дела.
     *
     * Порядок пар записей между собой — порядок подачи: первая названная пара
     * стоит раньше в выдаче отбора. Сортировать по «силе» расхождения нечем —
     * признаки не сравнимы между собой, и любая шкала здесь была бы придуманной.
     *
     * Пустые и пробельные тексты пропускаются, и реплика тоже: сверять в них
     * нечего, а в цитате они дали бы пустые кавычки.
     */
    fun of(contents: List<String>, utterance: String? = null): Result {
        val texts = contents.filter { it.isNotBlank() }
        val speech = utterance?.takeIf { it.isNotBlank() }

        // Пара нужна целиком. Реплика без единой записи не с чем сверяется, а
        // одна запись становится стороной только вместе с репликой.
        val speechPairs = if (speech != null) texts.size else 0
        val recordPairs = texts.size * (texts.size - 1) / 2
        if (speechPairs + recordPairs == 0) return Result.NothingToCompare

        val lines = mutableListOf<String>()
        var found = 0

        if (speech != null) {
            for (text in texts) {
                // Порядок доводов тот же, что в строке: сперва запись, потом
                // реплика. На саму находку он не влияет — правило сравнивает
                // множества и симметрично. Влияет он на то, в какое поле
                // признака (first/second) лягут слова; здесь эти поля не
                // читаются, но порядок держим согласованным со строкой, чтобы
                // они означали то же, что видит глаз.
                val marks = RiskTrigger.contradictionMarks(text, speech)
                if (marks.isEmpty()) continue
                found++
                if (lines.size < MAX_PAIRS) {
                    lines += speechLine(text, marks)
                }
            }
        }

        for (i in texts.indices) {
            for (j in i + 1 until texts.size) {
                val marks = RiskTrigger.contradictionMarks(texts[i], texts[j])
                if (marks.isEmpty()) continue
                found++
                if (lines.size < MAX_PAIRS) {
                    lines += line(texts[i], texts[j], marks)
                }
            }
        }
        if (found == 0) return Result.Clean

        val out = StringBuilder()
        lines.forEach { out.append(it).append("\n") }
        // Строка об обрезке появляется только тогда, когда обрезка была, — а
        // была она лишь на полном потолке. Поэтому первое число здесь всегда
        // MAX_PAIRS, и согласовывать числительное не с чем.
        if (found > lines.size) {
            out.append("Названы первые ").append(lines.size)
                .append(" расхождения из ").append(found).append(".\n")
        }
        out.append(LIMIT_LINE)
        return Result.Found(out.toString(), found, lines.size)
    }

    /**
     * Одна строка о паре записей.
     *
     * Признак называется ИМЕНЕМ, а не числом. Счёт здесь уже пробовали на
     * экране и опровергли живыми данными: «признаков: 1» при совершенно чистой
     * второй цитате читается как поломка, хотя механизм работает — пустая
     * сторона у признака законна (см. `RiskTrigger.ContradictionMark`). Число
     * годится там, где меряемое симметрично; здесь оно несимметрично по
     * построению.
     */
    private fun line(
        a: String,
        b: String,
        marks: List<RiskTrigger.ContradictionMark>,
    ): String {
        val kinds = kindWords(marks)
        return "Сверка записей между собой нашла расхождение: «${quote(a)}» и «${quote(b)}» — $kinds."
    }

    /**
     * Одна строка о паре «запись и реплика».
     *
     * ПОДЛЕЖАЩЕЕ ТО ЖЕ, А ПРЕДМЕТ ДРУГОЙ, и различить их обязательно. Слитые в
     * одну формулировку, эти два вида пар сделали бы невидимым вот что: человек,
     * читая о расхождении, не понял бы, участвует ли в нём то, что он сказал
     * секунду назад, — и принял бы отражение собственных слов за независимое
     * свидетельство памяти.
     *
     * Цитируется только запись; про реплику сказано «ниже», см. шапку класса.
     */
    private fun speechLine(
        record: String,
        marks: List<RiskTrigger.ContradictionMark>,
    ): String {
        val kinds = kindWords(marks)
        return "Сверка нашла расхождение между записью «${quote(record)}» и репликой пользователя ниже — $kinds."
    }

    /** Имена признаков одной пары, без повторов и в порядке находки. */
    private fun kindWords(marks: List<RiskTrigger.ContradictionMark>): String =
        marks.map { kindWord(it.kind) }.distinct().joinToString(" и ")

    private fun kindWord(kind: RiskTrigger.MarkKind): String = when (kind) {
        RiskTrigger.MarkKind.NEGATION -> "отрицание"
        RiskTrigger.MarkKind.NUMBER -> "числа разошлись"
        RiskTrigger.MarkKind.SWAP -> "на месте одного слова стоит другое"
    }

    /**
     * Начало текста для цитаты: переносы строк сводятся в пробел, хвост
     * срезается.
     *
     * Обрезка здесь СВОЯ, а не общая с экранной. Величины разные по цене:
     * экранная обрезка косметическая и стоит места на панели, эта уходит в
     * запрос и остаётся в нём до конца разговора (чем именно платится —
     * сказано у [QUOTE_CHARS]). Связать их одной константой значило бы сделать
     * правку разметки способом изменить то, что уходит в модель.
     */
    private fun quote(text: String): String {
        val flat = text.replace("\n", " ").trim()
        return if (flat.length <= QUOTE_CHARS) flat else flat.take(QUOTE_CHARS) + "…"
    }

    /**
     * Граница механизма, сказанная рядом с ним же — в том самом тексте, который
     * читает модель.
     *
     * Без этой строки названная пара читается как указание на виноватого:
     * модель достроит, что помеченное ложно, и выберет вторую сторону — то есть
     * ровно тот вердикт, которого правило не выносило. Стоит один раз на блок,
     * а не на каждую пару: повторённая трижды, она сама стала бы весомее фактов
     * рядом с ней.
     */
    const val LIMIT_LINE = "Какая сторона верна, сверка не знает."

    /**
     * Сколько пар называется в блоке, обоих видов вместе.
     *
     * ЭТО ОБЪЯВЛЕННАЯ ГРАНИЦА, А НЕ ПОДОБРАННОЕ ЗНАЧЕНИЕ. Пять поданных записей
     * дают до десяти пар между собой и ещё до пяти с репликой, всего до
     * пятнадцати; трёх названных довольно, чтобы ответ перестал быть ровным, и
     * цена при этом остаётся ограниченной сверху. Область: число верно, пока
     * отбор подаёт около пяти записей — при другом пределе подачи считать надо
     * заново. Остаток назван в тексте числом, иначе обрезка была бы неотличима
     * от конца списка.
     *
     * Потолок ОБЩИЙ, а не по три на каждый вид пары: делить его пополам значило
     * бы назначить заранее, чего в разговоре окажется больше, — а это как раз
     * то, чего никто не знает. Вместо доли порядок: пары с репликой считаются
     * первыми и под обрезку попадают последними.
     */
    const val MAX_PAIRS = 3

    /**
     * Длина цитаты в знаках.
     *
     * ЭТО ОБЪЯВЛЕННАЯ ГРАНИЦА, А НЕ ЗАМЕР. Область: работает, пока записи
     * различаются НАЧАЛОМ. Записи, расходящиеся хвостом, дадут две одинаковые
     * цитаты, и строка назовёт расхождение, не показав его. Перепроверяется не
     * счётом, а глазом: на экране рядом стоят полные тексты обеих записей.
     *
     * Цена одной пары при этой длине — около шестидесяти токенов, у пары с
     * репликой около сорока: цитата там одна. Блок из трёх — около двухсот.
     *
     * ПЛАТИТСЯ ОДНАЖДЫ, А ЕДЕТ ДАЛЬШЕ ВСЕГДА, и читать цену надо так. Блок
     * появляется только на том ходе, где расхождение нашлось, — но лежит он
     * ВНУТРИ реплики этого хода, а лента хранит реплику целиком и подаёт её в
     * каждом следующем запросе. Значит двести токенов прибавляются не к одному
     * ходу, а ко всем последующим; уходят они только вместе с самим ходом —
     * отрезанием с конца или закрытием разговора.
     *
     * Отсюда и работа потолка [MAX_PAIRS]: он удерживает не цену одного хода, а
     * скорость, с которой растёт постоянная надбавка к каждому запросу.
     * Несколько найденных за разговор расхождений складываются.
     *
     * Разница с пояснением к записям, снятым ради экономии, при этом остаётся,
     * и она не в частоте: то пояснение стояло бы в каждом запросе с первого
     * хода и безусловно, а блок — начиная с того хода, где расхождение нашлось,
     * и только если оно нашлось.
     */
    const val QUOTE_CHARS = 40
}
