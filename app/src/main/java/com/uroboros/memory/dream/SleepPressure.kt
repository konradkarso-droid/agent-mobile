package com.uroboros.memory.dream

import com.uroboros.memory.Sticker

/**
 * Давление сна: насколько ночь, начатая сейчас, сплела бы иначе, чем последняя.
 *
 * ПОЧЕМУ СРАВНЕНИЕ НОЧЕЙ, А НЕ СУММА ПРИЗНАКОВ. Плетение ([DreamWeaver.weave])
 * зависит только от записей: ни часов, ни случайности. Поэтому вопрос «есть ли
 * смысл спать» решается прямо — сплести на пробу, в памяти, и сравнить со снами
 * последней ночи. Всё, что меняет сон (новая запись, скрытая или отвергнутая
 * запись, сдвиг потолка снов), попадает в число само, и только оно. Счётчики
 * «новых записей», «отклонений» и прочего по отдельности повторяли бы правила
 * плетения наизнанку и расходились бы с ним при первой его правке.
 *
 * Давление — сколько снов появилось бы и сколько ушло бы. Ноль значит, что ночь
 * сейчас сплела бы ровно те же сны: спать незачем. Это же защищает подачу снов:
 * [DreamRecall] берёт сны только последней ночи, и ночь-двойник обнулила бы для
 * подачи отметки «подан» у снов, которые на деле уже подавались.
 *
 * ЗДЕСЬ ТОЛЬКО МЕРА. Порога нет: решать, ложиться ли, — дело того, кто
 * запускает ночь. Функция ничего не пишет и никого не греет.
 *
 * ЧЕГО НЕ УМЕЕТ:
 *  - не взвешивает смысл: ушедший сон весит столько же, сколько новый, и
 *    сюжет — столько же, сколько связь по времени. Число — мера перемены, а не
 *    важности;
 *  - вопрос давления не даёт: сон вопросы пропускает, значит, и ночь от них не
 *    изменится. Разговор из одних вопросов не утомляет никогда;
 *  - новая запись, ни с кем не связавшаяся, давления тоже не даёт — ночь от неё
 *    не изменилась бы. На экране это сказано отдельно (см. [line]), иначе
 *    выросшее число записей при нулевом давлении читалось бы как поломка;
 *  - остывание записей по слоям перед пробой не зовётся: это запись в базу, а
 *    мера писать не должна. На то, КАКИЕ сны сплетутся, слой не влияет — только
 *    на счёт холодных и архивных в итоге ночи, который здесь не сравнивается;
 *  - цена — одно полное плетение на каждый замер, то есть столько же, сколько
 *    сама ночь (оценку по размеру памяти см. в [DreamWeaver]).
 */
object SleepPressure {

    data class Reading(
        /** Снов, которых в последней ночи не было. */
        val appeared: Int,
        /** Снов последней ночи, которые сейчас не сплелись бы. */
        val gone: Int,
        /** Сколько снов сплелось бы сейчас. */
        val dreamsNow: Int,
        /** Сколько записей участвовало бы сейчас. */
        val dreamersNow: Int,
        /** Сколько участвовало в последней ночи; null — ночей ещё не было. */
        val dreamersThen: Int?,
    ) {
        /** Само давление: перемена в обе стороны. */
        val changed: Int get() = appeared + gone
    }

    /**
     * @param lastDreams сны именно [lastNight] — сравнивать с чужой ночью
     *        значит получить давление, которого нет.
     *
     * Сны сравниваются цепочками номеров, а не строкой из базы: так формат
     * хранения ([Dream.recordIds]) может меняться, не ломая сравнение. Одна
     * цепочка — один сон, как и в ключе таблицы снов.
     */
    fun measure(records: List<Sticker>, lastNight: DreamNight?, lastDreams: List<Dream>): Reading {
        val woven = DreamWeaver.weave(records)
        val now = woven.dreams.map { it.recordIds }.toSet()
        if (lastNight == null) {
            return Reading(
                appeared = now.size, gone = 0, dreamsNow = now.size,
                dreamersNow = woven.dreamers, dreamersThen = null,
            )
        }
        val then = lastDreams.map { it.ids() }.toSet()
        return Reading(
            appeared = (now - then).size,
            gone = (then - now).size,
            dreamsNow = now.size,
            dreamersNow = woven.dreamers,
            dreamersThen = lastNight.dreamers,
        )
    }

    /**
     * Строка для экрана. Рядом с давлением всегда стоит, сколько записей сон
     * видит сейчас и видел тогда: ноль при изменившемся числе записей объяснён
     * словами, ноль при том же числе значит «ничего не изменилось».
     */
    fun line(reading: Reading): String = buildString {
        append("Давление сна: ")
        val then = reading.dreamersThen
        if (then == null) {
            append("ночей ещё не было — первая сплела бы снов ").append(reading.dreamsNow)
            append(" из записей ").append(reading.dreamersNow).append(".")
            return@buildString
        }
        append(reading.changed)
        if (reading.changed > 0) {
            append(" — следующая ночь сплела бы иначе: новых снов ").append(reading.appeared)
            append(", ушедших ").append(reading.gone)
        } else if (reading.dreamersNow != then) {
            append(" — сон видит записей ").append(reading.dreamersNow)
            append(" (прошлой ночью ").append(then).append("), но перемена ни с чем не связалась")
            append(".")
            return@buildString
        } else {
            append(" — с прошлой ночи сон не сплёл бы ничего иначе")
        }
        append(" · сон видит записей ").append(reading.dreamersNow)
        append(", прошлой ночью ").append(then).append(".")
    }
}
