package com.uroboros.memory.dream

import androidx.room.Entity
import com.uroboros.memory.RiskTrigger
import com.uroboros.memory.Sticker

/**
 * Один сон одной ночи: цепочка номеров записей, связанных ночным проходом.
 *
 * ЧТО ТАКОЕ СОН ЗДЕСЬ. Не вывод и не факт, а связь, которую сон нашёл между
 * записями по дешёвым признакам (см. [DreamWeaver]). Сон ничего не утверждает о
 * мире, поэтому судье не подаётся и в память фактов не пишется. Модели он
 * подаётся только со своей меткой происхождения (см. [DreamRecall]).
 *
 * ПОЧЕМУ НОМЕРА, А НЕ ТЕКСТ. Сон, хранящий готовые слова записей, продолжал бы
 * приносить их и после того, как запись скрыли на проверку или удалили: это был
 * бы обход карантина. Номера превращаются в текст только в момент показа или
 * подачи, и тогда сон со скрытым или исчезнувшим звеном молчит целиком (см.
 * [silences]).
 *
 * Номера — строкой через запятую, в порядке цепочки: у сюжета порядок и есть
 * сюжет. Строка, а не список через конвертер типов, по той же причине, что в
 * ленте: конвертер регистрируется на всей базе ради одного поля.
 *
 * Ключ — ночь и цепочка: одна и та же цепочка в одну ночь снится один раз, в
 * разные ночи — сколько угодно, и это разные сны.
 *
 * ПОДАН. [servedCount] и [lastServedAt] говорят, сколько раз и когда сон ушёл
 * модели в запросе. Это НЕ «вспомнен»: что модель сделала с поданным, отсюда не
 * видно. Пишет только [DreamServedDao].
 *
 * ВСПОМНЕН. [recalledCount] и [lastRecalledAt] — сколько раз и когда агент
 * использовал в ответе запись, принесённую этим сном (правило — в
 * [AgentRecall]). Вспомненный сон становится притоком реки в следующую ночь
 * (см. [DreamRiver]). Пишет только [AgentRecallDao].
 *
 * ПОДХВАЧЕН. [pickedUpCount] и [lastPickedUpAt] — сколько раз и когда владелец
 * в следующей реплике заговорил о том, что было в поданном сне (правило — в
 * [DreamPickup]). Это вес для любопытства и ничего больше: записи не греет, в
 * память не пишет, подтверждением не считается. С [recalledCount] не
 * сливается: одно — сигнал владельца, другое — агента, и слитый счёт не
 * показал бы, чей сигнал сжал пружину (см. [CuriosityPressure]). Пишет только
 * [DreamServedDao].
 *
 * СПРОШЕН. [askedAt] — когда владельцу было предложено спросить об этом сне
 * (правило — [CuriosityAsk]); null — не спрашивался. [answeredCount] и
 * [lastAnsweredAt] — сколько раз и когда владелец заговорил о спрошенном сне
 * в следующей реплике (тем же правилом, что подхват, см. [DreamPickup]). Это
 * НЕ «подхвачено»: подхват — сигнал владельца, а ответ на вопрос агента —
 * результат собственного действия агента. Слитые, они дали бы петлю: агент
 * спросил, владелец ответил, давление выросло, агент спросил снова (см.
 * [CuriosityPressure]). Пишет только [DreamServedDao].
 *
 * Строки копятся по ночам и сами не удаляются; при нынешнем потолке снов за
 * ночь это десятки тысяч коротких строк за год.
 */
@Entity(
    tableName = "dreams",
    primaryKeys = ["nightAt", "recordIds"],
)
data class Dream(
    /** Начало ночного прохода, мс. Все сны одной ночи несут одно значение. */
    val nightAt: Long,

    /** Номера записей цепочки через запятую, в порядке цепочки. */
    val recordIds: String,

    /** Имя значения [DreamWeaver.Kind] или [DreamRiver.KIND] для сна реки. */
    val kind: String,

    /** Сколько раз сон ушёл модели в запросе. */
    val servedCount: Int = 0,

    /** Когда ушёл в последний раз, мс; null — не подавался ни разу. */
    val lastServedAt: Long? = null,

    /** Сколько раз агент вспомнил принесённое этим сном. */
    val recalledCount: Int = 0,

    /** Когда вспомнил в последний раз, мс; null — ни разу. */
    val lastRecalledAt: Long? = null,

    /** Сколько раз владелец подхватил сон следующей репликой. */
    val pickedUpCount: Int = 0,

    /** Когда подхватил в последний раз, мс; null — ни разу. */
    val lastPickedUpAt: Long? = null,

    /** Когда предложено спросить о сне, мс; null — не спрашивался. */
    val askedAt: Long? = null,

    /** Сколько раз владелец ответил о сне после вопроса. */
    val answeredCount: Int = 0,

    /** Когда ответил в последний раз, мс; null — ни разу. */
    val lastAnsweredAt: Long? = null,
) {
    /** Номера цепочки по порядку. Нечитаемые куски пропускаются. */
    fun ids(): List<Long> = recordIds.split(",").mapNotNull { it.trim().toLongOrNull() }

    companion object {
        /**
         * Молчит ли сон из-за этого звена: записи нет, она на проверке, отвергнута
         * или ничего не утверждает (одни вопросы или просьбы,
         * RiskTrigger.assertsNothing). Одно правило для показа и для подачи — сон,
         * замолчавший на экране, не должен говорить модели, и наоборот.
         *
         * Почему молчит весь сон, а не одно звено: половина цепочки
         * бессмысленна, а мост через скрытую запись выдавал бы её содержание
         * соседями.
         *
         * Зачем проверять «ничего не утверждает», раз такие записи и так не
         * снятся: сны хранятся, а признак меняется. Сны, сплетённые до того, как
         * признак узнал запись, иначе продолжали бы подаваться со звеном, которое
         * новому плетению уже не досталось бы.
         */
        fun silences(record: Sticker?): Boolean =
            record == null || record.reviewPending || record.rejectedAt != null ||
                RiskTrigger.assertsNothing(record.content)
    }
}
