package com.uroboros.memory.dream

import androidx.room.Entity
import com.uroboros.memory.Sticker

/**
 * Один сон одной ночи: цепочка номеров записей, связанных ночным проходом.
 *
 * ЧТО ТАКОЕ СОН ЗДЕСЬ. Не вывод и не факт, а связь, которую сон нашёл между
 * записями по дешёвым признакам (см. [DreamWeaver]). Сон ничего не утверждает о
 * мире, поэтому судье не подаётся и в память фактов не пишется. Модели он
 * подаётся только со своей меткой происхождения (см. [DreamRecall]).
 *
 * ПОЧЕМУ НОМЕРА, А НЕ ТЕКСТ. Сон, хранящий готовые слова записей, продолжал бы
 * приносить их и после того, как запись скрыли на проверку или удалили: это был
 * бы обход карантина. Номера превращаются в текст только в момент показа или
 * подачи, и тогда сон со скрытым или исчезнувшим звеном молчит целиком (см.
 * [silences]).
 *
 * Номера — строкой через запятую, в порядке цепочки: у сюжета порядок и есть
 * сюжет. Строка, а не список через конвертер типов, по той же причине, что в
 * ленте: конвертер регистрируется на всей базе ради одного поля.
 *
 * Ключ — ночь и цепочка: одна и та же цепочка в одну ночь снится один раз, в
 * разные ночи — сколько угодно, и это разные сны.
 *
 * ПОДАН. [servedCount] и [lastServedAt] говорят, сколько раз и когда сон ушёл
 * модели в запросе. Это НЕ «вспомнен» и не «использован»: что модель сделала с
 * поданным, отсюда не видно, и поле с таким именем врало бы. Отметка копится
 * уже сейчас, хотя читать её пока некому: будущая река снов (сплетение между
 * ночами) идёт по поданным, а неотмеченная подача потеряна навсегда. Пишет её
 * только [DreamServedDao].
 *
 * ЧЕГО ЗДЕСЬ ЕЩЁ НЕТ: остывания снов и сплетения между ночами. Строки копятся по
 * ночам и сами не удаляются; при нынешнем потолке снов за ночь это десятки
 * тысяч коротких строк за год.
 */
@Entity(
    tableName = "dreams",
    primaryKeys = ["nightAt", "recordIds"],
)
data class Dream(
    /** Начало ночного прохода, мс. Все сны одной ночи несут одно значение. */
    val nightAt: Long,

    /** Номера записей цепочки через запятую, в порядке цепочки. */
    val recordIds: String,

    /** Имя значения [DreamWeaver.Kind]. */
    val kind: String,

    /** Сколько раз сон ушёл модели в запросе. */
    val servedCount: Int = 0,

    /** Когда ушёл в последний раз, мс; null — не подавался ни разу. */
    val lastServedAt: Long? = null,
) {
    /** Номера цепочки по порядку. Нечитаемые куски пропускаются. */
    fun ids(): List<Long> = recordIds.split(",").mapNotNull { it.trim().toLongOrNull() }

    companion object {
        /**
         * Молчит ли сон из-за этого звена: записи нет, она на проверке или
         * отвергнута. Одно правило для показа и для подачи — сон, замолчавший на
         * экране, не должен говорить модели, и наоборот.
         *
         * Почему молчит весь сон, а не одно звено: половина цепочки
         * бессмысленна, а мост через скрытую запись выдавал бы её содержание
         * соседями.
         */
        fun silences(record: Sticker?): Boolean =
            record == null || record.reviewPending || record.rejectedAt != null
    }
}
