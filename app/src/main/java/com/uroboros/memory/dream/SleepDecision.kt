package com.uroboros.memory.dream

/**
 * Ложиться ли агенту спать сейчас — и если нет, то почему, словами.
 *
 * Условия, и все должны сойтись:
 *  - ничего не идёт: ни генерация модели, ни разбор памяти. Сон посреди работы
 *    сплёл бы память, которую эта работа сейчас меняет;
 *  - давление сна не меньше [MIN_PRESSURE]: ночь сплела бы что-то иначе, чем
 *    прошлая (см. [SleepPressure]). Ночь-двойник не нужна и вредна;
 *  - тишины не меньше, чем требует давление ([quietNeededMs]). Чем больше
 *    накопилось, тем скорее агент засыпает — как у человека, которого
 *    сильная усталость валит быстрее. Тишина считается от конца последней
 *    генерации, а если в этом процессе её не было — от подъёма тела агента:
 *    после комы о прошлой тишине ничего не известно.
 *
 * ПОЧЕМУ ТИШИНА ВООБЩЕ. Ночи — это часы реки: приток живёт одну ночь, и ночь
 * после каждой реплики не оставила бы агенту времени вспомнить вчерашний сон
 * (см. [DreamRiver]). Пол тишины [QUIET_FLOOR_MS] держит «ночь на разговор», а
 * не «ночь на реплику», при любом давлении.
 *
 * Проверка в два шага ([gate], затем [decide] и [waitReason]): давление — это
 * пробное плетение всей памяти, и платить за него, пока не набран даже пол
 * тишины, незачем.
 *
 * ПОРОГИ — ЗДЕСЬ И ТОЛЬКО ЗДЕСЬ. Их меняет человек, правкой кода. У модели нет
 * пути ни к этому файлу, ни к числам в нём, и словами она сон не включает:
 * фраза в чужом тексте иначе стала бы рычагом. Решает агент — счётом.
 *
 * Решение терминальное — оно пишет ночь, — поэтому сомнение решается в сторону
 * «не спать». Пропущенный сон восстановим: давление никуда не денется до
 * следующей проверки.
 *
 * ЧЕГО НЕ УМЕЕТ:
 *  - тишина — это отсутствие генерации, а не отсутствие человека: пока он
 *    читает ответ, для решения уже тихо. Потому пол и в минутах;
 *  - давление считает перемены, а не их смысл: десять мелких перемен
 *    «утомляют» сильнее одной важной;
 *  - не знает, день или ночь: часы циферблата сюда намеренно не входят;
 *  - не спрашивает нагрев и заряд: сон — счёт в миллисекунды, и не греет.
 *    Судья, который греет, сюда не входит вовсе.
 */
object SleepDecision {

    /**
     * Тишина при самом малом давлении — тридцать минут. Стартовое число,
     * объявленное, а не подобранное.
     */
    const val QUIET_MAX_MS = 30L * 60 * 1000

    /**
     * Тишина при давлении [PRESSURE_FOR_TEN_MINUTES] — десять минут. Между
     * двумя опорами шкала прямая.
     */
    const val QUIET_AT_TEN_MS = 10L * 60 * 1000

    /** Давление, при котором хватает десяти минут тишины. */
    const val PRESSURE_FOR_TEN_MINUTES = 10

    /**
     * Пол: меньше пяти минут тишины не хватает ни при каком давлении.
     * Перепроверять по ночам с отметкой «уснул сам» — не засыпает ли агент
     * посреди живого разговора и не остывает ли река от слишком частых ночей.
     */
    const val QUIET_FLOOR_MS = 5L * 60 * 1000

    /**
     * Спать можно, если хоть один сон сплёлся бы иначе. Сколько ждать тишины,
     * решает шкала [quietNeededMs].
     */
    const val MIN_PRESSURE = 1

    /**
     * Сколько тишины нужно при давлении [pressure]: 30 минут при давлении 1,
     * 10 минут при 10, дальше по той же прямой, но не меньше пола.
     */
    fun quietNeededMs(pressure: Int): Long {
        val p = pressure.coerceAtLeast(MIN_PRESSURE)
        // Умножение до деления: шаг прямой нецелый в миллисекундах, и
        // округлённый шаг сдвинул бы опору «10 минут при 10».
        val drop = (p - 1).toLong() * (QUIET_MAX_MS - QUIET_AT_TEN_MS) / (PRESSURE_FOR_TEN_MINUTES - 1)
        return (QUIET_MAX_MS - drop).coerceAtLeast(QUIET_FLOOR_MS)
    }

    /**
     * Первый шаг, дешёвый: занят ли агент и набран ли пол тишины. null — можно
     * спрашивать давление; иначе — почему нельзя, словами для уведомления.
     */
    fun gate(nowMs: Long, busy: Boolean, quietSinceMs: Long): String? = when {
        busy -> "Не сплю: работаю."
        nowMs - quietSinceMs < QUIET_FLOOR_MS ->
            "Не сплю: тихо ${minutes(nowMs - quietSinceMs)} мин, меньше ${minutes(QUIET_FLOOR_MS)}."
        else -> null
    }

    /** Есть ли что обдумать. null — есть; иначе — почему спать незачем. */
    fun decide(pressure: Int): String? =
        if (pressure < MIN_PRESSURE) "Не сплю: с прошлой ночи сон не сплёл бы ничего иначе." else null

    /**
     * Хватает ли тишины для этого давления. null — хватает, спать; иначе —
     * сколько набрано и сколько нужно.
     */
    fun waitReason(pressure: Int, quietMs: Long): String? {
        val needed = quietNeededMs(pressure)
        return if (quietMs >= needed) null
        else "Не сплю: давление $pressure, тихо ${minutes(quietMs)} мин из ${minutes(needed)}."
    }

    private fun minutes(ms: Long): Int = (ms.coerceAtLeast(0) / 60_000).toInt()
}
