package com.uroboros.memory.dream

/**
 * Ложиться ли агенту спать сейчас — и если нет, то почему, словами.
 *
 * Три условия, и все должны сойтись:
 *  - ничего не идёт: ни генерация модели, ни разбор памяти. Сон посреди работы
 *    сплёл бы память, которую эта работа сейчас меняет;
 *  - тихо не меньше [QUIET_MS]. Тишина считается от конца последней генерации,
 *    а если в этом процессе её не было — от подъёма тела агента: после комы о
 *    прошлой тишине ничего не известно, и её отсчитывают заново;
 *  - давление сна не меньше [MIN_PRESSURE]: ночь сплела бы что-то иначе, чем
 *    прошлая (см. [SleepPressure]). Ночь-двойник не нужна и вредна.
 *
 * Давление спрашивается ПОСЛЕДНИМ и отдельно ([gate], затем [decide]): это
 * пробное плетение всей памяти, и платить за него, пока не тихо, незачем.
 *
 * ПОРОГИ — ЗДЕСЬ И ТОЛЬКО ЗДЕСЬ. Их меняет человек, правкой кода. У модели нет
 * пути ни к этому файлу, ни к числам в нём: всё, что агент может, — видеть,
 * почему он сейчас не спит.
 *
 * Решение терминальное — оно пишет ночь, — поэтому сомнение решается в сторону
 * «не спать». Пропущенный сон восстановим: давление никуда не денется до
 * следующей проверки.
 *
 * ЧЕГО НЕ УМЕЕТ:
 *  - тишина — это отсутствие генерации, а не отсутствие человека: пока он
 *    читает ответ, для решения уже тихо. Потому порог и в десятках минут;
 *  - не знает, день или ночь: часы циферблата сюда намеренно не входят;
 *  - не спрашивает нагрев и заряд: сон — счёт в миллисекунды, и не греет.
 *    Судья, который греет, сюда не входит вовсе.
 */
object SleepDecision {

    /**
     * Тридцать минут тишины. Стартовое число, объявленное, а не подобранное:
     * верно для разговора, где между репликами проходят минуты. Перепроверять
     * по ночам с отметкой «уснул сам» — не засыпает ли агент посреди живого
     * разговора и не тянет ли часами.
     */
    const val QUIET_MS = 30L * 60 * 1000

    /**
     * Спать, если хоть один сон сплёлся бы иначе. Сон стоит миллисекунды,
     * поэтому ждать, пока перемен накопится больше, незачем.
     */
    const val MIN_PRESSURE = 1

    /**
     * Первые два условия. null — можно спрашивать давление; иначе — почему
     * нельзя, словами для уведомления.
     */
    fun gate(nowMs: Long, busy: Boolean, quietSinceMs: Long): String? = when {
        busy -> "Не сплю: работаю."
        nowMs - quietSinceMs < QUIET_MS -> {
            val quietMin = ((nowMs - quietSinceMs).coerceAtLeast(0) / 60_000).toInt()
            "Не сплю: тихо $quietMin мин из ${QUIET_MS / 60_000}."
        }
        else -> null
    }

    /** Третье условие. null — спать; иначе — почему нет. */
    fun decide(pressure: Int): String? =
        if (pressure < MIN_PRESSURE) "Не сплю: с прошлой ночи сон не сплёл бы ничего иначе." else null
}
