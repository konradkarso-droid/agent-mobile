package com.uroboros.memory

import java.time.Instant
import java.time.ZoneId
import java.time.temporal.ChronoUnit

/**
 * Метки происхождения: чьё это и откуда. Одно место на всё, что уходит модели
 * или человеку с меткой, — записи памяти и сны. Следующие виды (голос, чужой
 * собеседник в группе) ложатся сюда же, а не в экран, где их пришлось бы
 * искать.
 *
 * ДВА ЧИТАТЕЛЯ — ДВЕ ФУНКЦИИ. [forModel] и [forScreen] различаются только
 * словами и намеренно НЕ объединены. Если их слить, любая правка подписи на
 * экране молча поменяет текст, который читает модель, — а это уже смена смысла
 * запроса, и обнаружится она не на экране, а по странным ответам через неделю.
 *
 * ПОЧЕМУ У МОДЕЛИ ФРАЗА, А НЕ МЕТКА. Техническую метку вида «[от пользователя]»
 * модель не читает как указание, чьи это слова: отвечала «в моей памяти нет
 * информации», когда запись лежала прямо в запросе, и пересказывала найденную
 * запись с чужим местоимением («мой любимый инструмент» вместо «ваш»). Поэтому
 * модели подаётся фраза на человеческом языке, а не метка: работу делает
 * грамматика, а не инструкция, и это дешевле отдельного абзаца объяснений в
 * каждом запросе.
 *
 * ПОЧЕМУ ФРАЗА ОТ ЛИЦА АГЕНТА. Малая модель не перестраивает подпись в свою
 * речь, а переписывает её в ответ как есть: подпись, обращённая к модели
 * («Тебе снилось», «Пользователь сказал»), уходила собеседнику дословно, и
 * агент говорил о себе на «ты», а о собеседнике — в третьем лице. Поэтому
 * подписи написаны так, как агент сказал бы их собеседнику сам: «Мне снилось»,
 * «Я сам вывел», «Твои слова». Тогда дословный пересказ и есть правильная
 * речь. Стена написана так же, от первого лица. «Твои слова», а не «ты
 * сказал»: пол собеседника неизвестен, а глагол прошедшего времени его
 * называет.
 *
 * ЧЕГО НЕ УМЕЕТ: метка держится на том, что модель читает грамматику так, как
 * задумано. Что 3B-модель не скажет о приснившемся «было» и не примет «ты» в
 * подписи на свой счёт, отсюда не видно — это проверяется только чтением её
 * ответов.
 */
object ProvenanceLabels {

    /** Происхождение записи — словами, обращёнными к модели. */
    fun forModel(sourceName: String): String = when (sourceName) {
        SourceKind.USER_STATED.name -> "Твои слова"
        SourceKind.AGENT_INFERRED.name -> "Я сам вывел"
        SourceKind.OCR_EXTRACTED.name -> "Распознано на картинке"
        // Честнее сказать «не записан», чем подставить пользователя или себя.
        // Перепутать, кто что сказал, система права не имеет.
        else -> UNKNOWN_FOR_MODEL
    }

    private const val UNKNOWN_FOR_MODEL = "Источник не записан"

    /**
     * Строка записи для модели: кто сказал, когда и что —
     * «Твои слова вчера вечером: «…».». Одна на все записи, уходящие в
     * ответ, включая принесённые ассоциацией и дверью сна.
     *
     * Подпись времени стоит в сказуемом, а не меткой, — по той же причине,
     * что и происхождение (см. шапку). У записи без источника сказуемого нет,
     * поэтому время там называется отдельно.
     *
     * Запись из ПРОШЛОГО ЭПИЗОДА (memory.nav.Episodes) получает впереди
     * подписи «в прошлом разговоре»: «Твои слова в прошлом разговоре, пару
     * часов назад: «…».». Без этого модель знает только время, а не то, что
     * разговор уже был другой. Эпизоды не известны (null) — подпись прежняя.
     */
    fun recordForModel(
        sticker: Sticker,
        now: Long,
        zone: ZoneId = ZoneId.systemDefault(),
        recordEpisode: Int? = null,
        currentEpisode: Int? = null,
    ): String {
        val time = recordTime(sticker, now, zone, recordEpisode, currentEpisode)
        val who = forModel(sticker.source)
        val head = if (who == UNKNOWN_FOR_MODEL) "Записано $time, источник не записан" else "$who $time"
        return "$head: «${sticker.content}»."
    }

    /**
     * Строка развёрнутой записи владельца (memory.nav.Retelling) для модели:
     * «С твоих слов в прошлом разговоре, вчера днём: ты …». Время и эпизод —
     * как в [recordForModel]. Без кавычек: это пересказ со стороны агента, а
     * не цитата — местоимения в [retold] уже повёрнуты.
     *
     * Почему «С твоих слов», а не «Твои слова», как у остальных записей
     * владельца. Замер стендом (модель 3B, вопрос «Что знаешь обо мне?», 24
     * ответа на вариант): при том же развёрнутом тексте «Твои слова» давали 7
     * верных ответов, «С твоих слов» — 15; подпись от лица агента («Пересказываю
     * тебя — …») — 6. Почему так, замер не объясняет — менять подпись только
     * после нового замера. Пол собеседника подпись не называет (правило в
     * шапке). Форма без эпизода («С твоих слов вчера днём: …») не мерена.
     */
    fun retoldForModel(
        sticker: Sticker,
        retold: String,
        now: Long,
        zone: ZoneId = ZoneId.systemDefault(),
        recordEpisode: Int? = null,
        currentEpisode: Int? = null,
    ): String = "$RETOLD_FOR_MODEL ${recordTime(sticker, now, zone, recordEpisode, currentEpisode)}: $retold"

    const val RETOLD_FOR_MODEL = "С твоих слов"

    /** Время записи для подписи: возраст и, для прошлого эпизода, приставка [PAST_EPISODE]. */
    private fun recordTime(
        sticker: Sticker,
        now: Long,
        zone: ZoneId,
        recordEpisode: Int?,
        currentEpisode: Int?,
    ): String {
        val age = ageForModel(sticker.createdAt, now, zone)
        val past = recordEpisode != null && currentEpisode != null && recordEpisode < currentEpisode
        return if (past) "$PAST_EPISODE, $age" else age
    }

    /**
     * Строка своей речи агента для модели (nav.OwnSpeech): «Я говорил в
     * прошлом разговоре, вчера вечером: «…».». От первого лица агента — по той
     * же причине, что вся шапка. Время — время хода ([ageForModel]); не
     * известно — «когда-то». Своя речь ищется только в архиве, то есть всегда
     * в прошлом эпизоде ([pastEpisode] по умолчанию истина). [drift] —
     * поправка на дрейф показаний (nav.Drift), встаёт за цитатой; пусто — без
     * поправки.
     */
    fun ownSpeechForModel(
        sentence: String,
        at: Long?,
        now: Long,
        zone: ZoneId = ZoneId.systemDefault(),
        pastEpisode: Boolean = true,
        drift: String = "",
    ): String {
        val age = at?.let { ageForModel(it, now, zone) } ?: "когда-то"
        val time = if (pastEpisode) "$PAST_EPISODE, $age" else age
        return "$OWN_SPEECH_FOR_MODEL $time: «$sentence».$drift"
    }

    const val OWN_SPEECH_FOR_MODEL = "Я говорил"

    /** Приставка записи из прошлого эпизода. */
    const val PAST_EPISODE = "в прошлом разговоре"

    /**
     * Когда запись сделана — словами. Ступени объявленные, не подобранные,
     * считая от момента хода:
     *  - меньше 60 минут — «меньше часа назад»;
     *  - меньше 3 часов — «пару часов назад»;
     *  - тот же календарный день — «сегодня утром / днём / вечером / ночью»
     *    по часу создания (5–12 утро, 12–17 день, 17–23 вечер, иначе ночь);
     *  - вчера по календарю — «вчера утром / днём / вечером / ночью»;
     *  - дальше по календарным дням местного времени устройства: на днях
     *    (2–5 дней), с неделю назад (6–13), пару недель назад (14–24), около
     *    месяца назад (25–59), давно (60 и больше).
     *
     * ПОЧЕМУ СТУПЕНИ МЕЛЬЧЕ СУТОК. Шкала только по календарю называла
     * разговор в 23:40, спрошенный в 00:40, честным «вчера», хотя прошёл час.
     * Модель не знает, который час, и хватается за любую подпись в ходе.
     *
     * ПОЧЕМУ ПО ДАТЕ СОЗДАНИЯ, А НЕ ПО СЛОЮ. Слой говорит о прогреве, а не о
     * возрасте: новые записи рождаются в зелёном («месяц»), прогретые старые
     * лежат в жёлтом, и подпись по слою врала бы в обе стороны.
     *
     * Запись «из будущего» (часы устройства переводили назад) называется
     * «сегодня», а не отрицательным временем.
     *
     * ЧЕГО ПОДПИСЬ НЕ УМЕЕТ.
     *  - При смене часового пояса сдвигается граница суток и часть дня: запись
     *    в 23:00 одного пояса в другом может стать «сегодня» вместо «вчера».
     *    Для нового места это верно.
     *  - Она считается от момента хода и остаётся в ленте как есть: через
     *    неделю старый ход по-прежнему говорит «меньше часа назад». Лента не
     *    подаёт одну и ту же строку дважды (ConversationJournal.unseenRecords
     *    сравнивает строки целиком), а подпись — часть строки. Поэтому запись,
     *    чья подпись сменила ступень, отбор подаст ещё раз, уже со свежей
     *    подписью: за жизнь записи — не больше девяти раз, и только если отбор
     *    снова её выберет. Это сознательный выбор, а не недосмотр: сверка без
     *    подписи оставила бы в ленте устаревшую подпись без обновления, и
     *    модель не отличила бы её от свежей.
     */
    fun ageForModel(createdAt: Long, now: Long, zone: ZoneId = ZoneId.systemDefault()): String {
        if (createdAt > now) return "сегодня"
        val elapsed = now - createdAt
        if (elapsed < HOUR_MS) return "меньше часа назад"
        if (elapsed < 3 * HOUR_MS) return "пару часов назад"
        val created = Instant.ofEpochMilli(createdAt).atZone(zone)
        val days = ChronoUnit.DAYS.between(
            created.toLocalDate(),
            Instant.ofEpochMilli(now).atZone(zone).toLocalDate(),
        )
        return when {
            days <= 0 -> "сегодня ${partOfDay(created.hour)}"
            days == 1L -> "вчера ${partOfDay(created.hour)}"
            days <= 5 -> "на днях"
            days <= 13 -> "с неделю назад"
            days <= 24 -> "пару недель назад"
            days <= 59 -> "около месяца назад"
            else -> "давно"
        }
    }

    private const val HOUR_MS = 60L * 60 * 1000

    private fun partOfDay(hour: Int): String = when (hour) {
        in 5 until 12 -> "утром"
        in 12 until 17 -> "днём"
        in 17 until 23 -> "вечером"
        else -> "ночью"
    }

    /** Происхождение записи — меткой для человека на экране. */
    fun forScreen(sourceName: String): String = when (sourceName) {
        SourceKind.USER_STATED.name -> "[от пользователя]"
        SourceKind.AGENT_INFERRED.name -> "[вывод агента]"
        SourceKind.OCR_EXTRACTED.name -> "[из скриншота]"
        else -> "[?]"
    }

    /**
     * Подпись, которой сон подавался модели. Для новых строк не используется:
     * сны модели больше не подаются (почему — в шапке dream.DreamRecall).
     * Остаётся, чтобы показ ленты узнавал строки сна в старых ходах (см.
     * dream.DreamRecall.isDreamLine).
     */
    const val DREAM_FOR_MODEL = "Мне снилось"
}
