package com.uroboros.memory

import java.time.Instant
import java.time.ZoneId
import java.time.temporal.ChronoUnit

/**
 * Метки происхождения: чьё это и откуда. Одно место на всё, что уходит модели
 * или человеку с меткой, — записи памяти и сны. Следующие виды (голос, чужой
 * собеседник в группе) ложатся сюда же, а не в экран, где их пришлось бы
 * искать.
 *
 * ДВА ЧИТАТЕЛЯ — ДВЕ ФУНКЦИИ. [forModel] и [forScreen] различаются только
 * словами и намеренно НЕ объединены. Если их слить, любая правка подписи на
 * экране молча поменяет текст, который читает модель, — а это уже смена смысла
 * запроса, и обнаружится она не на экране, а по странным ответам через неделю.
 *
 * ПОЧЕМУ У МОДЕЛИ ФРАЗА, А НЕ МЕТКА. Техническую метку вида «[от пользователя]»
 * модель не читает как указание, чьи это слова: отвечала «в моей памяти нет
 * информации», когда запись лежала прямо в запросе, и пересказывала найденную
 * запись с чужим местоимением («мой любимый инструмент» вместо «ваш»). Поэтому
 * модели подаётся фраза на человеческом языке, а не метка: работу делает
 * грамматика, а не инструкция, и это дешевле отдельного абзаца объяснений в
 * каждом запросе.
 *
 * ПОЧЕМУ ФРАЗА ОТ ЛИЦА АГЕНТА. Малая модель не перестраивает подпись в свою
 * речь, а переписывает её в ответ как есть: подпись, обращённая к модели
 * («Тебе снилось», «Пользователь сказал»), уходила собеседнику дословно, и
 * агент говорил о себе на «ты», а о собеседнике — в третьем лице. Поэтому
 * подписи написаны так, как агент сказал бы их собеседнику сам: «Мне снилось»,
 * «Я сам вывел», «Твои слова». Тогда дословный пересказ и есть правильная
 * речь. Стена написана так же, от первого лица. «Твои слова», а не «ты
 * сказал»: пол собеседника неизвестен, а глагол прошедшего времени его
 * называет.
 *
 * ЧЕГО НЕ УМЕЕТ: метка держится на том, что модель читает грамматику так, как
 * задумано. Что 3B-модель не скажет о приснившемся «было» и не примет «ты» в
 * подписи на свой счёт, отсюда не видно — это проверяется только чтением её
 * ответов.
 */
object ProvenanceLabels {

    /** Происхождение записи — словами, обращёнными к модели. */
    fun forModel(sourceName: String): String = when (sourceName) {
        SourceKind.USER_STATED.name -> "Твои слова"
        SourceKind.AGENT_INFERRED.name -> "Я сам вывел"
        SourceKind.OCR_EXTRACTED.name -> "Распознано на картинке"
        // Честнее сказать «не записан», чем подставить пользователя или себя.
        // Перепутать, кто что сказал, система права не имеет.
        else -> UNKNOWN_FOR_MODEL
    }

    private const val UNKNOWN_FOR_MODEL = "Источник не записан"

    /**
     * Строка записи для модели: кто сказал, когда и что —
     * «Твои слова вчера: «…».». Одна на все записи, уходящие в
     * ответ, включая принесённые дверью сна; строк снов не касается.
     *
     * Подпись времени стоит в сказуемом, а не меткой, — по той же причине,
     * что и происхождение (см. шапку). У записи без источника сказуемого нет,
     * поэтому время там называется отдельно.
     */
    fun recordForModel(sticker: Sticker, now: Long, zone: ZoneId = ZoneId.systemDefault()): String {
        val age = ageForModel(sticker.createdAt, now, zone)
        val who = forModel(sticker.source)
        val head = if (who == UNKNOWN_FOR_MODEL) "Записано $age, источник не записан" else "$who $age"
        return "$head: «${sticker.content}»."
    }

    /**
     * Когда запись сделана — словами, огрублёнными по календарным дням
     * местного времени устройства: сегодня, вчера, на днях (2–5 дней), с
     * неделю назад (6–13), пару недель назад (14–24), около месяца назад
     * (25–59), давно (60 и больше). Границы объявленные, не подобранные.
     *
     * ПОЧЕМУ ПО ДАТЕ СОЗДАНИЯ, А НЕ ПО СЛОЮ. Слой говорит о прогреве, а не о
     * возрасте: новые записи рождаются в зелёном («месяц»), прогретые старые
     * лежат в жёлтом, и подпись по слою врала бы в обе стороны.
     *
     * Запись «из будущего» (часы устройства переводили назад) называется
     * «сегодня», а не отрицательным числом дней.
     *
     * ЧЕГО ПОДПИСЬ НЕ УМЕЕТ. Она считается от момента хода и остаётся в
     * ленте как есть: через неделю старый ход по-прежнему говорит «сегодня».
     * Лента не подаёт одну и ту же строку дважды (ConversationJournal.
     * unseenRecords сравнивает строки целиком), а подпись — часть строки.
     * Поэтому запись, чья подпись сменила ступень, отбор подаст ещё раз, уже
     * со свежей подписью: за жизнь записи — не больше семи раз, и только если
     * отбор снова её выберет. Это сознательный выбор, а не недосмотр: сверка
     * без подписи оставила бы в ленте устаревшую подпись без обновления, и
     * модель не отличила бы её от свежей. Записи, легшие в ленту до появления
     * подписи, по той же причине подаются заново один раз.
     */
    fun ageForModel(createdAt: Long, now: Long, zone: ZoneId = ZoneId.systemDefault()): String {
        val days = ChronoUnit.DAYS.between(
            Instant.ofEpochMilli(createdAt).atZone(zone).toLocalDate(),
            Instant.ofEpochMilli(now).atZone(zone).toLocalDate(),
        )
        return when {
            days <= 0 -> "сегодня"
            days == 1L -> "вчера"
            days <= 5 -> "на днях"
            days <= 13 -> "с неделю назад"
            days <= 24 -> "пару недель назад"
            days <= 59 -> "около месяца назад"
            else -> "давно"
        }
    }

    /** Происхождение записи — меткой для человека на экране. */
    fun forScreen(sourceName: String): String = when (sourceName) {
        SourceKind.USER_STATED.name -> "[от пользователя]"
        SourceKind.AGENT_INFERRED.name -> "[вывод агента]"
        SourceKind.OCR_EXTRACTED.name -> "[из скриншота]"
        else -> "[?]"
    }

    /**
     * Происхождение сна — для модели. Сон не утверждает, что было: он
     * связывает записи по дешёвым признакам (см. dream.DreamWeaver). Той же
     * грамматикой и от того же лица, что у записей (см. шапку): «Мне снилось:
     * …» само говорит, что это сон, и пересказанное дословно остаётся правдой.
     */
    const val DREAM_FOR_MODEL = "Мне снилось"
}
