package com.uroboros.memory

/**
 * Метки происхождения: чьё это и откуда. Одно место на всё, что уходит модели
 * или человеку с меткой, — записи памяти и сны. Следующие виды (голос, чужой
 * собеседник в группе) ложатся сюда же, а не в экран, где их пришлось бы
 * искать.
 *
 * ДВА ЧИТАТЕЛЯ — ДВЕ ФУНКЦИИ. [forModel] и [forScreen] различаются только
 * словами и намеренно НЕ объединены. Если их слить, любая правка подписи на
 * экране молча поменяет текст, который читает модель, — а это уже смена смысла
 * запроса, и обнаружится она не на экране, а по странным ответам через неделю.
 *
 * ПОЧЕМУ У МОДЕЛИ ФРАЗА, А НЕ МЕТКА. Техническую метку вида «[от пользователя]»
 * модель не читает как указание, чьи это слова: отвечала «в моей памяти нет
 * информации», когда запись лежала прямо в запросе, и пересказывала найденную
 * запись с чужим местоимением («мой любимый инструмент» вместо «ваш»). Поэтому
 * модели подаётся подлежащее со сказуемым — «Пользователь сказал: «…»»: работу
 * делает грамматика, а не инструкция, и это дешевле отдельного абзаца
 * объяснений в каждом запросе.
 *
 * ЧЕГО НЕ УМЕЕТ: метка держится на том, что модель читает грамматику так, как
 * задумано. Что 3B-модель не скажет о приснившемся «было», отсюда не видно —
 * это проверяется только чтением её ответов.
 */
object ProvenanceLabels {

    /** Происхождение записи — словами, обращёнными к модели. */
    fun forModel(sourceName: String): String = when (sourceName) {
        SourceKind.USER_STATED.name -> "Пользователь сказал"
        SourceKind.AGENT_INFERRED.name -> "Ты сам вывел"
        SourceKind.OCR_EXTRACTED.name -> "Распознано на картинке"
        // Честнее сказать «не записан», чем подставить пользователя или себя.
        // Перепутать, кто что сказал, система права не имеет.
        else -> "Источник не записан"
    }

    /** Происхождение записи — меткой для человека на экране. */
    fun forScreen(sourceName: String): String = when (sourceName) {
        SourceKind.USER_STATED.name -> "[от пользователя]"
        SourceKind.AGENT_INFERRED.name -> "[вывод агента]"
        SourceKind.OCR_EXTRACTED.name -> "[из скриншота]"
        else -> "[?]"
    }

    /**
     * Происхождение сна — для модели. Сон не утверждает, что было: он
     * связывает записи по дешёвым признакам (см. dream.DreamWeaver). Той же
     * грамматикой, что у записей: «Тебе снилось: …» само говорит, что это
     * сон, и подсказывает, как о нём сказать — «мне снилось».
     */
    const val DREAM_FOR_MODEL = "Тебе снилось"
}
