package com.uroboros.memory

/**
 * Прибор входа в очередь на проверку: сколько сохранений прошло через сравнение
 * на противоречие и сколько из них встало в очередь — отдельно по спору и
 * отдельно по сбою самого сравнения.
 *
 * ЗАЧЕМ. Число "На проверке: N" — это уровень очереди, а не поток в неё. Оно
 * падает, когда человек разбирает очередь, поэтому при быстром разборе оно
 * близко к нулю при любой частоте прихода, и узнать по нему, часто ли приходят
 * дела, нельзя в принципе. Решение о том, нужен ли памяти судья, стоит на
 * утверждении "дел доходит мало" — проверяется оно только счётом входов.
 *
 * ПОЧЕМУ СПОР И СБОЙ СЧИТАЮТСЯ ПОРОЗНЬ. Бит в базе означает "запись не годится
 * в выдачу" и ставится в обоих случаях; различить их по самой базе нечем.
 * Слитый счёт сделал бы невидимым главный промах: систематически падающее
 * сравнение выглядит в точности как всплеск споров — очередь растёт, человек её
 * разбирает, а механизм при этом мёртв.
 *
 * ПОЧЕМУ ПРИБОР СЧИТАЕТ ПРОВЕРКИ САМ, хотя число записей в базе даёт примерно
 * то же. Это второй канал показаний, а не знаменатель. Неподключённый или
 * незаметно сломанный прибор показывал бы ноль входов при растущей базе, и ноль
 * прочитался бы как "споров нет" — то есть как ответ, ради которого прибор и
 * строился. Два числа живут в разных отчётах, порога расхождения нет
 * намеренно: сравнивает человек.
 *
 * ЧЕГО ПРИБОР НЕ УМЕЕТ:
 *  - он меряет ВХОД в очередь, а не количество противоречий в памяти. Пара,
 *    сложившаяся в базе вне момента сохранения, не видна ему вовсе: сравнение
 *    зовётся один раз за жизнь записи и лежащие записи не пересматривает;
 *  - он не знает, что стало с записью дальше — принята она человеком или ждёт;
 *  - счёт обнуляется очисткой данных приложения. Поэтому момент начала счёта
 *    хранится рядом со счётом и печатается: без него ноль неотличим от "не
 *    считали".
 *
 * Класс без Android намеренно: укладка на диск вынесена в [ReviewWitnessStore],
 * благодаря чему прибор запускается в обычном JVM-юнит-тесте. Время передаётся
 * снаружи по той же причине.
 */

/** Чем кончилась проверка одного сохранения. */
enum class ReviewEntry {
    /** Сравнение прошло, спора нет — запись видна сразу. */
    CLEAN,

    /** Сравнение нашло противоречие — запись встала в очередь. */
    DISPUTE,

    /** Сравнение не состоялось — запись встала в очередь непроверенной. */
    FAILURE
}

/**
 * Показания прибора. Четыре числа держатся вместе и порознь мало что значат:
 * без [checks] нельзя отличить "дел не было" от "прибор не считает", без
 * [startedAt] — "дел не было" от "счёт начали вчера".
 */
data class ReviewCounts(
    /** Сколько сохранений прошло через сравнение. */
    val checks: Long,
    /** Из них встало в очередь из-за найденного противоречия. */
    val disputes: Long,
    /** Из них встало в очередь из-за падения самого сравнения. */
    val failures: Long,
    /** Момент первого отсчёта (мс). */
    val startedAt: Long
)

/**
 * Куда прибор кладёт показания, чтобы они пережили перезапуск процесса.
 *
 * Отдельный интерфейс, а не прямая работа с хранилищем: сам прибор обязан
 * оставаться без Android, иначе его нельзя ни протестировать, ни держать в том
 * же слое, что и остальная память.
 *
 * Реализация имеет право бросить исключение — прибор его поймает и скажет об
 * этом в отчёте. Ронять сохранение записи из-за потери показания нельзя:
 * потерянное показание восстановимо наблюдением, потерянная запись нет.
 */
interface ReviewWitnessStore {
    /**
     * Переживают ли показания перезапуск. Печатается в отчёте: прибор, чей счёт
     * умирает вместе с процессом, систематически показывает "дел мало" — ровно
     * тот вывод, который он должен проверять, поэтому молчать об этом нельзя.
     */
    val persistent: Boolean

    /** Показания прошлых запусков, либо null, если их ещё нет. */
    fun load(): ReviewCounts?

    /** Уложить показания. */
    fun save(counts: ReviewCounts)
}

/**
 * Заглушка для случая, когда прибор собран без укладки: счёт идёт, но живёт до
 * перезапуска. Молчаливой деградации здесь нет — [ReviewWitness.report] говорит
 * об этом первой же строкой про укладку.
 */
object NoReviewWitnessStore : ReviewWitnessStore {
    override val persistent: Boolean = false
    override fun load(): ReviewCounts? = null
    override fun save(counts: ReviewCounts) = Unit
}

class ReviewWitness(private val store: ReviewWitnessStore = NoReviewWitnessStore) {

    private var counts: ReviewCounts? = null

    /**
     * Сколько раз укладка отказала. Само это число уложить некуда — хранилище
     * и есть то, что сломалось, — поэтому оно живёт до перезапуска и говорит
     * только о текущем запуске.
     */
    private var storeFailures: Int = 0

    /**
     * Учесть одну проверку. Зовётся на КАЖДОМ сохранении, а не только на тех,
     * что встали в очередь: без этого ноль дел неотличим от неработающего
     * прибора.
     */
    @Synchronized
    fun note(entry: ReviewEntry, now: Long = System.currentTimeMillis()) {
        val current = loaded(now)
        val updated = when (entry) {
            ReviewEntry.CLEAN -> current.copy(checks = current.checks + 1)
            ReviewEntry.DISPUTE -> current.copy(
                checks = current.checks + 1,
                disputes = current.disputes + 1
            )
            ReviewEntry.FAILURE -> current.copy(
                checks = current.checks + 1,
                failures = current.failures + 1
            )
        }
        counts = updated
        try {
            store.save(updated)
        } catch (e: Exception) {
            storeFailures++
        }
    }

    /** Показания как есть — для проверок и для того, кто захочет считать сам. */
    @Synchronized
    fun counts(now: Long = System.currentTimeMillis()): ReviewCounts = loaded(now)

    /**
     * Человекочитаемый вид. Возвращается строка, а не объект: за пределами
     * памяти показания нужны только чтобы их показать, и ветвиться по ним в UI
     * значило бы решать про память мимо того, кто её ведёт.
     */
    @Synchronized
    fun report(now: Long = System.currentTimeMillis()): String {
        val c = loaded(now)
        val days = (now - c.startedAt) / MemorySnapshot.MS_IN_DAY
        return buildString {
            appendLine("ПРИБОР ОЧЕРЕДИ")
            appendLine("Проверок:           ${c.checks}")
            appendLine("Встало по спору:    ${c.disputes}")
            appendLine("Встало по сбою:     ${c.failures}")
            appendLine(
                if (days == 0L) "Считаем:            менее суток"
                else "Считаем:            $days дн."
            )
            appendLine(
                when {
                    !store.persistent ->
                        "Укладка:            не подключена — счёт до перезапуска"
                    storeFailures > 0 ->
                        "Укладка:            отказов $storeFailures — показания под сомнением"
                    else ->
                        "Укладка:            работает"
                }
            )
            // Сверять глазами со строкой "Всего записей" из снимка памяти:
            // проверок должно быть примерно столько же. Порога расхождения нет
            // намеренно — числа приходят с разных сторон и совпасть обязаны
            // только по порядку величины.
            appendLine("Сверить с числом записей в снимке памяти.")
        }.trimEnd()
    }

    /**
     * Показания текущего запуска, поднятые из укладки при первом обращении.
     *
     * Подъём отложен до первого обращения намеренно: сборка прибора происходит
     * при создании фасада памяти, и чтение с диска в этот момент легло бы на
     * поток, который его создаёт.
     */
    private fun loaded(now: Long): ReviewCounts {
        counts?.let { return it }
        val stored = try {
            store.load()
        } catch (e: Exception) {
            storeFailures++
            null
        }
        val fresh = stored ?: ReviewCounts(
            checks = 0,
            disputes = 0,
            failures = 0,
            startedAt = now
        )
        counts = fresh
        return fresh
    }
}
