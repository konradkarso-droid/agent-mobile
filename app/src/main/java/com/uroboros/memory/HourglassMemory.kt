package com.uroboros.memory

import android.util.Log

/**
 * Строка важности → число для сортировки, по убыванию: LOW=0, MEDIUM=1, HIGH=2.
 * Неизвестное значение не роняет выборку, а получает ранг LOW.
 *
 * Почему LOW, а не середина: значение колонки по умолчанию — MEDIUM, поэтому при
 * запасном варианте MEDIUM честная средняя запись и нечитаемая попадают в одну
 * корзину и больше ничем не различаются. LOW их разводит.
 *
 * Правило записано в проекте дважды, и свести копии в одно место нельзя: вторая
 * живёт строкой SQL в @Query у StickerDao.getRanked, а SQL не может позвать
 * функцию Kotlin. Равенство копий держится снаружи — ImportanceRankTest падает,
 * если в Importance добавить значение, переставить объявления или разойтись
 * запасным вариантом. Меняя одно место, меняйте второе.
 *
 * Чего механизм НЕ умеет: он молчит. Ни здесь, ни в SQL срабатывание запасного
 * варианта ничем не отмечается, поэтому мусорное значение важности неотличимо от
 * честного LOW. Сегодня это безвредно — importance не пишет никто, — но в день,
 * когда путь к записи появится, отметку надо завести раньше самой записи.
 *
 * internal, а не private, только ради теста.
 */
internal fun importanceRank(raw: String): Int =
    runCatching { Importance.valueOf(raw).ordinal }.getOrDefault(Importance.LOW.ordinal)

/**
 * Зачем обратились к памяти. Указывается обязательно, значения по умолчанию нет —
 * тот же приём и та же причина, что у source/confidence в TrustedMediator.saveEvent:
 * умолчание молча приписало бы обращению чужой смысл.
 *
 * Ось здесь "зачем", а не "кто спрашивает", и это не оговорка. Пользователь стоит по
 * обе её стороны: вопрос агенту и просмотр памяти оба идут от него, но пользу
 * приносит только первый. Просмотр — это диагностика, и засчитывать её значило бы
 * записывать в пользу каждый осмотр памяти хозяином.
 */
enum class RetrievalPurpose {
    /** Записи уйдут в ответ на вопрос пользователя. Только это засчитывается. */
    ANSWERING_USER,

    /** Память просто показывают. Не засчитывается ничего. */
    BROWSING,

    /**
     * Читает сам агент, для собственной работы. Сегодня таких вызовов в проекте нет
     * ни одного: значение объявлено заранее, чтобы тот, кто первым приведёт агента к
     * памяти, был вынужден назвать это явно, а не подставил ближайшее подходящее.
     * Не засчитывается — иначе система накачивала бы важность собственных записей
     * и через неё лепила свой будущий контекст.
     */
    AGENT_INTERNAL
}

/**
 * Кому из выданных записей засчитывается польза. Чистая функция: ни базы, ни
 * Android — затем и вынесена, чтобы правило можно было закрепить тестом.
 *
 * Правил здесь два, и оба должны быть видны с одного взгляда. Засчитывается только
 * при ANSWERING_USER, и только тем, кто нашёлся по словам вопроса: принципы приезжают
 * из getRanked по слою, ни с какими словами не совпадали, и платить им было бы за
 * попадание в выдачу, а попаданием распоряжается сортировка по важности — вышла бы
 * обратная связь, снятая с собственного выхода.
 *
 * Запись, попавшая и в принципы, и в совпадения, отметку получает: она действительно
 * совпала, а порядок сборки списка к этому отношения не имеет.
 *
 * Чего эта функция НЕ проверяет: она не знает, правда ли matched собран по словам
 * вопроса и доходит ли отметка до базы. Тест закрепляет правило, а не проводку.
 * Проводка проверена на устройстве двусторонней приёмкой: при вопросе агенту отметка
 * появляется, при повторных нажатиях "Показать" с тем же запросом accessCount растёт,
 * а отметок остаётся столько же. Юнит-тестом проводка не покрыта и сейчас, но
 * причина другая, чем была: путь выборки больше не пишет в android.util.Log —
 * он ходит в базу, а подставного DAO в сборке пока нет.
 */
internal fun usefulnessMarks(
    purpose: RetrievalPurpose,
    returned: List<Long>,
    matched: Set<Long>
): Set<Long> =
    if (purpose != RetrievalPurpose.ANSWERING_USER) emptySet()
    else returned.filter { it in matched }.toSet()

// Два порога ниже стояли в private companion object класса и вынесены сюда
// вместе с правилом, которое их читает: число и единственное место, где оно
// применяется, должны лежать рядом, иначе правка одного не видна из другого.
// Плата за вынос — видимость: теперь их видит весь модуль. Звать их больше
// неоткуда, и появление второго места, где они понадобились, — повод
// пересмотреть отбор, а не переиспользовать число.

/**
 * Проверка 1. Какую долю значимых слов вопроса запись обязана покрыть.
 *
 * Половина: одно слово из четырёх — случайность, два из четырёх — уже разговор
 * об одном и том же. Ровно половина ПРОХОДИТ, и это часть правила, а не деталь
 * записи: сравнение в scoreCandidate строгое намеренно.
 *
 * Область. Доля считается от числа значимых слов вопроса, а знаменатель задаёт
 * список STOP_WORDS: добавленное туда слово меняет смысл этого порога, не меняя
 * самого числа. Перепроверяется строкой вердикта по кандидату (см. trace в
 * SelectionResult).
 */
internal const val MIN_COVERAGE = 0.5

/**
 * Проверка 2. Сколько знаков объёма записи допустимо на один знак совпадения.
 *
 * Замеры на живой базе 29.08.2026: фраза пользователя, честно относящаяся к
 * вопросу, — 1.4-9.5; лог прогона TOTE, зацепившийся случайным обрубком внутри
 * комментария, — 67. Порог поставлен между ними с запасом в обе стороны, а не
 * впритык к наблюдённому. Ровно пороговое значение проходит.
 *
 * Область: база из 13 записей, вопросы в 3-6 значимых слов, записи до сотен
 * знаков. На длинных вопросах и на записях в тысячи знаков не проверялся.
 * Перепроверяется той же строкой вердикта.
 */
internal const val MAX_CHARS_PER_MATCH = 20.0

/**
 * Меры кандидата вместе с вердиктом по нему.
 *
 * Одна величина, а не две. Вердикт получается из мер прямо здесь, и разнести их
 * по разным местам значило бы позволить им разойтись: строка на экране начала бы
 * говорить одно, а отбор делать другое, и увидеть это было бы неоткуда.
 */
internal data class CandidateScore(
    /** Сколько РАЗНЫХ слов вопроса нашли эту запись. */
    val matchedWords: Int,
    /** Доля слов вопроса, покрытых записью: 0.0 … 1.0. */
    val coverage: Double,
    /**
     * Насколько точны совпадения: 1.0 — все слова нашлись целиком, меньше —
     * находились укороченными. Отдельная величина, НЕ смешанная с долей и
     * ценой: точное совпадение не должно выкупаться количеством размытых.
     */
    val precision: Double,
    /** Сколько знаков объёма записи приходится на один знак совпадения. */
    val charsPerMatch: Double,
    val tooNarrow: Boolean,
    val tooExpensive: Boolean
) {
    val passed: Boolean get() = !tooNarrow && !tooExpensive

    /** Причина словами. Признака ровно два, других причин отсева нет. */
    val verdict: String
        get() = when {
            tooNarrow && tooExpensive -> "отсев: узко и дорого"
            tooNarrow -> "отсев: узко"
            tooExpensive -> "отсев: дорого"
            else -> "взято"
        }
}

/**
 * В каком состоянии закончился отбор под запрос — и текст, которым это состояние
 * называется человеку.
 *
 * Зачем запечатанный тип, а не набор чисел. Состояний пять, и часть из них при
 * счёте нулями неразличима: "искать было не по чему" и "искали, не нашли ни
 * одного" дали бы одинаковые нули, хотя лечатся противоположным — первое требует
 * задать вопрос словами, второе двинуть пороги. Тот же довод, по которому
 * StopCause сделан одной ссылкой вместо двух обнуляемых полей.
 *
 * Текст живёт здесь, а не на экране: так его проверяет обычный тест, без
 * устройства и без разметки.
 *
 * ЧЕГО ЭТИ ЧИСЛА НЕ СЧИТАЮТ. Все они считают записи, которые ПРИНЁС поиск.
 * Запись, до которой лестница префиксов не дотянулась, не попадает ни в
 * кандидатов, ни в отсеянных — она не появляется на экране никак и ни одним
 * числом не названа. Это как раз потеря в невосстановимую сторону, и заметить её
 * этими числами нельзя: они говорят, что случилось с найденным, а не о том, всё
 * ли найдено.
 */
internal sealed class SelectionSummary {

    /** Одна строка для экрана. */
    abstract val text: String

    /** Вопроса не было: отдан срез памяти по рангу, поиск не запускался. */
    object NoQuery : SelectionSummary() {
        override val text =
            "Отбор не выполнялся: вопроса не было — показан срез памяти по рангу."
    }

    /**
     * Место в выдаче целиком заняли принципы, на поиск не осталось ни одного
     * места. Отдельное состояние, а не "ничего не нашли": лечится оно лимитом
     * выдачи, а не порогами отбора, и спутать эти два лечения дорого.
     */
    object NoRoom : SelectionSummary() {
        override val text =
            "Отбор не выполнялся: всю выдачу заняли принципы — увеличьте лимит."
    }

    /** В вопросе не осталось слов, по которым можно искать. */
    object NoSearchableWords : SelectionSummary() {
        override val text =
            "Отбор не выполнялся: в вопросе нет слов длиннее трёх букв, " +
                "не считая общеупотребительных."
    }

    /** Искали, но ни одна запись не нашлась ни на одной ступени. */
    data class NothingFound(val words: Int) : SelectionSummary() {
        override val text = "Отбор: слов $words · не нашлось ни одной записи."
    }

    /**
     * Кандидаты нашлись и были взвешены.
     *
     * passed и shown разделены намеренно. Прошедшие отбор режутся ещё и лимитом
     * выдачи, и запись, потерянная лимитом, со стороны выглядит точно так же,
     * как отсеянная порогом, — а лечится противоположным. Из трёх способов не
     * дойти до экрана этот единственный, о котором иначе нельзя было бы узнать.
     */
    data class Weighed(
        val words: Int,
        val candidates: Int,
        val passed: Int,
        val shown: Int,
        val tooNarrow: Int,
        val tooExpensive: Int,
        val tooBoth: Int
    ) : SelectionSummary() {

        val rejected: Int get() = tooNarrow + tooExpensive + tooBoth
        val trimmed: Int get() = passed - shown

        override val text: String
            get() {
                val head =
                    "Отбор: слов $words · кандидатов $candidates · " +
                        "прошло $passed · показано $shown"
                val trim = if (trimmed > 0) " (лимит отрезал $trimmed)" else ""
                val why =
                    if (rejected == 0) " · отсеяно 0"
                    else " · отсеяно $rejected: " + listOfNotNull(
                        if (tooNarrow > 0) "узко $tooNarrow" else null,
                        if (tooExpensive > 0) "дорого $tooExpensive" else null,
                        if (tooBoth > 0) "узко и дорого $tooBoth" else null
                    ).joinToString(", ")
                return head + trim + why
            }
    }
}

/**
 * Записи под запрос вместе с готовой строкой о том, как отбор к ним пришёл.
 *
 * Строка, а не сам SelectionSummary: за пределами памяти состояние отбора нужно
 * только чтобы его показать, а отдавать наружу тип, по которому кто-то начнёт
 * ветвиться, значило бы вынести решение об отборе за пределы того, кто отбирает.
 * Так же устроена канарейка — memoryCanaryReport() тоже отдаёт готовый текст.
 */
data class ContextResult(
    val stickers: List<Sticker>,
    val summary: String,
    /**
     * Построчный разбор отбора: по строке на каждую ступень каждого слова и по
     * строке на каждого взвешенного кандидата. Нужен при калибровке порогов —
     * обычно уезжает в лог, на экран не выводится.
     *
     * Отдельное поле, а не хвост к summary. Слить их в один текст значило бы
     * либо вывалить на экран несколько десятков служебных строк, либо, при
     * обрезке, потерять сам разбор — то есть ровно то, ради чего он собирается.
     *
     * Границы. Это отчёт ОДНОЙ ТОЛЬКО лестницы: в нём нет ни канала принципов,
     * ни того, что поиск не нашёл. Пустой список означает "поиск не запускался",
     * а не "ничего не происходило". Содержимого записей строки не несут — только
     * идентификаторы, счёт слов и длины; это важно, потому что список пересекает
     * границу слоя памяти и дальше им распоряжается вызывающий.
     */
    val trace: List<String>
)

/**
 * Правило, по которому кандидат проходит отбор или отсеивается. Чистая функция:
 * ни базы, ни Android — затем и вынесена, чтобы правило можно было закрепить
 * тестом. Тот же приём, что и у usefulnessMarks выше.
 *
 * Оба сравнения строгие в сторону прохождения: `coverage < MIN_COVERAGE` и
 * `charsPerMatch > MAX_CHARS_PER_MATCH`, то есть ровно пороговое значение
 * проходит. Замена любого из двух знаков на нестрогий меняет правило, и это
 * закреплено тестом на граничные значения.
 *
 * Пустой matched даёт гарантированный отсев по обоим признакам сразу. В отборе
 * такого кандидата не бывает — в candidates попадают только найденные записи, —
 * но правило обязано быть определено на своём входе целиком, а не полагаться на
 * то, что вызывающий проверил раньше.
 *
 * Чего эта функция НЕ проверяет. Она не знает, откуда взялся matched: правда ли
 * его ключи — слова вопроса, правда ли значения — ступени лестницы. Не знает и
 * того, дошёл ли кандидат до неё вообще: запись, потерянную поиском, здесь не
 * увидеть, а это как раз промах в невосстановимую сторону. Тест закрепляет
 * правило, а не отбор целиком.
 *
 * @param matched слово вопроса → ступень (длина префикса), на которой оно нашлось
 * @param totalWords сколько значимых слов было в вопросе; нулём не бывает —
 *        при пустом списке слов поиск заканчивается раньше
 * @param contentLength длина содержимого записи в знаках
 */
internal fun scoreCandidate(
    matched: Map<String, Int>,
    totalWords: Int,
    contentLength: Int
): CandidateScore {
    val coverage = matched.size.toDouble() / totalWords
    // Считаются РЕАЛЬНО совпавшие знаки, а не длина исходных слов: совпадение
    // четырьмя буквами и должно стоить меньше, чем целым словом в десять, —
    // иначе размытая ступень покупала бы место даром.
    val matchedChars = matched.values.sum()
    val precision =
        if (matched.isEmpty()) 0.0
        else matched.entries
            .sumOf { (word, prefixLength) -> prefixLength.toDouble() / word.length }
            .div(matched.size)
    // Знаменатель нулём быть не может: слова короче MIN_WORD_LENGTH сюда не
    // доходят. Ветка оставлена на случай будущей правки отсева — без неё
    // деление дало бы бесконечность, то есть запись прошла бы как самая дешёвая.
    val charsPerMatch =
        if (matchedChars == 0) Double.MAX_VALUE
        else contentLength.toDouble() / matchedChars

    return CandidateScore(
        matchedWords = matched.size,
        coverage = coverage,
        precision = precision,
        charsPerMatch = charsPerMatch,
        tooNarrow = coverage < MIN_COVERAGE,
        tooExpensive = charsPerMatch > MAX_CHARS_PER_MATCH
    )
}

/**
 * Дыра №4, вторая половина (аудит 2026-08-21). Что изменилось и почему:
 *
 * 1. migrateExpired() больше не сканирует всю таблицу — запрашивает только строки,
 *    у которых expiryTime реально истёк, и пишет точечным UPDATE по id.
 *
 * 2. getContext() больше не вызывает dao.getAll() (раньше — дважды за вызов).
 *    Отбор по слоям, отсев reviewPending, ранжирование и лимит выполняются в SQL
 *    (StickerDao.getRanked + Prism.layersFor). Результат тот же: слой-выборка
 *    ограничивается сверху тем же limit'ом, а запись, не вошедшая в топ-limit
 *    своей выборки, не могла бы войти и в итоговый топ-limit — её уже обгоняют
 *    limit других.
 *
 * 3. Обновления доступа/прогрева стали точечными по колонкам вместо @Update всей
 *    строки. Инкремент accessCount живёт в SQL-выражении. Раньше параллельные
 *    обращения перетирали друг другу счётчик и слой: прогрев мог молча откатиться.
 *
 * 4. Возвращаемые объекты собираются через copy() — сущность Sticker больше не
 *    мутируется на месте в бизнес-логике (см. ARCHITECTURE.md, §3.3).
 *
 * ЧЕГО ЗДЕСЬ НЕТ, сознательно: обёртки withTransaction. Точечные UPDATE по
 * колонкам уже снимают класс "потерянного обновления" ради которого транзакция
 * и заводилась бы; остаётся лишь неатомарность связки "прочитали строку — решили
 * прогревать". Это эвристика с дебаунсом, устаревшее на миллисекунды чтение на
 * неё не влияет, а транзакция потребовала бы протащить сам объект базы через
 * HourglassMemory и TrustedMediator — расширение поверхности правки ради
 * несущественного выигрыша.
 *
 * ЧИСТОТА ПУТИ ЧТЕНИЯ ОТ ANDROID (04.09.2026). Правило записано в KDoc
 * MemoryCanary, пункт 2: класс уровня памяти не зовёт android.util.Log, а
 * возвращает готовый текст, который показывает вызывающий слой. Иначе класс
 * невозможно запустить в обычном JVM-тесте — Log там бросает исключение, и
 * UnitTestEnvironmentTest удерживает это свойство намеренно.
 *
 * Путь чтения (getContextWithSummary и всё, что он зовёт) правилу теперь
 * следует: разбор отбора уезжает полем trace, а печатает его экран.
 *
 * ЧЕГО ЭТО НЕ ЗАКРЫВАЕТ, сознательно: repairStuckLayers, repairToteProvenance и
 * saveEvent по-прежнему пишут в Log сами. Они вне пути чтения, тестам не мешают
 * и потому оставлены как есть — но это тот же класс, и при попытке покрыть их
 * тестом первым делом упрётесь в это. Заплатка, а не решение, и выбор сделан
 * осознанно: чинить их вместе с путём чтения значило бы тронуть ещё три метода
 * ради теста, которого пока никто не пишет.
 */
class HourglassMemory(private val dao: StickerDao) {

    private val HOT_LAYERS = listOf(Layer.RED.name, Layer.ORANGE.name, Layer.YELLOW.name, Layer.GREEN.name)

    suspend fun migrateExpired() {
        val now = System.currentTimeMillis()
        for (sticker in dao.getExpired(now)) {
            val newLayer = Prism.colderLayer(Layer.valueOf(sticker.layer))
            val newExpiry = Prism.newInterval(newLayer)?.let { now + it }
            dao.updateLayer(sticker.id, newLayer.name, newExpiry)
        }
    }

    /**
     * Разовый ремонт данных (2026-08-22). Чинит записи, застрявшие ВНЕ спектра
     * из-за прежнего храповика прогрева: они доехали до RED по обращениям,
     * получили expiryTime = null и стали невидимы для migrateExpired навсегда.
     *
     * Потолок прогрева в Prism закрыл путь на будущее, но уже застрявшие строки
     * правкой кода не расколдовываются — отсюда эта функция.
     *
     * Куда возвращать, решает Prism.classify — тот же код, что и при создании
     * записи. Отдельного SQL-условия сознательно нет: оно повторяло бы правила
     * классификации наизнанку и разошлось бы с ними при первом же изменении.
     *
     * Две категории пропускаются, и обе — законно без срока:
     *  - PURPLE: конец спектра, холоднее некуда, следующего срока не бывает;
     *  - настоящие принципы: classify вернул RED с null-интервалом, значит
     *    признак явный (tag identity / слово "принцип"), и трогать их нельзя.
     *
     * Функция идемпотентна: повторный запуск на уже починенной базе не найдёт
     * ни одной строки без срока, кроме законных, и вернёт 0.
     *
     * dao.getAll() здесь допустим в отличие от горячего пути: операция разовая,
     * при старте, вне цикла чтения контекста.
     *
     * @return сколько записей возвращено в спектр.
     */
    suspend fun repairStuckLayers(): Int {
        val now = System.currentTimeMillis()
        var repaired = 0
        for (sticker in dao.getAll()) {
            if (sticker.expiryTime != null) continue
            if (sticker.layer == Layer.PURPLE.name) continue

            val (layer, interval) = Prism.classify(sticker)
            if (interval == null) continue

            dao.updateLayer(sticker.id, layer.name, now + interval)
            repaired++
        }
        if (repaired > 0) {
            Log.d("HourglassMemory", "repairStuckLayers: вернул в спектр $repaired записей")
        }
        return repaired
    }

    /**
     * Разовый ремонт провенанса (2026-08-24). Строки, порождённые самим агентом
     * до правки "дыры №4", лежат в базе с source = USER_STATED: тогда saveEvent()
     * провенанс не принимал вообще, и вывод агента о собственной работе
     * записывался как сказанное пользователем.
     *
     * Правка кода прошлые строки не переписывает — они до сих пор попадают в
     * getContext() и читаются моделью как показания человека. Наблюдалось живьём:
     * на вопрос пользователя модель ответила "функцию sumPositive ВЫ запустили
     * 6 раз", пересказав ему его же словами отчёт агента.
     *
     * Отбор идёт по СОДЕРЖИМОМУ, а не по дате: дата сработала бы только на этой
     * конкретной базе и промахнулась бы на записях, перенесённых с другого
     * устройства. Условие source = USER_STATED в самом запросе делает операцию
     * идемпотентной — повторный вызов не найдёт ничего и вернёт 0.
     *
     * Это сознательное исключение из правила "провенанс ставится один раз при
     * создании и не пересматривается" (Sticker.kt). Исключение разовое и
     * ограничено историческими записями; ничего в текущем пути записи оно
     * не меняет.
     *
     * @return сколько записей перемаркировано.
     */
    suspend fun repairToteProvenance(): Int {
        val fixed = dao.reassignProvenanceByPrefix(
            contentPrefix = HISTORICAL_TOTE_PREFIX,
            oldSource = SourceKind.USER_STATED.name,
            newSource = SourceKind.AGENT_INFERRED.name,
            newConfidence = ConfidenceLevel.INFERRED.name
        )
        if (fixed > 0) {
            Log.d("HourglassMemory", "repairToteProvenance: перемаркировано $fixed записей")
        }
        return fixed
    }

    /**
     * Достать записи под запрос.
     *
     * Польза засчитывается только при purpose = ANSWERING_USER и только тем записям,
     * которые нашлись ПО СЛОВАМ вопроса. Принципы приезжают из getRanked по слою и ни
     * с какими словами не совпадали, поэтому им не засчитывается ничего: иначе платой
     * была бы не уместность, а сам факт попадания в выдачу, а попаданием распоряжается
     * сортировка по важности — и получилась бы обратная связь, снятая с собственного
     * выхода.
     *
     * Прогрев слоя и accessCount работают как раньше, для всех целей обращения. Это
     * другая ось: она про давность, а не про пользу, и сливать их нельзя.
     *
     * Прежний контракт сохранён: этот вызов отдаёт только записи. Кому нужно ещё и
     * состояние отбора — зовёт getContextWithSummary. Тело у них общее, второго
     * экземпляра логики не заводится.
     */
    suspend fun getContextFor(
        purpose: RetrievalPurpose,
        query: String?,
        limit: Int
    ): List<Sticker> = getContextWithSummary(purpose, query, limit).stickers

    /**
     * То же самое плюс готовая строка о том, чем закончился отбор.
     *
     * Отдельный вход, а не смена типа у getContextFor: прежний контракт остаётся
     * у всех, кто состоянием отбора не интересуется, и правка не расползается по
     * вызывающим ради того, что нужно одному экрану.
     *
     * Строка отдаётся всегда, в том числе когда всё нашлось. Показывать её только
     * при пустой выдаче значило бы завести прибор, молчащий ровно тогда, когда всё
     * хорошо, — и его собственная поломка выглядела бы нормальной работой.
     */
    suspend fun getContextWithSummary(
        purpose: RetrievalPurpose,
        query: String?,
        limit: Int
    ): ContextResult {
        migrateExpired()

        val layers = Prism.layersFor(query)

        if (query.isNullOrBlank()) {
            // Прежнее поведение сохранено: пустой запрос отдаёт срез памяти по рангу
            // и НЕ считается обращением — ни accessCount, ни прогрев не трогаются.
            // Польза тем более: слов не было, значит совпадать было нечему.
            return ContextResult(
                stickers = dao.getRanked(layers, limit),
                summary = SelectionSummary.NoQuery.text,
                trace = emptyList()
            )
        }

        // Два канала, намеренно НЕ сливаемые в один рейтинг (разделённая
        // непрерывность). Каждый отвечает за своё, и свежесть одного не может
        // вытеснить уместность другого.
        val principles = dao.getRanked(listOf(Layer.RED.name), PRINCIPLE_LIMIT)

        val roomLeft = (limit - principles.size).coerceAtLeast(0)
        val selection =
            if (roomLeft == 0) SelectionResult(emptyList(), emptyList(), SelectionSummary.NoRoom)
            else searchByWords(query, roomLeft, layers)
        val matches = selection.stickers

        val result = (principles + matches).distinctBy { it.id }.take(limit)

        // Кому засчитывается польза — решает usefulnessMarks, там же и объяснение.
        val toMark = usefulnessMarks(
            purpose = purpose,
            returned = result.map { it.id },
            matched = matches.map { it.id }.toSet()
        )

        val now = System.currentTimeMillis()
        val touched = result.map { sticker ->
            val timeSinceLastAccess = now - sticker.lastAccessedAt
            val isFirstAccess = sticker.accessCount == 0

            val currentLayer = Layer.valueOf(sticker.layer)
            val debounce = Prism.warmDebounce(currentLayer)
            val warmer = Prism.warmerLayer(currentLayer)
            val shouldWarm = (isFirstAccess || timeSinceLastAccess >= debounce) && warmer != currentLayer

            dao.touchAccess(sticker.id, now)

            val useful = sticker.id in toMark
            if (useful) {
                dao.touchUserMatch(sticker.id)
            }

            if (shouldWarm) {
                val newExpiry = Prism.newInterval(warmer)?.let { now + it }
                dao.updateLayer(sticker.id, warmer.name, newExpiry)
                sticker.copy(
                    accessCount = sticker.accessCount + 1,
                    lastAccessedAt = now,
                    layer = warmer.name,
                    expiryTime = newExpiry,
                    userMatchCount = sticker.userMatchCount + if (useful) 1 else 0
                )
            } else {
                sticker.copy(
                    accessCount = sticker.accessCount + 1,
                    lastAccessedAt = now,
                    userMatchCount = sticker.userMatchCount + if (useful) 1 else 0
                )
            }
        }

        return ContextResult(
            stickers = touched,
            summary = selection.summary.text,
            trace = selection.trace
        )
    }

    /** Запись-кандидат вместе с мерами, по которым решается её судьба. */
    private data class Scored(
        val sticker: Sticker,
        val score: CandidateScore
    )

    /**
     * Отобранные записи вместе с объяснением, как отбор к ним пришёл.
     *
     * Объяснение возвращается ЗНАЧЕНИЕМ, а не пишется в лог изнутри отбора. Так
     * же устроен ToteEngine: он не логирует ничего, а отдаёт диагностику полями
     * результата. Причина одна — функция, вызывающая android.util.Log, в
     * JVM-тесте падает, и проверить её нельзя.
     *
     * Побочная выгода важнее самой проверяемости: строки отбора перестали быть
     * доступны только через logcat. Куда их девать, решает вызывающий; сегодня
     * getContextFor пишет их в лог, но их же можно вывести на экран, а без этого
     * пустая выдача выглядит одинаково и когда в памяти нечего найти, и когда
     * отбор всё отсеял.
     *
     * Чего этот тип НЕ гарантирует: что вызывающий на trace посмотрит. Выбросить
     * объяснение можно — но это видимое поле результата, а не умолчание в
     * конструкторе, так что молча это не произойдёт.
     */
    private data class SelectionResult(
        val stickers: List<Sticker>,
        val trace: List<String>,
        val summary: SelectionSummary
    )

    /**
     * Переменный канал: записи, действительно связанные с ВОПРОСОМ.
     *
     * Зачем понадобилось (26.08.2026). Прежний dao.search(query, limit) искал
     * весь вопрос ЦЕЛИКОМ как подстроку содержимого — `content LIKE '%<весь
     * вопрос>%'`. Совпадение при таком условии практически невозможно, так что
     * текстовый канал молча не находил ничего никогда, а весь блок памяти
     * набивался соседней выборкой "топ по рангу", одинаковой для любого
     * вопроса. Наблюдалось живьём: на "Сколько будет семью восемь?" и на
     * "Какой длины должно быть полотенце?" подтягивались одни и те же пять
     * записей на 628 знаков, и модель отвечала "в семье восемь детей" —
     * добросовестно связывая вопрос с посторонним текстом, который ей вручили.
     *
     * Что делаем: ищем по отдельным значимым словам вопроса. Запросов
     * получается несколько, но это обращения к локальной базе — миллисекунды;
     * платим мы не за поиск, а за то, что попадёт в запрос к модели.
     *
     * Слои. dao.search не ограничен слоями вообще и заглянул бы в архив, чего
     * замысел Призмы не допускает без явной просьбы. Поэтому найденное
     * фильтруется по тем же слоям, что вернул Prism.layersFor — BLUE и PURPLE
     * попадают в список, только если в вопросе есть слова вроде "архив" или
     * "старое". RED отсеивается: принципы уже пришли постоянным каналом, и
     * второй раз занимать ими место незачем.
     *
     * Пустой результат — нормальный исход, а не сбой. Лучше "не знаю", чем
     * уверенная чушь из чужой записи.
     *
     * ---
     *
     * МЕРА УМЕСТНОСТИ (29.08.2026). Зачем понадобилась.
     *
     * Найденное раньше сортировалось по важности и дате создания — то есть
     * "насколько запись подходит к вопросу" не измерялось ВООБЩЕ. Запись,
     * совпавшая одним словом из шести, стояла в очереди наравне с записью,
     * совпавшей всеми шестью.
     *
     * Измерено на живой базе 29.08.2026 (13 записей). На вопрос "Какое правило
     * перехода дороги главное?" в запрос ушли три записи на 889 знаков при
     * вопросе в 38 знаков: сама фраза про мнемоническое правило и ДВА лога
     * прогонов TOTE с кодом на Kotlin. Все три зацепились одним и тем же
     * обрубком "правил" — в логах он сидел внутри комментариев "исправлено на
     * ПРАВИЛьное имя переменной" и "убедились в ПРАВИЛьности обновления".
     * Запрос вырос с 422 до 745 токенов, ожидание первого токена — с 9.2 до
     * 35.7 секунды. По счётчику обращений те же логи подтягивались 140-157 раз
     * против 6-9 у фраз пользователя: в двадцать раз чаще.
     *
     * Причина — размер. У фразы в 57 знаков одно совпавшее слово занимает
     * заметную долю записи; у лога в 400 знаков то же слово — полтора процента.
     * Чем крупнее запись, тем больше у неё поверхность для случайного
     * совпадения, и тем чаще она выигрывает отбор.
     *
     * Две проверки, намеренно НЕ сливаемые в один балл (разделённая
     * непрерывность): хорошая оценка по одной не должна выкупать провал по
     * другой, иначе достаточно крупная запись снова начнёт побеждать за счёт
     * объёма.
     *
     *  1. ДОЛЯ ВОПРОСА (coverage). Сколько разных значимых слов вопроса нашли
     *     запись. Одно слово из четырёх — не "про то же самое", а случайность.
     *
     *  2. ЦЕНА МЕСТА (charsPerMatch). Сколько знаков своего объёма запись
     *     просит за один знак совпадения. Это не абстрактная уместность, а
     *     прямая плата: место в запросе конечно (лента и окно контекста), и
     *     запись должна за него отработать.
     *
     * Порядок в очереди: сперва по доле вопроса, затем по цене места, и только
     * потом прежний ранг (важность, свежесть). Ранг остался последним слогом, а
     * не исчез: при равной уместности осмысленно предпочесть важное и свежее.
     *
     * Оба порога — ПЕРВАЯ ДОГАДКА, выведенная из этих самых 13 записей, а не
     * откуда-то ещё. Известная слабость: проверка 1 бьёт по длинным вопросам —
     * если вопрос из шести слов, а годная запись покрывает два, она вылетит. На
     * маленькой базе это правильный размен (пустой ответ лучше чуши), но с
     * ростом памяти порог придётся смягчать. Двигать оба числа дёшево, и
     * значения обеих мер идут в объяснение по каждому кандидату — чтобы решение
     * об отсеве можно было проверить глазами, а не принимать на веру.
     *
     * Само правило отсева живёт не здесь, а в scoreCandidate: эта функция чистая
     * и закреплена тестом, включая ровно пороговые значения. Здесь остались
     * лестница и сортировка — то, что без базы не проверить.
     *
     * ---
     *
     * ЛЕСТНИЦА СТУПЕНЕЙ (29.08.2026, второй проход). Зачем понадобилась.
     *
     * Первая версия отрезала у слов от семи букв ровно две последние буквы и
     * искала получившийся обрубок. Замер на живой базе в тот же день показал три
     * промаха подряд, и все — мимо нужной записи, лежавшей в базе:
     *
     *   - "Сколько цветов в радуге?" — искались "цветов" и "радуге" целиком
     *     (шесть букв, до порога обрубания не дотянули), а в записи "цвета
     *     радуги". Ноль совпадений из двух;
     *   - "Из какого дерева сделана колодка рубанка?" — "рубанка" обрубилось до
     *     "рубанк", а в записи "рубанок": беглая гласная, подстрока не совпала.
     *     "дерева" не нашлось в "деревянной";
     *   - в обоих случаях модель отвечала вообще без памяти и достраивала ответ
     *     из себя ("колодка рубанка из дерева берёзовой").
     *
     * Ошибка отбора в сторону ПРОПУСКА невосстановима: ни одна проверка ниже по
     * конвейеру не может добыть запись, которой ей не подали, и молчание на
     * выходе неотличимо от честного "в памяти нет ответа". Ошибка в другую
     * сторону — лишнее в выборке — как раз восстановима. Отсюда асимметрия:
     * отбор при сомнении ПРИНОСИТ, а не теряет.
     *
     * Как устроено. Для каждого слова вопроса строится лестница префиксов от
     * самого точного к самому грубому: слово целиком, слово минус окончание,
     * пять букв, четыре. Спуск идёт вниз до первой ступени, набравшей
     * STOP_DESCENT записей, и на ней останавливается — слово, нашедшееся
     * целиком, до размытых ступеней не доходит вовсе и не тащит за собой
     * случайную родню. Спуск СВОЙ у каждого слова: одно может найтись целиком,
     * соседнее — только четырьмя буквами.
     *
     * Замеренные ступени: цветов → "цвет" (4) даёт "цвета"; рубанка → "рубан"
     * (5) даёт "рубанок"; дерева → "дерев" (5) даёт "деревянной"; полотенце →
     * "полотенц" (7); инструмент → находится целиком.
     *
     * Ступень, на которой слово нашлось, сама по себе есть мера качества, и она
     * идёт в сортировку отдельной величиной (precision): точное совпадение
     * стоит выше размытого при равной доле вопроса. Так лестница может тащить
     * широко, не позволяя грубым совпадениям занимать верхние места, — лишнее
     * не теряется, но отсекается лимитом само собой.
     *
     * Нижняя ступень в четыре буквы заведомо шумная: "пере" от "перехода"
     * находит "переменной" в старых логах. Ловит это не сама лестница, а
     * проверка доли вопроса — одно случайное слово из четырёх даёт 25% и
     * отсев. Ступени и проверки работают в разные стороны намеренно: лестница
     * отвечает за то, чтобы не потерять, проверки — за то, чтобы не пропустить
     * мусор.
     *
     * Число CANDIDATE_LIMIT заменило прежний per-word limit. Раньше выборка по
     * каждому слову резалась тем же лимитом, что и итоговый ответ, и частое
     * слово могло вытеснить годную запись ЕЩЁ ДО взвешивания. С лестницей это
     * стало реальным риском (грубая ступень находит много), поэтому кандидаты
     * набираются широко, а режет их уже взвешивание — сперва дёшево и грубо,
     * потом точно.
     *
     * РЕГИСТР. Префикс спрашивается в двух вариантах — как есть и с заглавной
     * первой буквы: LIKE в SQLite сравнивает кириллицу побайтно, и слово,
     * стоящее в записи с заглавной, иначе не находится вовсе. Промах при этом
     * идёт в сторону потери записи, а не лишней в выборке. Замер и границы
     * починки — в KDoc searchAnyCase (StickerDao.kt).
     */
    private suspend fun searchByWords(
        query: String,
        limit: Int,
        allowedLayers: List<String>
    ): SelectionResult {
        // Объяснение копится строками и уезжает вызывающему вместе с результатом.
        // Пустой список записей при непустом trace — это "искали и не нашли";
        // пустые оба — "искать было нечего". Раньше эти два случая на выходе
        // выглядели одинаково.
        val trace = mutableListOf<String>()

        val words = meaningfulWords(query)
        if (words.isEmpty()) {
            return SelectionResult(emptyList(), trace, SelectionSummary.NoSearchableWords)
        }

        // Для каждой записи помним, КАКИЕ слова её нашли и НА КАКОЙ ступени.
        // Ступень запоминается первая (самая длинная) — качество совпадения не
        // должно ухудшаться от того, что позже слово нашлось ещё и огрызком.
        val candidates = LinkedHashMap<Long, Sticker>()
        val hits = HashMap<Long, MutableMap<String, Int>>()

        for (word in words) {
            val foundForWord = HashSet<Long>()
            for (prefixLength in ladder(word)) {
                val prefix = word.take(prefixLength)
                val prefixCapitalized = prefix.replaceFirstChar { it.uppercaseChar() }
                var foundHere = 0
                for (sticker in dao.searchAnyCase(prefix, prefixCapitalized, CANDIDATE_LIMIT)) {
                    if (sticker.layer == Layer.RED.name) continue
                    if (sticker.layer !in allowedLayers) continue
                    candidates[sticker.id] = sticker
                    hits.getOrPut(sticker.id) { HashMap() }.putIfAbsent(word, prefixLength)
                    foundForWord.add(sticker.id)
                    foundHere++
                }
                trace += "слово «$word» · ступень $prefixLength («$prefix») · " +
                    "найдено $foundHere · всего по слову ${foundForWord.size}" +
                    if (foundForWord.size >= STOP_DESCENT) " · спуск остановлен" else ""
                if (foundForWord.size >= STOP_DESCENT) break
            }
        }
        if (candidates.isEmpty()) {
            return SelectionResult(emptyList(), trace, SelectionSummary.NothingFound(words.size))
        }

        val totalWords = words.size
        val passed = mutableListOf<Scored>()
        var tooNarrow = 0
        var tooExpensive = 0
        var tooBoth = 0

        for (sticker in candidates.values) {
            val matched = hits[sticker.id].orEmpty()
            val score = scoreCandidate(matched, totalWords, sticker.content.length)

            trace += "id=${sticker.id} слов ${score.matchedWords}/$totalWords " +
                "(${(score.coverage * 100).toInt()}%) · точность " +
                "${(score.precision * 100).toInt()}% · цена места " +
                "${"%.1f".format(score.charsPerMatch)} · ${sticker.content.length} зн. · " +
                score.verdict

            if (!score.passed) {
                when {
                    score.tooNarrow && score.tooExpensive -> tooBoth++
                    score.tooNarrow -> tooNarrow++
                    else -> tooExpensive++
                }
                continue
            }
            passed += Scored(sticker, score)
        }

        val stickers = passed
            .sortedWith(
                compareByDescending<Scored> { it.score.matchedWords }
                    .thenByDescending { it.score.precision }
                    .thenBy { it.score.charsPerMatch }
                    .thenByDescending { importanceRank(it.sticker.importance) }
                    .thenByDescending { it.sticker.createdAt }
            )
            .take(limit)
            .map { it.sticker }

        return SelectionResult(
            stickers = stickers,
            trace = trace,
            summary = SelectionSummary.Weighed(
                words = totalWords,
                candidates = candidates.size,
                // Прошедшие считаются ДО обрезки лимитом: иначе потеря по лимиту
                // была бы неотличима от отсева порогом.
                passed = passed.size,
                shown = stickers.size,
                tooNarrow = tooNarrow,
                tooExpensive = tooExpensive,
                tooBoth = tooBoth
            )
        )
    }

    /**
     * Ступени поиска для одного слова, от точной к грубой.
     *
     * Слово целиком → минус окончание (две буквы) → пять букв → четыре. Ступени
     * короче слова и короче MIN_PREFIX отбрасываются, повторы схлопываются: у
     * шестибуквенного слова лестница выходит 6-5-4, у десятибуквенного —
     * 10-8-5-4.
     *
     * Пять и четыре стоят в списке явными числами, а не вычисляются: это не
     * продолжение ряда "минус две буквы", а нижние границы, за которыми
     * начинается шум. Четыре — та же граница, что и MIN_WORD_LENGTH: короче
     * этого подстрока совпадает с чем угодно.
     *
     * Это по-прежнему грубая замена морфологии, а не морфология. Настоящее
     * разделение по смыслу потребовало бы второй модели в памяти, чего
     * устройство не выдержит.
     */
    private fun ladder(word: String): List<Int> =
        listOf(word.length, word.length - 2, 5, MIN_PREFIX)
            .filter { it in MIN_PREFIX..word.length }
            .distinct()
            .sortedDescending()

    /**
     * Слова вопроса, по которым имеет смысл искать.
     *
     * Три отсева, каждый по своей причине:
     *  - короткие слова: предлоги и частицы, совпадут с чем угодно;
     *  - список служебных слов: "сколько", "должно", "будет" — длинные, но
     *    встречаются в любом вопросе и тащат за собой случайные записи. Список
     *    заведомо неполон и пополняется по мере того, как мусор себя покажет;
     *  - потолок числа слов: длинный вопрос иначе даёт десятки обращений к базе
     *    и вычерпывает всю память подряд, возвращая нас к тому же результату.
     *
     * Окончания здесь БОЛЬШЕ НЕ ОТРЕЗАЮТСЯ. Прежде слово от семи букв теряло
     * две последние, и это давало ровно один вариант поиска — либо угаданный,
     * либо промах без второй попытки. Теперь слово отдаётся целиком, а
     * укорачиванием ведает лестница ступеней (см. ladder), которая спускается
     * от точного к грубому и останавливается на первом, что нашлось.
     *
     * Список этих слов задаёт знаменатель "доли вопроса" в searchByWords, так
     * что каждое добавленное служебное слово заодно смягчает порог отсева.
     */
    private fun meaningfulWords(query: String): List<String> =
        query.lowercase()
            .split(Regex("[^\\p{L}\\p{N}]+"))
            .filter { it.length >= MIN_WORD_LENGTH && it !in STOP_WORDS }
            .distinct()
            .take(MAX_SEARCH_WORDS)

    suspend fun saveEvent(sticker: Sticker): Long {
        val (layer, interval) = Prism.classify(sticker)
        sticker.layer = layer.name
        sticker.expiryTime = interval?.let { System.currentTimeMillis() + it }
        val newId = dao.insert(sticker)

        // RiskTrigger — настоящий жёсткий чекпоинт (ставит reviewPending), но его
        // сбой не должен каскадом ронять сам факт сохранения. Здесь @Update всей
        // строки допустим: строка только что вставлена, параллельных читателей ещё нет.
        try {
            val hotPool = dao.getByTagInLayers(sticker.tag, HOT_LAYERS).filter { it.id != newId }
            val saved = sticker.copy(id = newId)
            val decision = RiskTrigger.evaluate(saved, hotPool)
            Log.d(
                "RiskTrigger",
                "sticker id=$newId tag=${sticker.tag} shouldReview=${decision.shouldReview} reasons=${decision.reasons}"
            )
            if (decision.shouldReview) {
                saved.reviewPending = true
                dao.update(saved)
            }
        } catch (e: Exception) {
            Log.e("RiskTrigger", "evaluation failed for sticker id=$newId, save not blocked", e)
        }

        return newId
    }

    private companion object {
        /**
         * Префикс вакцина-строк в том виде, в каком их писала прежняя версия кода.
         *
         * Литерал здесь СОЗНАТЕЛЬНО продублирован, а не взят из KotlinCodingTask:
         * ремонт работает с историческими строками, уже лежащими в базе, и не
         * должен меняться вслед за тем, как задача формирует новые записи.
         * Общая константа связала бы прошлое с будущим и при первой же правке
         * формулировки молча перестала бы находить старьё.
         */
        const val HISTORICAL_TOTE_PREFIX = "[TOTE]"

        /**
         * Сколько принципов постоянный канал кладёт в контекст.
         *
         * Потолок, а не "сколько есть": RED пополняется только явным признаком
         * (Prism.classify — тег identity или слово "принцип"), но со временем
         * записей там станет больше, чем помещается в бюджет запроса. Предел
         * поставлен заранее, пока в него ничего не упирается: это граница, а не
         * догадка о поведении, и выводить её снизу нечему.
         *
         * Когда RED перерастёт этот предел, отбор ВНУТРИ принципов придётся
         * задать явно — сейчас берутся первые по рангу, то есть по важности и
         * свежести, и это временное решение, а не осмысленный выбор.
         */
        const val PRINCIPLE_LIMIT = 3

        /** Короче этого слово совпадёт с чем угодно. */
        const val MIN_WORD_LENGTH = 4

        /** Нижняя ступень лестницы: короче искать бессмысленно (см. ladder). */
        const val MIN_PREFIX = 4

        /**
         * Сколько записей должна набрать ступень, чтобы спуск по этому слову
         * прекратился.
         *
         * Число пока НЕ выведено из замеров, в отличие от порогов ниже, — оно
         * держится в уме как разумное и проверяется наблюдением: каждая ступень
         * пишет в объяснение отбора, сколько нашла и где спуск остановился (см.
         * trace в SelectionResult). Смотрим на
         * нескольких вопросах, на какой ступени поиск реально замирает, и
         * ставим число по факту.
         */
        const val STOP_DESCENT = 3

        /**
         * Сколько кандидатов база отдаёт по одной ступени.
         *
         * Раньше выборка по каждому слову резалась тем же лимитом, что и
         * итоговый ответ (пять), и частое слово могло вытеснить годную запись
         * ещё ДО взвешивания. Лестница сделала это реальным риском: грубая
         * ступень находит много. Поэтому кандидаты набираются широко, а режет
         * их взвешивание — грубо и дёшево сперва, точно потом.
         *
         * Это потолок, а не мера: он должен быть заведомо больше любой разумной
         * выборки и существует только чтобы очень частое слово не подняло в
         * память всю таблицу.
         */
        const val CANDIDATE_LIMIT = 20

        /** Потолок числа слов, по которым идёт поиск. */
        const val MAX_SEARCH_WORDS = 6

        // MIN_COVERAGE и MAX_CHARS_PER_MATCH переехали на верхний уровень файла,
        // к scoreCandidate — единственному месту, которое их читает.

        /**
         * Слова, которые есть почти в любом вопросе. Длинные, поэтому предыдущий
         * отсев их не ловит, а тащат они за собой что попало.
         *
         * Косвенные падежи добраны 29.08.2026 по замеру: на вопросе "Из какого
         * дерева сделана колодка моего рубанка?" слова "какого" и "моего" заняли
         * два места из шести и раздули знаменатель доли вопроса до отсева нужной
         * записи. Это достройка уже начатого — именительные "какой/какая/моя"
         * в списке были с самого начала, — а не новое правило под один случай.
         */
        val STOP_WORDS = setOf(
            "что", "чтобы", "если", "или", "как", "какой", "какая", "какое", "какие",
            "какого", "какую", "каким", "каких", "каком", "какому",
            "когда", "где", "куда", "почему", "зачем", "сколько",
            "быть", "было", "были", "будет", "будут", "есть",
            "должно", "должен", "должна", "должны", "можно", "нужно", "надо",
            "это", "этот", "эта", "эти", "тот", "там", "тут",
            "для", "при", "про", "над", "под", "без", "перед", "после",
            "меня", "тебя", "него", "неё", "нему", "мной", "тобой",
            "очень", "просто", "только", "ещё", "уже", "тоже", "также",
            "твой", "твоя", "свой", "своя", "мой", "моя",
            "моего", "моему", "моих", "моим", "твоего", "твоему",
            "своего", "своему", "своих", "своим"
        )
    }
