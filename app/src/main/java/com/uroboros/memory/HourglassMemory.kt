     *
     * ЛЕСТНИЦА СТУПЕНЕЙ (29.08.2026, второй проход). Зачем понадобилась.
     *
     * Первая версия отрезала у слов от семи букв ровно две последние буквы и
     * искала получившийся обрубок. Замер на живой базе в тот же день показал три
     * промаха подряд, и все — мимо нужной записи, лежавшей в базе:
     *
     *   - "Сколько цветов в радуге?" — искались "цветов" и "радуге" целиком
     *     (шесть букв, до порога обрубания не дотянули), а в записи "цвета
     *     радуги". Ноль совпадений из двух;
     *   - "Из какого дерева сделана колодка рубанка?" — "рубанка" обрубилось до
     *     "рубанк", а в записи "рубанок": беглая гласная, подстрока не совпала.
     *     "дерева" не нашлось в "деревянной";
     *   - в обоих случаях модель отвечала вообще без памяти и достраивала ответ
     *     из себя ("колодка рубанка из дерева берёзовой").
     *
     * Ошибка отбора в сторону ПРОПУСКА невосстановима: ни одна проверка ниже по
     * конвейеру не может добыть запись, которой ей не подали, и молчание на
     * выходе неотличимо от честного "в памяти нет ответа". Ошибка в другую
     * сторону — лишнее в выборке — как раз восстановима. Отсюда асимметрия:
     * отбор при сомнении ПРИНОСИТ, а не теряет.
     *
     * Как устроено. Для каждого слова вопроса строится лестница префиксов от
     * самого точного к самому грубому: слово целиком, слово минус окончание,
     * пять букв, четыре. Спуск идёт вниз до первой ступени, набравшей
     * STOP_DESCENT записей, и на ней останавливается — слово, нашедшееся
     * целиком, до размытых ступеней не доходит вовсе и не тащит за собой
     * случайную родню. Спуск СВОЙ у каждого слова: одно может найтись целиком,
     * соседнее — только четырьмя буквами.
     *
     * Замеренные ступени: цветов → "цвет" (4) даёт "цвета"; рубанка → "рубан"
     * (5) даёт "рубанок"; дерева → "дерев" (5) даёт "деревянной"; полотенце →
     * "полотенц" (7); инструмент → находится целиком.
     *
     * Ступень, на которой слово нашлось, сама по себе есть мера качества, и она
     * идёт в сортировку отдельной величиной (precision): точное совпадение
     * стоит выше размытого при равной доле вопроса. Так лестница может тащить
     * широко, не позволяя грубым совпадениям занимать верхние места, — лишнее
     * не теряется, но отсекается лимитом само собой.
     *
     * Нижняя ступень в четыре буквы заведомо шумная: "пере" от "перехода"
     * находит "переменной" в старых логах. Ловит это не сама лестница, а
     * проверка доли вопроса — одно случайное слово из четырёх даёт 25% и
     * отсев. Ступени и проверки работают в разные стороны намеренно: лестница
     * отвечает за то, чтобы не потерять, проверки — за то, чтобы не пропустить
     * мусор.
     *
     * Число CANDIDATE_LIMIT заменило прежний per-word limit. Раньше выборка по
     * каждому слову резалась тем же лимитом, что и итоговый ответ, и частое
     * слово могло вытеснить годную запись ЕЩЁ ДО взвешивания. С лестницей это
     * стало реальным риском (грубая ступень находит много), поэтому кандидаты
     * набираются широко, а режет их уже взвешивание — сперва дёшево и грубо,
     * потом точно.
     *
     * РЕГИСТР. Префикс спрашивается в двух вариантах — как есть и с заглавной
     * первой буквы: LIKE в SQLite сравнивает кириллицу побайтно, и слово,
     * стоящее в записи с заглавной, иначе не находится вовсе. Промах при этом
     * идёт в сторону потери записи, а не лишней в выборке. Замер и границы
     * починки — в KDoc searchAnyCase (StickerDao.kt).
     */
    private suspend fun searchByWords(
        query: String,
        limit: Int,
        allowedLayers: List<String>
    ): SelectionResult {
        // Объяснение копится строками и уезжает вызывающему вместе с результатом.
        // Пустой список записей при непустом trace — это "искали и не нашли";
        // пустые оба — "искать было нечего". Раньше эти два случая на выходе
        // выглядели одинаково.
        val trace = mutableListOf<String>()

        val words = meaningfulWords(query)
        if (words.isEmpty()) {
            return SelectionResult(emptyList(), trace, SelectionSummary.NoSearchableWords)
        }

        // Для каждой записи помним, КАКИЕ слова её нашли и НА КАКОЙ ступени.
        // Ступень запоминается первая (самая длинная) — качество совпадения не
        // должно ухудшаться от того, что позже слово нашлось ещё и огрызком.
        val candidates = LinkedHashMap<Long, Sticker>()
        val hits = HashMap<Long, MutableMap<String, Int>>()

        // Записи карантина, попавшие под те же слова. Множество, а не счётчик:
        // одна запись, найденная двумя словами или на двух ступенях, обязана
        // считаться один раз.
        val hidden = HashSet<Long>()

        for (word in words) {
            val foundForWord = HashSet<Long>()
            for (prefixLength in ladder(word)) {
                val prefix = word.take(prefixLength)
                val prefixCapitalized = prefix.replaceFirstChar { it.uppercaseChar() }
                var foundHere = 0
                for (sticker in dao.searchAnyCase(prefix, prefixCapitalized, CANDIDATE_LIMIT)) {
                    if (sticker.layer == Layer.RED.name) continue
                    if (sticker.layer !in allowedLayers) continue
                    candidates[sticker.id] = sticker
                    hits.getOrPut(sticker.id) { HashMap() }.putIfAbsent(word, prefixLength)
                    foundForWord.add(sticker.id)
                    foundHere++
                }
                // Зеркальный запрос: те же префиксы, те же слои, но карантин.
                // Стоит ДО проверки STOP_DESCENT намеренно — счёт скрытых не
                // участвует в решении спускаться дальше или нет. Иначе запись в
                // карантине меняла бы то, что находится для всех остальных, и
                // карантин перестал бы быть просто вычитанием.
                //
                // Обратное направление есть и оно намеренное: спуск, остановленный
                // видимыми находками, останавливает и счёт скрытых. Оба числа
                // обязаны описывать ОДИН поиск, иначе их нельзя ставить рядом.
                var hiddenHere = 0
                for (row in dao.searchHiddenAnyCase(prefix, prefixCapitalized, CANDIDATE_LIMIT)) {
                    if (row.layer == Layer.RED.name) continue
                    if (row.layer !in allowedLayers) continue
                    hidden.add(row.id)
                    hiddenHere++
                }

                trace += "слово «$word» · ступень $prefixLength («$prefix») · " +
                    "найдено $foundHere · скрыто $hiddenHere · " +
                    "всего по слову ${foundForWord.size}" +
                    if (foundForWord.size >= STOP_DESCENT) " · спуск остановлен" else ""
                if (foundForWord.size >= STOP_DESCENT) break
            }
        }
        if (candidates.isEmpty()) {
            return SelectionResult(
                emptyList(),
                trace,
                SelectionSummary.NothingFound(words.size, hidden.size)
            )
        }

        val totalWords = words.size
        val passed = mutableListOf<Scored>()
        var tooNarrow = 0
        var tooExpensive = 0
        var tooBoth = 0

        for (sticker in candidates.values) {
            val matched = hits[sticker.id].orEmpty()
            val score = scoreCandidate(matched, totalWords, sticker.content.length)

            trace += "id=${sticker.id} слов ${score.matchedWords}/$totalWords " +
                "(${(score.coverage * 100).toInt()}%) · точность " +
                "${(score.precision * 100).toInt()}% · цена места " +
                "${"%.1f".format(score.charsPerMatch)} · ${sticker.content.length} зн. · " +
                score.verdict

            if (!score.passed) {
                when {
                    score.tooNarrow && score.tooExpensive -> tooBoth++
                    score.tooNarrow -> tooNarrow++
                    else -> tooExpensive++
                }
                continue
            }
            passed += Scored(sticker, score)
        }

        val stickers = passed
            .sortedWith(
                compareByDescending<Scored> { it.score.matchedWords }
                    .thenByDescending { it.score.precision }
                    .thenBy { it.score.charsPerMatch }
                    .thenByDescending { importanceRank(it.sticker.importance) }
                    .thenByDescending { it.sticker.createdAt }
            )
            .take(limit)
            .map { it.sticker }

        return SelectionResult(
            stickers = stickers,
            trace = trace,
            summary = SelectionSummary.Weighed(
                words = totalWords,
                candidates = candidates.size,
                // Прошедшие считаются ДО обрезки лимитом: иначе потеря по лимиту
                // была бы неотличима от отсева порогом.
                passed = passed.size,
                shown = stickers.size,
                tooNarrow = tooNarrow,
                tooExpensive = tooExpensive,
                tooBoth = tooBoth,
                hidden = hidden.size
            )
        )
    }

    /**
     * Ступени поиска для одного слова, от точной к грубой.
     *
     * Слово целиком → минус окончание (две буквы) → пять букв → четыре. Ступени
     * короче слова и короче MIN_PREFIX отбрасываются, повторы схлопываются: у
     * шестибуквенного слова лестница выходит 6-5-4, у десятибуквенного —
     * 10-8-5-4.
     *
     * Пять и четыре стоят в списке явными числами, а не вычисляются: это не
     * продолжение ряда "минус две буквы", а нижние границы, за которыми
     * начинается шум. Четыре — та же граница, что и MIN_WORD_LENGTH: короче
     * этого подстрока совпадает с чем угодно.
     *
     * Это по-прежнему грубая замена морфологии, а не морфология. Настоящее
     * разделение по смыслу потребовало бы второй модели в памяти, чего
     * устройство не выдержит.
     */
    private fun ladder(word: String): List<Int> =
        listOf(word.length, word.length - 2, 5, MIN_PREFIX)
            .filter { it in MIN_PREFIX..word.length }
            .distinct()
            .sortedDescending()

    /**
     * Слова вопроса, по которым имеет смысл искать.
     *
     * Три отсева, каждый по своей причине:
     *  - короткие слова: предлоги и частицы, совпадут с чем угодно;
     *  - список служебных слов: "сколько", "должно", "будет" — длинные, но
     *    встречаются в любом вопросе и тащат за собой случайные записи. Список
     *    заведомо неполон и пополняется по мере того, как мусор себя покажет;
     *  - потолок числа слов: длинный вопрос иначе даёт десятки обращений к базе
     *    и вычерпывает всю память подряд, возвращая нас к тому же результату.
     *
     * Окончания здесь БОЛЬШЕ НЕ ОТРЕЗАЮТСЯ. Прежде слово от семи букв теряло
     * две последние, и это давало ровно один вариант поиска — либо угаданный,
     * либо промах без второй попытки. Теперь слово отдаётся целиком, а
     * укорачиванием ведает лестница ступеней (см. ladder), которая спускается
     * от точного к грубому и останавливается на первом, что нашлось.
     *
     * Список этих слов задаёт знаменатель "доли вопроса" в searchByWords, так
     * что каждое добавленное служебное слово заодно смягчает порог отсева.
     */
    private fun meaningfulWords(query: String): List<String> =
        query.lowercase()
            .split(Regex("[^\\p{L}\\p{N}]+"))
            .filter { it.length >= MIN_WORD_LENGTH && it !in STOP_WORDS }
            .distinct()
            .take(MAX_SEARCH_WORDS)

    /**
     * Чем кончилось сохранение.
     *
     * Запечатан, потому что «сохранено» и «не сохранено, такое уже есть» —
     * разные события, а вызывающему видно одно и то же поле ввода. Пока исход
     * был числом, экран не мог их различить и говорил «Сохранено» в обоих
     * случаях: показание, которое врёт ровно в тот момент, когда его читают.
     *
     * Третье значение здесь — [SavedNearDuplicate]. Без него «похоже на
     * лежащую» пришлось бы слить либо с обычной вставкой (и человек не узнает
     * о близнеце), либо с повтором (и запись съедят, хотя различие могло быть
     * значащим).
     */
    sealed class SaveOutcome {
        /** Запись вставлена, похожих рядом не нашлось. */
        data class Saved(val id: Long) : SaveOutcome()

        /**
         * Запись вставлена, но в горячей памяти под тем же тегом уже лежит
         * почти такая же: тексты сходятся всюду, кроме знаков препинания и
         * разделителей. Различие могло быть значащим («пункт 2.1» и «пункт
         * 2,1»), поэтому запись сохранена, а не съедена; человеку сказано.
         */
        data class SavedNearDuplicate(
            val id: Long,
            val similarToId: Long,
            val similarToCreatedAt: Long
        ) : SaveOutcome()

        /**
         * Запись НЕ вставлена: дословный повтор уже лежащей. У лежащей
         * обновлено время обращения — повтор той же мысли продлевает ей жизнь
         * в горячих слоях, иначе она остынет так, будто о ней не вспоминали.
         */
        data class Duplicate(
            val existingId: Long,
            val existingCreatedAt: Long
        ) : SaveOutcome()
    }

    /**
     * Приведение текста для поиска дословного повтора.
     *
     * Список приведений короткий НАМЕРЕННО, и расширять его без замера нельзя.
     * Совпадение по этой мерке ведёт к тому, что запись не сохраняется вовсе;
     * промах в эту сторону невосстановим — записи нет ни в базе, ни в очереди,
     * ни в отчёте, и узнать о нём будет неоткуда. Всё, в чём есть хоть тень
     * значения (цифры, знаки внутри текста, порядок слов), здесь не трогается
     * и уходит в [normalizeLoose], где исход мягче.
     *
     * Концевая пунктуация срезается: «колодкой.» и «колодкой —» — одна и та же
     * фраза, и различает их только то, чем человек закончил ввод.
     */
    private fun normalizeExact(text: String): String =
        text.lowercase()
            .replace('ё', 'е')
            .replace(Regex("\\s+"), " ")
            .trim()
            .trimEnd('.', ',', ';', ':', '!', '?', '-', '\u2014', '\u2013', ' ')

    /**
     * Приведение текста для поиска почти-повтора: всё, что не буква и не
     * цифра, становится пробелом.
     *
     * Цифры остаются НА МЕСТЕ и это главное свойство мерки: «у паука 8 ног» и
     * «у паука 6 ног» по ней не сходятся и уходят дальше, к проверке на
     * противоречие, которой такая пара и принадлежит. Сходятся здесь только
     * тексты, различающиеся оформлением: «ставка 7.5» и «ставка 7,5».
     *
     * Чего мерка не умеет: пересказ теми же по смыслу, но другими словами она
     * не берёт вовсе, как и всё остальное в этом файле. Порядок слов для неё
     * значим — переставленные слова дают разные строки.
     */
    private fun normalizeLoose(text: String): String =
        text.lowercase()
            .replace('ё', 'е')
            .replace(Regex("[^\\p{L}\\p{N}]+"), " ")
            .trim()

    /**
     * Первая запись пула, совпадающая с кандидатом по [mark], или null.
     *
     * Пустая мерка не ищется: текст из одних знаков препинания дал бы пустую
     * строку, и по ней совпало бы что угодно другое такое же.
     */
    private fun findTwin(
        candidate: Sticker,
        pool: List<Sticker>,
        mark: (String) -> String
    ): Sticker? {
        val key = mark(candidate.content)
        if (key.isEmpty()) return null
        return pool.firstOrNull { it.id != candidate.id && mark(it.content) == key }
    }

    /**
     * Сохранить запись, пройдя отсев повторов и проверку на противоречие.
     *
     * ПОРЯДОК: отсев повторов идёт ПЕРВЫМ, сравнение на противоречие вторым,
     * и оба до вставки. Дословный повтор до сравнения не доходит — сравнивать
     * запись с её же копией нечего, а в очередь она попала бы наравне с
     * настоящей поправкой и человек разбирал бы одно дело дважды.
     *
     * ОДИН ЗАПРОС НА ВСЁ. Горячий пул по тегу вытаскивается один раз и служит
     * обоим механизмам. Лишнего обращения к базе отсев повторов не стоит.
     *
     * ГДЕ ОТСЕВ СЛЕП. Пул горячий и по одному тегу, значит близнец, чей
     * двойник уже остыл, не ловится, и близнец под другим тегом тоже. Это
     * форма ступени, а не поломка: тот же пул, что у проверки на
     * противоречие, и расширять его отдельно для повторов значило бы завести
     * второй пул, расходящийся с первым.
     *
     * ПОЧЕМУ СЪЕДЕННЫЙ ПОВТОР НЕ ИДЁТ В ПРИБОР ОЧЕРЕДИ. Прибор считает
     * состоявшиеся сравнения, а здесь сравнения не было. Его правило сверки —
     * прирост проверок против прироста записей — от этого не страдает: при
     * съеденном повторе не растёт ни то, ни другое.
     *
     * НАЙДЕННЫЙ СПОР БИТА НЕ ПОДНИМАЕТ. Правило решает только, состоялось ли
     * сравнение; годится ли запись в выдачу, решает человек нажатием. Причина
     * не в мягкости: пряча вторую сторону здесь, механизм прятал её РАНЬШЕ
     * отбора, и до сверки поданных записей ([DisputeNotice], путь ввода) не
     * доживала ни одна свежая пара — сверка искала ровно то, что этот бит уже
     * убрал. Обе стороны теперь остаются в горячей памяти, едут в модель
     * вместе и сопровождаются механическим признаком расхождения.
     *
     * За этим стоит решение о том, как система обходится с противоречием:
     * агент его не разрешает, а ДЕРЖИТ — «говорили и так, и так». Вердикт
     * человека остаётся возможным, но перестаёт быть обязательным, и очередь
     * из русла всякого спора превращается в путь для двух случаев, которые
     * подачей не лечатся: одна сторона просто ложна, и сбой проверки.
     *
     * ПАДЕНИЕ СРАВНЕНИЯ ПОДНИМАЕТ БИТ, и это единственный путь в очередь
     * отсюда. Подстановка в благополучную сторону здесь недопустима: второй
     * попытки не бывает, [RiskTrigger.evaluate] зовётся один раз за жизнь
     * записи, так что непроверенное ушло бы в горячую память навсегда и молча.
     * Промах в эту сторону невосстановим; промах в обратную стоит одной лишней
     * записи в очереди, которую человек снимет.
     *
     * Разница между двумя абзацами выше — в слове «проверено». §0 требует
     * прятать НЕПРОВЕРЕННОЕ, а не противоречивое: при споре проверка
     * состоялась, и её результат известен и подан. Ссылаться на §0 ради
     * скрытия проверенной записи значило бы прикрываться им там, где он не об
     * этом.
     *
     * ОТСЕВ ПОВТОРОВ ПРИ ЭТОМ МОЛЧИТ, А НЕ СЪЕДАЕТ. Не вытащился пул — повтор
     * искать не в чем, и запись сохраняется. Направление у двух механизмов
     * поэтому разное и намеренно: сбой сравнения ужесточает исход, сбой
     * отсева смягчает. Оба промахиваются в восстановимую сторону.
     *
     * ВСТАВКА ОДНА. Сравнение и его исход входят в саму вставку. Если бы бит
     * дописывался вторым запросом, между запросами существовало бы окно, в
     * котором запись уже лежит в базе без бита и видна всем трём запросам
     * пути чтения (они начинаются с `reviewPending = 0`).
     *
     * УЧЁТ. Исход каждой состоявшейся проверки идёт в прибор очереди, включая
     * чистую: без счёта чистых проверок ноль дел неотличим от неработающего
     * прибора. Спор и сбой считаются порознь — по базе они неразличимы, по
     * счёту входов различимы.
     *
     * ЧЕГО ЭТОТ МЕХАНИЗМ НЕ УМЕЕТ:
     *  - бит означает "запись не годится в выдачу". Поставить его отсюда может
     *    только несостоявшееся сравнение; спор его не ставит, и по базе одно от
     *    другого по-прежнему не отличить — причина постановки нигде не
     *    сохраняется;
     *  - отсутствие бита не означает отсутствия спора, и никогда не означало:
     *    правило видит отрицание и числа, а не смысл;
     *  - систематическая поломка сравнения теперь видна ПРЯМО: очередь растёт,
     *    а счёт споров у прибора ([ReviewWitness]) стоит. Раньше эти два случая
     *    сливались в один всплеск. В самой очереди следа сбоя по-прежнему нет,
     *    и в логе тоже — класс живёт в слое без Android и не логирует (см.
     *    шапку класса);
     *  - записи, скрытые до этой правки, ею НЕ открываются. Бит у них уже
     *    стоит, и выпускает их только "принять" вручную;
     *  - почти-повтор ([SaveOutcome.SavedNearDuplicate]) в очередь НЕ ставится
     *    и следа в базе не оставляет. О нём говорится один раз, тому, кто
     *    только что ввёл текст; не услышал — узнать больше неоткуда;
     *  - пул сравнения НЕ совпадает с тем, что видит отбор. Запросы пути
     *    чтения начинаются с reviewPending = 0, а выборка горячих записей по
     *    тегу — нет. Запись, лежащая в очереди, для выдачи не существует, но
     *    противоречить новой записи может, и в разборе очереди человек увидит
     *    её как противника, хотя в ответах модели она не встречалась;
     *  - при систематическом падении новые записи перестают попадать в выдачу
     *    до разбора вручную. Это сознательная цена: скрытая запись цела,
     *    непроверенная в горячей памяти — нет (ARCHITECTURE.md §0).
     *
     * Бит, поднятый вызывающим, не сбрасывается: наш вердикт может его только
     * добавить.
     */
    suspend fun saveEventChecked(sticker: Sticker): SaveOutcome {
        val (layer, interval) = Prism.classify(sticker)
        sticker.layer = layer.name
        sticker.expiryTime = interval?.let { System.currentTimeMillis() + it }

        // Кандидата в горячем пуле ещё нет — он не вставлен. Самоисключение по
        // id внутри evaluate и findTwin при этом остаётся и просто не
        // срабатывает.
        //
        // null здесь означает "пул не достался", и дальше два механизма читают
        // это по-разному: отсев повторов молчит, проверка поднимает бит.
        val hotPool = try {
            dao.getByTagInLayers(sticker.tag, HOT_LAYERS)
        } catch (e: Exception) {
            null
        }

        val exactTwin = hotPool?.let { findTwin(sticker, it, ::normalizeExact) }
        if (exactTwin != null) {
            try {
                dao.touchAccess(exactTwin.id, System.currentTimeMillis())
            } catch (e: Exception) {
                // Отметка обращения не удалась. Исход от этого не меняется:
                // повтор всё равно не запись, и ронять сохранение из-за
                // потерянной отметки нечестно — запись важнее показания.
            }
            return SaveOutcome.Duplicate(exactTwin.id, exactTwin.createdAt)
        }

        // Ищется до вставки, по тому же пулу: после вставки кандидат попал бы
        // в пул сам и совпал бы с собой.
        val nearTwin = hotPool?.let { findTwin(sticker, it, ::normalizeLoose) }

        val entry = if (hotPool == null) {
            // Само исключение никуда не пишется: класс живёт в слое без
            // Android. Наружу сбой выходит битом — запись встаёт в очередь.
            ReviewEntry.FAILURE
        } else {
            try {
                if (RiskTrigger.evaluate(sticker, hotPool).shouldReview) ReviewEntry.DISPUTE
                else ReviewEntry.CLEAN
            } catch (e: Exception) {
                ReviewEntry.FAILURE
            }
        }

        // Учёт идёт до вставки и не влияет на неё: потерянное показание
        // восстановимо наблюдением, потерянная запись нет. Отказ укладки
        // прибор ловит сам и говорит о нём в своём отчёте.
        witness.note(entry)

        sticker.reviewPending = sticker.reviewPending || entry == ReviewEntry.FAILURE

        val id = dao.insert(sticker)

        return if (nearTwin == null) SaveOutcome.Saved(id)
        else SaveOutcome.SavedNearDuplicate(id, nearTwin.id, nearTwin.createdAt)
    }

    /**
     * Чем кончилась перепроверка записи, лежащей в очереди.
     *
     * Запечатан, потому что третье значение здесь обязательно: без [Failed]
     * упавшая проверка выглядела бы как чистота — тот самый промах в
     * благополучную сторону, ради которого сбой сравнения при сохранении и
     * поднимает бит.
     */
    sealed class RecheckOutcome {
        /** Сейчас спорит с лежащей записью. */
        data class Disputes(val withId: Long) : RecheckOutcome()

        /** Сейчас ни с чем не спорит. */
        object Clean : RecheckOutcome()

        /** Проверка не состоялась. Приём по такому исходу невозможен. */
        object Failed : RecheckOutcome()
    }

    /**
     * Перепроверить запись перед приёмом её из очереди.
     *
     * ЗАЧЕМ. Бит ставится и по спору, и по сбою сравнения, а приём необратим и
     * ниже него никого нет. Принимая запись, попавшую в очередь по сбою,
     * человек своей рукой проводит непроверенную запись в горячую память —
     * ровно то, от чего бит и защищает. Здесь эта запись получает вторую
     * попытку: [RiskTrigger.evaluate] зовётся один раз за жизнь записи, и
     * другого места для второй попытки нет.
     *
     * ОСВЕДОМЛЯЕТ, А НЕ ЗАПРЕЩАЕТ. Запись, попавшая сюда по настоящему спору,
     * будет давать [Disputes] сколько угодно раз: противная запись никуда не
     * делась. Если бы этот исход запрещал приём, очередь стала бы
     * неразбираемой ровно для тех записей, ради которых она заведена. Решает
     * человек, механизм показывает.
     *
     * Единственное исключение — [Failed]: приём терминален, отсеять лишнее
     * ниже некому, поэтому сомнительное не пропускается. Промах в эту сторону
     * восстановим — человек нажмёт ещё раз.
     *
     * ЧЕГО НЕ УМЕЕТ:
     *  - это НЕ ответ на вопрос, почему запись оказалась в очереди. Причина
     *    постановки нигде не сохраняется, а здесь считается сегодняшнее
     *    состояние. Записи, чей бит поднят сбоем сравнения или слабыми
     *    признаками, дают [Clean] совершенно законно;
     *  - обратное тоже верно: [Clean] не доказывает, что спора не было при
     *    сохранении. Противник мог устареть и уйти из горячих слоёв;
     *  - сравнивается только с горячими слоями и только по тому же тегу — с
     *    тем же пулом, что при сохранении.
     *
     * В отличие от сохранения, сама запись здесь уже лежит в базе и может
     * попасть в свой же пул. Самоисключение по id внутри evaluate на этом и
     * срабатывает.
     */
    suspend fun recheckForAccept(sticker: Sticker): RecheckOutcome =
        try {
            val hotPool = dao.getByTagInLayers(sticker.tag, HOT_LAYERS)
            val decision = RiskTrigger.evaluate(sticker, hotPool)
            val opponentId = decision.contradictionCandidateId
            if (opponentId != null) RecheckOutcome.Disputes(opponentId)
            else RecheckOutcome.Clean
        } catch (e: Exception) {
            RecheckOutcome.Failed
        }

    /**
     * Скрыть запись, лежащую в памяти, по решению человека.
     *
     * ЗАЧЕМ. Проверка стоит на входе, поэтому бит поднимается только той
     * записи, что пришла позже. Сторона, с которой спор начался, остаётся
     * видимой всегда, чем бы ей ни противоречило пришедшее после, и уходит в
     * ответы наравне с бесспорным. До появления этого метода вернуть её под
     * разбор было нечем: путь умел снимать бит и не умел поднимать.
     *
     * РЕШАЕТ ЧЕЛОВЕК, И ЭТО НЕ ОГОВОРКА. Правило противоречия отвечает
     * «спорят или нет» и о сторонах не знает ничего: из него невозможно
     * вывести, какая запись верна. Механизм, зовущий этот метод сам, выбирал
     * бы сторону по возрасту или по порядку и выдавал бы это за вердикт.
     * Поэтому здесь нет ни проверки, ни условия — только исполнение уже
     * принятого решения.
     *
     * НАПРАВЛЕНИЕ ПРОМАХА. Скрытие обратимо: запись цела, попадает в очередь и
     * принимается назад. Приём необратим, и в этом вся разница между двумя
     * действиями над спором — ошибиться скрытием стоит одного лишнего дела в
     * очереди.
     *
     * ИСХОД ВОЗВРАЩАЕТСЯ. Несработавшее скрытие обязано отличаться от
     * сработавшего: иначе человек, нажавший «убрать», уйдёт уверенным, что
     * запись под разбором, а она в выдаче.
     *
     * ЧЕГО НЕ УМЕЕТ:
     *  - причина скрытия нигде не сохраняется, ровно как и причина поднятия
     *    бита при вставке. В очереди запись, убранная рукой, неотличима от
     *    попавшей туда проверкой;
     *  - `true` означает «запрос прошёл», а не «строка нашлась». Обновление
     *    несуществующего id меняет ноль строк и ошибкой не считается. Сегодня
     *    такого случая нет по построению — записи в этом проекте не удаляются
     *    ничем, — и различать эти два исхода стало бы нужно только вместе с
     *    удалением;
     *  - повторный вызов на уже скрытой записи ничего не меняет.
     */
    suspend fun hideForReview(id: Long): Boolean =
        try {
            dao.setReviewPending(id)
            true
        } catch (e: Exception) {
            false
        }

    /**
     * С кем запись спорит СЕЙЧАС и где эти записи лежат.
     *
     * Только для показа. Ничего не решает, ничего не пишет, на приём не
     * влияет — тот идёт через [recheckForAccept].
     *
     * ЗАЧЕМ РАЗДЕЛЬНО «видимый» И «скрытый». Пул сравнения шире пула выдачи,
     * и из-за этого одна и та же пара лечится односторонне: скрывается та
     * запись, которая пришла позже, а её противник продолжает уходить в
     * ответы. На экране это не видно ничем: скрытая запись выглядит
     * одинаково независимо от того, лежит её противник в горячей памяти или
     * тоже спрятан.
     *
     * ЧЕТЫРЕ ИСХОДА, И ЧЕТВЁРТЫЙ НЕ ЛИШНИЙ. Пустой отчёт означает, что спора
     * нет сейчас; отдельно от него стоит [cooled] — противник нашёлся, но
     * только в холодных слоях, то есть спор был и распался сам, когда
     * противник остыл. Слить их значило бы выдать распавшийся спор за
     * отсутствие спора. Отдельно от обоих — [failed]: запрос к базе не
     * состоялся, и молчание отчёта тогда не значит ничего.
     *
     * ЧЕГО НЕ УМЕЕТ:
     *  - это НЕ причина постановки бита. Причина нигде не сохраняется, а
     *    здесь считается сегодняшнее состояние. Запись, чей бит подняли два
     *    слабых признака или сбой сравнения, законно даёт пустой отчёт;
     *  - отчёт шире правила, по которому бит ставится: при сохранении поиск
     *    останавливается на первом подошедшем противнике, здесь собираются
     *    все. Значит запись может спорить с тремя, а в очередь попасть из-за
     *    одной из них — какой именно, не знает никто;
     *  - холодный проход делается ТОЛЬКО когда горячих противников нет:
     *    он отвечает на вопрос «а был ли спор вообще», а не пополняет список.
     */
    suspend fun disputesOf(sticker: Sticker): DisputeReport {
        return try {
            var comparisons = 0
            val visible = mutableListOf<Sticker>()
            val hidden = mutableListOf<Sticker>()
            // Признаки складываются в том же обходе, что и сами противники:
            // пара существует только здесь, и второго места, где её можно было
            // бы разобрать, у показа нет.
            val marks = mutableMapOf<Long, List<RiskTrigger.ContradictionMark>>()
            for (other in dao.getByTagInLayers(sticker.tag, HOT_LAYERS)) {
                if (other.id == sticker.id) continue
                comparisons++
                val pairMarks = RiskTrigger.contradictionMarks(sticker.content, other.content)
                if (pairMarks.isEmpty()) continue
                marks[other.id] = pairMarks
                if (other.reviewPending) hidden += other else visible += other
            }
            if (visible.isNotEmpty() || hidden.isNotEmpty()) {
                return DisputeReport(visible, hidden, emptyList(), comparisons, marks = marks)
            }
            val cooled = mutableListOf<Sticker>()
            for (other in dao.getByTagInLayers(sticker.tag, COLD_LAYERS)) {
                if (other.id == sticker.id) continue
                comparisons++
                val pairMarks = RiskTrigger.contradictionMarks(sticker.content, other.content)
                if (pairMarks.isEmpty()) continue
                marks[other.id] = pairMarks
                cooled += other
            }
            DisputeReport(emptyList(), emptyList(), cooled, comparisons, marks = marks)
        } catch (e: Exception) {
            DisputeReport(emptyList(), emptyList(), emptyList(), 0, failed = true)
        }
    }

    /**
     * Итог [disputesOf]. Пустой отчёт при `failed = false` означает «спора
     * сейчас нет»; при `failed = true` не означает ничего.
     *
     * [comparisons] — сколько пар сравнено. Число нужно затем, чтобы пустой
     * отчёт при живом механизме отличался от пустого отчёта при мёртвом:
     * ноль сравнений при непустой памяти означает, что сравнивать даже не
     * начинали.
     *
     * [marks] — за что правило зацепилось в каждой паре, по номеру противника.
     * Отдельным полем, а не внутри списков: списки читает и группировка
     * записей в дела, и показ, и признаки не нужны ни одному из них — нужны
     * они только там, где печатается сам текст.
     *
     * ЧЕМ ЗА ЭТО ПЛАЧЕНО. Поле и списки могут разойтись: противник названным
     * есть, признаков под его номером нет. Случай этот незаконный — правило
     * признаёт спор только по признаку, значит их всегда хотя бы один, — но
     * выглядел бы он как «показывать нечего». Показывающий поэтому обязан
     * различать пустой список признаков и отсутствие ключа, а не молча
     * подставлять первое вместо второго.
     */
    data class DisputeReport(
        val visible: List<Sticker>,
        val hidden: List<Sticker>,
        val cooled: List<Sticker>,
        val comparisons: Int,
        val failed: Boolean = false,
        val marks: Map<Long, List<RiskTrigger.ContradictionMark>> = emptyMap(),
    )

    private companion object {
        /**
         * Префикс вакцина-строк в том виде, в каком их писала прежняя версия кода.
         *
         * Литерал здесь СОЗНАТЕЛЬНО продублирован, а не взят из KotlinCodingTask:
         * ремонт работает с историческими строками, уже лежащими в базе, и не
         * должен меняться вслед за тем, как задача формирует новые записи.
         * Общая константа связала бы прошлое с будущим и при первой же правке
         * формулировки молча перестала бы находить старьё.
         */
        const val HISTORICAL_TOTE_PREFIX = "[TOTE]"

        /**
         * Сколько принципов постоянный канал кладёт в контекст.
         *
         * Потолок, а не "сколько есть": RED пополняется только явным признаком
         * (Prism.classify — тег identity или слово "принцип"), но со временем
         * записей там станет больше, чем помещается в бюджет запроса. Предел
         * поставлен заранее, пока в него ничего не упирается: это граница, а не
         * догадка о поведении, и выводить её снизу нечему.
         *
         * Когда RED перерастёт этот предел, отбор ВНУТРИ принципов придётся
         * задать явно — сейчас берутся первые по рангу, то есть по важности и
         * свежести, и это временное решение, а не осмысленный выбор.
         */
        const val PRINCIPLE_LIMIT = 3

        /** Короче этого слово совпадёт с чем угодно. */
        const val MIN_WORD_LENGTH = 4

        /** Нижняя ступень лестницы: короче искать бессмысленно (см. ladder). */
        const val MIN_PREFIX = 4

        /**
         * Сколько записей должна набрать ступень, чтобы спуск по этому слову
         * прекратился.
         *
         * Число пока НЕ выведено из замеров, в отличие от порогов ниже, — оно
         * держится в уме как разумное и проверяется наблюдением: каждая ступень
         * пишет в объяснение отбора, сколько нашла и где спуск остановился (см.
         * trace в SelectionResult). Смотрим на
         * нескольких вопросах, на какой ступени поиск реально замирает, и
         * ставим число по факту.
         */
        const val STOP_DESCENT = 3

        /**
         * Сколько кандидатов база отдаёт по одной ступени.
         *
         * Раньше выборка по каждому слову резалась тем же лимитом, что и
         * итоговый ответ (пять), и частое слово могло вытеснить годную запись
         * ещё ДО взвешивания. Лестница сделала это реальным риском: грубая
         * ступень находит много. Поэтому кандидаты набираются широко, а режет
         * их взвешивание — грубо и дёшево сперва, точно потом.
         *
         * Это потолок, а не мера: он должен быть заведомо больше любой разумной
         * выборки и существует только чтобы очень частое слово не подняло в
         * память всю таблицу.
