package com.uroboros.memory

/**
 * Разрешение человека на выполнение опасного действия в рамках ОДНОЙ задачи.
 *
 * Зачем оно вообще есть. Честный запуск сгенерированного кода набирает в
 * ActionGate вес 8.0 при пороге DENY 7.0 (переход границы процесса 3.0 +
 * необратимость 3.0 + не-пользовательское происхождение 2.0). Без разрешения
 * цикл эвакуировался бы на первой же итерации. Вариант "подкрутить веса или
 * завести тип действия с порогом помягче" отвергнут сознательно: это подгонка
 * барьера под действие, которое он и должен судить.
 *
 * ЧТО ЭТО НЕ ДЕЛАЕТ: разрешение НЕ уменьшает вес риска. В журнале остаётся
 * честная восьмёрка, рядом — id разрешения. Видно и то, что действие опасное,
 * и то, что человек его разрешил. Согласие и опасность — две независимые вещи,
 * и они не смешиваются в одно число (разделённая непрерывность).
 *
 * ОБЛАСТЬ — тройка: тип действия, запросивший компонент, id задачи. Совпасть
 * должны все три. Разрешение на EXTERNAL_PROCESS от TermuxKotlinRunner в задаче
 * X не действует для той же пары в задаче Y. Глобального "выполнение включено"
 * не существует и не должно появиться.
 *
 * СРОК. Объект живёт внутри задачи, а не в глобальном реестре, поэтому умирает
 * вместе с ней сам собой. Поле expiresAt — независимая вторая граница на случай
 * задачи, которая зависла и не завершилась. Обе границы нужны: любая из них
 * поодиночке дырявая.
 *
 * ПЕРЕЗАПУСК. Объект в памяти, никуда не сохраняется. Вчерашнее согласие сегодня
 * не действует — это свойство конструкции, а не отдельная проверка.
 *
 * АВАРИЙНЫЙ СТОП отменяет все разрешения бесплатно: проверка стопа стоит первой
 * строкой ActionGate.evaluate(), выше всей арифметики и выше этой проверки.
 *
 * ЧЕСТНАЯ ОГОВОРКА про "создаётся только интерфейсом". Внутри одного процесса
 * это технически не гарантируется — любой код может позвать фабрику. Достижимо
 * другое: конструктор приватный, точка создания ровно одна, и все места, где
 * разрешение рождается, можно перечислить. Защита не в том, что обойти нельзя,
 * а в том, что обход виден. Ровно как с GatedAction: если однажды окажется, что
 * grantedByHuman() зовут из двух мест, это и есть сигнал.
 *
 * КАК ЭТО ПРОВЕРЯТЬ. Открытием файлов, а не поиском по репозиторию. Поиск здесь
 * не прибор: он молчит и когда вызовов нет, и когда файл не попал в указатель, —
 * а различить эти два молчания по его выводу нельзя. Отсутствие вызова
 * доказывается только чтением тех файлов, где вызов мог бы стоять.
 *
 * СЕГОДНЯ ФАБРИКУ НЕ ЗОВЁТ НИКТО, и это не недосмотр: потребитель (запуск
 * сгенерированного кода в песочнице) ещё не построен. Значит ни одно разрешение
 * не выдавалось, срок ни разу не истекал, и весь механизм ни разу не исполнялся —
 * при том что читается он как действующий. Строка перестаёт быть верной в день
 * первого вызова grantedByHuman(); тогда её снимают, а заодно считают, попадает
 * ли хоть одно реальное действие в зазор между весом разрешаемого и потолком
 * авторизации в ActionGate.
 */
class TaskAuthorization private constructor(
    /** Короткий идентификатор для журнала — по нему разрешение находится в action_evidence. */
    val id: String,
    /** Разрешённый тип действия. Ровно один, не набор. */
    val type: ActionType,
    /** Компонент, которому разрешено. Сравнивается со строкой requestedBy запроса. */
    val requestedBy: String,
    /** Задача, в рамках которой разрешение действует. */
    val taskSessionId: String,
    /** Кто подтвердил — для журнала, НЕ для решения (см. no-authority-via-text-claim). */
    val grantedBy: String,
    val grantedAt: Long,
    val expiresAt: Long
) {

    fun isExpired(now: Long): Boolean = now >= expiresAt

    /**
     * Подходит ли разрешение под конкретный запрос.
     *
     * Принимает примитивы, а не ActionRequest, намеренно: объект остаётся простым
     * значением и ничего не знает об устройстве запроса. Решение о том, что с чем
     * сравнивать, принимает гейт — в одном месте, где его видно.
     *
     * Любое несовпадение — false. Никаких "почти подходит".
     */
    fun covers(
        type: ActionType,
        requestedBy: String,
        taskSessionId: String,
        now: Long
    ): Boolean =
        !isExpired(now) &&
            this.type == type &&
            this.requestedBy == requestedBy &&
            this.taskSessionId == taskSessionId

    /** Строка для журнала и для экрана. Без неё в evidence осталась бы голая ссылка. */
    fun describe(): String =
        "разрешение $id: ${type} для $requestedBy в задаче $taskSessionId, выдал $grantedBy"

    companion object {

        /**
         * Срок жизни по умолчанию — потолок на случай зависшей задачи, НЕ ожидаемая
         * длительность.
         *
         * Значение назначенное, а не измеренное: час заметно больше прогона цикла
         * (порядок — десятки минут) и при этом не превращает разрешение в
         * бессрочное. Область у него узкая: оценка снята с нынешнего устройства и
         * нынешних maxIterations и maxTokens; при их правке потолок пересчитывается,
         * иначе он либо станет бессрочным по смыслу, либо начнёт рвать живые задачи.
         * Перепроверить можно будет тогда, когда пойдут настоящие задачи: сравнить
         * grantedAt с временем их завершения. Сейчас сравнивать не с чем.
         */
        const val DEFAULT_LIFETIME_MS: Long = 60 * 60 * 1000L

        /**
         * ЕДИНСТВЕННЫЙ способ создать разрешение. Вызывается только из обработчика
         * диалога подтверждения в интерфейсе — то есть после того, как человек
         * реально нажал кнопку.
         *
         * Осознанно принимается как факт: подтверждение процедурное. Оно
         * авторизует ПРОЦЕСС запуска попыток агента в песочнице Termux, а не
         * конкретный текст — код на каждой итерации разный, показывать его
         * человеку на каждом шаге бессмысленно и вредно (приучает жать "да"
         * рефлекторно). Поэтому безопасность держится на узости песочницы и на
         * возможности прервать — то есть на аварийном стопе, который является
         * второй половиной этой конструкции, а не дополнением к ней.
         */
        fun grantedByHuman(
            type: ActionType,
            requestedBy: String,
            taskSessionId: String,
            grantedBy: String,
            now: Long = System.currentTimeMillis(),
            lifetimeMs: Long = DEFAULT_LIFETIME_MS
        ): TaskAuthorization = TaskAuthorization(
            id = "auth-$now-${taskSessionId.take(8)}",
            type = type,
            requestedBy = requestedBy,
            taskSessionId = taskSessionId,
            grantedBy = grantedBy,
            grantedAt = now,
            expiresAt = now + lifetimeMs
        )
    }
}
