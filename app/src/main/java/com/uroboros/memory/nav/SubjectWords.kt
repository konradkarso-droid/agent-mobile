package com.uroboros.memory.nav

/**
 * Слово-предмет: слово вопроса, по которому запись может прийти в ответ сама.
 * Чистый объект: слово и словарь на входе, да или нет на выходе.
 *
 * ЗАЧЕМ. Отбор ищет записи по началу слов реплики, и общее слово без предмета
 * приводит запись не по делу: на «Хорошо, попробую» приходит «Хорошо.
 * Правильно», на «Потом. Сейчас не надо» — всё, где есть «потому». Таких
 * записей модель не отличает от нужных и строит ответ из них. Замер по
 * выгрузке ходов одного телефона: из 297 записей, пришедших по словам
 * вопроса, 92 пришли только по таким словам; из просмотренных 26 к вопросу
 * относились 3–4.
 *
 * ПРАВИЛО. Предмет — слово, у которого хоть один разбор словаря —
 * существительное, полное прилагательное или числительное, и нет ни одного
 * разбора связкой: наречием, местоимением, частицей, союзом, предлогом,
 * междометием, предикативом, притяжательным или указательным («мой»,
 * «такой» — пометка Apro). Глагол — тоже не предмет. Разбор связкой
 * перевешивает: «потом» в словаре ещё и «пот», «хорошо» — ещё и оценка, а в
 * реплике они почти всегда связки.
 * Слово, которого словарь не знает (редкий термин, латиница, число), —
 * предмет: незнакомое чаще имя или название, чем связка.
 *
 * Запись проходит окно, если среди совпавших с ней слов вопроса есть хоть
 * один предмет; остальные совпавшие слова по-прежнему считаются в её вес.
 *
 * ЧЕГО НЕ УМЕЕТ:
 *  - вопрос, вся суть которого в глаголе («ты выбрал?», «кто фехтует?»),
 *    записи по этому глаголу не найдёт — потеря в невосстановимую сторону,
 *    принята ради того, что отсекается; имена и предметы того же вопроса
 *    ищут как прежде, и окно якорей (Anchors) от этого правила не зависит;
 *  - существительное, совпадающее с наречием («дома», «утром», «весной»),
 *    предметом не считается — та же плата за «потом»;
 *  - общее существительное («разговор», «память», «раз») — предмет, и запись
 *    по нему придёт: правило снимает слова без предмета, а не все пустые;
 *  - смысла не знает: «работаю» и «профессия» для него разные слова;
 *  - словарь не загружен — правило молчит, отбор идёт как без него.
 */
object SubjectWords {

    /** Части речи, которыми бывает предмет: существительное, полное прилагательное, числительное. */
    val SUBJECT_PARTS: Set<String> = setOf("NOUN", "ADJF", "NUMR")

    /** Части речи связок: служебные слова портрета, предикативы и наречия. */
    val LINK_PARTS: Set<String> = Portrait.FUNCTION_WORDS + "PRED" + "ADVB"

    /** Пометка притяжательных и указательных слов в словаре. */
    private const val PRONOMINAL = "Apro"

    /** Предмет ли [word] (приведённое слово вопроса) — см. шапку, «ПРАВИЛО». */
    fun isSubject(word: String, dictionary: LemmaDictionary): Boolean {
        val analyses = dictionary.analyze(word)
        if (analyses.isEmpty()) return true
        if (analyses.any { it.partOfSpeech in LINK_PARTS || PRONOMINAL in it.tags }) return false
        return analyses.any { it.partOfSpeech in SUBJECT_PARTS }
    }

    /** Есть ли среди совпавших слов вопроса [matched] предмет. [dictionary] null — правило молчит: да. */
    fun hasSubject(matched: Collection<String>, dictionary: LemmaDictionary?): Boolean =
        dictionary == null || matched.any { isSubject(it, dictionary) }
}
