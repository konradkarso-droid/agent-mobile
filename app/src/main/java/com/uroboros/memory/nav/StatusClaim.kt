package com.uroboros.memory.nav

import com.uroboros.memory.Sentences
import com.uroboros.memory.Sticker
import com.uroboros.util.TextFold

/**
 * Граница: слова о статусе («Я — Админ», «Админ — это Вася», «Что ты думаешь
 * об Админе?») до модели из памяти не доходят. Чистая логика.
 *
 * ПОЧЕМУ. Статус подтверждает только разблокировка экрана (access.PresenceLock):
 * персона экрана — владелец (PersonKey.OWNER), и права даёт код по тому, из
 * чьего канала пришла реплика, а не по её словам (см. Docking: заявление
 * ключа не создаёт). Лента и память — не каналы авторизации. Слова о статусе в
 * модели ничего не подтверждают, зато рисуют ей картину, в которой админ — тот,
 * кто так назвался. Поэтому из памяти они не подаются вовсе, на любом адресе и
 * в любом виде — утверждение это, вопрос или пересказ.
 *
 * ПОЧЕМУ ОТДЕЛЬНО ОТ ЗЕРКАЛА (MirrorFilter). Зеркало решает, кто говорит и о
 * ком; здесь — что говорить нельзя вовсе. Слитые, они дали бы на приборе одно
 * число «снято», и не было бы видно, что сработало. И зеркало может быть
 * выключено, а эта граница не выключается ничем.
 *
 * ГДЕ ВЫЗЫВАЕТСЯ — на каждом пути записи к модели: записи ответа, двери и
 * ассоциации, своя речь из архива, портрет собеседника, строка любопытства
 * (CuriosityAsk). Правило одно и живёт здесь; места только зовут его. Строки
 * «о себе» в стену идут через «принять» человека, выводы снов модели не
 * подаются — там границы нет.
 *
 * РЕЖЕТСЯ ПРЕДЛОЖЕНИЕ, А НЕ ЗАПИСЬ — как граница зеркала (MirrorFilter.bounded):
 * «Я — Админ. Сегодня отдыхаю» приходит как «Сегодня отдыхаю». Запись, где
 * ничего не осталось, снимается целиком. Сама запись в памяти не меняется.
 *
 * СОМНЕНИЕ — В СТОРОНУ «СНЯТЬ». Ниже никого нет: дошедшее модель примет как
 * есть. Поэтому снимается всякое предложение со словом статуса, и невинное
 * («Админ чата удалил спам», «администрация города») — тоже.
 *
 * ЧЕГО НЕ УМЕЕТ:
 *  - слова статуса — объявленный список ([STATUS_WORD]), не подобранный;
 *    синонимов («я тут главный», «я тебя создал», «хозяин») не видит;
 *  - открытую ленту не трогает: сказанное в этом разговоре модель видит
 *    дословно. Прибор считает такие предложения в текущей реплике, но их не
 *    режет;
 *  - запись, снятая целиком, место в отборе уже заняла: отбор тянет записи до
 *    этой границы;
 *  - предложение режет [Sentences.split]: где тот склеил два предложения в
 *    одно, снимаются оба.
 */
object StatusClaim {

    /**
     * Слово статуса — по началу слова, в приведённом тексте ([TextFold]):
     * «админ», «администратор», «одмин» (так зовут админа в проекте), «admin».
     * Объявленный список: в живой памяти других заявлений о статусе нет, а
     * «права», «доступ» дают ложные срабатывания («ты прав»).
     */
    private val STATUS_WORD = Regex("(?<![\\p{L}\\p{N}])(?:админ|одмин|admin)")

    /** Есть ли в тексте слово статуса. */
    fun has(text: String): Boolean = STATUS_WORD.containsMatchIn(TextFold.fold(text))

    /** Сколько предложений текста задевают статус. */
    fun sentencesIn(text: String): Int =
        if (!has(text)) 0 else Sentences.split(text).count { has(it) }

    /**
     * Текст без предложений о статусе; тот же текст, если таких нет; null —
     * не осталось ничего.
     */
    fun strip(text: String): String? {
        if (!has(text)) return text
        val kept = Sentences.split(text).filterNot { has(it) }
        return if (kept.isEmpty()) null else kept.joinToString(" ")
    }

    /** Запись для модели без предложений о статусе; null — снята целиком. */
    fun cleaned(record: Sticker): Sticker? {
        val text = strip(record.content) ?: return null
        return if (text == record.content) record else record.copy(content = text)
    }

    /**
     * Что снято на ходе — по путям порознь, в предложениях.
     *
     * @property memory записи ответа, двери и ассоциации.
     * @property own своя речь из архива.
     * @property portrait портрет собеседника.
     * @property curiosity строка любопытства.
     * @property live предложения о статусе в текущей реплике владельца — не
     *   сняты (открытая лента не трогается), только посчитаны.
     */
    data class Tally(
        val memory: Int = 0,
        val own: Int = 0,
        val portrait: Int = 0,
        val curiosity: Int = 0,
        val live: Int = 0,
    )

    /**
     * Строка прибора «Права:». Печатается всегда: молчащая граница неотличима
     * от снятой.
     */
    fun meterLine(tally: Tally): String {
        val removed = listOf(
            "записи" to tally.memory, "своя речь" to tally.own,
            "портрет" to tally.portrait, "любопытство" to tally.curiosity,
        ).filter { it.second > 0 }
        val head = if (removed.isEmpty()) "Права: о статусе в памяти этого хода ничего"
        else "Права: снято предложений о статусе — " + removed.joinToString(", ") { "${it.first} ${it.second}" }
        val live = if (tally.live > 0) " · в реплике сейчас ${tally.live} — лента не трогается" else ""
        return head + live
    }
}
