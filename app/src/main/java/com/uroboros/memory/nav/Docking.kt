package com.uroboros.memory.nav

/**
 * Стыковочный узел для чатов: только форма, без таблиц и без входов.
 *
 * Сейчас канал один — экран, собеседников двое: владелец и агент. Их ключи —
 * постоянные константы того вида, какой будет у реестра персон. Реестра
 * (таблицы) нет: он появляется с третьей персоной, вместе с телеграмом, и
 * тогда же подключаются входы:
 *  - ключ персоны из проверяемого канала (телеграм id) — [PersonKey];
 *  - место каждой записи пишет дверь записи явно (HourglassMemory.saveEventChecked)
 *    — [Place];
 *  - слияние двух персон делает только владелец, отдельным действием, —
 *    [PersonMerge].
 *
 * ОТСУТСТВИЕ МЕСТА = ЭКРАН — верно только до включения телеграма: другого
 * канала не было. С его включением место перестаёт выводиться и начинает
 * храниться.
 */

/**
 * Неизменный ключ персоны. Всегда из проверяемого канала — никогда имя или
 * ник: имена совпадают и дрейфуют, ключ нет. Заявление в разговоре («я —
 * Петя») ключа не создаёт.
 */
@JvmInline
value class PersonKey(val id: String) {
    companion object {
        /** Владелец: тот, кто говорит с экрана телефона. */
        val OWNER = PersonKey("screen:owner")

        /** Агент: то, что отвечает моделью. */
        val AGENT = PersonKey("model:agent")
    }
}

/**
 * Где прозвучало. Сейчас используется только [SCREEN]; [DIRECT] и [GROUP]
 * объявлены для телеграма и ничем не выставляются. Содержимое из лички в
 * группу не переходит никогда — граница будет запретом, а не весом.
 */
enum class Place { SCREEN, DIRECT, GROUP }

/**
 * Связь «эти ключи — одна персона». Ключи не переписываются: слияние — это
 * связь, отмена — снять связь. Ставит только владелец отдельным действием.
 * Сейчас не создаётся нигде: персон, которых можно было бы слить, нет.
 */
data class PersonMerge(val first: PersonKey, val second: PersonKey)
