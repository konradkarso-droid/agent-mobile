    )

    // Ordered longest-first so the longest matching suffix is stripped.
    // Deliberately crude (no dictionary, no morphology) — this is cheap
    // friction toward the reviewPending checkpoint, not a linguistic tool.
    // 2026-08-18: added "ия" alongside the existing "ию" — without it, the
    // accusative ("-ию") and nominative ("-ия") forms of the same noun
    // (e.g. "функцию"/"функция") stemmed to different roots, silently killing
    // Jaccard overlap between them (found via item 9's QueryUrgencyClassifier
    // using RiskTrigger.textSimilarity on task descriptions vs. queries).
    private val SUFFIXES = listOf(
        "иями",
        "ями", "ами", "ого", "его", "ому", "ему", "ыми", "ими",
        "ев", "ов", "ам", "ям", "ах", "ях", "ом", "ем", "ей",
        "юю", "ая", "яя", "ое", "ее", "ых", "их", "ию", "ия", "ья", "ье", "ий", "ый",
        "ы", "и", "а", "я", "о", "е", "у", "ю", "й", "ь"
    )

    private const val MIN_ROOT_LENGTH = 3

    // Те же слова отрицания, приведённые к основе: остаток для
    // ContradictionMark.exactRemainder считается по основам, и снимать с него
    // надо основы, иначе «невозможно» осталось бы в остатке как «невозможн».
    //
    // Стоит ПОСЛЕ SUFFIXES намеренно: объект заполняет поля по порядку, и
    // выше SUFFIXES stem() увидел бы ещё пустой список окончаний.
    private val NEGATION_STEMS = NEGATION_MARKERS.mapTo(HashSet()) { stem(it) }

    // Порог схожести, при котором две записи вообще сравниваются на
    // противоречие. Подтверждён замером на восьми заведомых противоречиях,
    // шести заведомо безобидных парах и всех парах живой базы: 0.5 —
    // наибольшее значение, при котором ложных срабатываний ноль и на
    // выдуманных парах, и на живых. Ниже 0.5 ложные появляются сразу и
    // именно на живом материале: логи прогонов («успех за 3 итераций» и
    // «успех за 5 итераций») начинают считаться противоречащими, хотя это
    // разные прогоны, а не спорные утверждения.
    //
    // Чего порог стоит: пересказ теми же по смыслу, но другими словами
    // ("у паука восемь ног" / "пауки имеют четыре ноги") даёт схожесть
    // около 0.33 и до сравнения чисел не доходит. Опустить порог ради
    // таких пар нельзя — ложные начинаются раньше, чем ловятся эти.
    // Формальными средствами пересказ не берётся вовсе.
    private const val CONTRADICTION_JACCARD_THRESHOLD = 0.5

    // Граница предложений для withoutQuestions: знак конца и пробел после.
    private val SENTENCE_BREAK = Regex("(?<=[.!?…])\\s+")

    // Построения противительной связки; что они берут и чего нет — у clausesOf.
    private val CONTRAST_NOT_BUT = Regex(
        "^(.*?)(?<![\\p{L}\\p{N}])не\\s+(.+?),\\s*а\\s+(.+?)\\.?$",
        RegexOption.IGNORE_CASE,
    )
    private val CONTRAST_BUT_NOT = Regex(
        "^(.*[—-]\\s*)(.+?),\\s*а\\s+не\\s+(.+?)\\.?$",
        RegexOption.IGNORE_CASE,
    )
    private const val LONG_CONTENT_CHARS = 240

    // Порог схожести для распознавания "той же самой" ошибки компилятора
    // (item 7a: лавинообразный расход энергии при зацикливании).
    private const val REPEATED_ERROR_JACCARD_THRESHOLD = 0.7

    data class Decision(
        val shouldReview: Boolean,
        val reasons: List<String>,
        val contradictionCandidateId: Long? = null
    )

    /**
     * За что правило противоречия зацепилось в паре текстов.
     *
     * Порядок объявления значим: в нём [contradictionMarks] перечисляет
     * признаки, и экран печатает их так же.
     */
    enum class MarkKind {
        /**
         * Отрицание есть у одной стороны сравниваемой пары и отсутствует у
         * другой. Фраза со связкой сравнивается по частям, см. [clausesOf].
         *
         * Признак расслоен на два слоя разной надёжности — см.
         * [ContradictionMark.exactRemainder].
         */
        NEGATION,

        /** Числа сторон разошлись. */
        NUMBER,

        /**
         * На месте одного значимого слова стоит другое, всё остальное
         * совпало: «рубанок с ДЕРЕВЯННОЙ колодкой» против «рубанок с
         * ЖЕЛЕЗНОЙ колодкой».
         *
         * Отдельный признак, а не разновидность прежних: ни «не», ни числа
         * в таких парах нет, и до этого признака они не замечались вовсе.
         * Типичный случай — не спор двух старых записей, а расхождение
         * записи с тем, что человек говорит сейчас.
         *
         * СЧИТАЕТСЯ, ТОЛЬКО ЕСЛИ НИ У ОДНОЙ СТОРОНЫ НЕТ ОТРИЦАНИЯ. При двух
         * «не» замена слова спора не делает: «не светит белым» и «не светит
         * алым» уживаются вместе. При одном «не» работает [NEGATION].
         *
         * ЧЕГО НЕ УМЕЕТ: синонимы неотличимы от замены — «светит» против
         * «сияет» будет названо спором. Это граница правила, а не недочёт
         * его настройки: формальными средствами одно от другого не
         * отделяется.
         */
        SWAP,
    }

    /**
     * Один признак спора, найденный в паре текстов, со словами, которыми он
     * выражен.
     *
     * ЗАЧЕМ СЛОВА, А НЕ ПРОСТО ВИД ПРИЗНАКА. Показ обязан уметь выделить в
     * самой фразе то, за что зацепилось правило. Считать это на экране заново
     * значило бы завести вторую копию правила: она разойдётся с первой, и не
     * будет видно, какая врёт.
     *
     * СТОРОНЫ НЕ СИММЕТРИЧНЫ, И ПУСТАЯ СТОРОНА — ЗАКОННЫЙ ИСХОД. У [NEGATION]
     * слова есть ровно у одной стороны: признак в том и состоит, что у второй
     * отрицания НЕТ, и выделять там нечего. У [NUMBER] пустой может оказаться
     * любая из двух, когда числа одной стороны — подмножество чисел другой.
     *
     * Фраза со связкой сравнивается несколькими парами частей (см.
     * [clausesOf]), и один вид признака может найтись в нескольких из них.
     * Признак тогда один на вид, слова в нём — объединение по всем спорящим
     * парам частей. Взять одну пару частей вместо объединения нельзя: какую —
     * зависело бы от порядка аргументов, и признаки перестали бы
     * переворачиваться вместе с текстами. У [NUMBER] объединение может
     * заполнить обе стороны. У [NEGATION] — нет: утверждаемая часть связки
     * несёт явное «не», поэтому отрицание стоит у одной стороны и здесь.
     *
     * ЧЕГО ЗДЕСЬ НЕТ. Мест в тексте. Правило работает на множествах слов:
     * порядок и смещения теряются на разборе, и восстановить их нечем.
     * Вхождение ищет тот, кто показывает, и отсюда две его границы: слово,
     * встречающееся в тексте несколько раз, выделится везде, а искать надо не
     * различая регистра — слова здесь приведены к нижнему.
     *
     * @property first слова со стороны первого текста, как они стоят в нём
     *                 (для числительных словами — само слово, а не цифра).
     * @property second то же со стороны второго.
     * @property exactRemainder только у [MarkKind.NEGATION]: без слов
     *                 отрицания стороны совпали ПОЛНОСТЬЮ — одно и то же
     *                 утверждение сказано с «не» и без. У остальных признаков
     *                 всегда ложь.
     *
     * ДВА СЛОЯ ОТРИЦАНИЯ, А НЕ ОДИН. Отрицание у одной стороны при совпавшем
     * остатке — спор без вариантов: сравнивать больше нечего, других слов нет.
     * Отрицание при разошедшемся остатке — вопрос уже не в полярности, а в
     * том, о чём каждая сторона: сюда попадают и ложные споры из [clausesOf]
     * («не X, а Y» против «Y»), и настоящие споры, сказанные разными словами.
     * Слитые в один признак, два слоя выглядят одинаково надёжными, и ложная
     * тревога второго слоя тратит доверие к первому.
     *
     * Остаток сравнивается по основам слов ([stemmedTokenize]), без знаков
     * препинания и регистра — той же меркой, что и схожесть. Фраза со связкой
     * даёт точный остаток, если он точен хотя бы у одной пары её частей: такая
     * пара частей и есть спор без вариантов внутри фразы.
     *
     * ЧЕГО НЕ УМЕЕТ. Совпавший остаток значит «тексты различаются одними
     * словами отрицания», а не «одна сторона отрицает то, что утверждает
     * другая». Разница есть при двойном отрицании: «я не могу не работать по
     * субботам» против «я могу работать по субботам» получит точный остаток,
     * хотя первое значит «обязан», а не «не могу». Признак считает, есть ли
     * отрицание, а не сколько его и что оно отрицает. Обороты вроде «не зря»
     * и «не только» сюда НЕ попадают: у них в остатке лишнее слово. На
     * испытательной базе ложных точных пар не нашлось, но это свойство базы,
     * а не правила.
     *
     * Не вердикт о стороне: какая из двух верна, признак не знает и здесь.
     */
    data class ContradictionMark(
        val kind: MarkKind,
        val first: Set<String>,
        val second: Set<String>,
        val exactRemainder: Boolean = false,
    )

    fun evaluate(candidate: Sticker, sameTagHotStickers: List<Sticker>): Decision {
        val reasons = mutableListOf<String>()

        val contradiction = findContradiction(candidate, sameTagHotStickers)
        if (contradiction != null) {
            reasons += "contradiction"
            return Decision(
                shouldReview = true,
                reasons = reasons,
                contradictionCandidateId = contradiction.id
            )
        }

        var lowWeightCount = 0

        if (importanceOf(candidate.importance) == Importance.HIGH) {
            lowWeightCount++
            reasons += "high_importance"
        }

        if (hasUncertaintyMarker(candidate.content)) {
            lowWeightCount++
            reasons += "uncertainty_marker"
        }

        if (candidate.content.length >= LONG_CONTENT_CHARS) {
            lowWeightCount++
            reasons += "long_content"
        }

        val trigger = lowWeightCount >= 2
        return Decision(
            shouldReview = trigger,
            reasons = if (trigger) reasons else emptyList()
        )
    }

    /**
     * Считает две ошибки компилятора "той же самой" по текстовому сходству
     * (переиспользует ту же стемминг+Jaccard инфраструктуру, что и поиск
     * противоречий, только в обратную сторону: не различие, а повтор).
     * Используется item 7a для лавинообразного расхода энергии при зацикливании.
     */
    fun isRepeatedError(currentError: String, previousError: String): Boolean {
        val a = stemmedTokenize(currentError)
        val b = stemmedTokenize(previousError)
        return jaccard(a, b) >= REPEATED_ERROR_JACCARD_THRESHOLD
    }

    /**
     * Общего назначения коэффициент текстовой схожести (0.0–1.0), без встроенного
     * порога — вызывающий код сам решает, что считать "похоже". Переиспользует ту же
     * стемминг+Jaccard инфраструктуру, что isRepeatedError/findContradiction.
     *
     * Item 9 (2026-08-18): используется классификатором light/heavy для сравнения
     * входящего запроса пользователя с (текущей ошибкой + описанием подзадачи) на
     * швах TOTE-цикла — сюда сознательно НЕ зашит собственный порог, чтобы
     * RiskTrigger оставался общей утилитой, не завязанной на конкретный домен.
     */
    fun textSimilarity(a: String, b: String): Double =
        jaccard(stemmedTokenize(a), stemmedTokenize(b))

    /**
     * Важность записи из строки, лежащей в базе. Незнакомое или пустое
     * значение — [Importance.LOW], а не исключение.
     *
     * Поле строковое, и в нём может оказаться что угодно: значение из старой
     * схемы, опечатка, чужой импорт. Разворачивать его через
     * Importance.valueOf() нельзя: тот бросает на любом незнакомом слове, и
     * падение уносит с собой всю оценку записи — хотя важность здесь лишь
     * один из трёх слабых признаков и решающего голоса не имеет.
     * Направление ошибки выбрано в восстановимую сторону: непонятная
     * важность считается низкой, признак не срабатывает, запись сохраняется
     * как обычная.
     *
     * Ровно так же поступают два других места проекта, где та же строка
     * превращается в важность (ранжирование в отборе и importanceRank). Это
     * третий экземпляр одного приёма, и он приведён к тем же двум.
     *
     * Сравнение точное, без приведения регистра и обрезки пробелов: строку
     * пишет код, а не человек, и молчаливое исправление здесь скрыло бы
     * настоящий разнобой в том, кто и как её ставит.
     *
     * ЧТО ЭТО НЕ ЧИНИТ. Признак "high_importance" сегодня не срабатывает
     * никогда, и по другой причине: важность никто не выставляет, у всех
     * записей значение по умолчанию. Здесь исправлено только поведение при
     * мусоре в поле.
     */
    private fun importanceOf(raw: String): Importance =
        Importance.values().firstOrNull { it.name == raw } ?: Importance.LOW

    private fun hasUncertaintyMarker(text: String): Boolean {
        val words = tokenize(text)
        return UNCERTAINTY_MARKERS.any { marker ->
            if (marker.contains(' ')) text.lowercase().contains(marker) else words.contains(marker)
        }
    }

    /**
     * Противоречат ли два текста по тому же правилу, по которому запись
     * встаёт в очередь на проверку.
     *
     * Вынесено наружу, чтобы у правила была ОДНА реализация. Экран разбора
     * сопоставляет записи, уже вытащенные из базы, и без этого предиката ему
     * пришлось бы либо звать проверку по разу на запись, либо завести вторую
     * копию правила рядом. Вторая копия расходится с первой, и не видно,
     * какая врёт.
     *
     * ЧТО ЭТО НЕ ЗНАЧИТ. Предикат отвечает на вопрос о ПАРЕ и ничего не знает
     * о том, как решалось при сохранении. Там противник ищется перебором и
     * поиск останавливается на первом подошедшем (см. [findContradiction]),
     * поэтому две записи могут противоречить друг другу по этому предикату,
     * а бит при сохранении был поднят из-за третьей. Обратное тоже бывает:
     * бит поднимается и вовсе без противника — по двум слабым признакам
     * сразу (см. [evaluate]).
     *
     * ЧЕГО НЕ УМЕЕТ. Правило грубое намеренно: это дешёвое трение к проверке
     * человеком, а не разбор смысла. Пересказ теми же по смыслу, но другими
     * словами не берётся вовсе — до сравнения отрицаний и чисел такая пара не
     * доходит, схожесть ниже порога. Порог и его область — у
     * [CONTRADICTION_JACCARD_THRESHOLD]. Фраза с противительной связкой
     * сравнивается по частям; что это даёт и чего не даёт — у [clausesOf].
     * Предложения-вопросы не сравниваются вовсе, см. [withoutQuestions].
     *
     * Записи не сравниваются с самими собой: об этом заботится вызывающий,
     * предикату идентичности записей не видно — он получает только тексты.
     */
    fun contradicts(a: String, b: String): Boolean =
        contradictionMarks(a, b).isNotEmpty()

    /**
     * Пара, которую сравнивать не на что: отчёт агента о собственной работе
     * стоит с ОБЕИХ сторон.
     *
     * Отчёт о прогоне — запись события, а не утверждение о мире. Два прогона
     * не спорят никогда, сколько бы чисел в них ни разошлось: «Успех за 3
     * итераций» и «Успех за 5 итераций» — два разных прогона одной задачи.
     * Правило этого само не видит: тексты отчётов почти совпадают (тело кода
     * одно), а числа разные, и признак чисел срабатывает исправно.
     *
     * ПОЧЕМУ НЕ СНЯТЬ ОТЧЁТЫ СОВСЕМ. Отчёт против слов человека спорить
     * может, и такой случай наблюдался живьём: модель пересказала человеку
     * его же словами то, что на деле было отчётом агента. Снимаются пары, а
     * не записи.
     *
     * ОДНО МЕСТО НА ВЕСЬ ПРОЕКТ. Тем же правилом пользуется ночной судья
     * (см. JudgeRun): решение здесь одно, и двух его копий быть не должно —
     * разойдясь, они дали бы очередь и список судьи, спорящие друг с другом.
     * Сон устроен иначе и строже: отчёты не снятся вовсе, ни в какой паре.
     */
    fun bothAgentReports(oneSource: String, otherSource: String): Boolean =
        oneSource == SourceKind.AGENT_INFERRED.name &&
            otherSource == SourceKind.AGENT_INFERRED.name

    /**
     * Близки ли два текста настолько, что правило вообще берётся их
     * сравнивать: та же схожесть и тот же порог
     * [CONTRADICTION_JACCARD_THRESHOLD], с которого начинается поиск
     * признаков.
     *
     * Наружу вынесено ради показа снов: там близкие по словам записи
     * образуют семью («Меркурий светит белым / красным / алым на закате»), и
     * сны, отличающиеся только заменой записи внутри семьи, схлопываются в
     * один. Порог у семьи и у правила ОДИН намеренно: два порога рядом
     * разошлись бы при первой же настройке, и стало бы не видно, какой из них
     * что двигает.
     *
     * ЧТО ЭТО НЕ ЗНАЧИТ. Близость — не спор и не повтор: она говорит лишь,
     * что тексты об одном и том же, а спорят ли они, отвечает
     * [contradictionMarks]. Части фразы здесь не разбираются (см.
     * [clausesOf]) — сравниваются тексты целиком.
     */
    fun closeEnoughToCompare(a: String, b: String): Boolean =
        jaccard(stemmedTokenize(a), stemmedTokenize(b)) >= CONTRADICTION_JACCARD_THRESHOLD

    /**
     * Те же признаки, по которым отвечает [contradicts], но названные
     * поимённо и со словами, которыми они выражены.
     *
     * ЭТО ТО ЖЕ САМОЕ ПРАВИЛО, А НЕ ВТОРОЕ. [contradicts] спрашивает у него
     * же и отвечает "да", когда список непуст. Двух реализаций нет и заводить
     * их нельзя: разойдясь, они дадут экран, противоречащий очереди.
     *
     * ПУСТОЙ СПИСОК ОЗНАЧАЕТ "НЕ ПРОТИВОРЕЧАТ", и другого смысла у него нет.
     * Обратное тоже верно и нужнее: у пары, признанной спорящей, признаков
     * всегда хотя бы один. Ноль признаков рядом с названным противником —
     * поломка, а не тишина, и показывающий вправе на это опереться.
     *
     * ПОРЯДОК ПРИЗНАКОВ УСТОЙЧИВ: сперва отрицание, потом числа — в порядке
     * объявления [MarkKind]. Экран, перечисляющий их подряд, не должен
     * переставляться от запуска к запуску.
     *
     * СРАВНИВАЮТСЯ ЧАСТИ, А НЕ ФРАЗЫ ЦЕЛИКОМ. Каждая сторона раскладывается
     * [clausesOf], каждая часть одной сравнивается с каждой частью другой, и
     * признаки одного вида сводятся в один. Фраза без связки — сама себе
     * единственная часть, и для неё всё идёт как раньше.
     *
     * ЧЕГО НЕ УМЕЕТ — всё то же, что у [contradicts]: пара сравнивается только
     * после порога схожести, пересказ другими словами не берётся вовсе. Плюс
     * своё: числа сверяются как множества, поэтому названы будут только те,
     * что есть у одной стороны и нет у другой. Общее число, стоящее рядом с
     * разошедшимся, не назовётся, хотя спор может быть именно о нём.
     */
    fun contradictionMarks(a: String, b: String): List<ContradictionMark> {
        val found = clausesOf(a).flatMap { partA ->
            clausesOf(b).flatMap { partB -> clauseMarks(partA, partB) }
        }
        return MarkKind.values().mapNotNull { kind ->
            val ofKind = found.filter { it.kind == kind }
            if (ofKind.isEmpty()) null
            else ContradictionMark(
                kind,
                ofKind.flatMapTo(HashSet()) { it.first },
                ofKind.flatMapTo(HashSet()) { it.second },
                exactRemainder = ofKind.any { it.exactRemainder },
            )
        }
    }

    /**
     * Признаки одной пары частей — правило без разложения: порог схожести,
     * затем отрицание у одной стороны, расхождение чисел и замена одного
     * значимого слова.
     */
    private fun clauseMarks(a: String, b: String): List<ContradictionMark> {
        val wordsA = stemmedTokenize(a)
        val wordsB = stemmedTokenize(b)
        if (jaccard(wordsA, wordsB) < CONTRADICTION_JACCARD_THRESHOLD) return emptyList()

        val marks = mutableListOf<ContradictionMark>()

        val negationsA = tokenize(a).filterTo(HashSet()) { it in NEGATION_MARKERS }
        val negationsB = tokenize(b).filterTo(HashSet()) { it in NEGATION_MARKERS }
        if (negationsA.isEmpty() != negationsB.isEmpty()) {
            marks += ContradictionMark(
                MarkKind.NEGATION, negationsA, negationsB,
                exactRemainder = wordsA - NEGATION_STEMS == wordsB - NEGATION_STEMS,
            )
        }

        // Цифровая запись служит ключом сравнения, слова из текста — ответом
        // показу: "семь" и "7" спорят об одном, а выделить в тексте надо то,
        // что там написано.
        val numbersA = numbersWithSurface(a)
        val numbersB = numbersWithSurface(b)
        if (numbersA.isNotEmpty() && numbersB.isNotEmpty() && numbersA.keys != numbersB.keys) {
            marks += ContradictionMark(
                MarkKind.NUMBER,
                surfacesOf(numbersA, numbersA.keys - numbersB.keys),
                surfacesOf(numbersB, numbersB.keys - numbersA.keys),
            )
        }

        // Замена слова ищется последней и только при полном отсутствии
        // отрицаний — см. [MarkKind.SWAP]. Значимость слова здесь та же, что
        // у поиска и сна (MIN_WORD_LENGTH, STOP_WORDS): без неё в улов идут
        // предлоги и вопросительные слова, а спора в них нет.
        if (negationsA.isEmpty() && negationsB.isEmpty()) {
            val significantA = significantByStem(a)
            val significantB = significantByStem(b)
            val onlyA = significantA.keys - significantB.keys
            val onlyB = significantB.keys - significantA.keys
            // Ровно одно против одного. Два расхождения и больше — это уже
            // разные утверждения, а не спор об одном и том же: замер на
            // сочинённых парах показал, что при «до двух» в улов попадают
            // пары про разное время и разный цвет разом.
            if (onlyA.size == 1 && onlyB.size == 1) {
                marks += ContradictionMark(
                    MarkKind.SWAP,
                    onlyA.flatMapTo(HashSet()) { significantA.getValue(it) },
                    onlyB.flatMapTo(HashSet()) { significantB.getValue(it) },
                )
            }
        }

        return marks
    }

    /**
     * Основы значимых слов текста — та же мерка значимости, что у признака
     * «другое слово» и у поиска (MIN_WORD_LENGTH, STOP_WORDS). Открыта для
     * сита судьи (judge.JudgeSieve): судья отбирает пары той же меркой слов,
     * какой правило их сравнивает, а не второй, своей.
     */
    fun significantStems(text: String): Set<String> = significantByStem(text).keys

    /**
     * Основы слов текста для детекторов эха (llm.EchoCheck): то же разбиение и
     * та же основа, что у [significantStems], отсев коротких слов тот же, но
     * БЕЗ отсева по STOP_WORDS (зачем тот список — его KDoc в HourglassMemory).
     * Детектору нужны не слова темы, а слова, которые модель повторила:
     * «сейчас» темы не несёт, но несёт эхо. Со списком каждое его пополнение
     * ради поиска молча слепило бы детектор.
     */
    fun echoStems(text: String): Set<String> =
        tokenize(text)
            .filter { it.length >= MIN_WORD_LENGTH }
            .mapTo(HashSet()) { stem(it) }

    /**
     * Значимые слова текста: основа — ключ, написанные формы — значение.
     *
     * Два уровня по той же причине, что у чисел: сравнивать надо основы
     * («колодка» и «колодкой» — одно слово), а показать человеку надо то,
     * что стоит в тексте.
     */
    private fun significantByStem(text: String): Map<String, Set<String>> =
        tokenize(text)
            .filter { it.length >= MIN_WORD_LENGTH && it !in STOP_WORDS }
            .groupBy({ stem(it) }, { it })
            .mapValues { it.value.toSet() }

    /**
     * Части фразы с противительной связкой — или сама фраза, если связки нет.
     *
     * ЗАЧЕМ. «Мой любимый инструмент — не рубанок, а стамеска» говорит два
     * утверждения сразу. Целиком против записи «Мой любимый инструмент —
     * рубанок с деревянной колодкой» она до сравнения не доходит: вторая
     * половина связки добавляет свои слова, и схожесть падает ниже порога.
     * Разложенная, она даёт часть «…— не рубанок», и та спорит с записью
     * отрицанием.
     *
     * Два построения, и только они:
     *  - «X не Y, а Z» → «X не Y» и «X Z, не Y»;
     *  - «X — Z, а не Y» → «X — Z, не Y» и «X — не Y».
     *
     * ПОЧЕМУ «НЕ Y» ЕСТЬ И В УТВЕРЖДАЕМОЙ ЧАСТИ. Связка отрицает Y во всей
     * фразе, а не только в одной её половине: «не рубанок, а стамеска» —
     * это и «стамеска», и «не рубанок». Без явного «не» утверждаемая часть
     * «…— стамеска» спорила бы отрицанием с чужим «…— не рубанок», с которым
     * фраза на деле согласна. Отрицание здесь не додумано — оно написано в
     * самом тексте, его только перенесли в обе части.
     *
     * ЧЕГО НЕ УМЕЕТ:
     *  - связка без запятой перед «а», связки «но», «зато» и прочие не
     *    раскладываются; второе построение требует тире или дефиса перед
     *    утверждаемым, короткое тире «–» не берётся. Невзятая фраза
     *    сравнивается целиком, как без разложения, — промах в сторону «не
     *    заметили», а не «придумали»;
     *  - текст с переводом строки не раскладывается;
     *  - режет по первому «не» во фразе: фраза с двумя отрицаниями режется не
     *    там, и части выходят бессмысленными;
     *  - ЗАМЕНУ СЛОВА ПРАВИЛО НЕ ВИДИТ, И СВЯЗКА ЭТОГО НЕ МЕНЯЕТ. «Не рубанок,
     *    а стамеска» против «ножовка, а не рубанок» не спорят по правилу, хотя
     *    стамеска и ножовка друг друга исключают: у всех частей обеих фраз
     *    есть «не», и отрицанию не за что зацепиться;
     *  - ЛОЖНЫЙ СПОР ПРАВИЛА ОСТАЁТСЯ, КОГДА ОДНА СТОРОНА ОТРИЦАЕТ ОДНО, А
     *    ДРУГАЯ БЕЗ ОТРИЦАНИЯ УТВЕРЖДАЕТ ДРУГОЕ. «Не рубанок, а стамеска»
     *    против «любимый — стамеска» — спор, хотя фразы согласны. У целых
     *    фраз тот же класс: «не рубанок с деревянной колодкой» против
     *    «рубанок с железной».
     *
     * Начало отрицания ищется просмотром назад по \p{L}\p{N}, а не `\b`, —
     * по той же причине, что у [numbersWithSurface]. Здесь ловушка была бы
     * коварнее: с `\b` первое построение молча перестало бы раскладываться, а
     * второе, где `\b` нет, продолжило бы, и поломка наполовину не видна ни на
     * сборке, ни на прежних тестах. Сторож — тест на оба построения.
     */
    private fun clausesOf(text: String): List<String> {
        val statements = withoutQuestions(text) ?: return emptyList()
        val trimmed = statements.trim()
        CONTRAST_NOT_BUT.matchEntire(trimmed)?.let { match ->
            val (head, denied, affirmed) = match.destructured
            return listOf(head + "не " + denied, head + affirmed + ", не " + denied)
        }
        CONTRAST_BUT_NOT.matchEntire(trimmed)?.let { match ->
            val (head, affirmed, denied) = match.destructured
            return listOf(head + affirmed + ", не " + denied, head + "не " + denied)
        }
        return listOf(statements)
    }

    /**
     * Состоит ли текст из одних вопросов — то есть не утверждает ничего.
     *
     * Тот же признак, которым правило снимает вопросы со сравнения, и отдельного
     * определения вопроса у него нет: что считается вопросом и где признак
     * ошибается — в [withoutQuestions]. Вынесен наружу для тех, кому нужно
     * решение о записи целиком, а не о паре.
     */
    fun isOnlyQuestions(text: String): Boolean = withoutQuestions(text) == null

    /**
     * Текст без предложений-вопросов — или null, если в нём одни вопросы.
     *
     * ЗАЧЕМ. Вопрос ничего не утверждает, и спорить ему не с чем. «Я работаю
     * по субботам?» против записи «Я не работаю по субботам» — не расхождение:
     * запись на вопрос отвечает. Правило же видело бы отрицание у одной
     * стороны, и сверка сказала бы модели «расходятся» ровно там, где надо
     * просто ответить.
     *
     * ВОПРОС — ПРЕДЛОЖЕНИЕ, А НЕ ТЕКСТ. «Станок в мастерской не называется
     * Вымпел. Так как он называется?» — утверждение и вопрос в одной записи, и
     * утверждение спорит с «называется Вымпел». Поэтому убирается только
     * предложение, оканчивающееся на «?», а остаток сравнивается как обычно.
     *
     * Текст без «?» возвращается как есть, символ в символ, и для него всё
     * идёт как без этой функции. Текст со знаком собирается из оставшихся
     * предложений через пробел, так что переводы строк в нём теряются.
     *
     * ЧЕГО НЕ УМЕЕТ:
     *  - вопрос узнаётся только по знаку. Вопрос без «?» — а голосовой ввод
     *    знак может не ставить — сравнивается как утверждение, как раньше;
     *  - риторический вопрос — скрытое утверждение: «Разве я работаю по
     *    субботам?» говорит «не работаю», но убирается, и спор с «работаю»
     *    теряется;
     *  - косвенный вопрос внутри утверждения («не знаю, работаю ли я по
     *    субботам») знака не имеет и сравнивается как утверждение;
     *  - предложения режутся по «.», «!», «?», «…» с пробелом после: «т. е.»
     *    и сокращения режут предложение не там.
     */
    private fun withoutQuestions(text: String): String? {
        if ('?' !in text) return text
        val statements = text.trim()
            .split(SENTENCE_BREAK)
            .filter { sentence -> !isQuestionSentence(sentence) }
            .filter { it.isNotBlank() }
        return if (statements.isEmpty()) null else statements.joinToString(" ")
    }

    /** Предложение-вопрос: кончается на «?», обрамление после знака не в счёт. */
    private fun isQuestionSentence(sentence: String): Boolean =
        sentence.trimEnd('»', '"', ')', ' ').endsWith('?')

    /**
     * Состоит ли запись из одних просьб — или просьб вместе с вопросами, — то
     * есть не утверждает ничего, хотя [isOnlyQuestions] её не узнаёт. Запись из
     * одних вопросов сюда не входит: у неё свой признак и свой счёт.
     *
     * ЗАЧЕМ. Просьба, как и вопрос, ничего не утверждает: «Расскажи про
     * правило», «Назови цвета радуги», «Перепроверь по памяти свой ответ». Знака
     * «?» у неё нет, и всюду, где признак вопроса снимает запись, просьба
     * проходит как утверждение: снится, служит мостом, судится, занимает место в
     * отборе к ответу. Короткая просьба — идеальный мост: «Расскажи про правило»
     * связывает всё со всем.
     *
     * ГДЕ СНИМАЕТ. Там же, где вопросы: отбор к ответу, сны, дверь сна, суд.
     * Считается везде отдельно от вопросов: слитый счёт спрятал бы всплеск
     * ложных срабатываний этого признака под видом «вопросов стало больше».
     * Ошибка в сторону «принять факт за просьбу» прячет факт от каждого ответа,
     * поэтому то, что признак узнаёт, перечислено текстами на экране (см.
     * RequestCensus). Правило противоречия, режущее вопросы по предложениям,
     * просьбы не режет: его поведение измерено на нынешней резке.
     *
     * ПРОСЬБА — ПРЕДЛОЖЕНИЕ, А НЕ ТЕКСТ, как у вопроса. Предложение — просьба,
     * если его первое слово (после вводных вроде «а», «ну», «давай»,
     * «пожалуйста», см. [REQUEST_LEAD_INS]) — форма из закрытого трафарета
     * [REQUEST_STENCILS] или слово из [REQUEST_SINGLES]. Запись, где рядом с
     * просьбой стоит утверждение, остаётся утверждением целиком.
     *
     * НЕ КОМАНДА. Признак говорит «не утверждает» и больше ничего. Запускать ли
     * по такой записи работу — решение терминальное, промахивается в обратную
     * сторону и настраивается строже; «Расскажи про правило» — просьба, но не
     * задача. Строить запуск на этом признаке, не разведя их, нельзя.
     *
     * ЧЕГО НЕ УМЕЕТ:
     *  - трафарет закрытый: корень с приставками, а не разбор слова. Просьба
     *    глаголом не из трафарета («Помоги…», «Найди…») остаётся утверждением,
     *    как было. Угадывать повелительное наклонение по окончанию нельзя: «-и»,
     *    «-й», «-ь» бывают и у существительных;
     *  - слова, несущие факт, в трафарет не входят намеренно: «Запомни: станок
     *    называется Вымпел», «Запиши…», «Напомни, что…», «Знай», «Учти» —
     *    утверждения; чего нет у каждого корня и почему — у [REQUEST_STENCILS];
     *  - запрет («Не путай, станок называется Вымпел») просьбой не считается
     *    вовсе: за «не …» слишком часто идёт сам факт;
     *  - у корней из [REQUEST_CARRIERS] («пиши», «ответь», «повтори»,
     *    «проверь»…) после слова «что» стоит утверждение — «Допиши, что станок
     *    выключен». Такое предложение остаётся утверждением. Остальные глаголы
     *    с «что» — просьбы: «Расскажи, что ты помнишь»;
     *  - вопрос без знака, начатый вопросительным словом («Что помнишь о
     *    жёлтом»), не узнаётся: это шире и рискованнее;
     *  - знак ударения над буквой снимается, регистр не важен («запилИ»);
     *    другие написания одного слова («расскаж», «плз») не узнаются, если их
     *    нет в трафарете;
     *  - предложения режутся тем же [SENTENCE_BREAK], что и вопросы, с его
     *    промахами.
     */
    fun isOnlyRequests(text: String): Boolean {
        val sentences = text.trim().split(SENTENCE_BREAK).filter { it.isNotBlank() }
        var requests = 0
        for (sentence in sentences) {
            when {
                isQuestionSentence(sentence) -> Unit
                isRequestSentence(sentence) -> requests++
                else -> return false
            }
        }
        return requests > 0
    }

    /**
     * Не утверждает ли запись ничего: одни вопросы или одни просьбы. Для тех, кому
     * нужно только решение; кто считает, зовёт [isOnlyQuestions] и
     * [isOnlyRequests] порознь.
     */
    fun assertsNothing(text: String): Boolean = isOnlyQuestions(text) || isOnlyRequests(text)

    private fun isRequestSentence(sentence: String): Boolean {
        val words = sentence.lowercase()
            .replace("\u0301", "")
            .split(Regex("[^\\p{L}\\p{N}]+"))
            .filter { it.isNotEmpty() }
        var at = 0
        while (at < words.size && words[at] in REQUEST_LEAD_INS) at++
        val root = words.getOrNull(at)?.let { REQUEST_ROOTS[it] } ?: return false
        if (root in REQUEST_CARRIERS && "что" in words.drop(at + 1)) return false
        return true
    }

    // Вводные слова перед просьбой. Пропускать их безопасно: следующее слово
    // всё равно обязано стоять в списке, иначе предложение — утверждение.
    private val REQUEST_LEAD_INS = setOf(
        "а", "и", "ну", "так", "вот", "давай", "давайте", "ладно", "ок", "окей",
        "пожалуйста", "плиз", "пж", "пжлст",
    )

    // Трафарет просьб: корень и приставки, с которыми он даёт просьбу; "" —
    // форма без приставки. Набор приставок у каждого корня свой: приставка
    // меняет смысл, и часть форм несёт факт, а не просьбу. Чего нет и почему:
    //  - «запиши» — несёт факт, как «запомни»; «пиши» — это «продолжай»;
    //  - «скажи» — «скажи, что…» несёт факт;
    //  - «докажи» — «докажи, что…» несёт факт;
    //  - «смотри» — «Смотри, станок…» начинает утверждение;
    //  - «поверь» — утверждение, у «проверь» его нет.
    // Жаргонные слова стоят наравне с обычными: «запили» — такая же просьба,
    // как «напиши».
    private val REQUEST_STENCILS = mapOf(
        "пиши" to listOf("на", "о", "рас", "пере", "до", "вы"),
        "скажи" to listOf("рас", "пере", "под"),
        "кажи" to listOf("по", "у"),
        "смотри" to listOf("по", "про", "пере"),
        "думай" to listOf("при", "про", "об"),
        "считай" to listOf("по", "под", "пере", "рас"),
        "проверь" to listOf("", "пере"),
        "гугли" to listOf("по", "за"),
        "кидай" to listOf("на", "рас"),
    )

    // Слова без семьи — корень у каждого свой.
    private val REQUEST_SINGLES = listOf(
        "назови", "перечисли", "объясни", "переведи", "сравни", "ответь", "повтори",
        "запили", "замути", "набросай", "накатай", "настрочи", "глянь", "чекни",
        "зацени", "прогони", "выдай", "разжуй", "растолкуй", "скинь", "кинь", "обрисуй",
    )

    // Форма просьбы → её корень; форма на «-те» строится сама.
    private val REQUEST_ROOTS: Map<String, String> = buildMap {
        for ((root, prefixes) in REQUEST_STENCILS) {
            for (prefix in prefixes) {
                put(prefix + root, root)
                put(prefix + root + "те", root)
            }
        }
        for (word in REQUEST_SINGLES) {
            put(word, word)
            put(word + "те", word)
        }
    }

    // Корни, у которых после «что» стоит утверждение, а не предмет просьбы:
    // «Допиши, что станок выключен».
    private val REQUEST_CARRIERS = setOf(
        "пиши", "проверь", "ответь", "повтори", "накатай", "настрочи", "чекни",
    )

    private fun surfacesOf(
        numbers: Map<String, Set<String>>,
        keys: Set<String>,
    ): Set<String> = keys.flatMapTo(HashSet()) { numbers.getValue(it) }

    /**
     * Первый противник кандидата в пуле — или null.
     *
     * ПЕРВЫЙ, А НЕ ЕДИНСТВЕННЫЙ: перебор останавливается на подошедшем, и
     * порядок пула задаёт запрос к базе, у которого своей сортировки нет.
     * Значит выбор конкретного противника из нескольких возможных
     * произволен, и опираться на него как на "тот самый" нельзя.
     *
     * Разбор пары вынесен в [contradicts]. Слова кандидата стеммируются
     * заново на каждой паре, а не один раз на весь пул: пул ограничен
     * горячими слоями одного тега, и цена этого — десятки коротких строк на
     * сохранение. Плата за то, что правило живёт в одном месте.
     */
    private fun findContradiction(candidate: Sticker, pool: List<Sticker>): Sticker? {
        for (existing in pool) {
            if (existing.id == candidate.id) continue
            if (bothAgentReports(candidate.source, existing.source)) continue
            if (contradicts(candidate.content, existing.content)) return existing
        }
        return null
    }

    private fun tokenize(text: String): Set<String> =
        text.lowercase()
            .split(Regex("[^\\p{L}\\p{N}]+"))
            .filter { it.isNotBlank() }
            .toSet()

    // Used only for Jaccard overlap in findContradiction, so Russian case/number
    // endings ("кота" vs "котов") don't artificially suppress the overlap score
    // before negation/number comparison even runs.
    private fun stemmedTokenize(text: String): Set<String> =
        tokenize(text).map { stem(it) }.toSet()

    private fun stem(word: String): String {
        for (suffix in SUFFIXES) {
            if (word.length - suffix.length >= MIN_ROOT_LENGTH && word.endsWith(suffix)) {
                return word.substring(0, word.length - suffix.length)
            }
        }
        return word
    }

    /**
     * Числа из текста: цифровая запись как ключ, написанное в тексте как
     * значение. «семь» и «7» дают один и тот же ключ "7", а под ним лежит то
     * слово, которое в этом тексте стоит.
     *
     * ДВА УРОВНЯ, А НЕ ОДИН, потому что у них разные потребители. Сравнение
     * «то же число или другое» идёт по ключам: иначе «семь» и «7» считались бы
     * разными числами. Выделение в тексте идёт по значениям: искать там «7»,
     * когда написано «семь», не по чему.
     *
     * Числительные словами ищутся ЧЛЕНСТВОМ в разобранных токенах, а не
     * регулярным выражением с `\b`. Причина не стилистическая: в Java `\b`
     * определена через `\w`, а `\w` без флага UNICODE_CHARACTER_CLASS — это
     * [a-zA-Z_0-9]. Между пробелом и русской буквой границы слова поэтому не
     * возникает, и `\bсемь\b` не совпадает НИ С ЧЕМ, даже со строкой «семь».
     * Проверено на JVM 21. Здесь такой ловушки нет по построению: tokenize
     * режет по \p{L}\p{N}, которые юникодны сами по себе.
     *
     * Чего механизм не умеет, чтобы это не выяснялось заново:
     *  - только именительный падеж: «в пяти цветах» числом не считается,
     *    поскольку в карте лежит «пять». Прогон числительного через stem()
     *    закрыл бы часть падежей и молча не закрыл бы остальные («трёх» и
     *    «три» расходятся по букве ё), поэтому карта оставлена как есть;
     *  - составные числительные («двадцать пять») дают два отдельных числа;
     *  - цифры собираются ВСЕ подряд, включая случайные — в тексте ошибки
     *    компилятора сюда попадают адреса и длины. Для сравнения «то же число
     *    или другое» такой набор шумит; отсечь его нечем, пока нет разбора
     *    того, к чему число относится.
     *
     * Вызывающий, contradictionMarks, сравнивает эти ключи только после порога
     * схожести, так что шум из предыдущего пункта до сравнения обычно не
     * доходит.
     *
     * Под одним ключом может оказаться несколько написаний сразу: в тексте,
     * где стоит и «7», и «семь», выделены будут оба.
     */
    private fun numbersWithSurface(text: String): Map<String, Set<String>> {
        val found = mutableMapOf<String, MutableSet<String>>()
        for (match in Regex("\\d+").findAll(text)) {
            found.getOrPut(match.value) { mutableSetOf() } += match.value
        }
        val words = tokenize(text)
        for ((word, digits) in WORD_NUMBERS) {
            if (word in words) found.getOrPut(digits) { mutableSetOf() } += word
        }
        return found
    }

    private fun jaccard(a: Set<String>, b: Set<String>): Double {
        if (a.isEmpty() || b.isEmpty()) return 0.0
        val intersection = a.intersect(b).size
        val union = a.union(b).size
        return if (union == 0) 0.0 else intersection.toDouble() / union
    }
