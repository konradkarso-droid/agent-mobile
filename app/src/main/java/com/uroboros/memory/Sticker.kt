package com.uroboros.memory

import androidx.room.Entity
import androidx.room.PrimaryKey

enum class Layer { RED, ORANGE, YELLOW, GREEN, BLUE, PURPLE }
enum class Importance { LOW, MEDIUM, HIGH }

// Item 3 / Track A (info-source trust, designed 2026-08-20): два новых поля,
// tag-only — никогда не участвуют в Prism decay/ranking математике.
// Устанавливаются один раз при создании, затем не пересматриваются.
enum class SourceKind { USER_STATED, AGENT_INFERRED, OCR_EXTRACTED }
enum class ConfidenceLevel { OBSERVED, INFERRED, UNCERTAIN }

/**
 * Каким путём человек отверг запись. Хранится в [Sticker.rejectedVia] именем.
 *
 * ЭТО ПУТЬ, А НЕ МОТИВ. Записывается то, откуда нажали, и то, что было написано
 * в диалоге этого пути. Почему человек счёл запись неверной, по-прежнему не
 * записывается нигде: механизм знает, какой кнопкой воспользовались, а не что
 * при этом думали.
 *
 * ЗАЧЕМ РАЗЛИЧАТЬ. Запись, проигравшая спор, говорит об источнике: он сказал
 * неверное. Запись, отвергнутая как ошибка ввода (опечатка, случайно
 * отправленный черновик, испытательный текст), об источнике не говорит ничего.
 * Слитые в одно, они сделали бы невидимой ошибку любого будущего счёта доверия
 * к источнику: опечатки пользователя читались бы как его неправота, и никто бы
 * этого не увидел — из базы нельзя было бы узнать, почему запись замолчала.
 */
enum class RejectPath {
    /**
     * Из очереди проверки. Запись встала туда при сохранении — по спору,
     * найденному правилом, или по сбою самого сравнения; какое из двух, путь не
     * различает (см. KDoc ReviewEntry).
     */
    QUEUE,

    /** Из спорной пары, найденной судьёй: человек выбрал неверную сторону. */
    DISPUTE,

    /**
     * С экрана «Показать», как ошибочную саму по себе, без спора. Диалог этого
     * пути прямо говорит, что для стороны спора есть свой путь.
     */
    MISTAKE,
}

@Entity(tableName = "stickers")
data class Sticker(
    @PrimaryKey(autoGenerate = true)
    val id: Long = 0,
    val content: String,
    val createdAt: Long = System.currentTimeMillis(),
    var lastAccessedAt: Long = System.currentTimeMillis(),
    var accessCount: Int = 0,
    val tag: String = "general",
    var layer: String = Layer.GREEN.name,
    var expiryTime: Long? = null,
    var importance: String = Importance.MEDIUM.name,
    var reviewPending: Boolean = false,
    val source: String = SourceKind.USER_STATED.name,
    val confidence: String = ConfidenceLevel.OBSERVED.name,

    // Item 3: сырой счётчик пользы, из которого важность будет выводиться позже.
    //
    // Растёт только тогда, когда запись прошла отбор релевантности в поисковом пути
    // по запросу ПОЛЬЗОВАТЕЛЯ. Обращения, порождённые самим агентом, не считаются:
    // иначе система накачивала бы важность собственных записей и через неё лепила
    // свой будущий контекст. Отдельно от accessCount намеренно — тот растёт у всего,
    // что попало в выдачу, а выдачей распоряжается сортировка по важности, и замкнуть
    // одно на другое значит сделать запись важной за то, что она уже была наверху.
    //
    // Ноль означает "ни разу не совпала", а НЕ "неважна". Запись может быть жизненно
    // нужной и ни разу не пересечься словами ни с одним запросом: высокое значение —
    // свидетельство, низкое — не свидетельство обратного.
    //
    // Чего счётчик не умеет: он меряет совпадение слов, а не смысл, и не отличает
    // запись, которую прочли и она помогла, от записи, которую прочли и отбросили.
    //
    // Счётчик не сбрасывается никогда, в том числе при изменении content. Значит
    // после правки текста записи число описывает пользу СТАРОГО текста, а выглядит
    // как относящееся к новому. Сегодня это безвредно: способа отредактировать
    // содержимое записи в приложении нет. Появится — придётся решать, что делать со
    // счётом, и решать это надо будет тогда же, а не после первой перезаписи.
    //
    // Сегодня из него ничего не выводится — сначала надо посмотреть на живые числа.
    // Перетирать его вычисленной важностью нельзя: тогда правило вывода станет
    // непересчитываемым, а сырое наблюдение исчезнет.
    var userMatchCount: Int = 0,

    // Когда человек отверг запись, или null — не отвергал.
    //
    // Отвергнутая запись скрыта тем же битом, что и запись в очереди
    // (reviewPending), поэтому ответы, проверка при сохранении, судья и сон её не
    // видят без отдельных правил. Эта отметка отличает её от ждущей решения:
    // очередь её не показывает и не считает, а принять или выпустить её сбросом
    // очереди нельзя. Зачем два состояния вместо одного бита — в KDoc
    // HourglassMemory.reject.
    //
    // Хранится момент и путь (rejectedVia ниже), а не причина: почему человек
    // счёл запись неверной, не записывается нигде.
    val rejectedAt: Long? = null,

    // Каким путём отвергнута — имя RejectPath, или null.
    //
    // null у отвергнутой записи значит «путь не записан»: так у всех записей,
    // отвергнутых до появления этого поля. Восстановить его задним числом
    // нельзя и выводить нельзя — вердикты судьи намекают на путь лишь для части
    // случаев, а угаданный путь неотличим от записанного.
    //
    // Пишется одним запросом вместе с rejectedAt и только первым отвержением
    // (см. StickerDao.reject): второе нажатие не перетирает первое решение.
    val rejectedVia: String? = null
)
