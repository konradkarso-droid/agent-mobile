package com.uroboros.will

import java.util.concurrent.atomic.AtomicReference

/**
 * Item 9: канал связи между внешним вводом (UI) и TOTE-циклом, работающим в фоне.
 * Дешёвый неблокирующий poll вместо Channel/Flow (вариант F, зафиксировано 2026-08-18) —
 * движку нужно только "есть ли необработанный запрос", не полноценный стриминг.
 */
fun interface PendingQuerySource {
    /** Возвращает и одновременно очищает накопленный запрос, если он есть. */
    fun poll(): String?
}

/**
 * Простая реализация на AtomicReference — одна атомарная операция, без буферов и
 * диспетчеров корутин. UI-слой вызывает submit() при вводе пользователя;
 * ToteEngine вызывает poll() на шве между test() и operate().
 *
 * ЁМКОСТЬ — ОДИН ВОПРОС, И ЭТО ОБЪЯВЛЕННАЯ ГРАНИЦА, А НЕ ПОБОЧНОЕ СВОЙСТВО.
 * Пока необработанный запрос лежит здесь, следующий не принимается: submit()
 * отвечает отказом, и сказать об отказе человеку обязан вызывающий.
 *
 * Почему не очередь. Очередь потребовала бы объявить потолок и правило, что
 * делать при его достижении, а живых чисел для такого решения нет: наблюдалось
 * два вопроса за прогон. Но главное не в этом. Вопрос устаревает за минуты —
 * пока цикл дойдёт до шва, спрашивавший уже смотрит на другое, — и очередь
 * копила бы ответы невпопад. Отказ восстановим: человек видит его и повторяет
 * вопрос, когда прежний обработан. Тихая перезапись невосстановима — потерянный
 * вопрос не переспросят, потому что не узнают о потере.
 *
 * Возвращаться к очереди стоит тогда и только тогда, когда отказы начнут
 * случаться часто; это будет видно по счёту на экране.
 *
 * ЧЕГО ЭТОТ КЛАСС НЕ УМЕЕТ:
 *
 * - он не решает, когда запрос будет обработан. Между submit() и poll() проходит
 *   столько, сколько идёт текущий шаг цикла, — на кодинге это минуты;
 * - он не отличает пустую строку от осмысленного вопроса: что подано, то и
 *   занимает ячейку. Отсев пустого ввода — дело вызывающего, там же, где стоит
 *   поле ввода;
 * - он ничего не считает. Числа "принято / отвечено / осталось без ответа"
 *   ведёт тот, кто зовёт, — здесь их держать негде: класс живёт дольше прогона,
 *   а числа нужны за прогон.
 */
class SimplePendingQuerySource : PendingQuerySource {
    private val pending = AtomicReference<String?>(null)

    /**
     * Положить запрос, если ячейка свободна.
     *
     * @return true — запрос принят; false — ОТКАЗ, предыдущий ещё не обработан.
     *
     * Проверка и запись — одной атомарной операцией, а не "посмотреть, потом
     * положить": два одновременных ввода прошли бы обе проверки и второй затёр
     * бы первого ровно в том промежутке, ради которого всё это и заводится.
     */
    fun submit(query: String): Boolean = pending.compareAndSet(null, query)

    override fun poll(): String? = pending.getAndSet(null)
}
