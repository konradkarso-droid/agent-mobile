package com.uroboros.safety

import kotlinx.coroutines.flow.StateFlow

/**
 * Узкий контракт "откуда берётся текущая физическая зона".
 *
 * Существует ровно по одной причине (2026-08-24): ToteEngine нужна от
 * DeviceSafetyWatchdog единственная вещь — StateFlow с зоной, — но сам watchdog
 * в конструкторе требует android.Context и немедленно обращается к
 * getSystemService(POWER_SERVICE). В JVM-юнит-тесте такой объект не создать,
 * поэтому цикл (чистый Kotlin, никакой другой Android-зависимости не имеющий)
 * оказывался непроверяемым целиком из-за одного поля.
 *
 * ВАЖНО, чего этот интерфейс НЕ значит: он не делает физическую проверку
 * опциональной и не позволяет её выключить. Реализация обязательна везде, где
 * раньше требовался watchdog, — меняется только то, что в тесте её можно
 * подставить вручную. Принцип "физическая безопасность выше когнитивного
 * состояния" остаётся нетронутым: ни один метод здесь не принимает энергию,
 * confidence или что-либо ещё от модели.
 */
interface SafetyZoneSource {
    val zone: StateFlow<SafetyZone>
}
