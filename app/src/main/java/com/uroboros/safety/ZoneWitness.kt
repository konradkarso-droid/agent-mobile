package com.uroboros.safety

/**
 * Свидетель зоны — прибор, отвечающий на один вопрос: считается ли
 * [SafetyZone] вообще.
 *
 * ЗАЧЕМ. Зона почти всегда COMFORT, и на экране это выглядит одинаково в двух
 * совершенно разных случаях: устройству не жарко — и источник данных молчит,
 * потому что подписка не встала, отвалилась или никогда не работала на этом
 * железе. Различить их по значению нельзя ни при какой раскраске: обе картины
 * дают одну и ту же букву. Различить можно только по ПОТОКУ СОБЫТИЙ.
 *
 * Отсюда главное показание этого класса — ВРЕМЯ ПОСЛЕДНЕГО СОБЫТИЯ от каждого
 * источника, а не счётчик и не текущая зона. Счётчик отвечает лишь на вопрос
 * «работало ли когда-нибудь» и при нуле снова неотличим от «ещё не
 * случалось»; время отвечает на вопрос «жив ли источник прямо сейчас».
 *
 * ИСТОЧНИКОВ ДВА, А НОГ ТРИ, и это различие держится подписями методов, а не
 * комментарием. Зона собирается из трёх независимых оценок (системный тепловой
 * статус, температура батареи, уровень заряда), но приезжают они двумя
 * потоками: температура и заряд лежат в одном и том же широковещательном
 * сообщении о батарее. Поэтому события считаются по двум источникам, а худшее
 * виденное — по трём ногам. Слив их в один список, мы получили бы «заряд жив»
 * только потому, что жива температура.
 *
 * ПОЛНОМОЧИЙ НЕТ НИКАКИХ. Прибор не вычисляет зону, ничего не решает, не имеет
 * ни одного порога и ни на что не влияет. Он стоит на пути физического
 * предохранителя, поэтому обязан быть неспособен ему помешать: ни один метод
 * здесь не бросает исключений, не ждёт, не ходит на диск и не выделяет памяти
 * сверх нескольких полей. Наблюдатель, уронивший наблюдаемое, — худший из
 * возможных исходов, потому что ломает он ровно то, ради надёжности чего
 * поставлен.
 *
 * ЧЕГО ЭТОТ ПРИБОР НЕ УМЕЕТ:
 *
 * 1. Он живёт столько же, сколько владелец, который его кормит. Сегодня это
 *    экран: сторож создаётся на области жизни активности, значит поворот
 *    экрана начинает наблюдение заново. Поэтому все показания подписаны сроком
 *    наблюдения, а не выдаются как «за всё время». Постоянное наблюдение
 *    требует службы, живущей дольше экрана.
 * 2. Он показывает ДОСТИЖИМОСТЬ зоны, а не верность порогов. «Утомления не
 *    было» здесь всегда означает «не было за этот срок наблюдения» и никогда —
 *    «пороги выбраны правильно».
 * 3. Он ничего не пишет на диск. Истории между запусками нет, и это решение, а
 *    не недоделка: журнал наблюдений — другой предмет с другой ценой.
 * 4. Молчание источника он показывает, но не объясняет. «Событий нет» значит,
 *    что до прибора ничего не дошло; где именно оборвалось — в подписке, в
 *    системе или на этом железе такого источника нет вовсе — прибор не знает.
 *
 * О БЕЗОПАСНОСТИ ОБРАЩЕНИЯ ИЗ РАЗНЫХ ПОТОКОВ. Пишут сюда две разные корутины
 * (по одной на источник), читает третья. Замка нет намеренно: поля каждого
 * источника пишет ровно один поток, поля разных источников не пересекаются, а
 * `@Volatile` обеспечивает, что записанное будет видно читателю. Снимок при
 * этом может застать источники в слегка разные моменты — для прибора
 * наблюдения это безразлично, а замок на пути предохранителя стоил бы
 * ожидания, которого здесь быть не должно.
 */

/**
 * Одно измерение. Неизменяемый: снимок, отданный на отрисовку, не должен
 * меняться под руками, пока его читают.
 *
 * `null` в полях худшего означает «событий от этой ноги не было». Ноль или
 * COMFORT на этом месте были бы враньём в самую опасную сторону — они читаются
 * как «наблюдали и всё хорошо», тогда как на деле не наблюдали ничего.
 */
data class ZoneWitnessSnapshot(
    /** Момент начала наблюдения (мс). */
    val startedAtMs: Long,
    /** Момент снятия снимка (мс). */
    val takenAtMs: Long,
    /** Сколько событий пришло от системного теплового статуса. */
    val thermalEvents: Int,
    /** Когда пришло последнее из них, либо null, если их не было. */
    val thermalLastAtMs: Long?,
    /** Худшая зона, которую называл системный тепловой статус. */
    val worstThermalStatus: SafetyZone?,
    /** Сколько событий пришло от батареи (температура и заряд вместе). */
    val powerEvents: Int,
    /** Когда пришло последнее из них, либо null, если их не было. */
    val powerLastAtMs: Long?,
    /** Худшая зона, которую называла температура батареи. */
    val worstBatteryTemperature: SafetyZone?,
    /** Худшая зона, которую называл уровень заряда. */
    val worstCharge: SafetyZone?,
) {
    /** Сколько длится наблюдение. Никогда не отрицательно — см. [ZoneWitness.spanMs]. */
    val observedForMs: Long get() = ZoneWitness.spanMs(startedAtMs, takenAtMs)

    /**
     * Худшее, что видел прибор за срок наблюдения, по всем трём ногам сразу.
     *
     * Считается как строжайшее из трёх запомненных, и это законно: итоговая
     * зона в каждый момент есть строжайшее из трёх оценок, а наибольшее по
     * времени от наибольшего по ногам равно наибольшему по ногам от
     * наибольшего по времени. Хранить четвёртое поле «худшее итоговое» не
     * нужно — оно вывелось бы из тех же трёх и могло бы с ними разойтись.
     *
     * null, если не было ни одного события ни от одной ноги.
     */
    val worstOverall: SafetyZone?
        get() = listOfNotNull(worstThermalStatus, worstBatteryTemperature, worstCharge)
            .maxByOrNull { it.ordinal }
}

class ZoneWitness(private val startedAtMs: Long) {

    @Volatile private var thermalEvents: Int = 0
    @Volatile private var thermalLastAtMs: Long? = null
    @Volatile private var worstThermalStatus: SafetyZone? = null

    @Volatile private var powerEvents: Int = 0
    @Volatile private var powerLastAtMs: Long? = null
    @Volatile private var worstBatteryTemperature: SafetyZone? = null
    @Volatile private var worstCharge: SafetyZone? = null

    /**
     * Событие от системного теплового статуса — одна нога, один источник.
     *
     * @param zone во что этот источник оценил обстановку.
     * @param atMs когда событие пришло; время передаётся снаружи, чтобы прибор
     *             можно было проверить, не дожидаясь настоящих минут.
     */
    fun recordThermalStatus(zone: SafetyZone, atMs: Long) {
        thermalEvents++
        thermalLastAtMs = atMs
        worstThermalStatus = stricter(worstThermalStatus, zone)
    }

    /**
     * Событие от батареи — ОДИН источник, но ДВЕ ноги: температура и заряд
     * приходят одним сообщением, поэтому и записываются одним вызовом. Считать
     * их за два события значило бы удвоить счётчик источника и создать
     * впечатление вдвое более живой подписки.
     */
    fun recordPower(temperatureZone: SafetyZone, chargeZone: SafetyZone, atMs: Long) {
        powerEvents++
        powerLastAtMs = atMs
        worstBatteryTemperature = stricter(worstBatteryTemperature, temperatureZone)
        worstCharge = stricter(worstCharge, chargeZone)
    }

    /** Снять снимок. Только чтение, состояние прибора не меняется. */
    fun snapshot(nowMs: Long): ZoneWitnessSnapshot = ZoneWitnessSnapshot(
        startedAtMs = startedAtMs,
        takenAtMs = nowMs,
        thermalEvents = thermalEvents,
        thermalLastAtMs = thermalLastAtMs,
        worstThermalStatus = worstThermalStatus,
        powerEvents = powerEvents,
        powerLastAtMs = powerLastAtMs,
        worstBatteryTemperature = worstBatteryTemperature,
        worstCharge = worstCharge,
    )

    /**
     * Человекочитаемый вид снимка. Ничего не печатает и никуда не пишет —
     * возвращает строку, которую показывает вызывающий слой. Благодаря этому
     * прибор проверяется обычным юнит-тестом, без телефона и без нагрева.
     *
     * @param label как называть зону по-русски. Передаётся снаружи, а не
     *              заводится здесь: название зоны для человека уже живёт на
     *              экране, и вторая копия разошлась бы с первой молча.
     */
    fun format(snapshot: ZoneWitnessSnapshot, label: (SafetyZone) -> String): String {
        val span = humanSpan(snapshot.observedForMs)
        val lines = mutableListOf("Наблюдение за зоной (с открытия экрана, $span):")

        lines += sourceLine(
            title = "Тепловой статус",
            events = snapshot.thermalEvents,
            lastAtMs = snapshot.thermalLastAtMs,
            worst = snapshot.worstThermalStatus,
            snapshot = snapshot,
            span = span,
            label = label,
        )
        lines += sourceLine(
            title = "Батарея",
            events = snapshot.powerEvents,
            lastAtMs = snapshot.powerLastAtMs,
            worst = snapshot.worstBatteryTemperature,
            snapshot = snapshot,
            span = span,
            label = label,
        )

        // У заряда нет своей строки событий: он приезжает тем же сообщением,
        // что и температура, и собственного счётчика у него быть не может.
        // Названа только его оценка.
        lines += "  Заряд: " + (
            snapshot.worstCharge?.let { "худшее «${label(it)}»" } ?: "оценок не было"
            )

        lines += "  Итог: " + (
            snapshot.worstOverall?.let { "худшее за сеанс «${label(it)}»" }
                ?: "наблюдать было нечего — ни одного события ни от одного источника"
            )

        return lines.joinToString("\n")
    }

    private fun sourceLine(
        title: String,
        events: Int,
        lastAtMs: Long?,
        worst: SafetyZone?,
        snapshot: ZoneWitnessSnapshot,
        span: String,
        label: (SafetyZone) -> String,
    ): String {
        // Молчание источника — единственное показание этого прибора, ради
        // которого он существует, поэтому оно называется словами и сразу
        // толкуется, а не оставляется читателю в виде нуля.
        if (lastAtMs == null) {
            return "  $title: событий нет за $span — источник молчит"
        }
        val ago = humanSpan(spanMs(lastAtMs, snapshot.takenAtMs))
        val worstText = worst?.let { "худшее «${label(it)}»" } ?: "оценок не было"
        // Число стоит после слова намеренно: «событий 1» и «событий 7»
        // одинаково грамотны, а «1 событие / 7 событий» требуют разных
        // окончаний, и правильная сегодня строка стала бы неграмотной завтра.
        return "  $title: событий $events, последнее $ago назад · $worstText"
    }

    /**
     * Строжайшая из двух зон; null слева означает «ничего ещё не видели».
     *
     * Держится на том, что константы [SafetyZone] перечислены по возрастанию
     * строгости. Это не самоочевидно и не проверяется компилятором:
     * перестановка констант местами молча сломает выбор худшего. Порядок
     * закреплён отдельной проверкой в тестах именно поэтому.
     */
    private fun stricter(current: SafetyZone?, incoming: SafetyZone): SafetyZone =
        if (current != null && current.ordinal >= incoming.ordinal) current else incoming

    /**
     * Промежуток словами. Единица укрупняется с ростом: секунды нужны на
     * свежем событии и не нужны на часовом, а «2820 с назад» читатель всё
     * равно переводит в уме сам.
     */
    private fun humanSpan(millis: Long): String {
        val seconds = millis / 1000L
        val minutes = seconds / 60L
        val hours = minutes / 60L
        return when {
            seconds < 1L -> "меньше секунды"
            seconds < 60L -> "$seconds с"
            minutes < 60L -> "$minutes мин"
            else -> "$hours ч"
        }
    }

    companion object {
        /**
         * Длительность между двумя моментами, никогда не отрицательная.
         *
         * Отрицательная разница здесь возможна и не является поломкой: системные
         * часы переводятся, в том числе назад, а прибор хранит моменты, а не
         * длительности. Показать «-5 мин назад» значило бы вывести на экран
         * заведомую бессмыслицу, поэтому такой случай схлопывается в ноль.
         * Плата названа: сразу после перевода часов назад показания промежутков
         * будут занижены, пока не придёт следующее событие.
         */
        fun spanMs(fromMs: Long, toMs: Long): Long = (toMs - fromMs).coerceAtLeast(0L)
    }
}
