package com.uroboros.safety

import java.util.Locale

/**
 * Тепловой статус системы и тепловой запас — как их понимает сторож. Чистая
 * логика без Android: числа статусов повторяют константы
 * `PowerManager.THERMAL_STATUS_*` (0..6, их значения в Android закреплены и не
 * меняются между версиями), поэтому перевод проверяется обычными тестами.
 *
 * ЧЕЙ ЭТО ПОРОГ. Статус и запас считает не агент, а производитель телефона по
 * своим датчикам и под своё охлаждение. Поэтому порог сторожа по статусу
 * переезжает с телефона на телефон сам: игровой телефон с большой
 * испарительной камерой дойдёт до «сильного» позже, чем тонкий. Свои градусы
 * у сторожа остались только у батареи ([DeviceSafetyWatchdog]), и это верхняя
 * граница: её ничем не подменить, потому что вредит перегрев именно элементу.
 *
 * ПОЧЕМУ «СЛАБЫЙ» — НОРМА. По описанию Android это лёгкое торможение, при
 * котором работа пользователя не страдает; систему при этом уже тормозит она
 * сама, своими средствами. Считать его поводом для зоны «нагрев» значило бы
 * остановиться раньше, чем сама система сочла нужным что-то менять, — на
 * мощном телефоне это случается от обычного ответа модели. «Умеренный» —
 * «нагрев» (ничего не останавливает, пишется в «дом»), «сильный» —
 * «утомление», «критический» и выше — «критическая». Что делает каждая зона,
 * сказано у [SafetyZone].
 *
 * ЧЕГО НЕ УМЕЕТ: проверять производителя. Если телефон выставляет статусы
 * слишком поздно, сторож узнает об этом только по температуре батареи — для
 * того она и остаётся отдельной ногой.
 */
object ThermalStatus {

    const val NONE = 0
    const val LIGHT = 1
    const val MODERATE = 2
    const val SEVERE = 3
    const val CRITICAL = 4
    const val EMERGENCY = 5
    const val SHUTDOWN = 6

    /** Зона сторожа по статусу системы. Незнакомое число — строже всего. */
    fun zone(status: Int): SafetyZone = when (status) {
        NONE, LIGHT -> SafetyZone.COMFORT
        MODERATE -> SafetyZone.WARNING
        SEVERE -> SafetyZone.FATIGUE
        else -> SafetyZone.CRITICAL
    }

    /** Статус словом — как его называет система, а не как его толкует сторож. */
    fun word(status: Int): String = when (status) {
        NONE -> "нет"
        LIGHT -> "слабый"
        MODERATE -> "умеренный"
        SEVERE -> "сильный"
        CRITICAL -> "критический"
        EMERGENCY -> "аварийный"
        SHUTDOWN -> "отключение"
        else -> "неизвестный ($status)"
    }

    /**
     * Строка порогов запаса, заданных производителем: статус → запас, при
     * котором он наступает. Пустой словарь — производитель порогов не задал.
     */
    fun thresholdsLine(thresholds: Map<Int, Float>): String =
        if (thresholds.isEmpty()) "производитель порогов не задал"
        else thresholds.toSortedMap().entries.joinToString(" · ") { (s, v) -> "${word(s)} ${headroom(v)}" }

    /** Запас числом: два знака после точки, «не число» — словами. */
    fun headroom(v: Float): String =
        if (v.isNaN()) "не число" else String.format(Locale.US, "%.2f", v)
}
