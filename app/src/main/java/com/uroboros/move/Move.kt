package com.uroboros.move

/**
 * ПЕРЕЕЗД АГЕНТА НА ДРУГОЙ ТЕЛЕФОН — одно описание механизма; остальные файлы
 * пакета ссылаются сюда.
 *
 * КАК. Старый и новый телефон в одной сети (домашний Wi‑Fi или точка доступа
 * старого). На новом — свежий агент с пустой памятью: «Принять агента» на
 * экране врат показывает адрес и код из [MoveCode.DIGITS] цифр. На старом —
 * «Переехать»: человек вводит адрес и код. Старый подключается к новому
 * ([PORT]) и передаёт себя ([MoveSession]): базы, настройки, токен бота,
 * модели из папки моделей. Сторонних программ и облака нет.
 *
 * ЧТО ЕДЕТ И ЧТО НЕТ. Едут все базы из одного списка (memory.DatabaseExporter),
 * все настройки приложения, кроме привязанных к телефону (пути к модели, замеры
 * памяти телефона — список у move.MoveAndroid), токен бота и `.gguf` из папки
 * моделей с подпапкой ночной накладки. Не едут: ключи врат (закрытая часть не
 * вынимается из хранилища — на новом телефоне ключи свои, см.
 * gate.store.GateKeystoreSigner), кэши (стена, куски записей — строятся
 * заново, первые ответы медленнее), Termux.
 *
 * ЗАЩИТА КАНАЛА ([MoveKeys]). Ключ сессии — из согласования ECDH одноразовых
 * ключей обеих сторон, смешанного с кодом, растянутым PBKDF2 ([ITERATIONS]).
 * Подслушавший в сети без закрытых ключей не прочтёт ничего. Посредник, не
 * знающий кода, проваливает первое же закрытое сообщение; подобрать код из
 * перехваченного он мог бы только перебором — 10^10 кодов, каждый стоит
 * растяжки, это дни, а сессия ждёт минуты. Подбор вживую — [MAX_TRIES]
 * попытки, потом приём закрывается.
 *
 * ДВА ЖИВЫХ АГЕНТА НЕДОПУСТИМЫ — отсюда порядок ([MoveSession]):
 *  1. старый на время передачи замирает ВРЕМЕННО (move.MoveState.hold, в
 *     памяти процесса): нет разговора, сна, суда, телеграма. Передача сорвалась
 *     — замирание снимается; процесс умер — снимается вместе с ним;
 *  2. новый принял всё, суммы и размеры сошлись — сообщает «принял»;
 *  3. старый замирает НАСОВСЕМ (запись на диск) и прячет токен — опрос
 *     телеграма с него прекращается — и отвечает «готово»;
 *  4. только после «готово» новый применяет принятое при следующем запуске
 *     процесса (move.MoveApply), раньше, чем откроется любая база.
 * Обрыв между 3 и 4 — оба замерли; лечится повтором «Переехать» на старом:
 * замерший насовсем старый отдаёт тот же пакет снова, а новый, у которого пакет
 * уже лежит целиком, просит только «готово».
 *
 * ЧЕГО НЕ УМЕЕТ:
 *  - сеть только локальная, адрес вводится руками; поиска телефона в сети нет.
 *    Подсказка адреса — начало своего адреса старого телефона (MoveCode.prefixOf);
 *  - сборка под Android 17 (targetSdk 37) потребует разрешения на локальную
 *    сеть (ACCESS_LOCAL_NETWORK); нынешней сборке хватает INTERNET;
 *  - обрыв посреди передачи — всё сначала, докачки нет;
 *  - база со старого новее сборки на новом — отказ: открыть её Room не сможет;
 *    старее — можно, Room доведёт её миграциями;
 *  - собеседники врат увидят у агента новый ключ подписи (тревога у каждого,
 *    см. gate.GateKeys); подписи новой карточки прежним ключом нет;
 *  - замерший насовсем старый не оживает сам: стирать его — дело человека;
 *  - модель с тем же именем и размером, уже лежащая в папке на новом, не
 *    едет и не сверяется по сумме.
 */
object Move {
    /** Порт приёма на новом телефоне. Занят — приём не открывается (строка на экране). */
    const val PORT = 48231

    /** Начало первых двух сообщений: чужой протокол на этом порту отсеется сразу. */
    val MAGIC: ByteArray = "uroboros move 1".toByteArray(Charsets.US_ASCII)

    /**
     * Растяжка кода. Область: на телефоне это доли секунды один раз за сессию,
     * а перебор 10^10 кодов с ней — дни даже на видеокарте. Перепроверить:
     * время одной растяжки на телефоне видно в строке хода приёма.
     */
    const val ITERATIONS = 200_000

    /** Кусок файла в одном закрытом сообщении. */
    const val CHUNK = 256 * 1024

    /** Неверных кодов на один приём; дальше приём закрывается. */
    const val MAX_TRIES = 3

    const val CONNECT_TIMEOUT_MS = 10_000

    /** Тишина в канале дольше этого — обрыв. Запас на запись модели в медленную память. */
    const val READ_TIMEOUT_MS = 120_000

    /** Сколько ждать первого подключения старого телефона. */
    const val ACCEPT_WAIT_MS = 30L * 60 * 1000
}
