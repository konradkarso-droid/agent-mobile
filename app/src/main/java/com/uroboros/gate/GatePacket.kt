package com.uroboros.gate

import com.uroboros.memory.SentenceKind
import com.uroboros.memory.SourceKind
import com.uroboros.memory.nav.PersonKey
import com.uroboros.memory.nav.Place

/**
 * Пакет врат — общая форма адреса для разговора двух агентов (трафарет).
 *
 * ЗАЧЕМ ФОРМА. У каждого агента навигация по памяти одной формы: кто сказал,
 * о ком, когда, где. Прорези трафарета одинаковы у всех агентов, а заполняет
 * и читает их код, не модель. Поэтому модели на концах могут быть разными:
 * общими должны быть только прорези. Модель получателя лишь пересказывает
 * [words] своему человеку.
 *
 * ЧТО ИДЁТ КЛЮЧАМИ, А НЕ СЛОВАМИ:
 *  - о ком — ключами ([about]), а не местоимениями. Через двух агентов «я» и
 *    «ты» разворачиваются дважды подряд, и модель путает уже один разворот.
 *    Местоимения делает получатель от своей точки отправления, кодом
 *    ([GateUnfold]); [words] при этом не меняются;
 *  - время — моментом и поясом ([atMs], [zone]), а не словами: «на днях» у
 *    отправителя и у получателя — разные дни. Огрубляет получатель;
 *  - точное (число, имя, дата, ссылка, код) — полями [exact], мимо модели.
 *
 * ТОЧКА ОТПРАВЛЕНИЯ — [from] и [represents]: какой агент прислал и за какого
 * человека он говорит. Без неё пакет не принимается (см. [GateIntake]).
 * Сказавший ([saidBy]) — только один из этих двоих: «с его слов» или «со слов
 * его владельца». Третьи руки через врата не идут.
 *
 * Ключи — [PersonKey] со схемой канала впереди («tg:user:456»). Имя в пакете
 * — только слова, ключа оно не создаёт.
 *
 * ЧЕГО НЕ УМЕЕТ:
 *  - не доказывает, что чужой агент говорит правду: форма несёт провенанс, а
 *    не истинность;
 *  - не доказывает, кто прислал. Сумма в шапке ([GateWire]) ловит случайную
 *    порчу, но не подделку. Подлинность даёт только канал с проверяемыми
 *    ключами или подпись; подписи здесь нет;
 *  - не решает, что из своей памяти можно отдать собеседнику (граница
 *    видимости), и не кладёт принятый пакет в память — это делает тот, кто
 *    подключит канал;
 *  - смысл между разными моделями точно не переносит: точны только поля.
 *
 * Чистая форма: ни сети, ни базы, ни Android.
 */
data class GatePacket(
    /** Какой агент прислал. */
    val from: PersonKey,
    /** За кого этот агент говорит — человека или чат. Заявление; верно ли оно, решает [GateWho]. */
    val represents: PersonKey,
    /** Кому пакет. */
    val to: PersonKey,
    /**
     * Номер пакета — случайное 64-битное число от отправителя
     * ([GateWire.newNumber]). Повтор того же пакета несёт тот же номер; зачем
     * — см. [GateIntake], «повторы».
     */
    val number: Long,
    /** Момент первой отправки — миллисекунды от 1970 года. Повтор несёт тот же момент. */
    val sentMs: Long,
    /** Где прозвучало: личка или группа. Экран через врата не идёт. */
    val place: Place,
    /** Кто сказал слова: [from] или [represents]. */
    val saidBy: PersonKey,
    /** О ком — ключами. Пусто и без [aboutUnclear] — о мире. */
    val about: List<PersonKey>,
    /** Отправитель сам не разобрал, о ком. */
    val aboutUnclear: Boolean,
    /** Момент, когда сказано, — миллисекунды от 1970 года. */
    val atMs: Long,
    /** Пояс отправителя, например «Europe/Moscow». */
    val zone: String,
    /** Откуда это известно отправителю — его заявление, а не наше доверие. */
    val source: SourceKind,
    /** Вид предложения по разбору отправителя. */
    val kind: SentenceKind.Kind,
    /** Тема — начальные формы слов (словарь языка, а не словарь модели). */
    val topic: List<String>,
    /** Точные поля: имя поля → значение. */
    val exact: Map<String, String>,
    /** Слова — их получатель перескажет своей моделью. */
    val words: String,
)
