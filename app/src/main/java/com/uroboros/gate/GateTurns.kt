package com.uroboros.gate

import com.uroboros.memory.nav.PersonKey

/**
 * Глубина разговора двух агентов: сколько пакетов слов подряд я пишу одному
 * агенту без новой реплики моего владельца.
 *
 * ЗАЧЕМ. Два агента, которые отвечают друг другу, легко уходят в бесконечную
 * петлю: каждый ответ — повод для следующего (об этом прямо предупреждает
 * документация Telegram о разговоре ботов). Петля тратит заряд телефона и
 * может привести к ограничениям со стороны канала. Поведение модели этого не
 * удержит, поэтому предел — в коде.
 *
 * ПРЕДЕЛ — [MAX_IN_A_ROW] пакетов слов одному агенту после последней реплики
 * моего владельца на экране; потом молчу, пока владелец не скажет что-нибудь.
 * Любая реплика владельца, не обязательно об этом агенте: он здесь, и петлю
 * видит. Реплики самого собеседника счёт не сбрасывают — иначе петля
 * поддерживала бы себя сама. Объявленное число, не подобранное.
 *
 * Сюда идут только пакеты слов. «Принял» в счёт не идёт: на него не отвечают
 * ([GateAck]); повтор того же пакета ([GateOutbox]) — тоже не идёт: это не
 * новая реплика.
 *
 * Промах — в сторону молчания: предел режет и законный длинный разговор. Это
 * видно строкой прибора и снимается одной репликой владельца.
 *
 * ЧЕГО НЕ УМЕЕТ: сам ничего не считает между перезапусками — моменты подаются
 * на вход; разговоров сразу со многими агентами вместе не ограничивает — только
 * каждый по отдельности; что именно писать, не решает.
 *
 * Чистый объект: ни сети, ни базы, ни Android.
 */
object GateTurns {

    const val MAX_IN_A_ROW = 3

    sealed class Decision {
        /** Можно написать; после этого останется [left]. */
        data class May(val left: Int) : Decision()

        /** Предел набран: [inARow] пакетов подряд без реплики владельца. */
        data class Silent(val inARow: Int) : Decision()
    }

    /**
     * [sentToPeerMs] — моменты новых пакетов слов, что я отправил этому агенту
     * (без повторов); [lastOwnerMs] — момент последней реплики моего владельца на
     * экране, null — не было ни одной.
     */
    fun decide(sentToPeerMs: List<Long>, lastOwnerMs: Long?): Decision {
        val inARow = sentToPeerMs.count { lastOwnerMs == null || it > lastOwnerMs }
        return if (inARow >= MAX_IN_A_ROW) Decision.Silent(inARow) else Decision.May(MAX_IN_A_ROW - inARow - 1)
    }

    /** Строка прибора, когда молчу. Имя — из своего знания ([nameOf]); не знаю имени — ключ. */
    fun meterLine(peer: PersonKey, d: Decision.Silent, nameOf: (PersonKey) -> String?): String {
        val who = nameOf(peer)?.takeIf { it.isNotBlank() } ?: peer.id
        return "Разговор: $who — пакетов подряд без вашей реплики ${d.inARow}, предел $MAX_IN_A_ROW — молчу"
    }
}
