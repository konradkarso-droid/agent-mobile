package com.uroboros.gate.link

import com.uroboros.gate.GateBotApi

/**
 * Матрица разрешений на переход по присланным ссылкам — решение владельца,
 * объявленное границей. Записана в одном месте (здесь) и закреплена тестами
 * на молчание: случайная «починка» границу сломает заметно.
 *
 * ЧТО РАЗРЕШЕНО:
 *  - чат приложения — владелец говорит с агентом напрямую;
 *  - личный чат телеграма владельца — тот же владелец, другой канал;
 *  - группы телеграма — только при отдельном разрешении владельца
 *    (ChatPrefs.groupLinks) и только по сообщениям, адресованным агенту:
 *    чужая болтовня со ссылкой — не «прислали ему».
 * ЧТО ЗАПРЕЩЕНО:
 *  - личные чаты телеграма всех остальных — без исключений и без кнопки,
 *    которая это открыла бы.
 *
 * ГРУППА ГРАНИЧИТСЯ ПО МЕСТУ, А НЕ ПО АВТОРУ: даже ссылка от владельца в
 * группе ждёт разрешения — решение «группы отдельно» принято про место, и
 * поднимать доверие по автору значило бы тихо обойти его.
 *
 * ЧЕГО НЕ УМЕЕТ: различить группы между собой (разрешение одно на все);
 * открыть запрет чужой лички ничем нельзя — ни разрешением, ни согласием.
 *
 * Чистый объект: ни Android, ни сети, ни базы.
 */
object LinkFollow {

    /** Где ссылка пришла. Перечисление закрытое: новое место обязано пройти через этот же when — «не знаю, что это» не может стать открытием (fail-closed). */
    enum class Where { APP, OWNER_DIRECT, GROUP, STRANGER_DIRECT }

    sealed interface Verdict {
        data object Allow : Verdict

        /** Не открывать; [why] — причина для строки событий и ответа. */
        data class Deny(val why: String) : Verdict
    }

    fun decide(where: Where, groupAllowed: Boolean): Verdict = when (where) {
        Where.APP, Where.OWNER_DIRECT -> Verdict.Allow
        Where.GROUP -> if (groupAllowed) {
            Verdict.Allow
        } else {
            Verdict.Deny("в группах — только с отдельного разрешения владельца (кнопка «Ссылки»)")
        }
        Where.STRANGER_DIRECT -> Verdict.Deny("в чужих личках не открываю")
    }

    // --- Извлечение ссылки из сообщения ---

    /**
     * Первая ссылка сообщения телеграма: сущности `url` (видимый адрес) и
     * `text_link` (адрес под текстом). Телеграм размечает ссылки сам — его
     * разметка надёжнее угадывания по подстрокам, поэтому голых доменов в
     * тексте здесь не ищем: сущность и есть признак.
     *
     * null — ссылок нет. Несколько ссылок: открывается первая, остальные
     * объявленно игнорируются (одна сеть на сообщение).
     */
    fun telegramUrl(m: GateBotApi.Message): String? {
        val text = m.text
        for (e in m.entities) {
            when (e.type) {
                "url" -> {
                    if (text != null && e.offset >= 0 && e.length > 0 && e.offset + e.length <= text.length) {
                        text.substring(e.offset, e.offset + e.length).trim().takeIf { it.isNotEmpty() }?.let { return it }
                    }
                }
                "text_link" -> e.url?.trim()?.takeIf { it.isNotEmpty() }?.let { return it }
            }
        }
        return null
    }

    /**
     * Явная ссылка в тексте чата приложения: адрес со схемой или с «www.».
     * Голый домен («nplus1.ru») ссылкой не считается — в свободном тексте он
     * неотличим от имени файла и обрыва фразы; в телеграме такой случай ловит
     * разметка сущностей, здесь её нет.
     *
     * null — явной ссылки нет. Хвостовые знаки препинания срезаются.
     */
    fun plainTextUrl(text: String): String? {
        val found = Regex("""(?i)\b(?:https?://|www\.)\S+""").find(text)?.value ?: return null
        return found.trimEnd('.', ',', ';', ':', '!', '?', ')', ']', '}', '»', '"', '\'').takeIf { it.isNotEmpty() }
    }

    /**
     * Текст сообщения без самих ссылок — то, что остаётся репликой и может
     * лечь в память. Видимые адреса (сущности `url`) вырезаются из текста:
     * адрес — не речь, и репликой он не ложится, иначе суд памяти разобрал бы
     * его как обычные слова — основы из домена и слагов свели бы адрес в пары
     * с записями, которых человек не говорил (суд судит записи кольца «к
     * агенту», а ссылка в личке всегда ему). Скрытый адрес (`text_link`) в
     * тексте не стоит — вырезать нечего, слова над ним остаются словами
     * автора.
     *
     * Пусто — сообщение из одних ссылок: реплики в нём нет. Без сущностей
     * `url` текст возвращается как есть, до последнего пробела: вырезу нечего
     * делать, и переформатирование чужого текста было бы молчаливой правкой.
     * Сущности за краем текста не читаются — как у [telegramUrl]. Пробелы на
     * месте выреза схлопываются в один.
     */
    fun withoutLinks(m: GateBotApi.Message): String {
        val text = m.text ?: return ""
        val spans = ArrayList<Pair<Int, Int>>()
        for (e in m.entities) {
            if (e.type != "url") continue
            if (e.offset < 0 || e.length <= 0 || e.offset + e.length > text.length) continue
            spans += e.offset to e.offset + e.length
        }
        if (spans.isEmpty()) return text
        spans.sortBy { it.first }
        val out = StringBuilder()
        var at = 0
        for ((start, end) in spans) {
            if (start < at) continue // перекрытие с уже вырезанным — телеграм их не присылает, перекрытый кусок молча пропускаем
            out.append(text, at, start)
            at = end
        }
        out.append(text, at, text.length)
        return Regex("\\s+").replace(out.toString(), " ").trim()
    }

    /**
     * Вопрос к читателю страницы: сообщение без самой ссылки; пусто — значит,
     * ссылку прислали без слов, читатель получит свой вопрос по умолчанию.
     */
    fun question(text: String, url: String): String =
        Regex("\\s+").replace(text.replace(url, ""), " ").trim()
}
