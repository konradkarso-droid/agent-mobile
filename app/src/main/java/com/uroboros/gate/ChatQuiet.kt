package com.uroboros.gate

import com.uroboros.memory.nav.AddressSorter

/**
 * Идёт ли разговор в телеграме — для того, кто решает, начинать ли долгую
 * работу модели: самостоятельный суд, шаги ночи, сон (AgentService).
 *
 * ЗАЧЕМ. Тишина у суда и сна меряется от конца последней генерации
 * (llm.EngineActivity). Ответ в телеграме — тоже генерация, но разговор там
 * идёт и без неё: собеседник написал, а агент ещё не ответил (очередь,
 * загрузка модели, нет разрешения), или собеседник думает над ответом дольше,
 * чем порог суда. Суд, начатый в такую паузу, держит модель часами, а ответ,
 * прождавший дольше [ChatReply.STALE_MS], уже не уходит.
 *
 * ЧТО СЧИТАЕТСЯ РАЗГОВОРОМ. Строка ленты чата, на которую агент отвечает или
 * переспрашивает ([dialogRings]), и свой ответ агента. Общее группы и
 * сказанное про агента — не разговор с ним, и долгую работу не держат.
 *
 * ПОРОГ — У КАЖДОГО РЕШАЮЩЕГО СВОЙ, а мерка одна: тишина в телеграме
 * сравнивается с тем же порогом, что тишина экрана (суд и шаги ночи —
 * memory.judge.SelfJudgeDecision.QUIET_MS, сон — memory.dream.SleepDecision).
 * Отказ называется отдельной строкой ([refusal]), чтобы «жду из-за телеграма»
 * отличалось на экране от «тихо мало».
 *
 * НЕ ПРОЧИТАЛОСЬ — ЗНАЧИТ НЕЛЬЗЯ. Все три решения начинают строго: сомнение —
 * в сторону «не начинать». Сбой чтения ленты чатов поэтому держит работу, как
 * идущий разговор, и называется словами.
 *
 * ЧЕГО НЕ УМЕЕТ:
 *  - время строки собеседника — время сервера телеграма: сообщение, дошедшее с
 *    опозданием (не было сети, телефон спал), считается сказанным тогда, когда
 *    его отправили, а не когда агент его увидел;
 *  - не знает, закончил ли собеседник: долгая пауза в телеграме для него — тишина;
 *  - одна мерка на все чаты: тишина считается от последней строки разговора в
 *    любом чате.
 *
 * Чистый объект.
 */
object ChatQuiet {

    /** Имена колец, на которые агент отвечает или переспрашивает (AddressSorter.answer). */
    val dialogRings: List<String> = AddressSorter.Ring.entries
        .filter { AddressSorter.answer(it) != AddressSorter.Answer.SILENT }
        .map { it.name }

    /** Что известно о разговоре в телеграме. */
    sealed class Reading {
        /** Строк разговора нет: в телеграме с агентом не говорили. */
        object None : Reading()

        /** С последней строки разговора прошло [ms]. */
        data class Quiet(val ms: Long) : Reading()

        /** Ленту чатов прочитать не удалось; [why] — словами. */
        data class Failed(val why: String) : Reading()
    }

    /** Показание по времени последней строки разговора [lastAt]; null — строк нет. */
    fun reading(nowMs: Long, lastAt: Long?): Reading =
        if (lastAt == null) Reading.None else Reading.Quiet((nowMs - lastAt).coerceAtLeast(0))

    /**
     * Почему долгая работа ждёт телеграма, словами, — при пороге тишины
     * [neededMs]; null — телеграм ей не мешает.
     */
    fun refusal(reading: Reading, neededMs: Long): String? = when (reading) {
        Reading.None -> null
        is Reading.Failed -> "лента чатов телеграма не прочиталась (${reading.why})"
        is Reading.Quiet ->
            if (reading.ms >= neededMs) null
            else "в телеграме разговор: тихо ${minutes(reading.ms)} мин из ${minutes(neededMs)}"
    }

    private fun minutes(ms: Long): Long = ms.coerceAtLeast(0) / 60_000
}
