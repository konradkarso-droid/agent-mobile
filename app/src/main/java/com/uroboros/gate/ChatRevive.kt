package com.uroboros.gate

/**
 * Подхват после комы: на какие сообщения телеграма агент ответить не успел,
 * потому что служба умерла, — по двум отметкам на диске и ленте чатов.
 *
 * ЗАЧЕМ. Очередь ответов (gate.link.ChatLink) живёт в памяти службы и умирает
 * вместе с ней, а сообщение к этому времени уже лежит в ленте чатов и
 * подтверждено телеграму — второй раз он его не пришлёт. Без подхвата такое
 * сообщение остаётся без ответа, и снаружи это неотличимо от молчания.
 *
 * ОЧЕРЕДЬ НЕ ХРАНИТСЯ, А ВЫВОДИТСЯ ИЗ ЛЕНТЫ. Все ждавшие ответа лежат в ленте
 * чатов; не хватает только знания, по каким из них решение уже было. Его дают
 * две отметки ([Marks]):
 *  - [Marks.decidedUpTo] — номер строки ленты, по которой ответ кончился
 *    чем угодно: ушёл, промолчал сам, отказали сторож или согласие, сбой.
 *    Очередь одна на все чаты и идёт по порядку, а номера строк растут в том
 *    же порядке, поэтому всё до этой отметки решено;
 *  - [Marks.taken] и [Marks.tries] — за какую строку ответ взялся и сколько раз.
 *
 * РЕШИЛ И НЕ УСПЕЛ — РАЗНОЕ. Сообщение, на которое агент сознательно не
 * ответил (жарко, нет согласия, ветка ушла), отметку «решено» получает, и после
 * комы на него ответа нет. Слитые в одно «нет ответа в ленте», они дали бы
 * ответ на то, от чего агент отказался.
 *
 * ПОВТОР ОДИН. Строка, на ответе по которой служба умерла, берётся ещё раз —
 * и только раз ([MAX_TRIES]): если ответ сам роняет службу (нехватка памяти
 * посреди генерации), повторы по кругу съели бы заряд. Решение владельца.
 *
 * СВЕЖЕСТЬ — та же, что у ответа ([ChatReply.STALE_MS]): старше — не
 * подхватывается, решение «ветка ушла» и так было бы молчанием.
 *
 * ЧЕГО НЕ УМЕЕТ:
 *  - сообщение, пролежавшее дольше [ChatReply.STALE_MS] потому, что служба
 *    лежала, молчит: срок считается от времени сервера телеграма, а не от
 *    того, когда агент сообщение увидел;
 *  - до первой записи отметок подхвата нет: первый запуск только ставит
 *    отметку на конец ленты ([startMarks]) — иначе отвеченное за последние
 *    минуты получило бы второй ответ;
 *  - отказ «очередь полна» отметки «решено» не ставит, и после комы такое
 *    сообщение подхватывается, если ещё свежее;
 *  - отметки — в настройках приложения: очистка данных стирает их вместе с
 *    остальным, и подхват начинается заново, как при первом запуске.
 *
 * Чистый объект.
 */
object ChatRevive {

    /** Сколько раз браться за один ответ: первый раз и один повтор. Решение владельца, не подобранное число. */
    const val MAX_TRIES = 2

    /** Сколько знаков сообщения показывать в строке экрана. Объявленное число, не подобранное. */
    const val QUOTE_CHARS = 40

    /** Отметки подхвата; смысл полей — в шапке. [taken] 0 — ни за что не брался. */
    data class Marks(val decidedUpTo: Long, val taken: Long, val tries: Int)

    /** Строка ленты, ждущая ответа: номер в ленте, время сервера телеграма, текст. */
    data class Waiting(val id: Long, val at: Long, val text: String)

    /**
     * Что делать после подъёма. [again] — номера строк, на которые ответить, по
     * порядку; [givenUp] — строка, на ответе по которой служба умерла
     * [MAX_TRIES] раз; [stale] — сколько ждавших старше срока; [firstRun] —
     * отметок ещё не было.
     */
    data class Plan(val again: List<Long>, val givenUp: Waiting?, val stale: Int, val firstRun: Boolean)

    /** Отметки первого запуска: всё, что уже в ленте до [maxId], считается решённым. */
    fun startMarks(maxId: Long): Marks = Marks(maxId, 0L, 0)

    /** Ответ берётся за строку [id]: та же — ещё одна попытка, другая — первая. */
    fun taking(m: Marks, id: Long): Marks = if (m.taken == id) m.copy(tries = m.tries + 1) else m.copy(taken = id, tries = 1)

    /** Ответ по строке [id] кончился — чем бы ни кончился. */
    fun decided(m: Marks, id: Long): Marks = m.copy(decidedUpTo = maxOf(m.decidedUpTo, id))

    /**
     * План по [waiting] — строкам ленты к агенту после [Marks.decidedUpTo], по
     * порядку. [marks] null — отметок ещё не было.
     */
    fun plan(waiting: List<Waiting>, marks: Marks?, nowMs: Long, staleMs: Long = ChatReply.STALE_MS): Plan {
        if (marks == null) return Plan(emptyList(), null, 0, firstRun = true)
        val again = ArrayList<Long>()
        var givenUp: Waiting? = null
        var stale = 0
        for (w in waiting.sortedBy { it.id }) {
            if (w.id <= marks.decidedUpTo) continue
            when {
                nowMs - w.at > staleMs -> stale++
                w.id == marks.taken && marks.tries >= MAX_TRIES -> givenUp = w
                else -> again += w.id
            }
        }
        return Plan(again, givenUp, stale, firstRun = false)
    }

    /** Строка экрана врат после подъёма. Печатается всегда: «ждавших нет» отличается от «не смотрел». */
    fun line(plan: Plan): String {
        if (plan.firstRun) return "После комы: отметок ещё не было — подхватывать начну со следующей комы"
        val parts = ArrayList<String>()
        parts += if (plan.again.isEmpty()) "ждавших ответа нет" else "подхватил без ответа: ${plan.again.size}"
        plan.givenUp?.let { parts += "на «${quote(it.text)}» не отвечаю — служба умерла посреди этого ответа $MAX_TRIES раза" }
        if (plan.stale > 0) parts += "старше ${ChatReply.STALE_MS / 60_000} мин, не подхватываю: ${plan.stale}"
        return "После комы: " + parts.joinToString(" · ")
    }

    private fun quote(text: String): String {
        val t = text.trim().replace('\n', ' ')
        return if (t.length <= QUOTE_CHARS) t else t.take(QUOTE_CHARS).trimEnd() + "…"
    }
}
