package com.uroboros.memory.nav

import com.uroboros.util.TextFold
import org.junit.Assert.assertEquals
import org.junit.Test

/**
 * Фразы придуманные, не из памяти владельца. Таблица — те строки настоящей
 * таблицы (assets/verb_person_pairs.txt), где встречаются слова этих фраз.
 */
class RetellingTest {

    private val table = RetellTable.parse(
        sequenceOf(
            "вижу видишь", "говорю говоришь", "займусь займёшься", "закончу закончишь",
            "замечу заметишь", "знаю знаешь", "лечу летишь", "лечу лечишь", "отдохну отдохнёшь",
            "отдыхаю отдыхаешь", "пишу пишешь", "работаю работаешь",
        )
    )

    private fun check(input: String, expected: String?, dropped: Int, t: RetellTable = table) {
        val r = Retelling.retell(input, t)
        assertEquals(expected, r.text)
        assertEquals(dropped, r.dropped)
    }

    // --- Разворот ---

    @Test
    fun `просьба выброшена, ты в начале своих частей`() = check(
        "В последнее время я много работаю над твоими настройками. Скажи, если заметишь ошибку. " +
            "Хотя я пока что не уверен, что ты видишь свои настройки.",
        "ты в последнее время много работаешь над моими настройками; хотя ты пока что не уверен, что я вижу свои настройки.",
        1,
    )

    @Test
    fun `дефис не рвёт слово — когда-нибудь не союз`() = check(
        "Когда-нибудь я закончу чинить велосипед, но только не сегодня.",
        "ты когда-нибудь закончишь чинить велосипед, но только не сегодня.",
        0,
    )

    @Test
    fun `без ты — ничего не вставляется, ё из таблицы`() = check(
        "Пока да, отдыхаю - выходной. Займусь сегодня твоими настройками",
        "пока да, отдыхаешь - выходной; займёшься сегодня моими настройками.",
        0,
    )

    @Test
    fun `мы с тобой — тобой не трогается`() = check(
        "Вот мы с тобой просто разговариваем, и это здорово. Потому что я тебя собрал.",
        "вот мы с тобой просто разговариваем, и это здорово; потому что ты меня собрал.",
        0,
    )

    @Test
    fun `чем — союз, ты не уходит за него`() = check(
        "Ты знаешь о птицах больше, чем я думал.",
        "я знаю о птицах больше, чем ты думал.",
        0,
    )

    @Test
    fun `предлоги подстраиваются под новое местоимение`() = check(
        "Со мной всё хорошо, я говорю о тебе.",
        "с тобой всё хорошо, ты говоришь обо мне.",
        0,
    )

    @Test
    fun `ты сразу за союзом — не двигается`() = check(
        "Когда я закончу, ты отдохнёшь.",
        "когда ты закончишь, я отдохну.",
        0,
    )

    @Test
    fun `слов не из таблицы разворот не трогает`() = check(
        "Я пишу агенту про радугу и твою память, поскольку обещал.",
        "ты пишешь агенту про радугу и мою память, поскольку обещал.",
        0,
    )

    @Test
    fun `передо мной — перед тобой, ты в начало части`() = check(
        "Вчера я был у тебя в настройках, передо мной было много строк.",
        "ты вчера был у меня в настройках, перед тобой было много строк.",
        0,
    )

    @Test
    fun `латинская ё становится русской`() = check(
        "Жëлтый цвет мне нравится.",
        "жёлтый цвет тебе нравится.",
        0,
    )

    @Test
    fun `вопрос не берётся`() = check("Я устал. Как ты?", "ты устал.", 1)

    // --- Молчание ---

    @Test
    fun `неоднозначная форма — предложение не берётся`() = check("Сегодня я лечу домой.", null, 1)

    @Test
    fun `только вопрос — выхода нет`() = check("Тебе снились сны?", null, 1)

    @Test
    fun `только просьба — выхода нет`() = check("Назови цвета радуги.", null, 1)

    @Test
    fun `пустая таблица — местоимения меняются, глаголы нет`() = check(
        "Я работаю над твоей памятью.",
        "ты работаю над моей памятью.",
        0,
        RetellTable.EMPTY,
    )

    // --- Граница (починка будет заметна) ---

    @Test
    fun `просьба не первым словом не ловится`() = check(
        "Ладно, потерпи немного, скоро закончу работу.",
        "ладно, потерпи немного, скоро закончишь работу.",
        0,
    )

    // --- Одно место для местоимений ---

    @Test
    fun `пары местоимений — те же слова, что у определителя лица`() {
        val firsts = Retelling.PRONOUN_PAIRS.map { TextFold.fold(it.first) }.toSet()
        val seconds = Retelling.PRONOUN_PAIRS.map { TextFold.fold(it.second) }.toSet()
        assertEquals(PersonForm.FIRST_PRONOUNS, firsts)
        assertEquals(PersonForm.SECOND_PRONOUNS, seconds)
    }
}
