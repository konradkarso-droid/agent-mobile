package com.uroboros.memory

import org.junit.Assert.assertEquals
import org.junit.Test

/**
 * Границы разрезалки [Sentences] — и те, что починены, и те, что оставлены.
 *
 * ОТКУДА ЗАДАЧА. В памяти лежит запись в двенадцать тысяч знаков: шесть
 * предложений про станок, набранных нумерованным списком и повторённых два
 * десятка раз. Судья её не видит — она длиннее его потолка, — и в ответ она
 * тоже не попадает: отбор считает её слишком дорогой. Запись лежит в самом
 * доверенном слое и не участвует ни в чём.
 *
 * ЧТО ЗАКРЕПЛЯЮТ ТЕСТЫ НА МОЛЧАНИЕ. Половина здешних проверок говорит, чего
 * разрезалка НЕ делает: не склеивает по регистру, не чинит составное
 * предложение, не знает незнакомых сокращений. Такая проверка не даёт
 * «улучшению» молча перейти границу — а перейдя её, разрезалка начала бы
 * терять утверждения, и заметно это стало бы только по пропавшим спорам.
 */
class SentencesTest {

    @Test
    fun `номер пункта не считается концом предложения`() {
        val text = "1. Кожух закрывает зону резания. 2. Смазка подаётся по каналу."
        assertEquals(
            listOf(
                "Кожух закрывает зону резания.",
                "Смазка подаётся по каналу.",
            ),
            Sentences.split(text),
        )
    }

    @Test
    fun `одинаковые предложения под разными номерами склеиваются`() {
        val text = "1. Подача двигает заготовку. 2. Кожух закрывает зону. " +
            "3. Подача двигает заготовку. 4. Кожух закрывает зону. " +
            "5. Подача двигает заготовку."
        assertEquals(
            listOf(
                Sentences.Piece("Подача двигает заготовку.", 3),
                Sentences.Piece("Кожух закрывает зону.", 2),
            ),
            Sentences.statements(text),
        )
    }

    @Test
    fun `сокращение из списка не рвёт предложение`() {
        val text = "Нужны гвозди, шурупы и т.п. мелочь. Потом покраска."
        assertEquals(
            listOf(
                "Нужны гвозди, шурупы и т.п. мелочь.",
                "Потом покраска.",
            ),
            Sentences.split(text),
        )
    }

    @Test
    fun `на обычном тексте разрез прежний`() {
        val text = "Я работаю по субботам. Меркурий светит белым на закате. Ставка 7.5 годовых."
        assertEquals(
            listOf(
                "Я работаю по субботам.",
                "Меркурий светит белым на закате.",
                "Ставка 7.5 годовых.",
            ),
            Sentences.split(text),
        )
    }

    @Test
    fun `порядок первого появления сохраняется`() {
        val text = "Второе предложение. Первое предложение. Второе предложение."
        assertEquals(
            listOf("Второе предложение.", "Первое предложение."),
            Sentences.statements(text).map { it.text },
        )
    }

    // --- границы, оставленные намеренно ---

    @Test
    fun `различие в регистре повторы не склеивает`() {
        val text = "Станок называется Вымпел. Станок называется вымпел."
        assertEquals(2, Sentences.statements(text).size)
    }

    @Test
    fun `составное предложение остаётся одним куском`() {
        val text = "В мастерской стоит станок, и у него есть подача, шпиндель и кожух."
        assertEquals(1, Sentences.split(text).size)
    }

    @Test
    fun `незнакомое сокращение рвёт предложение — граница известна`() {
        val text = "Рядом оз. Байкал."
        assertEquals(listOf("Рядом оз.", "Байкал."), Sentences.split(text))
    }

    @Test
    fun `предложение, начатое числом с точкой, теряет число — граница известна`() {
        val text = "1861. Отмена крепостного права."
        assertEquals(listOf("Отмена крепостного права."), Sentences.split(text))
    }

    @Test
    fun `пустой текст даёт пустой список`() {
        assertEquals(emptyList<String>(), Sentences.split("   "))
    }
}
