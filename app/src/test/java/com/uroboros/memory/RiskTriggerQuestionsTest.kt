package com.uroboros.memory

import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Предложения-вопросы в правиле противоречия: они не сравниваются.
 *
 * Пары взяты из живых данных устройства: первая — ход ленты, где сверка
 * сказала модели «расходятся» на вопрос, на который запись отвечала; вторая —
 * запись из базы, где утверждение и вопрос стоят рядом.
 *
 * ЧЕГО ЭТОТ ФАЙЛ НЕ ДОКАЗЫВАЕТ: что вопрос узнаётся надёжно. Узнаётся он
 * только по знаку, и обе границы этого закреплены ниже как границы, а не как
 * цель.
 */
class RiskTriggerQuestionsTest {

    private val notOnSaturdays = "Я не работаю по субботам"

    @Test
    fun `вопрос против утверждения не спорит`() {
        assertFalse(RiskTrigger.contradicts("Я работаю по субботам?", notOnSaturdays))
        assertFalse(RiskTrigger.contradicts(notOnSaturdays, "Я работаю по субботам?"))
    }

    @Test
    fun `утверждение рядом с вопросом в той же записи сравнивается`() {
        // Если снимать всю запись со знаком вопроса, этот спор пропадёт.
        assertTrue(
            RiskTrigger.contradicts(
                "Станок в мастерской называется Вымпел",
                "Станок в мастерской НЕ называется Вымпел. Так как он называется?",
            )
        )
    }

    @Test
    fun `вопрос без знака сравнивается как утверждение`() {
        // Закреплённая граница: знака нет — правило вопроса не видит.
        assertTrue(RiskTrigger.contradicts("Разве я работаю по субботам", notOnSaturdays))
    }

    @Test
    fun `известная потеря - риторический вопрос со знаком снимается`() {
        // «Разве я работаю по субботам?» говорит «не работаю» и спорит с
        // «работаю», но как вопрос не сравнивается. Тест упадёт, когда
        // риторический вопрос научатся отличать, — и это будет видно.
        assertFalse(
            RiskTrigger.contradicts("Разве я работаю по субботам?", "Я работаю по субботам")
        )
    }
}
