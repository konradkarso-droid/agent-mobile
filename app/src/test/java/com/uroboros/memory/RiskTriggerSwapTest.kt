package com.uroboros.memory

import com.uroboros.memory.RiskTrigger.MarkKind
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Признак «на месте одного слова стоит другое» (MarkKind.SWAP).
 *
 * ОТКУДА ВЗЯТЫ ПАРЫ И ЧЕГО ОНИ НЕ ЗНАЧАТ. Все тексты ниже — из памяти живого
 * устройства, но сочинены человеком нарочно, чтобы проверять правило
 * противоречия: «рубанок», «Меркурий», «суббота». Это образцы, а НЕ замер
 * частоты. Сколько таких пар встречается в обычном разговоре, отсюда не
 * следует никак: человек в норме сам себе так не противоречит, и настоящий
 * случай для этого признака другой — запись в памяти расходится с тем, что
 * человек говорит СЕЙЧАС (см. DisputeNotice).
 *
 * ГЛАВНЫЕ ЗДЕСЬ — ПРОВЕРКИ НА МОЛЧАНИЕ: две стороны с «не», расхождение в два
 * слова, расхождение в незначимом слове. Каждая закрепляет границу, за которой
 * признак начал бы наполнять очередь парами, где спора нет.
 *
 * СИНОНИМЫ ПРОВЕРЯЮТСЯ КАК ИЗВЕСТНЫЙ ПРОМАХ, а не как желаемое поведение:
 * «светит» против «сияет» правило называет спором и отличить одно от другого
 * не может. Тест стоит здесь, чтобы промах был виден в коде, а не всплыл
 * однажды на экране как неожиданность.
 */
class RiskTriggerSwapTest {

    private fun kinds(a: String, b: String) =
        RiskTrigger.contradictionMarks(a, b).map { it.kind }

    private fun swap(a: String, b: String) =
        RiskTrigger.contradictionMarks(a, b).firstOrNull { it.kind == MarkKind.SWAP }

    // --- Ловит ---

    @Test
    fun `замена определения — спор`() {
        val mark = swap(
            "Мой любимый инструмент — рубанок с деревянной колодкой",
            "Мой любимый инструмент — рубанок с железной колодкой",
        )
        assertTrue("замена слова не замечена", mark != null)
        assertEquals(setOf("деревянной"), mark!!.first)
        assertEquals(setOf("железной"), mark.second)
    }

    @Test
    fun `замена цвета — спор`() {
        assertTrue(kinds("Меркурий светит белым на закате.", "Меркурий светит алым на закате")
            .contains(MarkKind.SWAP))
    }

    @Test
    fun `слова названы так, как написаны в тексте`() {
        // Основа у слов общая, показать надо написанное: искать в тексте
        // основу не по чему.
        val mark = swap("Станок в мастерской зелёный", "Станок в мастерской красный")
        assertEquals(setOf("зелёный"), mark!!.first)
        assertEquals(setOf("красный"), mark.second)
    }

    // --- Молчит ---

    @Test
    fun `две стороны с отрицанием — не спор`() {
        // «Не светит белым» и «не светит алым» уживаются: Меркурий может
        // светить жёлтым, и ни одна сторона другой не противоречит.
        assertTrue(
            kinds("Меркурий не светит белым на закате.", "Меркурий не светит алым на закате")
                .isEmpty()
        )
    }

    @Test
    fun `отрицание у одной стороны — прежний признак, без замены`() {
        val marks = kinds("Я работаю по субботам", "Я не работаю по субботам")
        assertEquals(listOf(MarkKind.NEGATION), marks)
    }

    @Test
    fun `разошлись два слова — не спор об одном и том же`() {
        assertFalse(
            kinds("Меркурий не светит красным на восходе", "Меркурий не светит алым на закате")
                .contains(MarkKind.SWAP)
        )
        assertFalse(
            kinds("Меркурий светит красным на восходе", "Меркурий светит алым на закате")
                .contains(MarkKind.SWAP)
        )
    }

    @Test
    fun `расхождение в незначимом слове не считается`() {
        // «Где» и «чем» — стоп-слова, «ел» короче значимого. Спор в таких
        // парах если и есть, то не в этих словах.
        assertFalse(kinds("Обедал воробей на крыше", "Обедал воробей под крышей")
            .contains(MarkKind.SWAP))
    }

    @Test
    fun `одинаковые записи спором не становятся`() {
        assertTrue(
            kinds(
                "Мой любимый инструмент — рубанок с деревянной колодкой",
                "Мой любимый инструмент — рубанок с деревянной колодкой.",
            ).isEmpty()
        )
    }

    @Test
    fun `разные числа остаются числами, а не заменой слова`() {
        val marks = kinds("Ставка по вкладу 7.5", "Ставка по вкладу 8")
        assertTrue(marks.contains(MarkKind.NUMBER))
        assertFalse(marks.contains(MarkKind.SWAP))
    }

    // --- Известный промах ---

    @Test
    fun `синонимы правило называет спором — это его граница`() {
        assertTrue(
            kinds("Меркурий светит алым у полудня", "Меркурий сияет алым у полудня")
                .contains(MarkKind.SWAP)
        )
    }
}
