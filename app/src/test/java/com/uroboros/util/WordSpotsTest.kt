package com.uroboros.util

import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Границы поиска мест под подсветку.
 *
 * ЗАЧЕМ ОН ЕСТЬ. Подсветка признаков спора стоит на экране очереди рядом с
 * необратимым действием, и лишнее выделение хуже недостающего: закрашенное
 * слово направляет взгляд перед нажатием. Промах здесь не падает и в логе не
 * виден — экран выглядит правдоподобно в обоих случаях.
 *
 * САМЫЙ ВАЖНЫЙ ЗДЕСЬ — ПЕРВЫЙ ТЕСТ. Наивный поиск «не» внутри слова даёт
 * отрицание в каждом втором русском тексте: «нельзя», «конечно», «неделя»,
 * «неверно». Это единственное место, где такая находка ловится.
 *
 * ЧЕГО ЭТОТ ФАЙЛ НЕ ДОКАЗЫВАЕТ:
 *  - что искать надо было именно эти слова. Их называет правило противоречия,
 *    и сторож у него свой;
 *  - что заливка нарисовалась на экране. Здесь только места; назначение
 *    спанов и отрисовка живут в MainActivity и в JVM-тест не попадают.
 */
class WordSpotsTest {

    @Test
    fun `слово не находится внутри другого слова`() {
        val text = "Нельзя, конечно, всю неделю"

        assertEquals(
            "«не» здесь нет ни одного — есть три слова, которые с него начинаются",
            emptyList<WordSpot>(),
            wordSpots(text, setOf("не"))
        )
    }

    @Test
    fun `цифра не находится внутри другого числа`() {
        // Цифра проверяется как буква: без этого «7» нашлось бы внутри «17»,
        // и число на экране разошлось бы с тем, что сравнивало правило.
        assertEquals(emptyList<WordSpot>(), wordSpots("В доме 17 окон", setOf("7")))
        assertEquals(listOf(WordSpot(7, 8)), wordSpots("В доме 7 окон", setOf("7")))
    }

    @Test
    fun `регистр не различается`() {
        // Правило приводит слова к нижнему, в тексте стоит написанное
        // человеком. Место при этом указывается в исходном тексте, а не в
        // приведённом.
        val spots = wordSpots("Не мой инструмент", setOf("не"))

        assertEquals(listOf(WordSpot(0, 2)), spots)
    }

    @Test
    fun `слово на краях текста находится`() {
        // Края — отдельный случай: соседа с одной стороны там нет вовсе, и
        // проверка границы обязана считать его концом слова, а не буквой.
        assertEquals(listOf(WordSpot(0, 2)), wordSpots("не", setOf("не")))
        assertEquals(listOf(WordSpot(4, 6)), wordSpots("вот не", setOf("не")))
    }

    @Test
    fun `все вхождения находятся и идут по возрастанию`() {
        // Который из них имелся в виду, отсюда не видно, поэтому выделяются
        // все. Порядок задан затем, чтобы ответ не зависел от обхода набора.
        val spots = wordSpots("не тут и не там", setOf("не", "там"))

        assertEquals(listOf(0, 9, 12), spots.map { it.start })
    }

    @Test
    fun `ненайденное слово даёт пустой ответ, а не ошибку`() {
        // Законный исход: чаще всего текст обрезан по длине и нужное осталось
        // за обрезкой. Показывающий отличает этот случай от «искать было
        // нечего» по тому, что список слов непуст.
        assertTrue(wordSpots("Мой любимый инструмент", setOf("рубанок")).isEmpty())
        assertTrue(wordSpots("", setOf("не")).isEmpty())
        assertTrue(wordSpots("Мой любимый инструмент", emptySet()).isEmpty())
    }

    @Test
    fun `форма слова не подбирается`() {
        // Ищется ровно то, что дали. Правило работает на основах слов, а поиск
        // — на написанном, и разница эта намеренная: подбор формы здесь был бы
        // вторым, своим правилом.
        assertTrue(wordSpots("работаю рубанком", setOf("рубанок")).isEmpty())
    }
}
