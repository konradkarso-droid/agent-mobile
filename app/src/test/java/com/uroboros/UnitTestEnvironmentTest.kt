package com.uroboros

import android.util.Log
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Проверка на молчание для границы, которая живёт не в коде, а в файле сборки.
 *
 * Что закрепляется: в обычном JVM-юнит-тесте вызов android.util.Log НЕ работает, он
 * бросает исключение. Так ведёт себя сборка без testOptions { unitTests {
 * isReturnDefaultValues = true } }, и её отсутствие здесь намеренно: подмена
 * превратила бы любой случайный Android-вызов в тихий ноль, а в этом проекте
 * отличать "сломалось" от "промолчало" стоит дороже удобства.
 *
 * Зачем это закреплять тестом, а не комментарием. На этом факте держатся решения в
 * других местах: ToteEngine принимает SafetyZoneSource интерфейсом, MemoryCanary
 * обходится без Log и Context, а рядом с usefulnessMarks записано, что проводку
 * начисления юнит-тестом не покрыть. Все эти записи станут враньём в тот день, когда
 * кто-нибудь добавит в build.gradle.kts одну строку, — и не станет видно, что они
 * устарели. Этот тест в такой день падает и заставляет заметить.
 *
 * Падение здесь означает не поломку, а смену условий: подмена включена, значит надо
 * перечитать перечисленные выше места и решить, что теперь покрывается тестами.
 *
 * Чего проверка НЕ умеет: она смотрит только на Log. Room, Context и прочее
 * поведение Android в JVM-тестах она не описывает.
 */
class UnitTestEnvironmentTest {

    @Test
    fun `android util Log в JVM-тесте недоступен и бросает исключение`() {
        val outcome = runCatching { Log.d("uroboros", "проба") }
        assertTrue(
            "Log.d отработал без исключения — значит подмена Android-вызовов включена. " +
                "См. KDoc этого класса: устарели записи в ToteEngine, MemoryCanary и " +
                "рядом с usefulnessMarks.",
            outcome.isFailure
        )
    }
}
